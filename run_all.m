%% RUN_ALL Rebuild entry point for the robust-control project

clearvars;
close all force;
clc;

projectRoot = fileparts(mfilename('fullpath'));
originalDirectory = pwd;
cleanupDirectory = onCleanup(@() cd(originalDirectory));
cd(projectRoot);

rng(42, 'twister');
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));
addpath(genpath(fullfile(projectRoot, 'simulink')));

fprintf('Progetto CR - esecuzione riproducibile\n');
fprintf('Root: %s\n', projectRoot);
fprintf(['Struttura didattica: macrofase modellazione-linearizzazione-' ...
    'specifiche, quindi LQG, H-infinity, mu e validazioni finali.\n\n']);

try
    if strcmp(getenv('CR_RUN_SCOPE'),'simulink-completion')
        run_simulink_completion;
        return
    end
    if strcmp(getenv('CR_RUN_SCOPE'),'simulink')
        validate_simulink_integration;
        results=runtests(fullfile(projectRoot,'tests','test_simulink_integration.m'));
        assertSuccess(results);
        return
    end
    % Catena corrente. Il percorso precedente rimane esplicitamente storico.
    if isempty(getenv('CR_RUN_SCOPE')) || strcmp(getenv('CR_RUN_SCOPE'),'hinf-final')
        run_hinf_final_pipeline;
        return
    end
    % Percorso circoscritto alla revisione M6/M7. Gli artifact robusti
    % versionati restano congelati; il percorso completo sotto e invariato.
    % Esecuzione: setenv('CR_RUN_SCOPE','lqri'); run_all
    if strcmp(getenv('CR_RUN_SCOPE'),'lqri')
        baselineM6=load(fullfile(projectRoot,'results','data','m6_lqg_no_integrator.mat'));
        validate_m6_lqg_no_integrator;
        currentM6=load(fullfile(projectRoot,'results','data','m6_lqg_no_integrator.mat'));
        % Questo percorso e un replay della configurazione M6 corrente.
        % Se cambiano i guadagni occorre la catena downstream completa.
        assert(norm(currentM6.K-baselineM6.K,'fro')<1e-8);
        assert(isequal(currentM6.R,baselineM6.R) && isequal(currentM6.Q,baselineM6.Q));
        assert(isequal(currentM6.L,baselineM6.L) && ...
            isequal(currentM6.Qn,baselineM6.Qn) && isequal(currentM6.Rn,baselineM6.Rn));
        % Non aggiornare soltanto l'etichetta R di un calcolo didattico
        % obsoleto: matrici e risultati devono provenire dallo stesso M6.
        didacticPath=fullfile(projectRoot,'results','data','didactic_lqg_calculations.mat');
        didactic=load(didacticPath);
        assert(isequaln(didactic.Q,currentM6.Q) && ...
            isequaln(didactic.R,currentM6.R), ...
            'RunAll:StaleDidacticLqg', ...
            'Rigenerare progetto_lqg dopo la catena downstream corrente.');
        validate_m7_lqg_integral;
        plot_lqri_revision;
        % Le quattro suite coinvolte includono verifiche matematiche,
        % regressione M6, punti didattici e coerenza dei deliverable M18.
        names={'test_m6_lqg_no_integrator.m','test_m7_lqg_integral.m', ...
            'test_didactic_entry_points.m','test_m18_final_deliverables.m'};
        testResults=runtests(fullfile(projectRoot,'tests',names));
        verification=table(testResults);
        save(fullfile(projectRoot,'results','data','lqri_r_verification.mat'), ...
            'verification','-v7');
        writetable(verification(:,{'Name','Passed','Failed','Incomplete','Duration'}), ...
            fullfile(projectRoot,'results','data','lqri_r_verification.csv'));
        assertSuccess(testResults);
        fprintf('[PASS] RUN_ALL scope=lqri: %d/%d test. M8-M17 non rieseguiti.\n', ...
            sum([testResults.Passed]),numel(testResults));
        return
    end
    fprintf(['--- Test automatici M0 + M1 + M2 + M3/M3.1 + ' ...
        'M4/M4.1 + M5 + M6 + M7 + M8 + M9 + M10 + M11 + M12 + ' ...
        'M13 + M14 + M15 + M16 + M17 + M18 ---\n']);
    testResults = runtests(fullfile(projectRoot, 'tests'));
    assertSuccess(testResults);
    fprintf('Test automatici superati: %d/%d.\n', ...
        sum([testResults.Passed]), numel(testResults));

    fprintf('\n--- Validazione numerica M1 ---\n');
    m1Metrics = validate_m1_nonlinear_model;

    fprintf('\n--- Validazione, dataset e figura M2 ---\n');
    m2Metrics = validate_m2_equilibrium_linearization;

    fprintf('\n--- Scelta ingegneristica e verifica attuatori M3 ---\n');
    m3Metrics = validate_m3_nominal_actuated_plant;

    fprintf(['\n--- Incertezze dichiarate, fit WI, pianta incerta, dataset e ' ...
        'figure M4 ---\n']);
    m4Metrics = validate_m4_uncertainty_model;

    fprintf(['\n--- Specifiche dichiarate, pesi, disturbance path, dataset e ' ...
        'figure M5 ---\n']);
    m5Metrics = validate_m5_performance_specs;

    fprintf(['\n--- Ricerca LQR compatta, Kalman dichiarato, LQG, ' ...
        'dataset e figure M6 ---\n']);
    m6Metrics = validate_m6_lqg_no_integrator;

    fprintf('\n--- M7: LQRI con Kalman M6, integratori misurati e 30 stati chiusi ---\n');
    m7Metrics = validate_m7_lqg_integral;
    % Il confronto e i documenti M7 sono rigenerati dai risultati appena ottenuti.
    plot_lqri_revision;

    fprintf(['\n--- M8: Simulink non lineare, LTI/NL, disturbi, ' ...
        'rumore e RAS empirica ---\n']);
    m8Metrics = validate_m8_simulink_ras(true);

    fprintf(['\n--- M9: sintesi nominale mixsyn, ricostruzione ' ...
        'indipendente e confronto M6 ---\n']);
    m9Metrics = validate_m9_hinf_mixsyn;

    fprintf(['\n--- M10: generalized plant esplicita, gate M9, ' ...
        'hinfsyn e confronto M6/M9 ---\n']);
    m10Metrics = validate_m10_hinfsyn;

    fprintf(['\n--- M11: campagna hinfstruct strutturata A0-A5, ' ...
        'audit multistart e frontiera Pareto ---\n']);
    m11Metrics = validate_m11_hinfstruct;

    fprintf(['\n--- M12: mu-analysis NS/NP/RS/RP del controllore ' ...
        'A5 congelato sulla pianta incerta M4 ---\n']);
    m12Metrics = validate_m12_mu_analysis;

    fprintf(['\n--- M13: singola D-K synthesis musyn, history, ' ...
        'controller extraction e audit nominale ---\n']);
    m13Metrics = validate_m13_mu_synthesis;

    fprintf(['\n--- M14: mu-analysis finale NS/NP/RS/RP del Kmu ' ...
        'congelato e confronto robusto con A5 M12 ---\n']);
    m14Metrics = validate_m14_final_mu_analysis;

    fprintf(['\n--- M15: modello non lineare nominale, tracking, ' ...
        'disturbi, rumore, RAS e accordo LTI/NL Khinf/Kmu ---\n']);
    m15Metrics = validate_m15_nonlinear_robust(true);
    rasCommonMetrics = build_common_ras_comparison(string(projectRoot), true);

    fprintf(['\n--- M16: Monte Carlo lineare su 40 campioni comuni M4, ' ...
        'confronto M6/Khinf/Kmu congelati ---\n']);
    m16Metrics = validate_m16_monte_carlo(true);
    m16Stability = m16Metrics.summary.stabilitySummaryTable;
    m16PassRates = m16Metrics.summary.empiricalPassRatesTable;

    fprintf(['\n--- M17: confronto dei risultati M6/Khinf/Kmu, ' ...
        'trade-off e selezione finale per ruolo ---\n']);
    m17Metrics = validate_m17_final_comparison(true);
    m17Roles = m17Metrics.decision.finalRoleAssignment;

    fprintf(['\n--- M18: generazione documentale, audit numerico, ' ...
        'tracciabilita e verifica dei deliverable compilati ---\n']);
    m18Metrics = validate_m18_deliverables(true, true);

    fprintf(['\n[PASS] RUN_ALL completato senza errori: test e ' ...
        'validazioni M0-M18. ' ...
        'M7 resta PARTIAL terminale; M9-M10 restano PARTIAL e M11 ' ...
        'PARTIAL e accettata come studio strutturato concluso. ' ...
        'M12 resta PARTIAL: A5 e nominalmente stabile, ma fallisce NP ' ...
        'e non certifica RS/RP. M13 è COMPLETE come sintesi D-K e viene ' ...
        'ricaricata dall''artifact senza nuova musyn. M14 software=%s, ' ...
        'NS=%s, NP=%s, RS=%s, RP=%s; confronto A5/Kmu=%s e stato ' ...
        'M14=%s. M15 software=%s, tracking Khinf=%s, tracking Kmu=%s, ' ...
        'RAS rmin=[%.4g, %.4g] deg, agreement rmin=[%.4g, %.4g] deg, ' ...
        'stato M15=%s. M16 seed=%d, campioni=%d, stable M6/Khinf/Kmu=' ...
        '[%d/%d, %d/%d, %d/%d], all-core tracking pass rates=' ...
        '[%.4g, %.4g, %.4g], Kmu/M14=%s, stato M16=%s. ' ...
        'La Monte Carlo M16 è evidenza empirica lineare e non sostituisce ' ...
        'la certificazione mu M14. M17 ruoli=[%s:%s; %s:%s; %s:%s], ' ...
        'metodo=%s, stato=%s. M18 ha generato e auditato soltanto i ' ...
        'deliverable finali, senza seconda sintesi, riduzione d''ordine, ' ...
        'retuning, nuova Monte Carlo o simulazione dinamica.\n'], ...
        m14Metrics.qualityGate.softwareCorrectness, ...
        m14Metrics.qualityGate.nominalStability, ...
        m14Metrics.qualityGate.nominalPerformance, ...
        m14Metrics.qualityGate.robustStability, ...
        m14Metrics.qualityGate.robustPerformance, ...
        m14Metrics.robustComparison.rsImprovement.classification, ...
        m14Metrics.qualityGate.overallStatus, ...
        m15Metrics.qualityGate.softwareCorrectness, ...
        m15Metrics.qualityGate.trackingKhinf, ...
        m15Metrics.qualityGate.trackingKmu, ...
        m15Metrics.rasResults(1).metrics.minimumRadiusDeg, ...
        m15Metrics.rasResults(2).metrics.minimumRadiusDeg, ...
        m15Metrics.agreementResults(1).metrics.minimumRadiusDeg, ...
        m15Metrics.agreementResults(2).metrics.minimumRadiusDeg, ...
        m15Metrics.qualityGate.overallStatus, ...
        m16Metrics.config.seed, m16Metrics.config.numberSamples, ...
        m16Stability.NStable(1), m16Stability.NTotal(1), ...
        m16Stability.NStable(2), m16Stability.NTotal(2), ...
        m16Stability.NStable(3), m16Stability.NTotal(3), ...
        m16PassRates.AllCorePassFractionTotal(1), ...
        m16PassRates.AllCorePassFractionTotal(2), ...
        m16PassRates.AllCorePassFractionTotal(3), ...
        m16Metrics.qualityGate.KmuM14Consistency, ...
        m16Metrics.qualityGate.overallStatus, ...
        m17Roles.Role(1), m17Roles.Controller(1), ...
        m17Roles.Role(2), m17Roles.Controller(2), ...
        m17Roles.Role(3), m17Roles.Controller(3), ...
        m17Metrics.decision.method, ...
        m17Metrics.qualityGate.overallStatus);
    fprintf(['M18 traceability=%s, report=%s, presentation=%s, ' ...
        'stato=%s.\n'], ...
        m18Metrics.qualityGate.artifactTraceability, ...
        m18Metrics.qualityGate.reportCompilation, ...
        m18Metrics.qualityGate.presentationCompilation, ...
        m18Metrics.qualityGate.overallStatus);
catch executionError
    fprintf(2, '\n[FAIL] RUN_ALL interrotto: %s\n', executionError.message);
    rethrow(executionError);
end
