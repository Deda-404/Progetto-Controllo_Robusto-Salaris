function physical = build_m16_sampled_physical_plant( ...
    m4, BdMechanical, sampleValues, config)
%BUILD_M16_SAMPLED_PHYSICAL_PLANT One shared actuator/mechanical state.

arguments
    m4 (1, 1) struct
    BdMechanical double
    sampleValues = []
    config (1, 1) struct = monte_carlo_specs_m16
end

isNominalBenchmark = isempty(sampleValues);
if isNominalBenchmark
    actuator1 = ss(m4.uncertainPlantInfo.GactuatorNominal);
    actuator2 = ss(m4.uncertainPlantInfo.GactuatorNominal);
    sampledActuators = append(actuator1, actuator2);
    sampledMechanicsMeas = ss(m4.GmechUncMeas.NominalValue);
    sampledMechanicsQ = ss(m4.GmechUncQ.NominalValue);
    directMeasReference = ss(m4.GuncMeas.NominalValue);
    directQReference = ss(m4.GuncQ.NominalValue);
else
    actuatorValues = localSelectFields(sampleValues, ...
        ["Delta_act1"; "Delta_act2"]);
    mechanicalValues = localSelectFields(sampleValues, ...
        ["Jm1"; "k1"; "k2"]);
    sampledActuators = ss(usubs( ...
        m4.uncertainPlantInfo.GactuatorsUncertain, actuatorValues));
    sampledMechanicsMeas = ss(usubs( ...
        m4.GmechUncMeas, mechanicalValues));
    sampledMechanicsQ = ss(usubs(m4.GmechUncQ, mechanicalValues));
    directMeasReference = ss(usubs(m4.GuncMeas, sampleValues));
    directQReference = ss(usubs(m4.GuncQ, sampleValues));
end

[Aa, Ba, Ca, Da] = ssdata(sampledActuators);
[Am, Bm, Cm, Dm] = ssdata(sampledMechanicsMeas);
[AmQ, BmQ, Cq, Dq] = ssdata(sampledMechanicsQ);
assert(isequaln(Am, AmQ) && isequaln(Bm, BmQ), ...
    'M16:MechanicalStateMismatch', ...
    'Sampled measurement and q mechanics do not share A/B states.');
assert(norm(Dm, 'fro') <= eps && norm(Dq, 'fro') <= eps, ...
    'M16:MechanicalFeedthrough', ...
    'The sampled mechanical model must have zero feedthrough.');
assert(size(BdMechanical, 1) == size(Am, 1) && ...
    size(BdMechanical, 2) == 2, 'M16:DisturbanceInput', ...
    'The physical link-disturbance matrix has incompatible dimensions.');

numberMechanicalStates = size(Am, 1);
numberActuatorStates = size(Aa, 1);
Aphysical = [Am, Bm * Ca; ...
    zeros(numberActuatorStates, numberMechanicalStates), Aa];
Bcontrol = [Bm * Da; Ba];
Bdisturbance = [BdMechanical; zeros(numberActuatorStates, 2)];
Cmeasurement = [Cm, zeros(size(Cm, 1), numberActuatorStates)];
Cposition = [Cq, zeros(size(Cq, 1), numberActuatorStates)];
Dmeasurement = zeros(size(Cmeasurement, 1), 4);

sharedPlant = ss(Aphysical, [Bcontrol, Bdisturbance], ...
    Cmeasurement, Dmeasurement, ...
    'InputName', {'u1', 'u2', 'd1', 'd2'}, ...
    'OutputName', {'q1', 'q2', 'theta1', 'theta2'});
controlToMeas = sharedPlant(:, 1:2);
controlToQ = ss(Aphysical, Bcontrol, Cposition, zeros(2, 2));
disturbanceToMeas = sharedPlant(:, 3:4);
disturbanceToQ = ss(Aphysical, Bdisturbance, Cposition, zeros(2, 2));

measurementAudit = localCompareFrequency(controlToMeas, ...
    directMeasReference, config.auditFrequencyGrid);
positionAudit = localCompareFrequency(controlToQ, directQReference, ...
    config.auditFrequencyGrid);
mechanicalOutputAudit = localCompareFrequency( ...
    sampledMechanicsMeas(1:2, :), sampledMechanicsQ, ...
    config.auditFrequencyGrid);
auditPassed = measurementAudit.maximumAbsoluteError <= ...
    config.frequencyAbsoluteTolerance && ...
    measurementAudit.maximumRelativeError <= ...
    config.frequencyRelativeTolerance && ...
    positionAudit.maximumAbsoluteError <= ...
    config.frequencyAbsoluteTolerance && ...
    positionAudit.maximumRelativeError <= ...
    config.frequencyRelativeTolerance && ...
    mechanicalOutputAudit.maximumAbsoluteError <= ...
    config.frequencyAbsoluteTolerance;

physical = struct( ...
    'system', sharedPlant, ...
    'controlToMeas', controlToMeas, ...
    'controlToQ', controlToQ, ...
    'disturbanceToMeas', disturbanceToMeas, ...
    'disturbanceToQ', disturbanceToQ, ...
    'A', Aphysical, ...
    'Bcontrol', Bcontrol, ...
    'Bdisturbance', Bdisturbance, ...
    'Cmeasurement', Cmeasurement, ...
    'Cposition', Cposition, ...
    'actuatorOrder', numberActuatorStates, ...
    'mechanicalOrder', numberMechanicalStates, ...
    'physicalOrder', size(Aphysical, 1), ...
    'isNominalBenchmark', isNominalBenchmark, ...
    'audit', struct( ...
        'measurementPath', measurementAudit, ...
        'positionPath', positionAudit, ...
        'mechanicalOutputPath', mechanicalOutputAudit, ...
        'passed', auditPassed, ...
        'usesSharedPhysicalState', true, ...
        'disturbanceEntersLinkMechanics', true));

assert(auditPassed, 'M16:SampledPhysicalPlantMismatch', ...
    ['The shared-state sampled physical plant does not reproduce the ' ...
    'frozen M4 sampled transfer matrices.']);
end

function selected = localSelectFields(values, names)
selected = struct;
for index = 1:numel(names)
    name = char(names(index));
    selected.(name) = values.(name);
end
end

function comparison = localCompareFrequency(actual, reference, frequencies)
actualResponse = freqresp(ss(actual), frequencies);
referenceResponse = freqresp(ss(reference), frequencies);
difference = actualResponse - referenceResponse;
absoluteError = abs(difference);
numberFrequencies = numel(frequencies);
referenceNorm = zeros(numberFrequencies, 1);
differenceNorm = zeros(numberFrequencies, 1);
for index = 1:numberFrequencies
    referenceNorm(index) = norm(referenceResponse(:, :, index), 'fro');
    differenceNorm(index) = norm(difference(:, :, index), 'fro');
end
referenceFloor = max(1, max(referenceNorm)) * eps;
comparison = struct( ...
    'maximumAbsoluteError', max(absoluteError, [], 'all'), ...
    'maximumRelativeError', max(differenceNorm ./ ...
        max(referenceNorm, referenceFloor)), ...
    'frequencyCount', numberFrequencies);
end
