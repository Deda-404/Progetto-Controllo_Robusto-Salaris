function campaign = generate_m16_uncertainty_samples(m4, config)
%GENERATE_M16_UNCERTAINTY_SAMPLES Create one common M4 sample sequence.

arguments
    m4 (1, 1) struct
    config (1, 1) struct = monte_carlo_specs_m16
end

originalRng = rng;
cleanupRng = onCleanup(@() rng(originalRng));
rng(config.seed, char(config.rngAlgorithm));
[~, sampledValues] = usample(m4.GuncMeas, config.numberSamples);

% This second generation is an audit replay only. It is never simulated.
rng(config.seed, char(config.rngAlgorithm));
[~, replayValues] = usample(m4.GuncMeas, config.numberSamples);

numberSamples = config.numberSamples;
SampleID = (1:numberSamples).';
Jm1Actual = nan(numberSamples, 1);
k1Actual = nan(numberSamples, 1);
k2Actual = nan(numberSamples, 1);
Jm1DeviationPercent = nan(numberSamples, 1);
k1DeviationPercent = nan(numberSamples, 1);
k2DeviationPercent = nan(numberSamples, 1);
DeltaAct1 = cell(numberSamples, 1);
DeltaAct2 = cell(numberSamples, 1);
DeltaAct1HinfNorm = nan(numberSamples, 1);
DeltaAct2HinfNorm = nan(numberSamples, 1);
DeltaAct1PeakFrequency = nan(numberSamples, 1);
DeltaAct2PeakFrequency = nan(numberSamples, 1);
DeltaAct1Order = nan(numberSamples, 1);
DeltaAct2Order = nan(numberSamples, 1);
DeltaAct1Stable = false(numberSamples, 1);
DeltaAct2Stable = false(numberSamples, 1);
DeltaAct1Finite = false(numberSamples, 1);
DeltaAct2Finite = false(numberSamples, 1);
UrealInRange = false(numberSamples, 1);
BlockSetValid = false(numberSamples, 1);
Valid = false(numberSamples, 1);
replayScalarError = zeros(numberSamples, 1);
replayDynamicError = zeros(numberSamples, 1);

nominal = localNominalValues(m4.selectedMechanicalRanges);
expectedBlocks = sort(config.expectedUncertaintyBlocks);
for sampleIndex = 1:numberSamples
    current = sampledValues(sampleIndex);
    replay = replayValues(sampleIndex);
    Jm1Actual(sampleIndex) = current.Jm1;
    k1Actual(sampleIndex) = current.k1;
    k2Actual(sampleIndex) = current.k2;
    Jm1DeviationPercent(sampleIndex) = ...
        100 * (current.Jm1 / nominal.Jm1 - 1);
    k1DeviationPercent(sampleIndex) = ...
        100 * (current.k1 / nominal.k1 - 1);
    k2DeviationPercent(sampleIndex) = ...
        100 * (current.k2 / nominal.k2 - 1);
    DeltaAct1{sampleIndex} = ss(current.Delta_act1);
    DeltaAct2{sampleIndex} = ss(current.Delta_act2);
    [DeltaAct1HinfNorm(sampleIndex), ...
        DeltaAct1PeakFrequency(sampleIndex)] = ...
        norm(DeltaAct1{sampleIndex}, inf);
    [DeltaAct2HinfNorm(sampleIndex), ...
        DeltaAct2PeakFrequency(sampleIndex)] = ...
        norm(DeltaAct2{sampleIndex}, inf);
    DeltaAct1Order(sampleIndex) = order(DeltaAct1{sampleIndex});
    DeltaAct2Order(sampleIndex) = order(DeltaAct2{sampleIndex});
    DeltaAct1Stable(sampleIndex) = isstable(DeltaAct1{sampleIndex});
    DeltaAct2Stable(sampleIndex) = isstable(DeltaAct2{sampleIndex});
    DeltaAct1Finite(sampleIndex) = localFiniteSystem( ...
        DeltaAct1{sampleIndex});
    DeltaAct2Finite(sampleIndex) = localFiniteSystem( ...
        DeltaAct2{sampleIndex});
    UrealInRange(sampleIndex) = localUrealInRange( ...
        current, m4.selectedMechanicalRanges, config.rangeTolerance);
    BlockSetValid(sampleIndex) = isequal( ...
        sort(string(fieldnames(current))), expectedBlocks);
    dynamicBoundsValid = DeltaAct1Stable(sampleIndex) && ...
        DeltaAct2Stable(sampleIndex) && ...
        DeltaAct1Finite(sampleIndex) && DeltaAct2Finite(sampleIndex) && ...
        DeltaAct1HinfNorm(sampleIndex) <= ...
            1 + config.uncertaintyBoundTolerance && ...
        DeltaAct2HinfNorm(sampleIndex) <= ...
            1 + config.uncertaintyBoundTolerance;
    Valid(sampleIndex) = UrealInRange(sampleIndex) && ...
        BlockSetValid(sampleIndex) && dynamicBoundsValid;
    replayScalarError(sampleIndex) = max(abs([ ...
        current.Jm1 - replay.Jm1, current.k1 - replay.k1, ...
        current.k2 - replay.k2]));
    replayDynamicError(sampleIndex) = max( ...
        localFrequencyError(current.Delta_act1, replay.Delta_act1, ...
            config.deltaFrequencyGrid), ...
        localFrequencyError(current.Delta_act2, replay.Delta_act2, ...
            config.deltaFrequencyGrid));
end

sampleMetadataTable = table(SampleID, Jm1Actual, k1Actual, k2Actual, ...
    Jm1DeviationPercent, k1DeviationPercent, k2DeviationPercent, ...
    DeltaAct1, DeltaAct2, DeltaAct1HinfNorm, DeltaAct2HinfNorm, ...
    DeltaAct1PeakFrequency, DeltaAct2PeakFrequency, DeltaAct1Order, ...
    DeltaAct2Order, DeltaAct1Stable, DeltaAct2Stable, ...
    DeltaAct1Finite, DeltaAct2Finite, UrealInRange, BlockSetValid, Valid);

replayAudit = struct( ...
    'seedReset', true, ...
    'maximumScalarError', max(replayScalarError), ...
    'maximumDynamicFrequencyError', max(replayDynamicError), ...
    'tolerance', config.replayTolerance);
replayAudit.passed = replayAudit.maximumScalarError <= ...
    replayAudit.tolerance && ...
    replayAudit.maximumDynamicFrequencyError <= replayAudit.tolerance;

campaign = struct( ...
    'seed', config.seed, ...
    'rngAlgorithm', config.rngAlgorithm, ...
    'numberSamples', numberSamples, ...
    'sampledValues', sampledValues, ...
    'sampleMetadataTable', sampleMetadataTable, ...
    'replayAudit', replayAudit, ...
    'generationAudit', struct( ...
        'effectiveCampaignCalls', 1, ...
        'auditReplayCalls', 1, ...
        'sameSequenceForAllControllers', true, ...
        'simulationUsesReplay', false), ...
    'allSamplesValid', all(Valid), ...
    'numberValidSamples', sum(Valid));

assert(campaign.replayAudit.passed, 'M16:SampleReplayMismatch', ...
    'Resetting the M16 seed did not reproduce the uncertainty samples.');
assert(campaign.allSamplesValid, 'M16:InvalidSample', ...
    ['At least one usample result is outside the frozen M4 ensemble. ' ...
    'The campaign must stop without replacement sampling.']);
end

function nominal = localNominalValues(rangeTable)
nominal = struct;
for index = 1:height(rangeTable)
    nominal.(char(rangeTable.Parameter(index))) = ...
        rangeTable.NominalValue(index);
end
end

function valid = localUrealInRange(values, ranges, tolerance)
valid = true;
for index = 1:height(ranges)
    name = char(ranges.Parameter(index));
    nominal = ranges.NominalValue(index);
    fraction = ranges.Percentage(index) / 100;
    lower = nominal * (1 - fraction) - tolerance;
    upper = nominal * (1 + fraction) + tolerance;
    valid = valid && values.(name) >= lower && values.(name) <= upper;
end
end

function finite = localFiniteSystem(system)
[A, B, C, D] = ssdata(ss(system));
finite = all(isfinite([A(:); B(:); C(:); D(:)]));
end

function error = localFrequencyError(first, second, frequencies)
difference = freqresp(ss(first), frequencies) - ...
    freqresp(ss(second), frequencies);
error = max(abs(difference), [], 'all');
end
