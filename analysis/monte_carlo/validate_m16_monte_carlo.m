function metrics = validate_m16_monte_carlo(createFigures)
%VALIDATE_M16_MONTE_CARLO Run the frozen common-sample M4 campaign.

arguments
    createFigures (1, 1) logical = true
end

projectRoot = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
config = monte_carlo_specs_m16;
m4 = load(fullfile(projectRoot, config.m4Source));
m5 = load(fullfile(projectRoot, config.m5Source));
m6 = load(fullfile(projectRoot, config.controllerSources(1)));
m10 = load(fullfile(projectRoot, config.controllerSources(2)));
m13 = load(fullfile(projectRoot, config.controllerSources(3)));
m14 = load(fullfile(projectRoot, config.m14Source));
m15 = load(fullfile(projectRoot, config.m15Source));

m4SourceAudit = localM4SourceAudit(m4, config);
assert(m4SourceAudit.passed, 'M16:M4SourceChanged', ...
    'The frozen M4 uncertainty source failed its identity audit.');
assert(m5.spec.referenceAmplitude == deg2rad(config.trackingAmplitudeDeg) && ...
    m5.spec.disturbanceTorqueAmplitude == config.disturbanceAmplitudeNm && ...
    m5.spec.uScale == 12, 'M16:M5SourceChanged', ...
    'The M16 scenario or control scale does not match frozen M5.');

[controllers, controllerAudits] = ...
    load_m16_frozen_controllers(projectRoot, config);
campaign = generate_m16_uncertainty_samples(m4, config);

nominalPhysical = build_m16_sampled_physical_plant( ...
    m4, m5.Bd, [], config);
nominalReconstructionAudit = localNominalAudit( ...
    nominalPhysical, controllers, m4, m5, m6, m10, m13, config);
if ~nominalReconstructionAudit.passed
    for auditIndex = 1:numel(nominalReconstructionAudit.controllers)
        item = nominalReconstructionAudit.controllers(auditIndex);
        fprintf(2, ['M16 nominal gate %s: abs %.3e, rel %.3e, ' ...
            'pole %.3e, states %d/%d, pass=%d.\n'], ...
            item.controllerID, item.mapMaximumAbsoluteError, ...
            item.mapMaximumRelativeError, item.poleSetDistance, ...
            item.actualInternalStateCount, ...
            item.expectedInternalStateCount, item.passed);
    end
end
assert(nominalReconstructionAudit.passed, ...
    'M16:NominalReconstructionMismatch', ...
    'Sample 0 does not reproduce the frozen nominal closed-loop artifacts.');

nominalEvaluations = cell(numel(controllers), 1);
for controllerIndex = 1:numel(controllers)
    nominalClosedLoop = build_m16_sample_closed_loop( ...
        nominalPhysical, controllers(controllerIndex), config);
    nominalEvaluations{controllerIndex} = evaluate_m16_sample( ...
        nominalClosedLoop, 0, m5.spec, config);
end

numberRecords = config.numberSamples * numel(controllers);
Sample = zeros(numberRecords, 1);
Controller = strings(numberRecords, 1);
InternalStateCount = zeros(numberRecords, 1);
MaxRealPole = nan(numberRecords, 1);
NumberRhpPoles = nan(numberRecords, 1);
Stable = false(numberRecords, 1);
Classification = strings(numberRecords, 1);
PerformanceEligible = false(numberRecords, 1);
trackingTable = table;
disturbanceTable = table;
bandwidthTable = table;
physicalAuditRows = nan(config.numberSamples, 8);

record = 0;
for sampleIndex = 1:config.numberSamples
    physical = build_m16_sampled_physical_plant(m4, m5.Bd, ...
        campaign.sampledValues(sampleIndex), config);
    physicalAuditRows(sampleIndex, :) = [sampleIndex, ...
        physical.actuatorOrder, physical.mechanicalOrder, ...
        physical.physicalOrder, ...
        physical.audit.measurementPath.maximumAbsoluteError, ...
        physical.audit.measurementPath.maximumRelativeError, ...
        physical.audit.positionPath.maximumAbsoluteError, ...
        physical.audit.positionPath.maximumRelativeError];
    for controllerIndex = 1:numel(controllers)
        closedLoop = build_m16_sample_closed_loop( ...
            physical, controllers(controllerIndex), config);
        assert(closedLoop.classification ~= "NUMERICALLY_INVALID", ...
            'M16:NumericallyInvalidClosedLoop', ...
            'A sampled closed loop contains non-finite numerical data.');
        evaluation = evaluate_m16_sample( ...
            closedLoop, sampleIndex, m5.spec, config);
        record = record + 1;
        Sample(record) = sampleIndex;
        Controller(record) = controllers(controllerIndex).id;
        InternalStateCount(record) = closedLoop.internalStateCount;
        MaxRealPole(record) = closedLoop.maximumRealPole;
        NumberRhpPoles(record) = closedLoop.numberRhpPoles;
        Stable(record) = closedLoop.stable;
        Classification(record) = closedLoop.classification;
        PerformanceEligible(record) = evaluation.performanceEligible;
        bandwidthTable = [bandwidthTable; evaluation.bandwidth]; %#ok<AGROW>
        trackingTable = [trackingTable; evaluation.tracking]; %#ok<AGROW>
        disturbanceTable = [disturbanceTable; ...
            evaluation.disturbance]; %#ok<AGROW>
    end
end

stabilityTable = table(Sample, Controller, InternalStateCount, ...
    MaxRealPole, NumberRhpPoles, Stable, Classification, ...
    PerformanceEligible);
sampledPhysicalPlantAuditTable = array2table(physicalAuditRows, ...
    'VariableNames', {'Sample', 'ActuatorOrder', 'MechanicalOrder', ...
    'PhysicalOrder', 'MeasMaxAbsError', 'MeasMaxRelError', ...
    'QMaxAbsError', 'QMaxRelError'});
sampledPhysicalPlantAudit = struct( ...
    'table', sampledPhysicalPlantAuditTable, ...
    'maximumMeasurementAbsoluteError', ...
        max(sampledPhysicalPlantAuditTable.MeasMaxAbsError), ...
    'maximumMeasurementRelativeError', ...
        max(sampledPhysicalPlantAuditTable.MeasMaxRelError), ...
    'maximumPositionAbsoluteError', ...
        max(sampledPhysicalPlantAuditTable.QMaxAbsError), ...
    'maximumPositionRelativeError', ...
        max(sampledPhysicalPlantAuditTable.QMaxRelError), ...
    'usesSharedPhysicalState', true, ...
    'disturbanceEntersLinkMechanics', true, ...
    'passed', true);

KmuRows = stabilityTable.Controller == "Kmu";
KmuAllSamplesStable = all(stabilityTable.Stable(KmuRows));
m14Consistency = struct( ...
    'm14RobustStabilityOutcome', string(m14.qualityGate.robustStability), ...
    'marginLower', m14.robustStabilityMargin.LowerBound, ...
    'marginUpper', m14.robustStabilityMargin.UpperBound, ...
    'expectedStableSamples', config.numberSamples, ...
    'observedStableSamples', sum(stabilityTable.Stable(KmuRows)), ...
    'allValidM4SamplesStable', KmuAllSamplesStable, ...
    'interpretation', ...
        "MONTE_CARLO_COHERENT_WITH_M14_NOT_A_CERTIFICATE");
m14Consistency.passed = ...
    m14Consistency.m14RobustStabilityOutcome == "PASS_CERTIFIED" && ...
    KmuAllSamplesStable;
assert(m14Consistency.passed, 'M16:KmuM14Contradiction', ...
    ['A valid M4 sample is internally unstable with frozen Kmu, in ' ...
    'contradiction with M14. M16 is methodologically blocked.']);

summary = summarize_m16_monte_carlo(stabilityTable, bandwidthTable, ...
    trackingTable, disturbanceTable, m5.spec, config);
m15ComparisonMetadata = localM15Metadata(m15);

qualityGate = struct( ...
    'baselineGit', "PASS", ...
    'frozenUncertainty', "PASS", ...
    'frozenControllers', "PASS", ...
    'randomCampaign', "PASS", ...
    'sampleValidity', "PASS", ...
    'physicalSampledRealization', "PASS", ...
    'nominalReconstruction', "PASS", ...
    'KmuM14Consistency', "PASS", ...
    'monteCarloStability', "QUANTIFIED", ...
    'bandwidth', "QUANTIFIED_DIAGONAL_CLOSED_LOOP", ...
    'tracking', "QUANTIFIED_WITH_EMPIRICAL_PASS_RATES", ...
    'disturbance', "QUANTIFIED", ...
    'crossCoupling', "QUANTIFIED", ...
    'controlEffort', "QUANTIFIED_NO_SATURATION", ...
    'pairedComparison', "QUANTIFIED_NO_GLOBAL_SCORE", ...
    'softwareCorrectness', "PASS", ...
    'overallStatus', "COMPLETE");

metadata = struct( ...
    'milestone', "M16", ...
    'responsible', config.responsible, ...
    'baselineCommit', config.baselineCommit, ...
    'm4Source', config.m4Source, ...
    'm5Source', config.m5Source, ...
    'sampleGenerationAPI', ...
        "[~,sampledValues]=usample(GuncMeas,40); replay audit once", ...
    'singleCommonSimulationSequence', true, ...
    'sameSampleValuesUsedForAllControllers', true, ...
    'sampleZeroIncludedInStatistics', false, ...
    'linearUncertainMonteCarlo', true, ...
    'robustnessCertificateProduced', false, ...
    'probabilityClaimProduced', false, ...
    'synthesisPerformed', config.synthesisPerformed, ...
    'controllerTuningPerformed', config.controllerTuningPerformed, ...
    'controllerReductionPerformed', config.controllerReductionPerformed, ...
    'weightRetuningPerformed', config.weightRetuningPerformed, ...
    'saturationEnabled', config.saturationEnabled, ...
    'simulinkUsed', config.simulinkUsed, ...
    'nonlinearSimulationPerformed', ...
        config.nonlinearSimulationPerformed, ...
    'm15LoadedWithoutRerun', true, ...
    'm17Started', config.m17Started, ...
    'weightedNormDiagnostic', "NOT_IMPLEMENTED_OPTIONAL");

figurePaths = struct;
if createFigures
    figurePaths = plot_m16_results(summary, stabilityTable, ...
        trackingTable, disturbanceTable, m14Consistency, ...
        projectRoot, config);
end

seed = config.seed;
numberSamples = config.numberSamples;
sampledValuesRaw = campaign.sampledValues;
sampleMetadataTable = campaign.sampleMetadataTable;
sampledUncertaintyDiagnostics = campaign.sampleMetadataTable(:, ...
    {'SampleID', 'DeltaAct1HinfNorm', 'DeltaAct2HinfNorm', ...
    'DeltaAct1PeakFrequency', 'DeltaAct2PeakFrequency', ...
    'DeltaAct1Order', 'DeltaAct2Order', 'DeltaAct1Stable', ...
    'DeltaAct2Stable', 'DeltaAct1Finite', 'DeltaAct2Finite'});
sampleReplayAudit = campaign.replayAudit;
sampleGenerationAudit = campaign.generationAudit;
sampleLevelTable = summary.sampleLevelTable;
sampleControllerSummaryTable = summary.sampleControllerSummaryTable;
summaryStatistics = summary.statisticsTable;
empiricalPassRates = summary.empiricalPassRatesTable;
pairedComparisons = summary.pairedComparisonTable;
stabilitySummary = summary.stabilitySummaryTable;

save(fullfile(projectRoot, config.artifactPath), ...
    'config', 'seed', 'numberSamples', 'm4SourceAudit', ...
    'controllerAudits', 'sampledValuesRaw', 'sampleMetadataTable', ...
    'sampledUncertaintyDiagnostics', 'sampleReplayAudit', ...
    'sampleGenerationAudit', 'sampledPhysicalPlantAudit', ...
    'nominalReconstructionAudit', 'nominalEvaluations', ...
    'stabilityTable', 'bandwidthTable', 'trackingTable', ...
    'disturbanceTable', 'sampleLevelTable', ...
    'sampleControllerSummaryTable', 'summaryStatistics', ...
    'empiricalPassRates', 'pairedComparisons', 'stabilitySummary', ...
    'm14Consistency', 'm15ComparisonMetadata', 'qualityGate', ...
    'metadata', 'figurePaths', '-v7.3');

fprintf('\nM16 Monte Carlo lineare M4: seed %d, %d campioni comuni.\n', ...
    config.seed, config.numberSamples);
for index = 1:height(stabilitySummary)
    fprintf('%s: stable %d/%d, worst max Re %.6g s^-1.\n', ...
        stabilitySummary.Controller(index), ...
        stabilitySummary.NStable(index), ...
        stabilitySummary.NTotal(index), ...
        stabilitySummary.WorstMaxRealPole(index));
end
fprintf('Kmu/M14 consistency: %s; M14 RS=%s, margin [%.6g, %.6g].\n', ...
    qualityGate.KmuM14Consistency, ...
    m14Consistency.m14RobustStabilityOutcome, ...
    m14Consistency.marginLower, m14Consistency.marginUpper);
fprintf('M16 status: %s. Monte Carlo is empirical and not a certificate.\n', ...
    qualityGate.overallStatus);

metrics = struct( ...
    'config', config, ...
    'm4SourceAudit', m4SourceAudit, ...
    'controllerAudits', controllerAudits, ...
    'campaign', campaign, ...
    'sampledPhysicalPlantAudit', sampledPhysicalPlantAudit, ...
    'nominalReconstructionAudit', nominalReconstructionAudit, ...
    'stabilityTable', stabilityTable, ...
    'bandwidthTable', bandwidthTable, ...
    'trackingTable', trackingTable, ...
    'disturbanceTable', disturbanceTable, ...
    'summary', summary, ...
    'm14Consistency', m14Consistency, ...
    'm15ComparisonMetadata', m15ComparisonMetadata, ...
    'qualityGate', qualityGate, ...
    'metadata', metadata, ...
    'figurePaths', figurePaths);
end

function audit = localM4SourceAudit(m4, config)
blockNames = sort(string(fieldnames(m4.GuncMeas.Uncertainty)));
expectedNames = sort(config.expectedUncertaintyBlocks);
ranges = sortrows(m4.selectedMechanicalRanges(:, ...
    {'Parameter', 'NominalValue', 'Percentage'}), 'Parameter');
expectedRanges = sortrows(config.expectedMechanicalRanges, 'Parameter');
mechanicalRangesMatch = isequal(ranges.Parameter, ...
    expectedRanges.Parameter) && max(abs(ranges.NominalValue - ...
    expectedRanges.NominalValue)) <= config.rangeTolerance && ...
    max(abs(ranges.Percentage - expectedRanges.Percentage)) <= ...
    config.rangeTolerance;
deltaBounds = [m4.GuncMeas.Uncertainty.Delta_act1.Bound; ...
    m4.GuncMeas.Uncertainty.Delta_act2.Bound];
audit = struct( ...
    'sourceArtifact', config.m4Source, ...
    'blockNames', blockNames, ...
    'expectedBlockNames', expectedNames, ...
    'blockSetMatch', isequal(blockNames, expectedNames), ...
    'mechanicalRanges', ranges, ...
    'mechanicalRangesMatch', mechanicalRangesMatch, ...
    'deltaBounds', deltaBounds, ...
    'deltaBoundsMatch', max(abs(deltaBounds - 1)) <= ...
        config.uncertaintyBoundTolerance, ...
    'GuncMeasSize', size(m4.GuncMeas), ...
    'GuncQSize', size(m4.GuncQ), ...
    'GmechUncMeasSize', size(m4.GmechUncMeas), ...
    'GmechUncQSize', size(m4.GmechUncQ));
audit.passed = audit.blockSetMatch && audit.mechanicalRangesMatch && ...
    audit.deltaBoundsMatch && isequal(audit.GuncMeasSize, [4, 2]) && ...
    isequal(audit.GuncQSize, [2, 2]) && ...
    isequal(audit.GmechUncMeasSize, [4, 2]) && ...
    isequal(audit.GmechUncQSize, [2, 2]);
end

function audit = localNominalAudit(physical, controllers, m4, m5, ...
    m6, m10, m13, config)
actual = cell(3, 1);
for index = 1:3
    actual{index} = build_m16_sample_closed_loop( ...
        physical, controllers(index), config);
end

expectedM6 = m6.lqgClosedLoop([1:2, 5:6], 1:4);
expectedKhinf = localRobustExpected(m10.T10, m10.KS10, ...
    m10.S10, m5.disturbancePlant(1:2, 3:4));
expectedKmu = localRobustExpected(m13.nominalReconstruction.T, ...
    m13.nominalReconstruction.KS, m13.nominalReconstruction.S, ...
    m5.disturbancePlant(1:2, 3:4));
expectedSystems = {expectedM6, expectedKhinf, expectedKmu};
expectedPoles = {m6.combinedPoles, m10.closedLoopPoles10, ...
    m13.nominalReconstruction.internalPoles};

controllerAuditTemplate = struct('controllerID', "", ...
    'mapMaximumAbsoluteError', NaN, 'mapMaximumRelativeError', NaN, ...
    'poleSetDistance', NaN, 'actualInternalStateCount', 0, ...
    'expectedInternalStateCount', 0, 'passed', false);
controllerAudit = repmat(controllerAuditTemplate, 3, 1);
for index = 1:3
    frequency = localCompareFrequency(actual{index}.system, ...
        expectedSystems{index}, config.auditFrequencyGrid);
    poleSetDistance = localPoleSetDistance( ...
        actual{index}.internalPoles, expectedPoles{index});
    controllerAudit(index).controllerID = controllers(index).id;
    controllerAudit(index).mapMaximumAbsoluteError = ...
        frequency.maximumAbsoluteError;
    controllerAudit(index).mapMaximumRelativeError = ...
        frequency.maximumRelativeError;
    controllerAudit(index).poleSetDistance = poleSetDistance;
    controllerAudit(index).actualInternalStateCount = ...
        actual{index}.internalStateCount;
    controllerAudit(index).expectedInternalStateCount = ...
        numel(expectedPoles{index});
    controllerAudit(index).passed = frequency.maximumAbsoluteError <= ...
        config.frequencyAbsoluteTolerance && ...
        frequency.maximumRelativeError <= ...
        config.frequencyRelativeTolerance && ...
        poleSetDistance <= config.poleSetTolerance && ...
        actual{index}.internalStateCount == numel(expectedPoles{index});
end
nominalPlantMeas = localCompareFrequency(physical.controlToMeas, ...
    m4.GuncMeas.NominalValue, config.auditFrequencyGrid);
nominalPlantQ = localCompareFrequency(physical.controlToQ, ...
    m4.GuncQ.NominalValue, config.auditFrequencyGrid);
audit = struct( ...
    'sampleID', 0, ...
    'excludedFromMonteCarloStatistics', true, ...
    'usesM3NominalActuatorsForMinimalPhysicalOrder', true, ...
    'plantMeasurementAudit', nominalPlantMeas, ...
    'plantPositionAudit', nominalPlantQ, ...
    'controllers', controllerAudit, ...
    'passed', all([controllerAudit.passed]) && ...
        nominalPlantMeas.maximumAbsoluteError <= ...
            config.frequencyAbsoluteTolerance && ...
        nominalPlantQ.maximumAbsoluteError <= ...
            config.frequencyAbsoluteTolerance);
end

function expected = localRobustExpected(T, KS, S, Gd)
expected = [ss(T), ss(S) * ss(Gd); ss(KS), -ss(KS) * ss(Gd)];
end

function metadata = localM15Metadata(m15)
Controller = strings(2, 1);
WorstTrackingTs = nan(2, 1);
WorstTrackingOS = nan(2, 1);
WorstTrackingSteadyError = nan(2, 1);
WorstDisturbancePeakQ = nan(2, 1);
WorstDisturbancePeakU = nan(2, 1);
for index = 1:2
    Controller(index) = m15.trackingResults(index).controllerID;
    WorstTrackingTs(index) = ...
        max(m15.trackingResults(index).metrics.SettlingTime);
    WorstTrackingOS(index) = ...
        max(m15.trackingResults(index).metrics.OvershootPercent);
    WorstTrackingSteadyError(index) = max( ...
        m15.trackingResults(index).metrics.SteadyStateErrorRelative);
    WorstDisturbancePeakQ(index) = ...
        max(m15.disturbanceResults(index).metrics.PeakQRad);
    WorstDisturbancePeakU(index) = ...
        max(m15.disturbanceResults(index).metrics.PeakDeltaUNm);
end
metadata = struct( ...
    'sourceArtifact', "results/data/m15_nonlinear_robust_validation.mat", ...
    'm15ModelClass', "NOMINAL_NONLINEAR", ...
    'm16ModelClass', "UNCERTAIN_LINEAR_M4_MONTE_CARLO", ...
    'simulinkRerun', false, ...
    'semanticWarning', ...
        "M15 and M16 evidence must not be pooled or treated as equivalent", ...
    'nominalNonlinearSummary', table(Controller, WorstTrackingTs, ...
        WorstTrackingOS, WorstTrackingSteadyError, ...
        WorstDisturbancePeakQ, WorstDisturbancePeakU));
end

function comparison = localCompareFrequency(actual, reference, frequencies)
actualResponse = freqresp(localClearNames(actual), frequencies);
referenceResponse = freqresp(localClearNames(reference), frequencies);
difference = actualResponse - referenceResponse;
referenceNorm = zeros(numel(frequencies), 1);
differenceNorm = zeros(numel(frequencies), 1);
for index = 1:numel(frequencies)
    referenceNorm(index) = norm(referenceResponse(:, :, index), 'fro');
    differenceNorm(index) = norm(difference(:, :, index), 'fro');
end
referenceFloor = max(1, max(referenceNorm)) * eps;
comparison = struct( ...
    'maximumAbsoluteError', max(abs(difference), [], 'all'), ...
    'maximumRelativeError', max(differenceNorm ./ ...
        max(referenceNorm, referenceFloor)));
end

function system = localClearNames(system)
system = ss(system);
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function distance = localPoleSetDistance(first, second)
pairwiseDistance = abs(first(:) - second(:).');
distance = max([max(min(pairwiseDistance, [], 1)), ...
    max(min(pairwiseDistance, [], 2))]);
end
