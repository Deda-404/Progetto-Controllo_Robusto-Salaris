function screening = screen_parameter_sensitivity
%SCREEN_PARAMETER_SENSITIVITY Deterministic normalized M4 screening.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
m2 = load(fullfile(projectRoot, 'results', 'data', ...
    'm2_linearization_nominal.mat'));
m3 = load(fullfile(projectRoot, 'results', 'data', ...
    'm3_nominal_actuated_plant.mat'), 'GactuatorsMimo');

parameterNames = [ ...
    "m1"; "m2"; "l1"; "l2"; "Jm1"; "Jm2"; ...
    "Bm1"; "Bm2"; "k1"; "k2"];
physicalVariabilityScore = [0.45; 0.95; 0.15; 0.15; 0.40; ...
    0.40; 0.80; 0.80; 0.65; 0.65];
occurrenceRoleScore = [0.65; 1.00; 0.90; 0.85; 0.55; ...
    0.55; 0.45; 0.45; 0.80; 0.80];
interpretabilityScore = [0.90; 0.95; 0.60; 0.60; 0.90; ...
    0.90; 0.85; 0.85; 0.95; 0.95];
physicalRationale = [ ...
    "proximal link mass: moderate assembly variability"; ...
    "distal link/load mass: payload and tooling variability"; ...
    "proximal geometry: accurately manufactured and measured"; ...
    "distal geometry: accurately manufactured and measured"; ...
    "motor-1 inertia: moderate datasheet/drive-train variability"; ...
    "motor-2 inertia: moderate datasheet/drive-train variability"; ...
    "motor-1 viscous damping: condition-dependent but weakly known"; ...
    "motor-2 viscous damping: condition-dependent but weakly known"; ...
    "joint-1 stiffness: assembly and material variability"; ...
    "joint-2 stiffness: assembly and material variability"];
occurrenceRole = [ ...
    "inertia and gravity, mainly proximal dynamics"; ...
    "multiple inertia/coupling/gravity occurrences"; ...
    "multiple inertia, coupling and gravity occurrences"; ...
    "distal inertia, coupling and gravity occurrences"; ...
    "direct motor-1 acceleration scaling"; ...
    "direct motor-2 acceleration scaling"; ...
    "motor-1 velocity dissipation"; ...
    "motor-2 velocity dissipation"; ...
    "repeated elastic coupling in link/motor state blocks"; ...
    "repeated elastic coupling in link/motor state blocks"];

perturbationFraction = 0.01;
frequencies = logspace(-1, log10(300), 501);
[Cq, Dq, Cmeas, Dmeas] = sea_output_matrices;
[Anominal, Bnominal] = sea_linearize_static_equilibrium_analytic( ...
    m2.qbar, m2.p);
[GnominalMeas, GnominalQ] = build_m3_full_plant( ...
    Anominal, Bnominal, Cmeas, Dmeas, Cq, Dq, m3.GactuatorsMimo);
nominalResponse = freqresp(GnominalQ, frequencies);
nominalResponseNorm = localResponseNorm(nominalResponse);
nominalResponseFloor = 1e-8 * max(nominalResponseNorm);
nominalDominantSigma = localDominantSigma(nominalResponse);
[nominalUnstablePoles, nominalElasticFrequencies] = ...
    localMechanicalModes(pole(ss(Anominal, Bnominal, Cq, Dq)));

numberParameters = numel(parameterNames);
sensitivityFrf = zeros(numberParameters, 1);
sensitivityUnstablePoles = zeros(numberParameters, 1);
sensitivityElasticModes = zeros(numberParameters, 1);
sensitivityDominantSigma = zeros(numberParameters, 1);
peakFrequency = zeros(numberParameters, 1);
maximumEquilibriumResidual = zeros(numberParameters, 1);

for index = 1:numberParameters
    plusParameters = localPerturbParameter( ...
        m2.p, parameterNames(index), 1 + perturbationFraction);
    minusParameters = localPerturbParameter( ...
        m2.p, parameterNames(index), 1 - perturbationFraction);

    [~, ~, plusEquilibrium] = sea_static_equilibrium( ...
        m2.qbar, plusParameters);
    [~, ~, minusEquilibrium] = sea_static_equilibrium( ...
        m2.qbar, minusParameters);
    [Aplus, Bplus] = sea_linearize_static_equilibrium_analytic( ...
        m2.qbar, plusParameters);
    [Aminus, Bminus] = sea_linearize_static_equilibrium_analytic( ...
        m2.qbar, minusParameters);
    [~, GplusQ] = build_m3_full_plant(Aplus, Bplus, Cmeas, Dmeas, ...
        Cq, Dq, m3.GactuatorsMimo);
    [~, GminusQ] = build_m3_full_plant(Aminus, Bminus, Cmeas, Dmeas, ...
        Cq, Dq, m3.GactuatorsMimo);

    plusResponse = freqresp(GplusQ, frequencies);
    minusResponse = freqresp(GminusQ, frequencies);
    normalizedDerivative = (plusResponse - minusResponse) / ...
        (2 * perturbationFraction);
    derivativeNorm = localResponseNorm(normalizedDerivative);
    relativeFrfSensitivity = derivativeNorm ./ ...
        max(nominalResponseNorm, nominalResponseFloor);
    [sensitivityFrf(index), peakIndex] = max(relativeFrfSensitivity);
    peakFrequency(index) = frequencies(peakIndex);

    plusDominantSigma = localDominantSigma(plusResponse);
    minusDominantSigma = localDominantSigma(minusResponse);
    dominantSigmaDerivative = (plusDominantSigma - minusDominantSigma) / ...
        (2 * perturbationFraction);
    sensitivityDominantSigma(index) = max(abs(dominantSigmaDerivative) ./ ...
        max(nominalDominantSigma, 1e-8 * max(nominalDominantSigma)));

    [plusUnstablePoles, plusElasticFrequencies] = ...
        localMechanicalModes(pole(ss(Aplus, Bplus, Cq, Dq)));
    [minusUnstablePoles, minusElasticFrequencies] = ...
        localMechanicalModes(pole(ss(Aminus, Bminus, Cq, Dq)));
    unstableDerivative = (plusUnstablePoles - minusUnstablePoles) / ...
        (2 * perturbationFraction);
    elasticDerivative = (plusElasticFrequencies - ...
        minusElasticFrequencies) / (2 * perturbationFraction);
    sensitivityUnstablePoles(index) = max(abs(unstableDerivative) ./ ...
        abs(nominalUnstablePoles));
    sensitivityElasticModes(index) = max(abs(elasticDerivative) ./ ...
        nominalElasticFrequencies);
    maximumEquilibriumResidual(index) = max( ...
        plusEquilibrium.residualNorm, minusEquilibrium.residualNorm);
end

normalizedFrf = sensitivityFrf / max(sensitivityFrf);
normalizedUnstable = sensitivityUnstablePoles / ...
    max(sensitivityUnstablePoles);
normalizedElastic = sensitivityElasticModes / ...
    max(sensitivityElasticModes);
normalizedSigma = sensitivityDominantSigma / ...
    max(sensitivityDominantSigma);
dynamicScore = 0.30 * normalizedFrf + 0.25 * normalizedUnstable + ...
    0.25 * normalizedElastic + 0.20 * normalizedSigma;
overallPriority = 0.65 * dynamicScore + ...
    0.15 * physicalVariabilityScore + ...
    0.10 * occurrenceRoleScore + ...
    0.10 * interpretabilityScore;

parameterSensitivityTable = table(parameterNames, sensitivityFrf, ...
    sensitivityUnstablePoles, sensitivityElasticModes, ...
    sensitivityDominantSigma, peakFrequency, physicalVariabilityScore, ...
    occurrenceRoleScore, interpretabilityScore, dynamicScore, ...
    overallPriority, physicalRationale, occurrenceRole, ...
    maximumEquilibriumResidual, 'VariableNames', { ...
    'Parameter', 'SensitivityFRF', 'SensitivityUnstablePoles', ...
    'SensitivityElasticModes', 'SensitivityDominantSigma', ...
    'PeakFrequency', 'PhysicalVariabilityScore', 'OccurrenceRoleScore', ...
    'InterpretabilityScore', 'DynamicScore', 'OverallPriority', ...
    'PhysicalVariabilityRationale', 'OccurrenceDynamicRole', ...
    'MaximumEquilibriumResidual'});

rankingKeys = [-overallPriority, -dynamicScore, (1:numberParameters).'];
[~, rankingOrder] = sortrows(rankingKeys, 1:size(rankingKeys, 2));
overallRank = zeros(numberParameters, 1);
overallRank(rankingOrder) = (1:numberParameters).';
parameterSensitivityTable.OverallRank = overallRank;
parameterSensitivityTable = sortrows(parameterSensitivityTable, ...
    'OverallRank', 'ascend');
selectedMechanicalParameters = ...
    parameterSensitivityTable.Parameter(1:3);

screening.parameterSensitivityTable = parameterSensitivityTable;
screening.selectedMechanicalParameters = selectedMechanicalParameters;
screening.perturbationFraction = perturbationFraction;
screening.frequencies = frequencies;
screening.nominalMechanicalA = Anominal;
screening.nominalMechanicalB = Bnominal;
screening.GnominalMeas = GnominalMeas;
screening.GnominalQ = GnominalQ;
screening.nominalUnstablePoles = nominalUnstablePoles;
screening.nominalElasticFrequencies = nominalElasticFrequencies;
screening.priorityRule = [ ...
    "DynamicScore = 0.30 FRF + 0.25 unstable poles + " + ...
        "0.25 elastic modes + 0.20 dominant sigma, after max normalization"; ...
    "OverallPriority = 0.65 DynamicScore + 0.15 physical variability + " + ...
        "0.10 occurrence/dynamic role + 0.10 interpretability"; ...
    "Select the first three; ties use DynamicScore then fixed candidate order"];
end

function perturbed = localPerturbParameter(nominal, parameterName, factor)
perturbed = nominal;
switch parameterName
    case "m1"
        perturbed.m1 = nominal.m1 * factor;
    case "m2"
        perturbed.m2 = nominal.m2 * factor;
    case "l1"
        perturbed.l1 = nominal.l1 * factor;
    case "l2"
        perturbed.l2 = nominal.l2 * factor;
    case "Jm1"
        perturbed.Jm(1, 1) = nominal.Jm(1, 1) * factor;
    case "Jm2"
        perturbed.Jm(2, 2) = nominal.Jm(2, 2) * factor;
    case "Bm1"
        perturbed.Bm(1, 1) = nominal.Bm(1, 1) * factor;
    case "Bm2"
        perturbed.Bm(2, 2) = nominal.Bm(2, 2) * factor;
    case "k1"
        perturbed.Ks(1, 1) = nominal.Ks(1, 1) * factor;
    case "k2"
        perturbed.Ks(2, 2) = nominal.Ks(2, 2) * factor;
    otherwise
        error('M4Screening:UnknownParameter', ...
            'Unknown screening parameter %s.', parameterName);
end
end

function responseNorm = localResponseNorm(response)
responseNorm = zeros(1, size(response, 3));
for index = 1:size(response, 3)
    responseNorm(index) = norm(response(:, :, index), 'fro');
end
end

function dominantSigma = localDominantSigma(response)
dominantSigma = zeros(1, size(response, 3));
for index = 1:size(response, 3)
    singularValues = svd(response(:, :, index));
    dominantSigma(index) = singularValues(1);
end
end

function [unstablePoles, elasticFrequencies] = localMechanicalModes(poles)
unstablePoles = sort(real(poles(real(poles) > 1e-8)));
elasticFrequencies = sort(abs(poles(imag(poles) > 1e-8)));
assert(numel(unstablePoles) == 2 && numel(elasticFrequencies) == 2, ...
    'M4Screening:UnexpectedModes', ...
    'Expected two unstable poles and two positive-frequency elastic modes.');
end
