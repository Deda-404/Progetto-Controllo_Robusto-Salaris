function metrics = validate_m17_final_comparison(createFigures)
%VALIDATE_M17_FINAL_COMPARISON Build the evidence-based M17 decision.

arguments
    createFigures (1, 1) logical = true
end

projectRoot = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
config = final_comparison_specs_m17;
evidence = load_m17_frozen_evidence(projectRoot, config);
s = evidence.sources;

assert(s.m16.seed == 20260826 && s.m16.numberSamples == 40, ...
    'M17:M16CampaignMismatch', ...
    'The frozen M16 seed or sample count does not match the approved campaign.');
m6Unstable = s.m16.stabilityTable.Controller == "M6" & ...
    ~s.m16.stabilityTable.Stable;
assert(any(m6Unstable) && ...
    all(~s.m16.stabilityTable.PerformanceEligible(m6Unstable)), ...
    'M17:M16UnstableCasesMismatch', ...
    'The current M16 M6 unstable cases were not preserved.');
assert(s.m16.m14Consistency.passed, 'M17:M14M16Contradiction', ...
    'M16 is not coherent with the frozen M14 Kmu result.');

comparison = build_m17_master_comparison(evidence, config);
decision = evaluate_m17_controller_roles(comparison, config);
comparison.masterComparison = decision.masterComparison;

evidenceSeparationAudit = table(config.evidenceClasses, ...
    ["M6/M10/M13"; "M8/M15"; "M16"; "M12/M14"], ...
    ["LTI synthesis artifacts"; "nominal nonlinear simulations"; ...
        "common sampled M4 plants"; "mu/robstab/robgain analysis"], ...
    true(4, 1), ...
    'VariableNames', {'EvidenceClass', 'MilestoneSources', ...
        'Meaning', 'KeptSeparate'});

figurePaths = struct;
if createFigures
    figurePaths = plot_m17_final_comparison(comparison, decision, ...
        s.m5.spec, projectRoot, config);
end

sourceArtifactPaths = config.sources;
sourceCommitBaseline = config.baselineCommit;
controllerIdentityAudit = evidence.controllerIdentityAudit;
evidenceMatrix = comparison.evidenceMatrix;
stabilityComparison = table( ...
    comparison.nominalLinearComparison.Controller, ...
    comparison.nominalLinearComparison.NominalInternalStability, ...
    comparison.monteCarloComparison.NStable, ...
    comparison.monteCarloComparison.NTotal, ...
    comparison.formalRobustnessComparison.FormalRS, ...
    comparison.formalRobustnessComparison.RSMarginLower, ...
    comparison.formalRobustnessComparison.RSMarginUpper, ...
    'VariableNames', {'Controller', 'NominalInternalStability', ...
        'MonteCarloStable', 'MonteCarloTotal', 'FormalRS', ...
        'RSMarginLower', 'RSMarginUpper'});
performanceComparison = comparison.performanceComparison;
nominalLinearComparison = comparison.nominalLinearComparison;
nonlinearComparison = comparison.nonlinearComparison;
monteCarloComparison = comparison.monteCarloComparison;
robustnessComparison = comparison.formalRobustnessComparison;
historicalA5Comparison = comparison.historicalA5;
rasComparison = comparison.rasComparison;
controlEffortComparison = comparison.controlEffortComparison;
complexityComparison = comparison.complexityComparison;
masterComparison = comparison.masterComparison;
finalRoleAssignment = decision.finalRoleAssignment;
decisionRuleAudit = decision.decisionRuleAudit;
strengths = comparison.strengthWeaknessComparison(:, ...
    {'Controller', 'Strength'});
weaknesses = comparison.strengthWeaknessComparison(:, ...
    {'Controller', 'Weakness'});
limitations = [ ...
    "No primary controller satisfies all M5 performance columns"; ...
    "Kmu has formal RS but fails NP and RP in M14"; ...
    "M6 and Khinf have no formal RS certificate on M4"; ...
    "M16 is empirical linear evidence, not a robustness certificate"; ...
    "M8/M15 RAS estimates are empirical; search-box limits are not dynamic boundaries"; ...
    "uScale=12 N m is normalization only; no saturation claim is made"; ...
    "No controller reduction, retuning, new synthesis, or M18 work is authorized"];

qualityGate = struct( ...
    'baselineGit', "PASS", ...
    'frozenEvidence', localGate(evidence.allSourcesLoaded), ...
    'controllerIdentity', ...
        localGate(evidence.allControllerIdentitiesPassed), ...
    'evidenceSeparation', ...
        localGate(all(evidenceSeparationAudit.KeptSeparate)), ...
    'nominalComparison', localGate(height(nominalLinearComparison) == 3), ...
    'nonlinearComparison', localGate(height(nonlinearComparison) == 3), ...
    'monteCarloComparison', ...
        localGate(height(monteCarloComparison) == 3), ...
    'formalRobustnessComparison', ...
        localGate(height(robustnessComparison) == 3), ...
    'rasComparison', localGate(height(rasComparison) == 3), ...
    'controlEffort', localGate(height(controlEffortComparison) == 3), ...
    'complexity', localGate(height(complexityComparison) == 3), ...
    'decisionMethodology', localGate(~config.globalScoreUsed), ...
    'finalRoleSelection', localGate(decision.allRulesPassed), ...
    'softwareCorrectness', "PASS", ...
    'overallStatus', "COMPLETE");

metadata = struct( ...
    'milestone', config.milestone, ...
    'responsible', config.responsible, ...
    'baselineCommit', config.baselineCommit, ...
    'mergedPullRequest', config.mergedPullRequest, ...
    'mergedPullRequestState', config.mergedPullRequestState, ...
    'artifactOnlyAnalysis', true, ...
    'synthesisPerformed', config.synthesisPerformed, ...
    'musynPerformed', config.musynPerformed, ...
    'hinfsynPerformed', config.hinfsynPerformed, ...
    'mixsynPerformed', config.mixsynPerformed, ...
    'hinfstructPerformed', config.hinfstructPerformed, ...
    'controllerTuningPerformed', config.controllerTuningPerformed, ...
    'controllerReductionPerformed', config.controllerReductionPerformed, ...
    'weightRetuningPerformed', config.weightRetuningPerformed, ...
    'uncertaintyRetuningPerformed', ...
        config.uncertaintyRetuningPerformed, ...
    'monteCarloPerformed', config.monteCarloPerformed, ...
    'usampleSequenceGenerated', config.usampleSequenceGenerated, ...
    'simulinkUsed', config.simulinkUsed, ...
    'dynamicSimulationPerformed', config.dynamicSimulationPerformed, ...
    'prefilterUsed', config.prefilterUsed, ...
    'twoDegreeOfFreedomCreated', config.twoDegreeOfFreedomCreated, ...
    'globalScoreUsed', config.globalScoreUsed, ...
    'm18Started', config.m18Started, ...
    'monteCarloInterpretation', config.monteCarloInterpretation, ...
    'rasInterpretation', config.rasInterpretation, ...
    'uScaleInterpretation', config.uScaleInterpretation, ...
    'noAbsoluteWinnerClaimed', decision.noAbsoluteWinnerClaimed, ...
    'noControllerMeetsAllM5', decision.noControllerMeetsAllM5);

save(fullfile(projectRoot, config.artifactPath), ...
    'metadata', 'sourceArtifactPaths', 'sourceCommitBaseline', ...
    'controllerIdentityAudit', 'evidenceMatrix', ...
    'evidenceSeparationAudit', 'stabilityComparison', ...
    'performanceComparison', 'nominalLinearComparison', ...
    'nonlinearComparison', 'monteCarloComparison', ...
    'robustnessComparison', 'historicalA5Comparison', ...
    'rasComparison', 'controlEffortComparison', ...
    'complexityComparison', 'masterComparison', ...
    'finalRoleAssignment', 'decisionRuleAudit', 'strengths', ...
    'weaknesses', 'limitations', 'qualityGate', 'figurePaths', '-v7.3');

fprintf('\nM17 final comparison based on validated results (%s).\n', ...
    config.baselineCommit);
for index = 1:height(finalRoleAssignment)
    fprintf('%s: %s.\n', finalRoleAssignment.Role(index), ...
        finalRoleAssignment.Controller(index));
end
fprintf(['Kmu M14 RS=%s [%.6g, %.6g], RP=%s. ' ...
    'M16 remains empirical.\n'], ...
    robustnessComparison.FormalRS(3), ...
    robustnessComparison.RSMarginLower(3), ...
    robustnessComparison.RSMarginUpper(3), ...
    robustnessComparison.FormalRP(3));
fprintf('M17 status: %s; no global score and no M18 work.\n', ...
    qualityGate.overallStatus);

metrics = struct( ...
    'config', config, ...
    'controllerIdentityAudit', controllerIdentityAudit, ...
    'comparison', comparison, ...
    'decision', decision, ...
    'qualityGate', qualityGate, ...
    'figurePaths', figurePaths, ...
    'artifactPath', fullfile(projectRoot, config.artifactPath));
end

function status = localGate(passed)
status = "FAIL";
if passed
    status = "PASS";
end
end
