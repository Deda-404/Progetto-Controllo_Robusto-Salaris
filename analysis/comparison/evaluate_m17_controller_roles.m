function decision = evaluate_m17_controller_roles(comparison, config)
%EVALUATE_M17_CONTROLLER_ROLES Apply the documented hierarchical rules.

arguments
    comparison (1, 1) struct
    config (1, 1) struct = final_comparison_specs_m17
end

robust = comparison.formalRobustnessComparison;
mc = comparison.monteCarloComparison;
performance = comparison.performanceComparison;
nonlinear = comparison.nonlinearComparison;
complexity = comparison.complexityComparison;

robustEligible = robust.FormalRS == "PASS_CERTIFIED" & ...
    mc.NStable == mc.NTotal;
assert(sum(robustEligible) == 1, 'M17:RobustRoleNotUnique', ...
    ['The validated results do not yield one unique formal-RS controller ' ...
    'without a Monte Carlo contradiction.']);
robustController = robust.Controller(robustEligible);

nominalEligible = performance.Tracking == "PASS" & ...
    performance.Overshoot == "PASS" & performance.Error == "PASS" & ...
    performance.CrossCoupling == "PASS";
assert(any(nominalEligible), 'M17:NoNominalReference', ...
    'No controller satisfies the documented nominal-performance rule.');
eligibleRows = find(nominalEligible);
[~, localBest] = min(nonlinear.WorstTrackingTs(eligibleRows));
nominalController = performance.Controller(eligibleRows(localBest));

hinfEligible = contains(complexity.Type, "H-infinity", ...
    'IgnoreCase', true);
assert(sum(hinfEligible) == 1, 'M17:HinfReferenceNotUnique', ...
    'The H-infinity architecture does not identify one unique comparator.');
hinfController = complexity.Controller(hinfEligible);

Role = ["FINAL ROBUST CONTROLLER"; ...
    "NOMINAL PERFORMANCE REFERENCE"; ...
    "H-INFINITY REFERENCE / COMPARATOR"];
Controller = [robustController; nominalController; hinfController];
Rationale = [ ...
    "Unique M14 formal RS PASS_CERTIFIED with no M16 contradiction; tracking and RP failures remain explicit"; ...
    "Passes the M5 nominal nonlinear tracking criteria and is selected by the documented tracking hierarchy"; ...
    "Unique frozen H-infinity full-order architecture retained as methodological comparator"];
finalRoleAssignment = table(Role, Controller, Rationale);

Criterion = [ ...
    "Formal RS required for robust role"; ...
    "Monte Carlo must not contradict robust role"; ...
    "All nominal tracking criteria required for performance role"; ...
    "H-infinity role follows controller architecture"; ...
    "Global numerical score forbidden"];
Passed = [ ...
    robust.FormalRS(robustEligible) == "PASS_CERTIFIED"; ...
    mc.NStable(robustEligible) == mc.NTotal(robustEligible); ...
    all(nominalEligible(eligibleRows(localBest))); ...
    sum(hinfEligible) == 1; ...
    ~config.globalScoreUsed];
decisionRuleAudit = table(Criterion, Passed);

masterComparison = comparison.masterComparison;
for index = 1:height(finalRoleAssignment)
    row = masterComparison.Controller == finalRoleAssignment.Controller(index);
    masterComparison.FinalRole(row) = finalRoleAssignment.Role(index);
end

decision = struct( ...
    'method', "HIERARCHICAL_ROLE_BASED_NO_GLOBAL_SCORE", ...
    'finalRoleAssignment', finalRoleAssignment, ...
    'decisionRuleAudit', decisionRuleAudit, ...
    'masterComparison', masterComparison, ...
    'allRulesPassed', all(Passed), ...
    'noAbsoluteWinnerClaimed', true, ...
    'noControllerMeetsAllM5', ...
        ~any(all(performance{:, 2:6} == "PASS", 2)));
end
