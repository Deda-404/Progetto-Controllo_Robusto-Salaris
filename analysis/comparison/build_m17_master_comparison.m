function comparison = build_m17_master_comparison(evidence, config)
%BUILD_M17_MASTER_COMPARISON Traceable comparison of frozen evidence.

arguments
    evidence (1, 1) struct
    config (1, 1) struct = final_comparison_specs_m17
end

s = evidence.sources;
ids = config.controllerIDs;
m5 = s.m5.spec;

m6LinearTracking = s.m6.trackingMetrics.lqg;
m10LinearTracking = s.m10.trackingMetrics;
m6NonlinearTracking = [s.m8.tracking2deg.metrics; ...
    s.m8.tracking5deg.metrics; s.m8.tracking8deg.metrics];
m6NonlinearDisturbance = s.m8.disturbanceMetrics;
m15KhinfTracking = s.m15.trackingResults( ...
    string({s.m15.trackingResults.controllerID}) == "Khinf").metrics;
m15KmuTracking = s.m15.trackingResults( ...
    string({s.m15.trackingResults.controllerID}) == "Kmu").metrics;
m15KhinfDisturbance = s.m15.disturbanceResults( ...
    string({s.m15.disturbanceResults.controllerID}) == "Khinf").metrics;
m15KmuDisturbance = s.m15.disturbanceResults( ...
    string({s.m15.disturbanceResults.controllerID}) == "Kmu").metrics;

nominalLinearComparison = table(ids, ...
    [config.sources.m6; config.sources.m10; config.sources.m13], ...
    [max(real(s.m6.combinedPoles)); ...
        s.m10.stabilityDiagnostics.maximumClosedLoopRealPart; ...
        s.m13.nominalReconstruction.metrics.maximumRealPart], ...
    ["PASS"; string(s.m10.qualityGate.nominalStability); ...
        string(s.m13.nominalReconstruction.NSOutcome)], ...
    [max(m6LinearTracking.SettlingTime); ...
        max(m10LinearTracking.SettlingTime); NaN], ...
    [max(m6LinearTracking.Overshoot); ...
        max(m10LinearTracking.OvershootPercent); NaN], ...
    [max(m6LinearTracking.SteadyStateErrorRelative); ...
        max(m10LinearTracking.SteadyStateErrorRelative); NaN], ...
    [max(m6LinearTracking.CrossCouplingPeakRatio); ...
        max(m10LinearTracking.CrossCouplingPeakRatio); NaN], ...
    [NaN; s.m10.normMetrics.weightedNorm; ...
        s.m13.nominalReconstruction.metrics.weightedNorm], ...
    ["N/A"; string(s.m10.qualityGate.weightedNominalPerformance); ...
        "FAIL"], ...
    'VariableNames', {'Controller', 'Source', 'MaximumRealPole', ...
        'NominalInternalStability', 'WorstTrackingTs', ...
        'WorstTrackingOvershootPercent', ...
        'WorstTrackingSteadyErrorRelative', ...
        'WorstTrackingCrossCouplingRatio', 'WeightedNorm', ...
        'WeightedPerformance'});

worstTrackingTs = [max(m6NonlinearTracking.SettlingTime); ...
    max(m15KhinfTracking.SettlingTime); ...
    max(m15KmuTracking.SettlingTime)];
worstTrackingOvershoot = [max(m6NonlinearTracking.OvershootPercent); ...
    max(m15KhinfTracking.OvershootPercent); ...
    max(m15KmuTracking.OvershootPercent)];
worstTrackingError = [max(m6NonlinearTracking.SteadyStateErrorRelative); ...
    max(m15KhinfTracking.SteadyStateErrorRelative); ...
    max(m15KmuTracking.SteadyStateErrorRelative)];
worstTrackingCross = [max(m6NonlinearTracking.CrossCouplingPeakRatio); ...
    max(m15KhinfTracking.CrossCouplingPeakRatio); ...
    max(m15KmuTracking.CrossCouplingPeakRatio)];
worstTrackingPeakU = [max(m6NonlinearTracking.PeakControlNm); ...
    max(m15KhinfTracking.PeakAbsoluteUNm); ...
    max(m15KmuTracking.PeakAbsoluteUNm)];
worstDisturbancePeakQ = [max(m6NonlinearDisturbance.PeakQRad); ...
    max(m15KhinfDisturbance.PeakQRad); ...
    max(m15KmuDisturbance.PeakQRad)];
worstDisturbanceOffset = [max(abs(m6NonlinearDisturbance.SteadyStateOffsetRad)); ...
    max(abs(m15KhinfDisturbance.SteadyStateOffsetRad)); ...
    max(abs(m15KmuDisturbance.SteadyStateOffsetRad))];
worstDisturbanceCross = [max(m6NonlinearDisturbance.CrossCouplingPeakRatio); ...
    max(m15KhinfDisturbance.CrossCouplingPeakRatio); ...
    max(m15KmuDisturbance.CrossCouplingPeakRatio)];
worstDisturbancePeakU = [max(m6NonlinearDisturbance.PeakControlNm); ...
    max(m15KhinfDisturbance.PeakAbsoluteUNm); ...
    max(m15KmuDisturbance.PeakAbsoluteUNm)];
trackingStatus = ["PASS"; string(s.m15.qualityGate.trackingKhinf); ...
    string(s.m15.qualityGate.trackingKmu)];
crossStatus = ["PASS"; string(s.m15.qualityGate.crossCouplingKhinf); ...
    string(s.m15.qualityGate.crossCouplingKmu)];
nonlinearComparison = table(ids, ...
    [config.sources.m8; config.sources.m15; config.sources.m15], ...
    trackingStatus, worstTrackingTs, worstTrackingOvershoot, ...
    worstTrackingError, worstTrackingCross, crossStatus, ...
    worstTrackingPeakU, worstDisturbancePeakQ, ...
    worstDisturbanceOffset, worstDisturbanceCross, ...
    worstDisturbancePeakU, ...
    'VariableNames', {'Controller', 'Source', 'TrackingStatus', ...
        'WorstTrackingTs', 'WorstTrackingOvershootPercent', ...
        'WorstTrackingSteadyErrorRelative', ...
        'WorstTrackingCrossCouplingRatio', 'CrossCouplingStatus', ...
        'WorstTrackingPeakUNm', 'WorstDisturbancePeakQRad', ...
        'WorstDisturbanceOffsetRad', ...
        'WorstDisturbanceCrossCouplingRatio', ...
        'WorstDisturbancePeakUNm'});

stabilityRows = localRowsByController(s.m16.stabilitySummary, ids);
passRateRows = localRowsByController(s.m16.empiricalPassRates, ids);
unstableSamples = strings(3, 1);
for index = 1:3
    rows = s.m16.stabilityTable.Controller == ids(index) & ...
        ~s.m16.stabilityTable.Stable;
    unstableSamples(index) = strjoin(string( ...
        s.m16.stabilityTable.Sample(rows).'), ",");
    if unstableSamples(index) == ""
        unstableSamples(index) = "NONE";
    end
end
monteCarloComparison = table(ids, ...
    repmat(string(config.sources.m16), 3, 1), ...
    stabilityRows.NTotal, stabilityRows.NStable, ...
    stabilityRows.EmpiricalStabilityRate, unstableSamples, ...
    passRateRows.AllCorePassFractionTotal, ...
    passRateRows.AllCorePassFractionStable, ...
    localM16Medians(s.m16.summaryStatistics, ids, ...
        "WorstTrackingTs"), ...
    localM16Medians(s.m16.summaryStatistics, ids, ...
        "WorstTrackingSteadyError"), ...
    localM16Medians(s.m16.summaryStatistics, ids, ...
        "WorstTrackingCrossCoupling"), ...
    localM16Medians(s.m16.summaryStatistics, ids, ...
        "WorstTrackingPeakU"), ...
    localM16Medians(s.m16.summaryStatistics, ids, ...
        "WorstDisturbancePeakQ"), ...
    localM16Medians(s.m16.summaryStatistics, ids, ...
        "WorstDisturbanceAbsOffset"), ...
    localM16Medians(s.m16.summaryStatistics, ids, ...
        "WorstDisturbancePeakU"), ...
    repmat(string(config.monteCarloInterpretation), 3, 1), ...
    'VariableNames', {'Controller', 'Source', 'NTotal', 'NStable', ...
        'EmpiricalStabilityRate', 'UnstableSamples', ...
        'CoreTrackingPassRateTotal', 'CoreTrackingPassRateStable', ...
        'MedianWorstTrackingTs', 'MedianWorstTrackingErrorRelative', ...
        'MedianWorstTrackingCrossCouplingRatio', ...
        'MedianWorstTrackingPeakUNm', ...
        'MedianWorstDisturbancePeakQRad', ...
        'MedianWorstDisturbanceOffsetRad', ...
        'MedianWorstDisturbancePeakUNm', 'Interpretation'});

formalRobustnessComparison = table(ids, ...
    ["N/A"; "N/A"; string(s.m14.qualityGate.robustStability)], ...
    [NaN; NaN; s.m14.robustStabilityMargin.LowerBound], ...
    [NaN; NaN; s.m14.robustStabilityMargin.UpperBound], ...
    ["N/A"; "N/A"; string(s.m14.qualityGate.nominalPerformance)], ...
    ["N/A"; "N/A"; string(s.m14.qualityGate.robustPerformance)], ...
    ["No formal RS analysis for M6"; ...
        "M12 certifies A5, not Khinf M10"; ...
        "M14 Kmu certificate; RP remains failed"], ...
    'VariableNames', {'Controller', 'FormalRS', 'RSMarginLower', ...
        'RSMarginUpper', 'NominalWeightedPerformance', 'FormalRP', ...
        'Note'});
historicalA5 = table("A5 M11/M12", ...
    string(s.m12.qualityGate.robustStability), ...
    s.m12.robustStabilityMargin.LowerBound, ...
    s.m12.robustStabilityMargin.UpperBound, ...
    string(s.m12.qualityGate.robustPerformance), false, ...
    'VariableNames', {'Controller', 'FormalRS', 'RSMarginLower', ...
        'RSMarginUpper', 'FormalRP', 'IsM17PrimaryCandidate'});

m15KhinfRas = s.m15.rasResults( ...
    string({s.m15.rasResults.controllerID}) == "Khinf").metrics;
m15KmuRas = s.m15.rasResults( ...
    string({s.m15.rasResults.controllerID}) == "Kmu").metrics;
m15KhinfAgreement = s.m15.agreementResults( ...
    string({s.m15.agreementResults.controllerID}) == "Khinf").metrics;
m15KmuAgreement = s.m15.agreementResults( ...
    string({s.m15.agreementResults.controllerID}) == "Kmu").metrics;
rasComparison = table(ids, [config.sources.m8; config.sources.m15; ...
    config.sources.m15], ...
    [s.m8.rasMetrics.minimumRadiusDeg; m15KhinfRas.minimumRadiusDeg; ...
        m15KmuRas.minimumRadiusDeg], ...
    [s.m8.rasMetrics.maximumRadiusDeg; m15KhinfRas.maximumRadiusDeg; ...
        m15KmuRas.maximumRadiusDeg], ...
    [s.m8.rasMetrics.approximateAreaDeg2; ...
        m15KhinfRas.approximateAreaDeg2; ...
        m15KmuRas.approximateAreaDeg2], ...
    ["SEARCH-BOX LIMITED"; string(m15KhinfRas.classification); ...
        string(m15KmuRas.classification)], ...
    [true; false; true], false(3, 1), ...
    [NaN; m15KhinfAgreement.minimumRadiusDeg; ...
        m15KmuAgreement.minimumRadiusDeg], ...
    [NaN; m15KhinfAgreement.approximateAreaDeg2; ...
        m15KmuAgreement.approximateAreaDeg2], ...
    repmat(string(config.rasInterpretation), 3, 1), ...
    'VariableNames', {'Controller', 'Source', 'MinimumRadiusDeg', ...
        'MaximumRadiusDeg', 'ApproximateAreaDeg2', 'Classification', ...
        'SearchBoxLimited', 'AnalyticallyCertified', ...
        'AgreementMinimumRadiusDeg', 'AgreementAreaDeg2', ...
        'Interpretation'});

performanceComparison = table(ids, ...
    localPassFail(worstTrackingTs <= m5.settlingTimeTarget), ...
    localPassFail(worstTrackingOvershoot <= m5.overshootTarget), ...
    localPassFail(worstTrackingError <= m5.steadyStateTrackingTarget), ...
    localPassFail(worstTrackingCross <= m5.crossCouplingTarget), ...
    ["N/A"; string(s.m10.qualityGate.weightedNominalPerformance); ...
        string(s.m14.qualityGate.nominalPerformance)], ...
    ["M8 nominal nonlinear; weighted certificate N/A"; ...
        "M15 nominal nonlinear; M10 weighted objective"; ...
        "M15 nominal nonlinear; M14 NP/RP formal analysis"], ...
    'VariableNames', {'Controller', 'Tracking', 'Overshoot', 'Error', ...
        'CrossCoupling', 'WeightedPerformance', 'Note'});

controlEffortComparison = table(ids, ...
    [max(m6LinearTracking.PeakControl); ...
        s.m10.controlEffortMetrics.worstTrackingPeakNm; NaN], ...
    worstTrackingPeakU, monteCarloComparison.MedianWorstTrackingPeakUNm, ...
    worstDisturbancePeakU, ...
    monteCarloComparison.MedianWorstDisturbancePeakUNm, ...
    repmat(m5.uScale, 3, 1), repmat("NO SATURATION CLAIM", 3, 1), ...
    'VariableNames', {'Controller', 'NominalLinearTrackingPeakUNm', ...
        'NominalNonlinearTrackingPeakUNm', ...
        'MonteCarloMedianTrackingPeakUNm', ...
        'NominalNonlinearDisturbancePeakUNm', ...
        'MonteCarloMedianDisturbancePeakUNm', 'UScaleNm', ...
        'SaturationInterpretation'});

complexityComparison = table(ids, config.controllerArchitectures, ...
    evidence.controllerIdentityAudit.Order, config.controllerMeasurements, ...
    formalRobustnessComparison.FormalRS, ...
    ["Observer-based reference; no integral states"; ...
        "Full-order nominal H-infinity comparator"; ...
        "Highest order; no reduction authorized in M17"], ...
    'VariableNames', {'Controller', 'Type', 'Order', 'Measurements', ...
        'RobustCertificate', 'Note'});

strengths = [ ...
    "Best nominal nonlinear tracking; all M8 tracking targets pass"; ...
    "H-infinity full-order methodological baseline; 40/40 M16 stable"; ...
    "Only primary candidate with M14 RS PASS_CERTIFIED; 40/40 M16 stable"];
weaknesses = [ ...
    "M16 Sample 5 unstable; formal RS and RP are N/A"; ...
    "Nominal nonlinear tracking and weighted performance fail M5"; ...
    "Nominal tracking, NP and RP fail; order 52"];
strengthWeaknessComparison = table(ids, strengths, weaknesses, ...
    'VariableNames', {'Controller', 'Strength', 'Weakness'});

evidenceMatrix = table(ids, ...
    [config.sources.m6; config.sources.m10; config.sources.m13], ...
    [config.sources.m8; config.sources.m15; config.sources.m15], ...
    repmat(string(config.sources.m16), 3, 1), ...
    ["N/A"; "N/A"; string(config.sources.m14)], ...
    'VariableNames', {'Controller', 'NominalLinearSource', ...
        'NominalNonlinearSource', 'UncertainLinearMonteCarloSource', ...
        'FormalRobustnessSource'});

masterComparison = table(ids, config.controllerArchitectures, ...
    evidence.controllerIdentityAudit.Order, ...
    nominalLinearComparison.NominalInternalStability, trackingStatus, ...
    rasComparison.Classification, ...
    monteCarloComparison.NStable + "/" + monteCarloComparison.NTotal, ...
    monteCarloComparison.CoreTrackingPassRateTotal, ...
    formalRobustnessComparison.FormalRS, formalRobustnessComparison.FormalRP, ...
    performanceComparison.Tracking, repmat("QUANTIFIED", 3, 1), ...
    performanceComparison.CrossCoupling, ...
    repmat("QUANTIFIED_NO_SATURATION", 3, 1), strengths, weaknesses, ...
    repmat("PENDING_RULE_EVALUATION", 3, 1), ...
    'VariableNames', {'Controller', 'Architecture', 'Order', ...
        'NominalInternalStability', 'NominalNonlinearTrackingStatus', ...
        'NominalNonlinearRAS', 'MonteCarloStability', ...
        'MonteCarloTrackingPassRate', 'FormalRS', 'FormalRP', ...
        'Tracking', 'Disturbance', 'CrossCoupling', 'ControlEffort', ...
        'MainStrength', 'MainWeakness', 'FinalRole'});

comparison = struct( ...
    'evidenceMatrix', evidenceMatrix, ...
    'nominalLinearComparison', nominalLinearComparison, ...
    'nonlinearComparison', nonlinearComparison, ...
    'monteCarloComparison', monteCarloComparison, ...
    'formalRobustnessComparison', formalRobustnessComparison, ...
    'historicalA5', historicalA5, ...
    'rasComparison', rasComparison, ...
    'performanceComparison', performanceComparison, ...
    'controlEffortComparison', controlEffortComparison, ...
    'complexityComparison', complexityComparison, ...
    'strengthWeaknessComparison', strengthWeaknessComparison, ...
    'masterComparison', masterComparison);
end

function rows = localRowsByController(data, ids)
rows = data([],:);
for index = 1:numel(ids)
    rows = [rows; data(data.Controller == ids(index), :)]; %#ok<AGROW>
end
end

function values = localM16Medians(statistics, ids, metric)
values = nan(numel(ids), 1);
for index = 1:numel(ids)
    row = statistics.Controller == ids(index) & statistics.Metric == metric;
    values(index) = statistics.Median(row);
end
end

function status = localPassFail(passed)
status = repmat("FAIL", size(passed));
status(passed) = "PASS";
end
