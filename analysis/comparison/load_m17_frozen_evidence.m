function evidence = load_m17_frozen_evidence(projectRoot, config)
%LOAD_M17_FROZEN_EVIDENCE Load and audit the frozen M5-M16 artifacts.

arguments
    projectRoot (1, 1) string
    config (1, 1) struct = final_comparison_specs_m17
end

sourceNames = string(fieldnames(config.sources));
sourcePaths = strings(numel(sourceNames), 1);
sourceExists = false(numel(sourceNames), 1);
for index = 1:numel(sourceNames)
    sourcePaths(index) = string(config.sources.(sourceNames(index)));
    sourceExists(index) = isfile(fullfile(projectRoot, sourcePaths(index)));
end
sourceArtifactAudit = table(sourceNames, sourcePaths, sourceExists, ...
    'VariableNames', {'Artifact', 'Path', 'Loaded'});
assert(all(sourceExists), 'M17:MissingSourceArtifact', ...
    'At least one frozen source artifact required by M17 is missing.');

sources = struct;
for index = 1:numel(sourceNames)
    name = sourceNames(index);
    sources.(name) = load(fullfile(projectRoot, config.sources.(name)));
end

m15Khinf = sources.m15.controllerAudits( ...
    string({sources.m15.controllerAudits.id}) == "Khinf");
m15Kmu = sources.m15.controllerAudits( ...
    string({sources.m15.controllerAudits.id}) == "Kmu");
m16M6 = sources.m16.controllerAudits( ...
    string({sources.m16.controllerAudits.id}) == "M6");
m16Khinf = sources.m16.controllerAudits( ...
    string({sources.m16.controllerAudits.id}) == "Khinf");
m16Kmu = sources.m16.controllerAudits( ...
    string({sources.m16.controllerAudits.id}) == "Kmu");

[m6A, m6B, m6C, m6D] = ssdata(sources.m6.Klqg);
[hinfA, hinfB, hinfC, hinfD] = ssdata(sources.m10.Khinf);
[muA, muB, muC, muD] = ssdata(sources.m13.Kmu);

Controller = config.controllerIDs;
SourceArtifact = [config.sources.m6; config.sources.m10; config.sources.m13];
Order = [order(sources.m6.Klqg); order(sources.m10.Khinf); ...
    order(sources.m13.Kmu)];
InputCount = [size(sources.m6.Klqg, 2); size(sources.m10.Khinf, 2); ...
    size(sources.m13.Kmu, 2)];
OutputCount = [size(sources.m6.Klqg, 1); size(sources.m10.Khinf, 1); ...
    size(sources.m13.Kmu, 1)];
PrimaryIdentity = [ ...
    localMatricesEqual(m6A, m6B, m6C, m6D, m16M6); ...
    localMatricesEqual(hinfA, hinfB, hinfC, hinfD, m16Khinf); ...
    localMatricesEqual(muA, muB, muC, muD, m16Kmu)];
CrossMilestoneIdentity = [ ...
    isequal(sources.m6.K, sources.m8.controllerMetadata.K) && ...
        isequal(sources.m6.L, sources.m8.controllerMetadata.L) && ...
        isequal(sources.m6.Nr, sources.m8.controllerMetadata.Nr); ...
    localMatricesEqual(hinfA, hinfB, hinfC, hinfD, m15Khinf); ...
    localMatricesEqual(muA, muB, muC, muD, m15Kmu) && ...
        localSystemsEqual(sources.m13.Kmu, sources.m14.Kmu)];
OrderMatches = Order == config.expectedControllerOrders;
IdentityPassed = PrimaryIdentity & CrossMilestoneIdentity & OrderMatches;
controllerIdentityAudit = table(Controller, SourceArtifact, Order, ...
    InputCount, OutputCount, PrimaryIdentity, CrossMilestoneIdentity, ...
    OrderMatches, IdentityPassed);
assert(all(IdentityPassed), 'M17:ControllerIdentityMismatch', ...
    'A frozen controller identity or expected order changed.');

evidence = struct( ...
    'sources', sources, ...
    'sourceArtifactAudit', sourceArtifactAudit, ...
    'controllerIdentityAudit', controllerIdentityAudit, ...
    'allSourcesLoaded', all(sourceExists), ...
    'allControllerIdentitiesPassed', all(IdentityPassed));
end

function passed = localMatricesEqual(A, B, C, D, audit)
passed = isequal(A, audit.A) && isequal(B, audit.B) && ...
    isequal(C, audit.C) && isequal(D, audit.D);
end

function passed = localSystemsEqual(first, second)
[A1, B1, C1, D1] = ssdata(first);
[A2, B2, C2, D2] = ssdata(second);
passed = isequal(A1, A2) && isequal(B1, B2) && ...
    isequal(C1, C2) && isequal(D1, D2);
end
