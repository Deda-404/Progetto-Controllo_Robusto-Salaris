function metrics = validate_m15_nonlinear_robust(rebuild)
%VALIDATE_M15_NONLINEAR_ROBUST Execute the frozen-controller M15 campaign.

arguments
    rebuild (1, 1) logical = true
end

projectRoot = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));
addpath(genpath(fullfile(projectRoot, 'simulink')));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
datasetPath = fullfile(dataDirectory, ...
    'm15_nonlinear_robust_validation.mat');
if ~rebuild && isfile(datasetPath)
    saved = load(datasetPath);
    assert(saved.qualityGate.softwareCorrectness == "PASS", ...
        'M15:CachedQualityGate', 'Cached M15 software gate is not PASS.');
    metrics = localMetrics(saved, datasetPath);
    localPrint(metrics, true);
    return
end
if ~isfolder(dataDirectory), mkdir(dataDirectory); end
if ~isfolder(figureDirectory), mkdir(figureDirectory); end

config = m15_specs;
m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m6 = load(fullfile(dataDirectory, 'm6_lqg_no_integrator.mat'));
m8 = load(fullfile(dataDirectory, 'm8_lqg_nonlinear_ras.mat'));
controllers = load_m15_robust_controllers(projectRoot, config);
controllerAudits = controllers;
modelMetadata = build_m15_robust_simulink_model(projectRoot);
load_system(fullfile(projectRoot, config.modelRelativePath));
modelVariables = Simulink.findVars(char(config.modelName));
close_system(char(config.modelName), 0);

solverMetadata = struct('m15', config.solver, 'm8', m8.simulationConfig.solver, ...
    'identical', isequaln(config.solver, m8.simulationConfig.solver), ...
    'inputTimeStepM15', config.simulation.inputTimeStep, ...
    'inputTimeStepM8', m8.simulationConfig.simulation.inputTimeStep);
solverMetadata.inputTimeStepIdentical = ...
    solverMetadata.inputTimeStepM15 == solverMetadata.inputTimeStepM8;
plantAudit = struct( ...
    'm1FunctionReused', modelMetadata.nonlinearPlantSource == ...
        m8.modelMetadata.nonlinearPlantSource, ...
    'm8SFunctionReused', modelMetadata.nonlinearSFunction == ...
        "m8_nonlinear_sea_sfun", ...
    'm3ActuatorSourceReused', modelMetadata.actuatorSource == ...
        "results/data/m3_nominal_actuated_plant.mat", ...
    'xbarIdentity', isequaln(modelMetadata.xbar, m3.xbar), ...
    'taubarIdentity', isequaln(modelMetadata.taubar, m3.taubar), ...
    'actuatorEquilibriumIdentity', isequaln( ...
        modelMetadata.actuatorEquilibrium, m8.modelMetadata.actuatorEquilibrium), ...
    'physicalStateCountIdentity', ...
        modelMetadata.physicalPlantStateCount == ...
        m8.modelMetadata.physicalPlantStateCount, ...
    'm8ModelModified', false);
plantAudit.passed = plantAudit.m1FunctionReused && ...
    plantAudit.m8SFunctionReused && plantAudit.m3ActuatorSourceReused && ...
    plantAudit.xbarIdentity && plantAudit.taubarIdentity && ...
    plantAudit.actuatorEquilibriumIdentity && ...
    plantAudit.physicalStateCountIdentity && ~plantAudit.m8ModelModified;

checkpointPath = fullfile(dataDirectory, 'm15_campaign_checkpoint.mat');
campaignReused = false;
if isfile(checkpointPath)
    checkpoint = load(checkpointPath);
    requiredCheckpointFields = {'config', 'equilibriumResults', ...
        'controllerAudits', ...
        'trackingResults', 'trackingLtiNlMetrics', ...
        'disturbanceResults', 'disturbanceLtiNlMetrics', ...
        'noiseResults', 'noiseFourChannels', 'noiseIdentity', ...
        'rasResults', 'agreementResults', 'm6FrozenRasReference'};
    campaignReused = all(isfield(checkpoint, requiredCheckpointFields)) && ...
        isequaln(checkpoint.config, config) && ...
        isequaln(checkpoint.controllerAudits, controllerAudits);
    if campaignReused
        equilibriumResults = checkpoint.equilibriumResults;
        trackingResults = checkpoint.trackingResults;
        trackingLtiNlMetrics = checkpoint.trackingLtiNlMetrics;
        disturbanceResults = checkpoint.disturbanceResults;
        disturbanceLtiNlMetrics = checkpoint.disturbanceLtiNlMetrics;
        noiseResults = checkpoint.noiseResults;
        noiseFourChannels = checkpoint.noiseFourChannels;
        noiseIdentity = checkpoint.noiseIdentity;
        rasResults = checkpoint.rasResults;
        agreementResults = checkpoint.agreementResults;
        m6FrozenRasReference = checkpoint.m6FrozenRasReference;
        fprintf('[M15] Checkpoint numerico valido ricaricato.\n');
    end
end
if ~campaignReused
equilibriumCell = cell(2, 1);
for index = 1:2
    result = simulate_m15_nonlinear(controllers(index), struct, ...
        projectRoot, config);
    boundedSignals = [result.xMechanical, result.xActuator, ...
        result.xController, result.controlDelta, ...
        result.controlAbsolute, result.motorTorque];
    equilibriumCell{index} = struct( ...
        'controllerID', controllers(index).id, ...
        'horizon', result.time(end), ...
        'maxQDriftRad', max(abs(result.xMechanical(:, 1:2) - ...
            m3.xbar(1:2).'), [], 'all'), ...
        'maxThetaDriftRad', max(abs(result.xMechanical(:, 5:6) - ...
            m3.xbar(5:6).'), [], 'all'), ...
        'maxDeltaUNm', max(abs(result.controlDelta), [], 'all'), ...
        'maxControllerStateNorm', max(vecnorm( ...
            result.xController, 2, 2)), ...
        'finite', all(isfinite(boundedSignals), 'all'), ...
        'bounded', max(abs(boundedSignals), [], 'all') <= ...
            config.ras.numericMagnitudeLimit, 'passed', false);
    equilibriumCell{index}.passed = ...
        equilibriumCell{index}.finite && ...
        equilibriumCell{index}.bounded && ...
        equilibriumCell{index}.maxQDriftRad <= ...
            config.equilibrium.positionTolerance && ...
        equilibriumCell{index}.maxThetaDriftRad <= ...
            config.equilibrium.positionTolerance && ...
        equilibriumCell{index}.maxDeltaUNm <= ...
            config.equilibrium.controlTolerance;
end
equilibriumResults = vertcat(equilibriumCell{:});

trackingCell = cell(2, 1);
disturbanceCell = cell(2, 1);
for index = 1:2
    trackingCell{index} = evaluate_m15_tracking( ...
        controllers(index), projectRoot, config);
    disturbanceCell{index} = evaluate_m15_disturbance( ...
        controllers(index), projectRoot, config);
end
trackingResults = vertcat(trackingCell{:});
disturbanceResults = vertcat(disturbanceCell{:});
trackingLtiNlMetrics = [localLabel( ...
    trackingResults(1).ltiNonlinearMetrics, controllers(1).id); ...
    localLabel(trackingResults(2).ltiNonlinearMetrics, controllers(2).id)];
disturbanceLtiNlMetrics = [localLabel( ...
    disturbanceResults(1).ltiNonlinearMetrics, controllers(1).id); ...
    localLabel(disturbanceResults(2).ltiNonlinearMetrics, controllers(2).id)];

rng(config.noise.seed, 'twister');
noiseTime = (0:config.simulation.inputTimeStep: ...
    config.simulation.noiseHorizon).';
noiseFourChannels = m6.noiseMetrics.sigmaYRad * ...
    randn(numel(noiseTime), 4);
noiseCell = cell(2, 1);
for index = 1:2
    noiseCell{index} = evaluate_m15_noise(controllers(index), ...
        noiseFourChannels, projectRoot, config);
end
noiseResults = vertcat(noiseCell{:});
noiseIdentity = isequaln(noiseResults(1).noiseFourChannelIdentity, ...
    noiseResults(2).noiseFourChannelIdentity);

rasCell = cell(2, 1);
agreementCell = cell(2, 1);
for index = 1:2
    rasCell{index} = estimate_m15_robust_ras( ...
        controllers(index), projectRoot, config);
    agreementCell{index} = estimate_m15_lti_nl_agreement( ...
        controllers(index), projectRoot, config);
end
rasResults = vertcat(rasCell{:});
agreementResults = vertcat(agreementCell{:});
m6FrozenRasReference = struct( ...
    'sourceArtifact', "results/data/m8_lqg_nonlinear_ras.mat", ...
    'loadedWithoutRerun', true, 'rasBoundary', m8.rasBoundary, ...
    'rasMetrics', m8.rasMetrics, 'searchBoxLimited', ...
    m8.rasMetrics.allRadialEndpointsConvergent, ...
    'interpretation', "frozen search-box-limited empirical M8 result");
save(checkpointPath, 'config', 'controllerAudits', 'equilibriumResults', ...
    'trackingResults', 'trackingLtiNlMetrics', 'disturbanceResults', ...
    'disturbanceLtiNlMetrics', 'noiseResults', 'noiseFourChannels', ...
    'noiseIdentity', 'rasResults', 'agreementResults', ...
    'm6FrozenRasReference', '-v7.3');
end

controllerComparison = localComparison(controllers, equilibriumResults, ...
    trackingResults, disturbanceResults, noiseResults, rasResults, ...
    agreementResults);
m6Comparison = localM6Comparison(m8, trackingResults, ...
    disturbanceResults, rasResults);
figurePaths = plot_m15_results(trackingResults, disturbanceResults, ...
    rasResults, agreementResults, controllerComparison, ...
    m6FrozenRasReference, figureDirectory);

requiredSimulationsComplete = all(arrayfun(@(value) ...
    height(value.metrics) == 6, trackingResults)) && ...
    all(arrayfun(@(value) height(value.metrics) == 6, ...
    disturbanceResults)) && all([equilibriumResults.passed]) && ...
    all([noiseResults.repeatError] <= 1e-12);
qualityGate = struct( ...
    'frozenControllers', localPassFail(all([controllers.sourceIdentity]) && ...
        all([controllers.bestIterationIdentity]) && ...
        isequal([controllers.order].', config.expectedControllerOrders)), ...
    'frozenNonlinearPlant', localPassFail(plantAudit.passed), ...
    'solverConfigIdentityM8', localPassFail(solverMetadata.identical && ...
        solverMetadata.inputTimeStepIdentical), ...
    'equilibriumKhinf', localPassFail(equilibriumResults(1).passed), ...
    'equilibriumKmu', localPassFail(equilibriumResults(2).passed), ...
    'requiredNonlinearSimulations', localPassFail( ...
        requiredSimulationsComplete), ...
    'trackingKhinf', localPassFail(trackingResults(1).targets.passed), ...
    'trackingKmu', localPassFail(trackingResults(2).targets.passed), ...
    'crossCouplingKhinf', localPassFail( ...
        trackingResults(1).targets.crossCouplingPassed), ...
    'crossCouplingKmu', localPassFail( ...
        trackingResults(2).targets.crossCouplingPassed), ...
    'disturbance', "QUANTIFIED", 'noise', "QUANTIFIED", ...
    'controlEffort', "QUANTIFIED_NO_SATURATION", ...
    'ltiNonlinearTrackingAgreement', "QUANTIFIED", ...
    'ltiNonlinearDisturbanceAgreement', "QUANTIFIED", ...
    'rasKhinf', "QUANTIFIED_EMPIRICAL", ...
    'rasKmu', "QUANTIFIED_EMPIRICAL", ...
    'agreementRegionKhinf', "QUANTIFIED_EMPIRICAL", ...
    'agreementRegionKmu', "QUANTIFIED_EMPIRICAL", ...
    'softwareCorrectness', "FAIL", 'overallStatus', "BLOCKED");
figuresExist = all(structfun(@isfile, figurePaths));
softwarePassed = qualityGate.frozenControllers == "PASS" && ...
    qualityGate.frozenNonlinearPlant == "PASS" && ...
    qualityGate.solverConfigIdentityM8 == "PASS" && ...
    qualityGate.equilibriumKhinf == "PASS" && ...
    qualityGate.equilibriumKmu == "PASS" && ...
    qualityGate.requiredNonlinearSimulations == "PASS" && ...
    isempty(modelVariables) && noiseIdentity && figuresExist && ...
    all(arrayfun(@(value) height(value.boundary) == 36, rasResults)) && ...
    all(arrayfun(@(value) height(value.boundary) == 36, agreementResults));
qualityGate.softwareCorrectness = localPassFail(softwarePassed);
if ~softwarePassed
    qualityGate.overallStatus = "BLOCKED";
elseif qualityGate.trackingKhinf == "PASS" && ...
        qualityGate.trackingKmu == "PASS"
    qualityGate.overallStatus = "COMPLETE";
else
    qualityGate.overallStatus = "PARTIAL";
end

metadata = struct('milestone', "M15", ...
    'baselineCommit', config.baselineCommit, ...
    'mergedPullRequest', config.mergedPullRequest, ...
    'mergedPullRequestState', config.mergedPullRequestState, ...
    'studyType', "nominal nonlinear validation of frozen controllers", ...
    'm14Status', "PARTIAL", 'm14KmuLinearUncertainRS', ...
    controllers(2).m14RobustStability, 'nonlinearRobustGuaranteeClaimed', false, ...
    'controllerTuningPerformed', false, 'synthesisPerformed', false, ...
    'uncertaintySamplingPerformed', false, ...
    'monteCarloPerformed', false, 'controllerReductionPerformed', false, ...
    'prefilterUsed', false, 'integralAugmentationUsed', false, ...
    'saturationEnabled', false, 'm16Started', false, ...
    'responsible', "Alessio", 'matlabRelease', string(version('-release')));
save(datasetPath, 'config', 'controllerAudits', 'modelMetadata', ...
    'solverMetadata', 'plantAudit', 'equilibriumResults', ...
    'trackingResults', 'trackingLtiNlMetrics', 'disturbanceResults', ...
    'disturbanceLtiNlMetrics', 'noiseResults', 'noiseFourChannels', ...
    'noiseIdentity', 'rasResults', 'm6FrozenRasReference', ...
    'agreementResults', 'controllerComparison', 'm6Comparison', ...
    'qualityGate', 'metadata', 'figurePaths', '-v7.3');
assert(qualityGate.softwareCorrectness == "PASS", ...
    'M15:SoftwareQualityGate', 'M15 software correctness failed.');
metrics = localMetrics(load(datasetPath), datasetPath);
localPrint(metrics, false);
if isfile(checkpointPath), delete(checkpointPath); end
end

function tableOut = localComparison(controllers, equilibrium, tracking, ...
    disturbance, noise, ras, agreement)
tableOut = table(localColumn([controllers.id]), ...
    localColumn([controllers.order]), ...
    localColumn(string({controllers.m14RobustStability})), ...
    localColumn([equilibrium.maxQDriftRad]), ...
    localColumn(arrayfun(@(x) max(x.metrics.SettlingTime), tracking)), ...
    localColumn(arrayfun(@(x) max(x.metrics.OvershootPercent), tracking)), ...
    localColumn(arrayfun(@(x) max(x.metrics.SteadyStateErrorRelative), tracking)), ...
    localColumn(arrayfun(@(x) max(x.metrics.CrossCouplingPeakRatio), tracking)), ...
    localColumn(arrayfun(@(x) max(x.metrics.PeakDeltaUNm), tracking)), ...
    rad2deg(localColumn(arrayfun(@(x) max(x.metrics.PeakQRad), disturbance))), ...
    rad2deg(localColumn(arrayfun(@(x) ...
        max(abs(x.metrics.SteadyStateOffsetRad)), disturbance))), ...
    localColumn([noise.rmsTrackingError]), ...
    localColumn([noise.rmsControlVariation]), ...
    localColumn(arrayfun(@(x) x.metrics.minimumRadiusDeg, ras)), ...
    localColumn(arrayfun(@(x) x.metrics.approximateAreaDeg2, ras)), ...
    localColumn(arrayfun(@(x) ...
        x.metrics.allRadialEndpointsConvergent, ras)), ...
    localColumn(arrayfun(@(x) x.metrics.minimumRadiusDeg, agreement)), ...
    localColumn(arrayfun(@(x) x.metrics.approximateAreaDeg2, agreement)), ...
    'VariableNames', {'Controller', 'Order', 'M14RSOutcome', ...
    'EquilibriumMaxQDriftRad', 'WorstTrackingSettlingTime', ...
    'WorstTrackingOvershootPercent', 'WorstSteadyErrorRelative', ...
    'WorstCrossCouplingRatio', 'WorstTrackingPeakDeltaUNm', ...
    'WorstDisturbancePeakQDeg', 'WorstDisturbanceOffsetDeg', ...
    'NoiseRmsTrackingErrorRad', 'NoiseRmsControlVariationNm', ...
    'RasMinimumRadiusDeg', 'RasAreaDeg2', 'RasSearchBoxLimited', ...
    'AgreementMinimumRadiusDeg', 'AgreementAreaDeg2'});
end

function value = localColumn(value)
value = reshape(value, [], 1);
end

function comparison = localM6Comparison(m8, tracking, disturbance, ras)
comparison = struct('sourceArtifact', ...
    "results/data/m8_lqg_nonlinear_ras.mat", 'm6Rerun', false, ...
    'trackingSemanticCompatibility', true, ...
    'disturbanceSemanticCompatibility', true, ...
    'noiseComparisonCaveat', ...
        "M6 uses four noisy encoders; Khinf/Kmu use q1/q2 only", ...
    'm6RasMetrics', m8.rasMetrics, ...
    'robustRasMetrics', {arrayfun(@(x) x.metrics, ras)}, ...
    'robustTrackingWorstTs', ...
        arrayfun(@(x) max(x.metrics.SettlingTime), tracking), ...
    'robustDisturbanceWorstPeakQ', ...
        arrayfun(@(x) max(x.metrics.PeakQRad), disturbance));
end

function labeled = localLabel(input, id)
labeled = addvars(input, repmat(id, height(input), 1), ...
    'Before', 1, 'NewVariableNames', 'Controller');
end
function status = localPassFail(condition)
if condition, status = "PASS"; else, status = "FAIL"; end
end
function metrics = localMetrics(saved, path)
metrics = struct('config', saved.config, ...
    'controllerComparison', saved.controllerComparison, ...
    'qualityGate', saved.qualityGate, 'rasResults', saved.rasResults, ...
    'agreementResults', saved.agreementResults, ...
    'datasetPath', string(path));
end
function localPrint(metrics, reused)
fprintf('\n=== M15: validazione non lineare Khinf/Kmu congelati ===\n');
if reused, fprintf('Artifact M15 ricaricato senza nuove simulazioni.\n'); end
for index = 1:2
    row = metrics.controllerComparison(index, :);
    fprintf(['%s: tracking=%s, Ts=%g s, OS=%g%%, err=%g%%, ' ...
        'RAS rmin=%g deg (%s), agreement rmin=%g deg\n'], ...
        row.Controller, metrics.qualityGate.(['tracking' char(row.Controller)]), ...
        row.WorstTrackingSettlingTime, row.WorstTrackingOvershootPercent, ...
        100 * row.WorstSteadyErrorRelative, row.RasMinimumRadiusDeg, ...
        localRasLabel(row.RasSearchBoxLimited), ...
        row.AgreementMinimumRadiusDeg);
end
fprintf('Software=%s; M15=%s; dataset=%s\n', ...
    metrics.qualityGate.softwareCorrectness, ...
    metrics.qualityGate.overallStatus, metrics.datasetPath);
end
function label = localRasLabel(value)
if value, label = 'SEARCH-BOX LIMITED'; else, label = 'boundary located'; end
end
