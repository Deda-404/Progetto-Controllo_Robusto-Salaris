function controllers = load_m15_robust_controllers(projectRoot, config)
%LOAD_M15_ROBUST_CONTROLLERS Load frozen M10/M13 controllers and LTI maps.

arguments
    projectRoot (1, 1) string = string(fileparts(fileparts(fileparts( ...
        mfilename('fullpath')))))
    config (1, 1) struct = m15_specs
end

dataDirectory = fullfile(projectRoot, 'results', 'data');
m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m5 = load(fullfile(dataDirectory, 'm5_performance_specs.mat'));
m10 = load(fullfile(projectRoot, config.controllerSources(1)));
m13 = load(fullfile(projectRoot, config.controllerSources(2)));
m14 = load(fullfile(dataDirectory, 'm14_final_mu_analysis_kmu.mat'));

plant = build_m9_nominal_plant(m3, m5, hinf_specs_m10);
Khinf = ss(m10.Khinf);
Kmu = ss(m13.Kmu);
Khinf.InputName = repmat({''}, 2, 1);
Khinf.OutputName = repmat({''}, 2, 1);
Kmu.InputName = repmat({''}, 2, 1);
Kmu.OutputName = repmat({''}, 2, 1);

assert(isequal(size(Khinf), [2, 2]) && order(Khinf) == ...
    config.expectedControllerOrders(1), 'M15:KhinfIdentity', ...
    'The frozen M10 Khinf identity/order audit failed.');
assert(isequal(size(Kmu), [2, 2]) && order(Kmu) == ...
    config.expectedControllerOrders(2), 'M15:KmuIdentity', ...
    'The frozen M13 Kmu identity/order audit failed.');
assert(isequaln(Khinf, ss(m10.Khinf)) && isequaln(Kmu, ss(m13.Kmu)), ...
    'M15:ControllerChanged', 'A frozen controller was changed on load.');

controllers(1) = localRecord("Khinf", Khinf, ...
    config.controllerSources(1), m10.normMetrics.weightedNorm, ...
    m10.qualityGate.nominalStability, "NOT AVAILABLE", ...
    m10.T10, m10.KS10, plant.G, plant.Gd);
controllers(2) = localRecord("Kmu", Kmu, ...
    config.controllerSources(2), ...
    m13.nominalReconstruction.metrics.weightedNorm, ...
    m13.qualityGate.nominalInternalStability, ...
    m14.qualityGate.robustStability, ...
    m13.nominalReconstruction.T, ...
    m13.nominalReconstruction.KS, plant.G, plant.Gd);
controllers(1).sourceIdentity = isequaln(controllers(1).K, m10.Khinf);
controllers(2).sourceIdentity = isequaln(controllers(2).K, m13.Kmu);
controllers(1).bestIteration = NaN;
controllers(2).bestIteration = m13.history.bestIteration;
controllers(2).bestIterationIdentity = isequaln( ...
    controllers(2).K, m13.rawInfo(m13.history.bestIteration).K);
controllers(1).bestIterationIdentity = true;
controllers(1).S = feedback(ss(eye(2)), plant.G * Khinf);
controllers(2).S = feedback(ss(eye(2)), plant.G * Kmu);
end

function record = localRecord(id, K, source, weightedNorm, ns, rs, T, KS, G, Gd)
[A, B, C, D] = ssdata(K);
disturbanceClosedLoop = localDisturbanceClosedLoop(G, Gd, K);
record = struct('id', id, 'sourceArtifact', source, 'K', K, ...
    'order', order(K), 'inputCount', size(K, 2), ...
    'outputCount', size(K, 1), 'A', A, 'B', B, 'C', C, 'D', D, ...
    'matrixAudit', localMatrixAudit(A, B, C, D), ...
    'nominalWeightedNorm', weightedNorm, ...
    'nominalStability', string(ns), 'm14RobustStability', string(rs), ...
    'T', ss(T), 'KS', ss(KS), 'Gd', ss(Gd), ...
    'disturbanceQ', disturbanceClosedLoop(1:2, :), ...
    'disturbanceU', disturbanceClosedLoop(3:4, :), ...
    'disturbanceRealizationStable', isstable(disturbanceClosedLoop), ...
    'sourceIdentity', false, 'bestIteration', NaN, ...
    'bestIterationIdentity', false);
end

function closedLoop = localDisturbanceClosedLoop(G, Gd, K)
% One shared physical plant avoids unstable numerical cancellations in S*Gd.
G = ss(G); Gd = ss(Gd); K = ss(K);
[Ag, Bg, Cg, Dg] = ssdata(G);
[Ad, Bd, Cd, Dd] = ssdata(Gd);
[Ak, Bk, Ck, Dk] = ssdata(K);
assert(norm(Dg, 'fro') == 0 && norm(Dd, 'fro') == 0 && ...
    isequaln(Ag, Ad) && isequaln(Cg, Cd), ...
    'M15:DisturbancePlantIdentity', ...
    'The shared-state disturbance realization requires the frozen G/Gd plant.');
Ainternal = [Ag - Bg * Dk * Cg, Bg * Ck; -Bk * Cg, Ak];
Bdisturbance = [Bd; zeros(size(Ak, 1), size(Bd, 2))];
Cq = [Cg, zeros(size(Cg, 1), size(Ak, 1))];
Cu = [-Dk * Cg, Ck];
closedLoop = ss(Ainternal, Bdisturbance, [Cq; Cu], zeros(4, 2));
end

function audit = localMatrixAudit(A, B, C, D)
audit = struct('sizeA', size(A), 'sizeB', size(B), ...
    'sizeC', size(C), 'sizeD', size(D), ...
    'normAInf', norm(A, inf), 'normBInf', norm(B, inf), ...
    'normCInf', norm(C, inf), 'normDInf', norm(D, inf), ...
    'sumA', sum(A, 'all'), 'sumB', sum(B, 'all'), ...
    'sumC', sum(C, 'all'), 'sumD', sum(D, 'all'), ...
    'allFinite', all(isfinite([A(:); B(:); C(:); D(:)])));
end
