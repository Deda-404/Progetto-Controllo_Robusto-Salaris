function evaluation = evaluate_m15_tracking(controller, projectRoot, config)
%EVALUATE_M15_TRACKING Evaluate six frozen M5 tracking scenarios.

arguments
    controller (1, 1) struct
    projectRoot (1, 1) string
    config (1, 1) struct = m15_specs
end

m3 = load(fullfile(projectRoot, 'results', 'data', ...
    'm3_nominal_actuated_plant.mat'));
m5 = load(fullfile(projectRoot, 'results', 'data', ...
    'm5_performance_specs.mat'));
amplitudes = config.tracking.referenceAmplitudesDeg(:);
rows = zeros(numel(amplitudes) * 2, 12);
comparisonRows = zeros(numel(amplitudes) * 2, 6);
responses = cell(numel(amplitudes), 2);
rowIndex = 0;
dcGainT = dcgain(controller.T);
for amplitudeIndex = 1:numel(amplitudes)
    amplitude = deg2rad(amplitudes(amplitudeIndex));
    for jointIndex = 1:2
        scenario.reference = zeros(1, 2);
        scenario.reference(jointIndex) = amplitude;
        scenario.horizon = config.simulation.trackingHorizon;
        nonlinear = simulate_m15_nonlinear(controller, scenario, ...
            projectRoot, config);
        time = (0:config.simulation.inputTimeStep:scenario.horizon).';
        input = zeros(numel(time), 2);
        input(:, jointIndex) = amplitude;
        qLti = lsim(controller.T, input, time);
        uLti = lsim(controller.KS, input, time);
        q = nonlinear.xMechanical(:, 1:2) - m3.xbar(1:2).';
        qLtiAtNl = interp1(time, qLti, nonlinear.time, 'linear');
        uLtiAtNl = interp1(time, uLti, nonlinear.time, 'linear');
        qDifference = q - qLtiAtNl;
        uDifference = nonlinear.controlDelta - uLtiAtNl;
        finalVector = dcGainT(:, jointIndex) * amplitude;
        finalValue = finalVector(jointIndex);
        settling = localSettlingTime(q(:, jointIndex), finalValue, ...
            nonlinear.time, config.simulation.settlingBandFraction * ...
            abs(amplitude));
        overshoot = 100 * max(0, ...
            (max(q(:, jointIndex)) - amplitude) / abs(amplitude));
        steadyAbsolute = abs(finalValue - amplitude);
        steadyRelative = steadyAbsolute / abs(amplitude);
        otherJoint = 3 - jointIndex;
        crossCoupling = max(abs(q(:, otherJoint))) / ...
            max(max(abs(q(:, jointIndex))), eps);
        deformation = nonlinear.xMechanical(:, 5:6) - ...
            nonlinear.xMechanical(:, 1:2);
        elasticTorque = deformation * m3.mechanicalParams.Ks.';
        rowIndex = rowIndex + 1;
        rows(rowIndex, :) = [amplitudes(amplitudeIndex), jointIndex, ...
            settling, overshoot, steadyAbsolute, steadyRelative, ...
            crossCoupling, max(abs(nonlinear.controlDelta), [], 'all'), ...
            max(abs(nonlinear.controlAbsolute), [], 'all'), ...
            max(abs(nonlinear.controlDelta), [], 'all') / m5.spec.uScale, ...
            max(abs(deformation), [], 'all'), ...
            max(abs(elasticTorque), [], 'all')];
        comparisonRows(rowIndex, :) = [amplitudes(amplitudeIndex), ...
            jointIndex, max(abs(qDifference), [], 'all'), ...
            sqrt(mean(qDifference.^2, 'all')), ...
            max(abs(uDifference), [], 'all'), ...
            sqrt(mean(uDifference.^2, 'all'))];
        responses{amplitudeIndex, jointIndex} = struct( ...
            'amplitudeDeg', amplitudes(amplitudeIndex), ...
            'joint', jointIndex, 'time', nonlinear.time, 'q', q, ...
            'theta', nonlinear.xMechanical(:, 5:6) - m3.xbar(5:6).', ...
            'controlDelta', nonlinear.controlDelta, ...
            'controlAbsolute', nonlinear.controlAbsolute, ...
            'qLti', qLtiAtNl, 'uLti', uLtiAtNl);
    end
end
evaluation.controllerID = controller.id;
evaluation.metrics = array2table(rows, 'VariableNames', ...
    {'AmplitudeDeg', 'Joint', 'SettlingTime', 'OvershootPercent', ...
    'SteadyStateErrorAbsRad', 'SteadyStateErrorRelative', ...
    'CrossCouplingPeakRatio', 'PeakDeltaUNm', 'PeakAbsoluteUNm', ...
    'PeakUNormalized', 'PeakSeaDeformationRad', ...
    'PeakElasticTorqueNm'});
evaluation.ltiNonlinearMetrics = array2table(comparisonRows, ...
    'VariableNames', {'AmplitudeDeg', 'Joint', 'MaxQDifferenceRad', ...
    'RmsQDifferenceRad', 'MaxUDifferenceNm', 'RmsUDifferenceNm'});
evaluation.responses = responses;
evaluation.targets = struct( ...
    'settlingPassed', all(evaluation.metrics.SettlingTime <= ...
        m5.spec.settlingTimeTarget), ...
    'overshootPassed', all(evaluation.metrics.OvershootPercent <= ...
        m5.spec.overshootTarget), ...
    'steadyStateErrorPassed', all( ...
        evaluation.metrics.SteadyStateErrorRelative <= ...
        m5.spec.steadyStateTrackingTarget), ...
    'crossCouplingPassed', all( ...
        evaluation.metrics.CrossCouplingPeakRatio <= ...
        m5.spec.crossCouplingTarget));
evaluation.targets.passed = evaluation.targets.settlingPassed && ...
    evaluation.targets.overshootPassed && ...
    evaluation.targets.steadyStateErrorPassed;
end

function settlingTime = localSettlingTime(signal, finalValue, time, threshold)
outside = abs(signal - finalValue) > max(threshold, 100 * eps);
lastOutside = find(outside, 1, 'last');
if isempty(lastOutside), settlingTime = 0;
elseif lastOutside == numel(time), settlingTime = inf;
else, settlingTime = time(lastOutside + 1);
end
end
