function evaluation = evaluate_m15_noise(controller, noiseFourChannels, projectRoot, config)
%EVALUATE_M15_NOISE Run noisy, repeated, and noise-free q-only scenarios.

arguments
    controller (1, 1) struct
    noiseFourChannels (:, 4) double
    projectRoot (1, 1) string
    config (1, 1) struct = m15_specs
end

m3 = load(fullfile(projectRoot, 'results', 'data', ...
    'm3_nominal_actuated_plant.mat'));
noiseQ = noiseFourChannels(:, 1:2);
scenario.reference = [deg2rad(5), 0];
scenario.measurementNoise = noiseQ;
scenario.horizon = config.simulation.noiseHorizon;
noisy = simulate_m15_nonlinear(controller, scenario, projectRoot, config);
repeat = simulate_m15_nonlinear(controller, scenario, projectRoot, config);
scenario.measurementNoise = zeros(size(noiseQ));
deterministic = simulate_m15_nonlinear(controller, scenario, projectRoot, config);
qNoisy = noisy.xMechanical(:, 1:2) - m3.xbar(1:2).';
qDeterministic = interp1(deterministic.time, ...
    deterministic.xMechanical(:, 1:2) - m3.xbar(1:2).', ...
    noisy.time, 'linear');
uDeterministic = interp1(deterministic.time, ...
    deterministic.controlDelta, noisy.time, 'linear');
reference = [deg2rad(5) * ones(numel(noisy.time), 1), ...
    zeros(numel(noisy.time), 1)];
evaluation = struct( ...
    'controllerID', controller.id, 'seed', config.noise.seed, ...
    'noiseChannelPolicy', "first two channels of frozen M8 convention", ...
    'noiseFourChannelIdentity', localNoiseAudit(noiseFourChannels), ...
    'rmsTrackingErrorByJoint', ...
        sqrt(mean((qNoisy - reference).^2, 1)).', ...
    'rmsTrackingError', sqrt(mean((qNoisy - reference).^2, 'all')), ...
    'rmsControlVariationByJoint', ...
        sqrt(mean((noisy.controlDelta - uDeterministic).^2, 1)).', ...
    'rmsControlVariation', sqrt(mean( ...
        (noisy.controlDelta - uDeterministic).^2, 'all')), ...
    'rmsQVariationByJoint', ...
        sqrt(mean((qNoisy - qDeterministic).^2, 1)).', ...
    'rmsQVariation', sqrt(mean((qNoisy - qDeterministic).^2, 'all')), ...
    'repeatError', max(abs([noisy.xMechanical - repeat.xMechanical, ...
        noisy.xActuator - repeat.xActuator, ...
        noisy.xController - repeat.xController, ...
        noisy.controlDelta - repeat.controlDelta]), [], 'all'), ...
    'noisyResponse', localCompact(noisy, m3), ...
    'deterministicResponse', localCompact(deterministic, m3));
end

function audit = localNoiseAudit(noise)
audit = struct('size', size(noise), 'sum', sum(noise, 'all'), ...
    'normFro', norm(noise, 'fro'), 'allFinite', all(isfinite(noise), 'all'));
end
function response = localCompact(result, m3)
response = struct('time', result.time, ...
    'q', result.xMechanical(:, 1:2) - m3.xbar(1:2).', ...
    'controlDelta', result.controlDelta, ...
    'controlAbsolute', result.controlAbsolute);
end
