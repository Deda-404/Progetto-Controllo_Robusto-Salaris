function evaluation = evaluate_m9_closed_loop( ...
    reconstruction, m5, m6, synthesis, config)
%EVALUATE_M9_CLOSED_LOOP Evaluate M9 and the frozen M6 benchmark fairly.

arguments
    reconstruction (1, 1) struct
    m5 (1, 1) struct
    m6 (1, 1) struct
    synthesis (1, 1) struct
    config (1, 1) struct = hinf_specs_m9
end

m9ReferenceSystem = reconstruction.closedLoopReference;
m9DisturbanceSystem = reconstruction.closedLoopDisturbance;
m6ReferenceSystem = m6.lqgClosedLoop([1:2, 5:6], 1:2);
m6DisturbanceSystem = m6.lqgClosedLoop([1:2, 5:6], 3:4);

[trackingMetrics, trackingResponses] = localEvaluateTracking( ...
    m9ReferenceSystem, m5.spec, config);
[disturbanceMetrics, disturbanceResponses] = localEvaluateDisturbance( ...
    m9DisturbanceSystem, m5.spec, config);
[m6TrackingMetrics, m6TrackingResponses] = localEvaluateTracking( ...
    m6ReferenceSystem, m5.spec, config);
[m6DisturbanceMetrics, m6DisturbanceResponses] = ...
    localEvaluateDisturbance(m6DisturbanceSystem, m5.spec, config);

trackingComparison = [localLabelTable(trackingMetrics, "M9 mixsyn"); ...
    localLabelTable(m6TrackingMetrics, "M6 LQG")];
disturbanceComparison = [ ...
    localLabelTable(disturbanceMetrics, "M9 mixsyn"); ...
    localLabelTable(m6DisturbanceMetrics, "M6 LQG")];

trackingTargets = struct( ...
    'settlingPassed', all(trackingMetrics.SettlingTime <= ...
        m5.spec.settlingTimeTarget), ...
    'overshootPassed', all(trackingMetrics.OvershootPercent <= ...
        m5.spec.overshootTarget), ...
    'steadyStateErrorPassed', all( ...
        trackingMetrics.SteadyStateErrorRelative <= ...
        m5.spec.steadyStateTrackingTarget), ...
    'crossCouplingPassed', all( ...
        trackingMetrics.CrossCouplingPeakRatio <= ...
        m5.spec.crossCouplingTarget));
trackingTargets.passed = trackingTargets.settlingPassed && ...
    trackingTargets.overshootPassed && ...
    trackingTargets.steadyStateErrorPassed;

evaluation.trackingMetrics = trackingMetrics;
evaluation.trackingResponses = trackingResponses;
evaluation.disturbanceMetrics = disturbanceMetrics;
evaluation.disturbanceResponses = disturbanceResponses;
evaluation.m6TrackingMetrics = m6TrackingMetrics;
evaluation.m6TrackingResponses = m6TrackingResponses;
evaluation.m6DisturbanceMetrics = m6DisturbanceMetrics;
evaluation.m6DisturbanceResponses = m6DisturbanceResponses;
evaluation.comparison = struct( ...
    'tracking', trackingComparison, ...
    'disturbance', disturbanceComparison, ...
    'controllerOrder', table( ...
        ["M9 mixsyn"; "M6 LQG"], ...
        [synthesis.controllerOrder; order(m6.Klqg)], ...
        'VariableNames', {'Controller', 'Order'}));
evaluation.trackingTargets = trackingTargets;
evaluation.controlEffort = struct( ...
    'uScaleNm', m5.spec.uScale, ...
    'isPerformanceNormalization', true, ...
    'saturationEnabled', config.saturationEnabled, ...
    'worstTrackingPeakNm', max(trackingMetrics.PeakControlNm), ...
    'worstTrackingPeakNormalized', ...
        max(trackingMetrics.PeakControlNormalized), ...
    'worstDisturbancePeakNm', max(disturbanceMetrics.PeakControlNm), ...
    'worstDisturbancePeakNormalized', ...
        max(disturbanceMetrics.PeakControlNormalized));
end

function [metrics, responses] = localEvaluateTracking(system, spec, config)
amplitudesDeg = spec.referenceAmplitudeScenariosDeg(:);
time = (0:config.timeStep:config.trackingHorizon).';
rows = zeros(numel(amplitudesDeg) * 2, 9);
responses = cell(numel(amplitudesDeg), 2);
dcGain = dcgain(system(1:2, :));
rowIndex = 0;
for amplitudeIndex = 1:numel(amplitudesDeg)
    amplitude = deg2rad(amplitudesDeg(amplitudeIndex));
    for jointIndex = 1:2
        input = zeros(numel(time), 2);
        input(:, jointIndex) = amplitude;
        output = lsim(system, input, time);
        q = output(:, 1:2);
        u = output(:, 3:4);
        finalVector = dcGain(:, jointIndex) * amplitude;
        finalValue = finalVector(jointIndex);
        settling = localSettlingTime(q(:, jointIndex), finalValue, ...
            time, config.settlingBandFraction * abs(amplitude));
        overshoot = 100 * max(0, ...
            (max(q(:, jointIndex)) - amplitude) / abs(amplitude));
        steadyAbsolute = abs(finalValue - amplitude);
        steadyRelative = steadyAbsolute / abs(amplitude);
        otherJoint = 3 - jointIndex;
        crossCoupling = max(abs(q(:, otherJoint))) / ...
            max(max(abs(q(:, jointIndex))), eps);
        peakControl = max(abs(u), [], 'all');
        rowIndex = rowIndex + 1;
        rows(rowIndex, :) = [amplitudesDeg(amplitudeIndex), ...
            jointIndex, settling, overshoot, steadyAbsolute, ...
            steadyRelative, crossCoupling, peakControl, ...
            peakControl / spec.uScale];
        responses{amplitudeIndex, jointIndex} = struct( ...
            'time', time, 'q', q, 'u', u, ...
            'amplitudeDeg', amplitudesDeg(amplitudeIndex), ...
            'joint', jointIndex, 'finalValue', finalVector);
    end
end
metrics = array2table(rows, 'VariableNames', ...
    {'AmplitudeDeg', 'Joint', 'SettlingTime', 'OvershootPercent', ...
    'SteadyStateErrorAbsRad', 'SteadyStateErrorRelative', ...
    'CrossCouplingPeakRatio', 'PeakControlNm', ...
    'PeakControlNormalized'});
end

function [metrics, responses] = localEvaluateDisturbance(system, spec, config)
amplitudesNm = spec.disturbanceTorqueScenarios(:);
time = (0:config.timeStep:config.disturbanceHorizon).';
rows = zeros(numel(amplitudesNm) * 2, 8);
responses = cell(numel(amplitudesNm), 2);
dcGain = dcgain(system(1:2, :));
rowIndex = 0;
for amplitudeIndex = 1:numel(amplitudesNm)
    amplitude = amplitudesNm(amplitudeIndex);
    for jointIndex = 1:2
        input = zeros(numel(time), 2);
        input(:, jointIndex) = amplitude;
        output = lsim(system, input, time);
        q = output(:, 1:2);
        u = output(:, 3:4);
        finalVector = dcGain(:, jointIndex) * amplitude;
        finalValue = finalVector(jointIndex);
        affectedPeak = max(abs(q(:, jointIndex)));
        threshold = config.settlingBandFraction * max( ...
            [affectedPeak, abs(finalValue), eps]);
        settling = localSettlingTime(q(:, jointIndex), finalValue, ...
            time, threshold);
        otherJoint = 3 - jointIndex;
        crossCoupling = max(abs(q(:, otherJoint))) / ...
            max(affectedPeak, eps);
        peakControl = max(abs(u), [], 'all');
        rowIndex = rowIndex + 1;
        rows(rowIndex, :) = [amplitude, jointIndex, affectedPeak, ...
            finalValue, settling, crossCoupling, peakControl, ...
            peakControl / spec.uScale];
        responses{amplitudeIndex, jointIndex} = struct( ...
            'time', time, 'q', q, 'u', u, ...
            'amplitudeNm', amplitude, 'joint', jointIndex, ...
            'finalValue', finalVector);
    end
end
metrics = array2table(rows, 'VariableNames', ...
    {'AmplitudeNm', 'Joint', 'PeakQRad', 'SteadyStateOffsetRad', ...
    'SettlingTime', 'CrossCouplingPeakRatio', 'PeakControlNm', ...
    'PeakControlNormalized'});
end

function labeled = localLabelTable(inputTable, label)
labeled = addvars(inputTable, repmat(label, height(inputTable), 1), ...
    'Before', 1, 'NewVariableNames', 'Controller');
end

function settlingTime = localSettlingTime(signal, finalValue, time, threshold)
outside = abs(signal - finalValue) > max(threshold, 100 * eps);
lastOutside = find(outside, 1, 'last');
if isempty(lastOutside)
    settlingTime = 0;
elseif lastOutside == numel(time)
    settlingTime = inf;
else
    settlingTime = time(lastOutside + 1);
end
end
