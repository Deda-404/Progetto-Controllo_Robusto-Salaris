function metrics = validate_m10_hinfsyn
%VALIDATE_M10_HINFSYN Rebuild and validate the equivalent M10 baseline.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));

dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory), mkdir(dataDirectory); end
if ~isfolder(figureDirectory), mkdir(figureDirectory); end

m3Path = fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat');
m5Path = fullfile(dataDirectory, 'm5_performance_specs.mat');
m6Path = fullfile(dataDirectory, 'm6_lqg_no_integrator.mat');
m9Path = fullfile(dataDirectory, 'm9_hinf_mixsyn_nominal.mat');
if ~isfile(m3Path), validate_m3_nominal_actuated_plant; end
if ~isfile(m5Path), validate_m5_performance_specs; end
if ~isfile(m6Path), validate_m6_lqg_no_integrator; end
if ~isfile(m9Path), validate_m9_hinf_mixsyn; end
m3 = load(m3Path);
m5 = load(m5Path);
m6 = load(m6Path);
m9 = load(m9Path);
config = hinf_specs_m10;

plant = build_m9_nominal_plant(m3, m5, config);
[~, regeneratedW1, ~, regeneratedW2] = build_m5_weights(m5.spec);
weightAudit = struct( ...
    'W1TransferError', norm(m5.W1 - regeneratedW1, inf), ...
    'W2TransferError', norm(m5.W2 - regeneratedW2, inf), ...
    'M5SynthesisGateUnchanged', ~m5.spec.controllerSynthesisAllowed, ...
    'W3Absent', isempty(config.W3), ...
    'retuningPerformed', config.weightRetuningEnabled, ...
    'source', "results/data/m5_performance_specs.mat");
assert(weightAudit.W1TransferError <= config.weightConsistencyTolerance && ...
    weightAudit.W2TransferError <= config.weightConsistencyTolerance && ...
    weightAudit.M5SynthesisGateUnchanged && weightAudit.W3Absent && ...
    ~weightAudit.retuningPerformed, 'M10:WeightScopeMismatch', ...
    'M10 does not preserve the frozen M5 weights and scope.');

generalized = build_m10_generalized_plant( ...
    plant.G, m5.W1, m5.W2, config);

% Mandatory methodological gate: this assertion occurs before hinfsyn.
equivalenceGateM9 = validate_m10_generalized_plant( ...
    generalized, m9, config);

synthesis = synthesize_m10_hinfsyn(generalized.P, config);
reconstruction = reconstruct_m10_closed_loop( ...
    plant.G, plant.Gd, m5.W1, m5.W2, synthesis, config);
evaluation = evaluate_m10_closed_loop( ...
    reconstruction, synthesis, plant, m5, m6, m9, config);

[eigenvectors, diagonalPoles] = eig(reconstruction.Ainternal);
explicitPoles = diag(diagonalPoles);
sensitivityPoles = pole(reconstruction.S);
stabilityDiagnostics = struct( ...
    'plantStateCount', order(plant.G), ...
    'controllerStateCount', synthesis.controllerOrder, ...
    'internalStateCount', numel(explicitPoles), ...
    'sensitivityRealizationPoleCount', numel(sensitivityPoles), ...
    'poleSetDistance', localPoleSetDistance( ...
        explicitPoles, sensitivityPoles), ...
    'eigenvectorConditionNumber', cond(eigenvectors), ...
    'minimumPoleSeparation', localMinimumPoleSeparation(explicitPoles), ...
    'maximumClosedLoopRealPart', max(real(explicitPoles)), ...
    'minrealUsedForGate', false);

qualityGate.generalizedPlantCorrectness = localPassFail( ...
    equivalenceGateM9.passed && ...
    generalized.audit.analyticMaximumFrequencyError <= ...
        config.generalizedPlantTolerance && ...
    generalized.audit.P22MaximumFrequencyError <= ...
        config.generalizedPlantTolerance);
qualityGate.nominalStability = localPassFail( ...
    reconstruction.metrics.nominallyStable && ...
    reconstruction.metrics.sensitivityStable && ...
    reconstruction.metrics.complementarySensitivityStable && ...
    reconstruction.metrics.controlSensitivityStable && ...
    reconstruction.metrics.clmixStable);
qualityGate.hinfReconstruction = localPassFail( ...
    reconstruction.metrics.normRelativeError <= ...
        config.normRelativeTolerance && ...
    reconstruction.metrics.clmixError <= ...
        config.closedLoopConsistencyTolerance);
qualityGate.weightedNominalPerformance = localPassFail( ...
    synthesis.gammaHinf < 1 && ...
    qualityGate.hinfReconstruction == "PASS");
qualityGate.tracking = localPassFail(evaluation.trackingTargets.passed);
qualityGate.crossCoupling = localPassFail( ...
    evaluation.trackingTargets.crossCouplingPassed);
qualityGate.disturbanceRejection = "QUANTIFIED";
qualityGate.controlEffort = "QUANTIFIED_NO_SATURATION";
if evaluation.consistencyM9M10.passed
    qualityGate.m9M10Consistency = "PASS";
elseif evaluation.consistencyM9M10.gammaRelativeDifference <= 10 * ...
        config.gammaConsistencyDiagnosticTolerance
    qualityGate.m9M10Consistency = "DIAGNOSTIC";
else
    qualityGate.m9M10Consistency = "FAIL_METHODOLOGICAL";
end
qualityGate.softwareCorrectness = localPassFail( ...
    qualityGate.generalizedPlantCorrectness == "PASS" && ...
    qualityGate.hinfReconstruction == "PASS" && ...
    qualityGate.m9M10Consistency == "PASS" && ...
    weightAudit.W1TransferError <= config.weightConsistencyTolerance && ...
    weightAudit.W2TransferError <= config.weightConsistencyTolerance);
fundamentalPass = qualityGate.generalizedPlantCorrectness == "PASS" && ...
    qualityGate.nominalStability == "PASS" && ...
    qualityGate.hinfReconstruction == "PASS" && ...
    qualityGate.weightedNominalPerformance == "PASS" && ...
    qualityGate.tracking == "PASS";
if fundamentalPass
    qualityGate.overallStatus = "COMPLETE";
else
    qualityGate.overallStatus = "PARTIAL";
end

figurePaths = plot_m10_results(reconstruction, evaluation, m5, m9, ...
    figureDirectory, config);

P = generalized.P;
partition = generalized.partition;
generalizedPlantAudit = generalized.audit;
Khinf = synthesis.Khinf;
CLhinf = synthesis.CLhinf;
gammaHinf = synthesis.gammaHinf;
infoHinf = synthesis.infoHinf;
S10 = reconstruction.S;
T10 = reconstruction.T;
KS10 = reconstruction.KS;
weightedClosedLoop10 = reconstruction.weightedClosedLoop;
weightedW1S10 = reconstruction.weightedW1S;
weightedW2KS10 = reconstruction.weightedW2KS;
closedLoopPoles10 = reconstruction.internalPoles;
normMetrics = reconstruction.metrics;
trackingMetrics = evaluation.trackingMetrics;
disturbanceMetrics = evaluation.disturbanceMetrics;
controlEffortMetrics = evaluation.controlEffort;
comparisonM6M9M10 = evaluation.comparison;
consistencyM9M10 = evaluation.consistencyM9M10;
plantAudit = plant.audit;
synthesisDiagnostics = struct( ...
    'controllerOrder', synthesis.controllerOrder, ...
    'controllerPoles', synthesis.controllerPoles, ...
    'controllerStableInIsolation', ...
        synthesis.controllerStableInIsolation, ...
    'warningMessage', synthesis.warningMessage, ...
    'warningIdentifier', synthesis.warningIdentifier, ...
    'infoGamma', infoHinf.gamma, ...
    'infoGammaDifference', abs(infoHinf.gamma - gammaHinf), ...
    'infoProperties', string(properties(infoHinf)), ...
    'defaultOptionsUsed', synthesis.defaultOptionsUsed, ...
    'method', synthesis.method);
metadata = struct( ...
    'milestone', "M10", ...
    'principle', ...
        "same plant / same weights / same scaling / different interface", ...
    'plantSource', "results/data/m3_nominal_actuated_plant.mat", ...
    'weightSource', weightAudit.source, ...
    'm9Source', "results/data/m9_hinf_mixsyn_nominal.mat", ...
    'm6Source', "results/data/m6_lqg_no_integrator.mat", ...
    'nominalOnly', true, ...
    'disturbanceInSynthesisObjective', false, ...
    'retuningPerformed', config.weightRetuningEnabled, ...
    'robustAnalysisPerformed', config.robustAnalysisEnabled, ...
    'saturationEnabled', config.saturationEnabled, ...
    'twoDegreeOfFreedomUsed', config.twoDegreeOfFreedomEnabled);

datasetPath = fullfile(dataDirectory, 'm10_hinfsyn_nominal.mat');
save(datasetPath, 'P', 'partition', 'generalizedPlantAudit', ...
    'equivalenceGateM9', 'Khinf', 'CLhinf', 'gammaHinf', 'infoHinf', ...
    'S10', 'T10', 'KS10', 'weightedClosedLoop10', 'weightedW1S10', ...
    'weightedW2KS10', 'closedLoopPoles10', 'normMetrics', ...
    'stabilityDiagnostics', 'trackingMetrics', 'disturbanceMetrics', ...
    'controlEffortMetrics', 'comparisonM6M9M10', ...
    'consistencyM9M10', 'plantAudit', 'weightAudit', ...
    'synthesisDiagnostics', 'qualityGate', 'config', 'metadata', ...
    'figurePaths', '-v7');

assert(qualityGate.generalizedPlantCorrectness == "PASS" && ...
    qualityGate.hinfReconstruction == "PASS" && ...
    qualityGate.softwareCorrectness == "PASS", ...
    'M10:SoftwareQualityGate', ...
    'The generalized-plant or reconstruction quality gate did not pass.');
assert(qualityGate.nominalStability == "PASS", ...
    'M10:NominalStability', ...
    'The nominal M10 interconnection is not internally stable.');
assert(isfile(datasetPath) && all(structfun(@isfile, figurePaths)), ...
    'M10:Artifacts', 'One or more required M10 artifacts are missing.');

fprintf('\n=== Validazione M10: generalized plant e hinfsyn ===\n');
fprintf(['P: %dx%d, order=%d, analytic error=%.3e, P22+G=' ...
    '%.3e, augw error=%.3e\n'], size(P, 1), size(P, 2), order(P), ...
    generalizedPlantAudit.analyticMaximumFrequencyError, ...
    generalizedPlantAudit.P22MaximumFrequencyError, ...
    generalizedPlantAudit.augwMaximumFrequencyError);
fprintf(['M9 gate via P: CLmix error=%.3e, stack error=%.3e, ' ...
    'norm=%.12g, relative gamma error=%.3e\n'], ...
    equivalenceGateM9.metrics.clmixError, ...
    equivalenceGateM9.metrics.weightedClosedLoopError, ...
    equivalenceGateM9.metrics.closedLoopNorm, ...
    equivalenceGateM9.metrics.gammaRelativeError);
fprintf(['Khinf order=%d, gamma=%.12g, reconstructed norm=%.12g, ' ...
    'relative error=%.3e\n'], synthesis.controllerOrder, ...
    synthesis.gammaHinf, reconstruction.metrics.weightedNorm, ...
    reconstruction.metrics.normRelativeError);
fprintf(['||W1*S10||inf=%.12g, ||W2*KS10||inf=%.12g, ' ...
    'CLhinf error=%.3e\n'], reconstruction.metrics.W1SNorm, ...
    reconstruction.metrics.W2KSNorm, reconstruction.metrics.clmixError);
fprintf('Closed loop: max real pole=%.12g, states=%d, warning="%s"\n', ...
    reconstruction.metrics.maximumClosedLoopRealPart, ...
    reconstruction.metrics.internalStateCount, synthesis.warningMessage);
fprintf(['M9/M10: gamma relative difference=%.3e, weighted map ' ...
    'error=%.3e, interpretation=%s\n'], ...
    consistencyM9M10.gammaRelativeDifference, ...
    consistencyM9M10.weightedMapError, ...
    consistencyM9M10.interpretation);
fprintf(['Tracking: worst Ts=%.6g s, OS=%.6g%%, error=%.6g%%, ' ...
    'cross=%.6g%%, peak |u|=%.6g N m\n'], ...
    max(trackingMetrics.SettlingTime), ...
    max(trackingMetrics.OvershootPercent), ...
    100 * max(trackingMetrics.SteadyStateErrorRelative), ...
    100 * max(trackingMetrics.CrossCouplingPeakRatio), ...
    max(trackingMetrics.PeakControlNm));
fprintf(['Gates: P=%s, stability=%s, reconstruction=%s, weighted=%s, ' ...
    'tracking=%s, consistency=%s; M10=%s\n'], ...
    qualityGate.generalizedPlantCorrectness, ...
    qualityGate.nominalStability, qualityGate.hinfReconstruction, ...
    qualityGate.weightedNominalPerformance, qualityGate.tracking, ...
    qualityGate.m9M10Consistency, qualityGate.overallStatus);
fprintf('Dataset: %s\n', datasetPath);

metrics.config = config;
metrics.plant = plant;
metrics.weightAudit = weightAudit;
metrics.generalized = generalized;
metrics.equivalenceGateM9 = equivalenceGateM9;
metrics.synthesis = synthesis;
metrics.reconstruction = reconstruction;
metrics.evaluation = evaluation;
metrics.stabilityDiagnostics = stabilityDiagnostics;
metrics.qualityGate = qualityGate;
metrics.figurePaths = figurePaths;
metrics.datasetPath = datasetPath;
end

function status = localPassFail(condition)
if condition
    status = "PASS";
else
    status = "FAIL";
end
end

function distance = localPoleSetDistance(first, second)
pairwiseDistance = abs(first(:) - second(:).');
distance = max([max(min(pairwiseDistance, [], 1)), ...
    max(min(pairwiseDistance, [], 2))]);
end

function separation = localMinimumPoleSeparation(poles)
distances = abs(poles(:) - poles(:).');
distances(eye(numel(poles), 'logical')) = inf;
separation = min(distances, [], 'all');
end
