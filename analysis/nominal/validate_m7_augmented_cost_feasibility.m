function metrics = validate_m7_augmented_cost_feasibility
%VALIDATE_M7_AUGMENTED_COST_FEASIBILITY Validate the final M7 cost study.
%   This is the last authorized feasibility expansion before a formal M5
%   specification review. It never searches outside Stages C1--C3.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m5 = load(fullfile(dataDirectory, 'm5_performance_specs.mat'));
m6 = load(fullfile(dataDirectory, 'm6_lqg_no_integrator.mat'));
checkpoint1Dof = load(fullfile(dataDirectory, ...
    'm7_lqi_grid_partial.mat'));
checkpoint2Dof = load(fullfile(dataDirectory, ...
    'm7_lqi_2dof_feasibility.mat'));
config = lqg_specs_m7;
selection = retune_lqi_augmented_cost_m7(m3, m5, m6, config);

stageC1CandidateTable = selection.stageC1.candidateTable;
stageC2CandidateTable = selection.stageC2.candidateTable;
stageC3CandidateTable = selection.stageC3.candidateTable;
allCandidateTable = selection.allCandidateTable;
paretoC1Table = selection.paretoC1Table;
paretoAllTable = selection.paretoAllTable;
bestC1SettlingRow = selection.bestC1SettlingRow;
bestC1OvershootRow = selection.bestC1OvershootRow;
bestSettlingWithOvershootTargetRow = ...
    selection.bestSettlingWithOvershootTargetRow;
minimumOvershootRow = selection.minimumOvershootRow;
bestOvershootNearSettlingTargetRow = ...
    selection.bestOvershootNearSettlingTargetRow;

physicalScaleChecks = cellfun(@(design) isequaln( ...
    design.physicalScales, m6.validationMetrics.cost.scales), ...
    selection.designs);
xiScaleExpected = m5.spec.referenceAmplitude * ...
    m5.spec.settlingTimeTarget;
xiScaleChecks = cellfun(@(design) design.xiScale == xiScaleExpected, ...
    selection.designs);
costConstructionChecks = cellfun(@(design) norm(design.Qaug - ...
    design.CaugCost.' * design.CaugCost, 'fro') <= 1e-10, ...
    selection.designs);

stageExecution.c1CandidateCount = height(stageC1CandidateTable);
stageExecution.c1PromisingCount = height(selection.c1PromisingTable);
stageExecution.c1SeedCount = height(selection.c1SeedTable);
stageExecution.c2Executed = selection.stageC2Executed;
stageExecution.c2CandidateCount = height(stageC2CandidateTable);
stageExecution.c2PromisingCount = height(selection.c2PromisingTable);
stageExecution.c2SeedCount = height(selection.c2SeedTable);
stageExecution.c3Necessary = selection.stageC3Necessary;
stageExecution.c3Executed = selection.stageC3Executed;
stageExecution.c3CandidateCount = height(stageC3CandidateTable);
stageExecution.maximumStageReached = localMaximumStage(stageExecution);
stageExecution.noSearchBeyondC3 = selection.noSearchBeyondC3;

comparisonTable = localBuildComparisonTable(m5, m6, ...
    checkpoint1Dof, checkpoint2Dof, selection, config);
admissibleCount = numel(selection.admissibleIndices);
finalControllerBuilt = admissibleCount > 0;
if finalControllerBuilt
    status = "COMPLETE";
    feasibilityConclusion = string(sprintf( ...
        ['Lo studio C1-C3 ha prodotto %d candidati ammissibili; ' ...
        'il candidato finale e'' stato selezionato dalla griglia.'], ...
        admissibleCount));
else
    status = "PARTIAL";
    feasibilityConclusion = ...
        "Con l'architettura LQI/LQG-I studiata e l'ensemble di costi " + ...
        "fisicamente normalizzati analizzato, la coppia di requisiti " + ...
        "Ts<=0.8 s e OS<=10% non e' risultata simultaneamente " + ...
        "raggiungibile.";
end

validationMetrics.status = status;
validationMetrics.admissibleCount = admissibleCount;
validationMetrics.finalControllerBuilt = finalControllerBuilt;
validationMetrics.m5SourceUnchanged = isequaln( ...
    m5.spec, performance_specs_m5);
validationMetrics.physicalScalesUnchanged = all(physicalScaleChecks);
validationMetrics.xiScaleUnchanged = all(xiScaleChecks);
validationMetrics.costBuiltFromCaugCost = all(costConstructionChecks);
validationMetrics.onlyDimensionlessPrioritiesTuned = ...
    validationMetrics.physicalScalesUnchanged && ...
    validationMetrics.xiScaleUnchanged;
validationMetrics.stageExecution = stageExecution;
validationMetrics.noCandidatePreselected = ...
    all(allCandidateTable.Selected == allCandidateTable.FundamentalPass & ...
    allCandidateTable.Ranking == 1 | ~allCandidateTable.Selected);
validationMetrics.allCandidatesStable = all(allCandidateTable.Stable);
validationMetrics.allFeedforwardsValid = all( ...
    allCandidateTable.FeedforwardWellConditioned);
validationMetrics.maximumFeedforwardResidual = max( ...
    allCandidateTable.FeedforwardResidual);
validationMetrics.allDisturbanceOffsetsPass = all( ...
    allCandidateTable.DisturbanceOffsetD1 <= ...
    config.disturbanceSteadyStateTolerance & ...
    allCandidateTable.DisturbanceOffsetD2 <= ...
    config.disturbanceSteadyStateTolerance);
validationMetrics.checkpoint1DofPreserved = ...
    any(checkpoint1Dof.lqiCandidateTable.CandidateIndex == 25 & ...
    strcmp(checkpoint1Dof.lqiCandidateTable.Candidate, 'I25'));
validationMetrics.checkpoint2DofPreserved = ...
    checkpoint2Dof.bestStageBRow.CandidateIndex == 44 && ...
    strcmp(checkpoint2Dof.bestStageBRow.Candidate{1}, 'E16');
validationMetrics.feasibilityConclusion = feasibilityConclusion;

assert(height(stageC1CandidateTable) == 75 && ...
    isequal(unique(stageC1CandidateTable.Wq), config.stageC1.wq) && ...
    isequal(unique(stageC1CandidateTable.Wi), config.stageC1.wi) && ...
    isequal(unique(stageC1CandidateTable.RhoU), ...
    config.stageC1.rhoU), 'M7FinalFeasibility:IncompleteC1', ...
    'Stage C1 must contain the complete authorized 75-point grid.');
assert(height(stageC2CandidateTable) == ...
    height(selection.c1SeedTable) * ...
    numel(config.stageC2.wVelocity) && ...
    height(selection.c1SeedTable) <= ...
    config.maximumPromisingSeeds, ...
    'M7FinalFeasibility:InvalidC2Scope', ...
    'Stage C2 was not restricted to at most five promising C1 seeds.');
if ~isempty(stageC2CandidateTable)
    assert(all(ismember(stageC2CandidateTable.ParentCandidate, ...
        selection.c1SeedTable.Candidate)) && ...
        all(stageC2CandidateTable.Wdelta == config.stageC1.wdelta), ...
        'M7FinalFeasibility:InvalidC2Parent', ...
        'Stage C2 contains a non-promising parent or changed wdelta.');
end
assert(selection.stageC3Executed == selection.stageC3Necessary && ...
    height(stageC3CandidateTable) == ...
    height(selection.c2SeedTable) * ...
    numel(config.stageC3.wdelta) * selection.stageC3Executed, ...
    'M7FinalFeasibility:InvalidC3Scope', ...
    'Stage C3 was not conditioned or bounded as authorized.');
if ~isempty(stageC3CandidateTable)
    assert(all(ismember(stageC3CandidateTable.ParentCandidate, ...
        selection.c2SeedTable.Candidate)), ...
        'M7FinalFeasibility:InvalidC3Parent', ...
        'Stage C3 contains a parent outside the promising C2 set.');
end
assert(validationMetrics.physicalScalesUnchanged && ...
    validationMetrics.xiScaleUnchanged && ...
    validationMetrics.costBuiltFromCaugCost && ...
    validationMetrics.m5SourceUnchanged, ...
    'M7FinalFeasibility:NormalizationChanged', ...
    'A fixed physical scale, xiScale, M5 or the cost construction changed.');
assert(validationMetrics.allFeedforwardsValid && ...
    validationMetrics.maximumFeedforwardResidual <= ...
    config.feedforwardResidualTolerance, ...
    'M7FinalFeasibility:InvalidFeedforward', ...
    'At least one Nff is not derived consistently from its candidate Kx.');
assert(validationMetrics.allDisturbanceOffsetsPass, ...
    'M7FinalFeasibility:DisturbanceOffset', ...
    'At least one candidate does not remove both constant offsets.');
assert(stageExecution.noSearchBeyondC3, ...
    'M7FinalFeasibility:UnauthorizedExpansion', ...
    'A search beyond Stage C3 was attempted.');
assert(validationMetrics.checkpoint1DofPreserved && ...
    validationMetrics.checkpoint2DofPreserved, ...
    'M7FinalFeasibility:CheckpointMissing', ...
    'One of the two approved M7 checkpoints is unavailable.');

finalDatasetPath = fullfile(dataDirectory, 'm7_lqg_integral.mat');
if ~finalControllerBuilt
    assert(~isfile(finalDatasetPath), ...
        'M7FinalFeasibility:UnexpectedFinalController', ...
        'A final M7 controller exists despite a failed feasibility gate.');
end

localPlotPareto(allCandidateTable, paretoAllTable, m5.spec, ...
    fullfile(figureDirectory, 'm7_augmented_cost_pareto.png'));
localPlotTradeoff(allCandidateTable, bestC1SettlingRow, ...
    fullfile(figureDirectory, 'm7_augmented_cost_tradeoff.png'));

c1PromisingTable = selection.c1PromisingTable;
c1SeedTable = selection.c1SeedTable;
c2PromisingTable = selection.c2PromisingTable;
c2SeedTable = selection.c2SeedTable;
candidateDesigns = selection.designs;
datasetPath = fullfile(dataDirectory, ...
    'm7_augmented_cost_feasibility.mat');
save(datasetPath, 'stageC1CandidateTable', 'stageC2CandidateTable', ...
    'stageC3CandidateTable', 'allCandidateTable', 'paretoC1Table', ...
    'paretoAllTable', 'bestC1SettlingRow', 'bestC1OvershootRow', ...
    'bestSettlingWithOvershootTargetRow', 'minimumOvershootRow', ...
    'bestOvershootNearSettlingTargetRow', 'comparisonTable', ...
    'c1PromisingTable', 'c1SeedTable', 'c2PromisingTable', ...
    'c2SeedTable', 'candidateDesigns', 'stageExecution', ...
    'feasibilityConclusion', 'validationMetrics', '-v7');

fprintf('\n=== M7: co-tuning strutturato del costo augmentato ===\n');
fprintf(['C1: %d candidati, stable=%d, promising=%d, ' ...
    'admissible=%d.\n'], height(stageC1CandidateTable), ...
    sum(stageC1CandidateTable.Stable), ...
    height(c1PromisingTable), ...
    sum(stageC1CandidateTable.FundamentalPass));
fprintf(['C2: executed=%d, candidates=%d, promising=%d; ' ...
    'C3: necessary=%d, executed=%d, candidates=%d.\n'], ...
    selection.stageC2Executed, height(stageC2CandidateTable), ...
    height(c2PromisingTable), selection.stageC3Necessary, ...
    selection.stageC3Executed, height(stageC3CandidateTable));
fprintf(['Best C1 settling: %s, Ts=%.6g s, OS=%.6g%%, ' ...
    'peakU/uScale=%.6g, peakDelta/deltaScale=%.6g.\n'], ...
    bestC1SettlingRow.Candidate, ...
    bestC1SettlingRow.WorstSettlingTime, ...
    bestC1SettlingRow.WorstOvershoot, ...
    bestC1SettlingRow.PeakUNormalized, ...
    bestC1SettlingRow.PeakDeltaNormalized);
if ~isempty(bestSettlingWithOvershootTargetRow)
    fprintf('Best Ts with OS<=10%%: %s, Ts=%.6g s, OS=%.6g%%.\n', ...
        bestSettlingWithOvershootTargetRow.Candidate, ...
        bestSettlingWithOvershootTargetRow.WorstSettlingTime, ...
        bestSettlingWithOvershootTargetRow.WorstOvershoot);
else
    fprintf('Best Ts with OS<=10%%: no stable candidate observed.\n');
end
fprintf(['Closest finite Ts to 0.8 s: %s, Ts=%.6g s, ' ...
    'OS=%.6g%%.\n'], bestOvershootNearSettlingTargetRow.Candidate, ...
    bestOvershootNearSettlingTargetRow.WorstSettlingTime, ...
    bestOvershootNearSettlingTargetRow.WorstOvershoot);
fprintf('%s\n', feasibilityConclusion);
fprintf('Dataset: %s\n', datasetPath);
if finalControllerBuilt
    fprintf('[PASS] M7 completata con selezione dalla griglia.\n');
else
    fprintf(['[PARTIAL] Ultima feasibility M7 conclusa senza candidato; ' ...
        'stop prima di revisione M5, nessun M8.\n']);
end

metrics.config = config;
metrics.selection = selection;
metrics.stageC1CandidateTable = stageC1CandidateTable;
metrics.stageC2CandidateTable = stageC2CandidateTable;
metrics.stageC3CandidateTable = stageC3CandidateTable;
metrics.allCandidateTable = allCandidateTable;
metrics.comparisonTable = comparisonTable;
metrics.validationMetrics = validationMetrics;
metrics.datasetPath = datasetPath;
end

function stageName = localMaximumStage(stageExecution)
if stageExecution.c3Executed
    stageName = "Stage C3";
elseif stageExecution.c2Executed
    stageName = "Stage C2";
else
    stageName = "Stage C1";
end
end

function comparison = localBuildComparisonTable( ...
    m5, m6, checkpoint1Dof, checkpoint2Dof, selection, config)
controller = ["M6 no integrator"; "M7 checkpoint I25 1-DoF"; ...
    "M7 Stage B E16 2-DoF"; "M7 final"];
available = [true; true; true; ~isempty(selection.selectedIndex)];
trackingSettling = NaN(4, 1);
overshoot = NaN(4, 1);
peakControl = NaN(4, 1);
peakControlNormalized = NaN(4, 1);
peakDeformation = NaN(4, 1);
peakDeformationNormalized = NaN(4, 1);
disturbanceOffset = NaN(4, 1);
disturbanceSettling = NaN(4, 1);

trackingSettling(1) = max(m6.trackingMetrics.lqg.SettlingTime);
overshoot(1) = max(m6.trackingMetrics.lqg.Overshoot);
peakControl(1) = max(m6.trackingMetrics.lqg.PeakControl);
peakControlNormalized(1) = peakControl(1) / m5.spec.uScale;
peakDeformation(1) = localM6PeakDeformation( ...
    m6.lqgClosedLoop, m5.spec, config);
peakDeformationNormalized(1) = peakDeformation(1) / ...
    m6.validationMetrics.cost.scales.delta;
disturbanceOffset(1) = max(abs( ...
    m6.disturbanceMetrics.lqg.SteadyStateOffset));
disturbanceSettling(1) = max( ...
    m6.disturbanceMetrics.lqg.SettlingTime);

i25 = checkpoint1Dof.diagnosticCandidate;
trackingSettling(2) = i25.WorstSettlingTime;
overshoot(2) = i25.WorstOvershoot;
peakControl(2) = i25.PeakU;
peakControlNormalized(2) = i25.PeakUNormalized;
peakDeformation(2) = i25.PeakDelta;
peakDeformationNormalized(2) = i25.PeakDeltaNormalized;
disturbanceOffset(2) = i25.WorstDisturbanceSteadyStateOffset;
disturbanceSettling(2) = i25.WorstDisturbanceSettlingTime;

e16 = checkpoint2Dof.bestStageBRow;
trackingSettling(3) = e16.WorstSettlingTime;
overshoot(3) = e16.WorstOvershoot;
peakControl(3) = e16.PeakU;
peakControlNormalized(3) = e16.PeakUNormalized;
peakDeformation(3) = e16.PeakDelta;
peakDeformationNormalized(3) = e16.PeakDeltaNormalized;
disturbanceOffset(3) = e16.WorstDisturbanceSteadyStateOffset;
disturbanceSettling(3) = e16.WorstDisturbanceSettlingTime;

if available(4)
    final = selection.selectedRow;
    trackingSettling(4) = final.WorstSettlingTime;
    overshoot(4) = final.WorstOvershoot;
    peakControl(4) = final.PeakU;
    peakControlNormalized(4) = final.PeakUNormalized;
    peakDeformation(4) = final.PeakDelta;
    peakDeformationNormalized(4) = final.PeakDeltaNormalized;
    disturbanceOffset(4) = final.WorstDisturbanceSteadyStateOffset;
    disturbanceSettling(4) = final.WorstDisturbanceSettlingTime;
end
comparison = table(controller, available, trackingSettling, ...
    overshoot, peakControl, peakControlNormalized, peakDeformation, ...
    peakDeformationNormalized, disturbanceOffset, ...
    disturbanceSettling, 'VariableNames', {'Controller', 'Available', ...
    'TrackingSettling', 'Overshoot', 'PeakControl', ...
    'PeakControlNormalized', 'PeakDeformation', ...
    'PeakDeformationNormalized', 'DisturbanceOffset', ...
    'DisturbanceSettling'});
end

function peakDelta = localM6PeakDeformation(system, spec, config)
time = (0:config.simulationTimeStep:config.referenceHorizon).';
peakDelta = 0;
for jointIndex = 1:2
    input = zeros(numel(time), size(system, 2));
    input(:, jointIndex) = spec.referenceAmplitude;
    output = lsim(system, input, time);
    peakDelta = max(peakDelta, max(abs( ...
        output(:, 3:4) - output(:, 1:2)), [], 'all'));
end
end

function localPlotPareto(candidateTable, paretoTable, spec, filePath)
finiteMask = candidateTable.Stable & ...
    isfinite(candidateTable.WorstSettlingTime) & ...
    isfinite(candidateTable.WorstOvershoot);
figureHandle = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1120, 760]);
axesHandle = axes(figureHandle, 'Color', 'white', ...
    'XColor', 'black', 'YColor', 'black');
scatter(axesHandle, candidateTable.WorstSettlingTime(finiteMask), ...
    candidateTable.WorstOvershoot(finiteMask), 48, ...
    candidateTable.Wq(finiteMask), 'filled', ...
    'MarkerFaceAlpha', 0.55, 'DisplayName', 'candidati C1-C3');
hold(axesHandle, 'on');
plot(axesHandle, paretoTable.WorstSettlingTime, ...
    paretoTable.WorstOvershoot, ...
    '-o', 'Color', [0.85, 0.12, 0.10], 'LineWidth', 2, ...
    'MarkerFaceColor', [0.85, 0.12, 0.10], ...
    'DisplayName', 'frontiera di Pareto');
xline(axesHandle, spec.settlingTimeTarget, '--k', 'Ts target', ...
    'HandleVisibility', 'off', 'LabelColor', 'black');
yline(axesHandle, spec.overshootTarget, '--k', 'OS target', ...
    'HandleVisibility', 'off', 'LabelColor', 'black');
set(axesHandle, 'Color', 'white', ...
    'XColor', 'black', 'YColor', 'black');
grid(axesHandle, 'on'); box(axesHandle, 'on');
xlabel(axesHandle, 'Worst settling [s]');
ylabel(axesHandle, 'Worst overshoot [%]');
title(axesHandle, ...
    'M7 — Ultima feasibility: frontiera settling/overshoot', ...
    'Color', 'black');
colorbarHandle = colorbar(axesHandle);
colorbarHandle.Label.String = 'w_q';
colorbarHandle.Color = 'black';
legend(axesHandle, 'Location', 'best');
exportgraphics(figureHandle, filePath, 'Resolution', 180);
close(figureHandle);
end

function localPlotTradeoff(candidateTable, bestRow, filePath)
finiteMask = candidateTable.Stable & ...
    isfinite(candidateTable.WorstSettlingTime) & ...
    isfinite(candidateTable.WorstOvershoot);
tableData = candidateTable(finiteMask, :);
figureHandle = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1180, 820]);
layout = tiledlayout(figureHandle, 2, 1, 'TileSpacing', 'compact');
title(layout, ['M7 — Co-tuning fisicamente normalizzato: ' ...
    'comando, deformazione e prestazione'], 'Color', 'black');
axesHandle = nexttile;
set(axesHandle, 'Color', 'white', 'XColor', 'black', 'YColor', 'black');
scatter(axesHandle, tableData.PeakUNormalized, ...
    tableData.WorstSettlingTime, 55, tableData.WorstOvershoot, 'filled');
hold(axesHandle, 'on');
scatter(axesHandle, bestRow.PeakUNormalized, ...
    bestRow.WorstSettlingTime, 150, [0.85, 0.12, 0.10], ...
    'p', 'filled');
yline(axesHandle, 0.8, '--k', 'Ts target', ...
    'HandleVisibility', 'off', 'LabelColor', 'black');
set(axesHandle, 'Color', 'white', ...
    'XColor', 'black', 'YColor', 'black');
grid(axesHandle, 'on');
xlabel(axesHandle, 'peak |u| / uScale');
ylabel(axesHandle, 'Worst settling [s]');
colorbarHandle = colorbar(axesHandle);
colorbarHandle.Label.String = 'Worst overshoot [%]';
colorbarHandle.Color = 'black';

axesHandle = nexttile;
set(axesHandle, 'Color', 'white', 'XColor', 'black', 'YColor', 'black');
scatter(axesHandle, tableData.PeakDeltaNormalized, ...
    tableData.WorstOvershoot, 55, tableData.Wq, 'filled');
hold(axesHandle, 'on');
yline(axesHandle, 10, '--k', 'OS target', ...
    'HandleVisibility', 'off', 'LabelColor', 'black');
set(axesHandle, 'Color', 'white', ...
    'XColor', 'black', 'YColor', 'black');
grid(axesHandle, 'on');
xlabel(axesHandle, 'peak |theta-q| / deltaScale');
ylabel(axesHandle, 'Worst overshoot [%]');
colorbarHandle = colorbar(axesHandle);
colorbarHandle.Label.String = 'w_q';
colorbarHandle.Color = 'black';
exportgraphics(figureHandle, filePath, 'Resolution', 180);
close(figureHandle);
end
