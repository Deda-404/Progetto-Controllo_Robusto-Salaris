function metrics = validate_m11_hinfstruct
%VALIDATE_M11_HINFSTRUCT Execute and validate the finite M11 campaign.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));

dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory), mkdir(dataDirectory); end
if ~isfolder(figureDirectory), mkdir(figureDirectory); end

m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m5 = load(fullfile(dataDirectory, 'm5_performance_specs.mat'));
m6 = load(fullfile(dataDirectory, 'm6_lqg_no_integrator.mat'));
m9 = load(fullfile(dataDirectory, 'm9_hinf_mixsyn_nominal.mat'));
m10 = load(fullfile(dataDirectory, 'm10_hinfsyn_nominal.mat'));
config = hinfstruct_specs_m11;
plant = build_m9_nominal_plant(m3, m5, config);

regenerated = build_m10_generalized_plant( ...
    plant.G, m5.W1, m5.W2, config);
P = localClearNames(ss(m10.P));
regeneratedP = localClearNames(ss(regenerated.P));
generalizedPlantError = localMaximumFrequencyError( ...
    P, regeneratedP, config.frequencyGrid);
[~, regeneratedW1, ~, regeneratedW2] = build_m5_weights(m5.spec);
sourceAudit = struct( ...
    'baselineCommit', ...
        "47ea295aef28a941f2f443033c03f10c5a6caa4d", ...
    'm10Artifact', "results/data/m10_hinfsyn_nominal.mat", ...
    'm9Artifact', "results/data/m9_hinf_mixsyn_nominal.mat", ...
    'm9Gamma', m9.gamma, ...
    'generalizedPlantMaximumFrequencyError', generalizedPlantError, ...
    'W1TransferError', norm(m5.W1 - regeneratedW1, inf), ...
    'W2TransferError', norm(m5.W2 - regeneratedW2, inf), ...
    'gammaFullM10', m10.gammaHinf, ...
    'sameInputNames', isequal(string(m10.P.InputName), ...
        ["r(1)"; "r(2)"; "u(1)"; "u(2)"]), ...
    'sameOutputNames', isequal(string(m10.P.OutputName), ...
        ["z1(1)"; "z1(2)"; "z2(1)"; "z2(2)"; ...
        "e(1)"; "e(2)"]), ...
    'W3Absent', isempty(config.W3), ...
    'retuningPerformed', config.weightRetuningEnabled);
assert(generalizedPlantError <= ...
    config.generalizedPlantIdentityTolerance && ...
    sourceAudit.W1TransferError <= config.weightConsistencyTolerance && ...
    sourceAudit.W2TransferError <= config.weightConsistencyTolerance && ...
    sourceAudit.sameInputNames && sourceAudit.sameOutputNames && ...
    sourceAudit.W3Absent && ~sourceAudit.retuningPerformed, ...
    'M11:FrozenProblemMismatch', ...
    'M11 does not reproduce the frozen M10 generalized problem.');

campaign = run_m11_hinfstruct_campaign(P, plant.G, plant.Gd, ...
    m5.W1, m5.W2, m10.gammaHinf, config);
selection = select_m11_pareto_candidates(campaign, config);
representativeResults = evaluate_m11_representatives( ...
    campaign, m5, m6, config);

m10Audit = evaluate_m11_candidate(m10.Khinf, m10.gammaHinf, P, ...
    plant.G, plant.Gd, m5.W1, m5.W2, m10.gammaHinf, config);
m10Alias.controllerOrder = order(m10.Khinf);
m10Evaluation = evaluate_m9_closed_loop( ...
    m10Audit, m5, m6, m10Alias, config);
comparisonM6M9M10M11 = build_m11_comparison( ...
    representativeResults, m10);

[architectureGate, allRepresentativesReconstructed, ...
    anyWeightedPass, allTrackingPass, allCrossCouplingPass] = ...
    localArchitectureGate(campaign, representativeResults, config);
qualityGate = struct;
qualityGate.structuredCampaignCorrectness = localPassFail( ...
    campaign.correctlyExecuted && ...
    campaign.totalRequestedStarts == 30 && generalizedPlantError <= ...
        config.generalizedPlantIdentityTolerance);
qualityGate.internalStabilityAllStarts = localPassFail( ...
    campaign.totalStableStarts == campaign.totalReturnedStarts);
qualityGate.reconstruction = localPassFail( ...
    allRepresentativesReconstructed);
qualityGate.fullOrderLowerBoundSanity = localPassFail( ...
    campaign.lowerBoundViolationCount == 0);
qualityGate.weightedNominalPerformance = localPassFail(anyWeightedPass);
qualityGate.tracking = localPassFail(allTrackingPass);
qualityGate.crossCoupling = localPassFail(allCrossCouplingPass);
qualityGate.disturbance = "QUANTIFIED";
qualityGate.controlEffort = "QUANTIFIED_NO_SATURATION";
qualityGate.startVariability = "QUANTIFIED";
qualityGate.implementability = selection.representativeTable(:, ...
    {'ArchitectureID', 'ArchitectureType', 'Order', ...
    'ParameterCount', 'Stable', 'FamilyStatus'});
qualityGate.architectures = architectureGate;
qualityGate.softwareCorrectness = localPassFail( ...
    qualityGate.structuredCampaignCorrectness == "PASS" && ...
    qualityGate.reconstruction == "PASS" && ...
    qualityGate.fullOrderLowerBoundSanity == "PASS");
if qualityGate.softwareCorrectness == "PASS" && ...
        qualityGate.internalStabilityAllStarts == "PASS" && ...
        qualityGate.weightedNominalPerformance == "PASS" && ...
        qualityGate.tracking == "PASS" && ...
        qualityGate.crossCoupling == "PASS"
    qualityGate.overallStatus = "COMPLETE";
else
    qualityGate.overallStatus = "PARTIAL";
end

recommendation = struct( ...
    'outcome', selection.recommendation, ...
    'architectureIDs', selection.paretoArchitectureIDs, ...
    'requiresGroupReview', ~isempty(selection.paretoArchitectureIDs), ...
    'm12Authorized', false);
figurePaths = plot_m11_results(campaign, selection, ...
    representativeResults, m10, m10Evaluation, ...
    comparisonM6M9M10M11, figureDirectory, config);

architectureList = config.architectures;
variabilityTable = campaign.variabilityTable;
representativeTable = selection.representativeTable;
paretoTable = representativeTable(representativeTable.Pareto, :);
gammaFullM10 = m10.gammaHinf;
metadata = struct( ...
    'milestone', "M11", ...
    'nominalOnly', true, ...
    'sameGeneralizedPlantAsM10', true, ...
    'disturbanceInSynthesisObjective', false, ...
    'retuningPerformed', false, ...
    'W3Used', false, ...
    'twoDegreeOfFreedomUsed', false, ...
    'prefilterUsed', false, ...
    'robustAnalysisPerformed', false, ...
    'm12Started', false, ...
    'saturationEnabled', false);
datasetPath = fullfile(dataDirectory, ...
    'm11_hinfstruct_structured.mat');
save(datasetPath, 'config', 'architectureList', 'sourceAudit', ...
    'gammaFullM10', 'campaign', 'variabilityTable', ...
    'representativeResults', 'representativeTable', 'paretoTable', ...
    'comparisonM6M9M10M11', 'qualityGate', 'recommendation', ...
    'metadata', 'figurePaths', '-v7.3');

assert(qualityGate.softwareCorrectness == "PASS", ...
    'M11:SoftwareQualityGate', ...
    'The structured campaign failed a methodological software gate.');
assert(isfile(datasetPath) && all(structfun(@isfile, figurePaths)), ...
    'M11:Artifacts', 'One or more required M11 artifacts are missing.');

fprintf('\n=== Validazione M11: campagna hinfstruct A0-A5 ===\n');
fprintf(['P error=%.3e, gamma full M10=%.12g, starts returned=' ...
    '%d/%d, stable=%d\n'], generalizedPlantError, m10.gammaHinf, ...
    campaign.totalReturnedStarts, campaign.totalRequestedStarts, ...
    campaign.totalStableStarts);
for index = 1:height(variabilityTable)
    row = variabilityTable(index, :);
    fprintf(['%s: returned=%d, successful=%d, stable=%d, ' ...
        'best=%.12g, median=%.12g, worst=%.12g, status=%s\n'], ...
        row.ArchitectureID, row.ReturnedStarts, row.SuccessfulStarts, ...
        row.StableStarts, row.BestGamma, row.MedianGamma, ...
        row.WorstFiniteGamma, row.FamilyStatus);
end
fprintf('Pareto: %s; recommendation=%s\n', ...
    strjoin(selection.paretoArchitectureIDs, ','), ...
    selection.recommendation);
fprintf(['Gates: campaign=%s, all-start stability=%s, ' ...
    'reconstruction=%s, lower-bound=%s, weighted=%s, tracking=%s, ' ...
    'cross=%s; M11=%s\n'], ...
    qualityGate.structuredCampaignCorrectness, ...
    qualityGate.internalStabilityAllStarts, ...
    qualityGate.reconstruction, qualityGate.fullOrderLowerBoundSanity, ...
    qualityGate.weightedNominalPerformance, qualityGate.tracking, ...
    qualityGate.crossCoupling, qualityGate.overallStatus);
fprintf('Dataset: %s\n', datasetPath);

metrics.config = config;
metrics.sourceAudit = sourceAudit;
metrics.campaign = campaign;
metrics.selection = selection;
metrics.representativeResults = representativeResults;
metrics.comparison = comparisonM6M9M10M11;
metrics.qualityGate = qualityGate;
metrics.recommendation = recommendation;
metrics.figurePaths = figurePaths;
metrics.datasetPath = datasetPath;
end

function [gateTable, allReconstruction, anyWeightedPass, ...
    allTrackingPass, allCrossPass] = localArchitectureGate( ...
    campaign, representatives, config)
numberArchitectures = numel(campaign.architectureResults);
architectureID = strings(numberArchitectures, 1);
stableStarts = zeros(numberArchitectures, 1);
totalStarts = zeros(numberArchitectures, 1);
reconstruction = strings(numberArchitectures, 1);
weightedPerformance = strings(numberArchitectures, 1);
tracking = strings(numberArchitectures, 1);
crossCoupling = strings(numberArchitectures, 1);
allReconstruction = true;
availableRepresentatives = 0;
anyWeightedPass = false;
trackingPassValues = true(numberArchitectures, 1);
crossPassValues = true(numberArchitectures, 1);
for index = 1:numberArchitectures
    architectureID(index) = campaign.architectureResults(index).id;
    stableStarts(index) = sum([campaign.architectureResults(index). ...
        runs.internalStable]);
    totalStarts(index) = numel(campaign.architectureResults(index).runs);
    representative = representatives(index);
    if ~representative.available
        reconstruction(index) = "NOT RUN";
        weightedPerformance(index) = "NOT RUN";
        tracking(index) = "NOT RUN";
        crossCoupling(index) = "NOT RUN";
        trackingPassValues(index) = false;
        crossPassValues(index) = false;
        continue;
    end
    availableRepresentatives = availableRepresentatives + 1;
    metrics = representative.reconstruction.metrics;
    reconstruction(index) = localPassFail( ...
        metrics.objectiveRelativeError <= ...
            config.objectiveRelativeTolerance && ...
        metrics.closedLoopError <= config.closedLoopConsistencyTolerance);
    weightedPerformance(index) = localPassFail( ...
        metrics.weightedNorm < 1);
    targets = representative.evaluation.trackingTargets;
    tracking(index) = localPassFail(targets.passed);
    crossCoupling(index) = localPassFail(targets.crossCouplingPassed);
    allReconstruction = allReconstruction && ...
        reconstruction(index) == "PASS";
    anyWeightedPass = anyWeightedPass || ...
        weightedPerformance(index) == "PASS";
    trackingPassValues(index) = targets.passed;
    crossPassValues(index) = targets.crossCouplingPassed;
end
allReconstruction = allReconstruction && availableRepresentatives > 0;
allTrackingPass = all(trackingPassValues);
allCrossPass = all(crossPassValues);
gateTable = table(architectureID, stableStarts, totalStarts, ...
    reconstruction, weightedPerformance, tracking, crossCoupling);
end

function maximumError = localMaximumFrequencyError(first, second, frequencies)
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
maximumError = max(abs(difference), [], 'all');
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function status = localPassFail(condition)
if condition
    status = "PASS";
else
    status = "FAIL";
end
end
