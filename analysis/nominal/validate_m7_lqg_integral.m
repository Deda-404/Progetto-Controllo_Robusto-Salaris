function metrics = validate_m7_lqg_integral
%VALIDATE_M7_LQG_INTEGRAL Validate the authorized M7 2-DoF feasibility run.
%   The original 1-DoF PARTIAL checkpoint is preserved. Stage A adds a
%   candidate-specific reference feedforward to the same 28 designs. Since
%   Stage A fails, exactly one 25-candidate Stage B is evaluated. No final
%   LQG-I controller is published when both stages are infeasible.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m5 = load(fullfile(dataDirectory, 'm5_performance_specs.mat'));
m6 = load(fullfile(dataDirectory, 'm6_lqg_no_integrator.mat'));
checkpoint = load(fullfile(dataDirectory, 'm7_lqi_grid_partial.mat'));
config = lqg_specs_m7;
selection = select_lqi_integral(m3, m5, m6, config);

stageACandidateTable = selection.stageA.candidateTable;
assert(selection.stageBExecuted, 'M7Completion:UnexpectedStageAPass', ...
    'Stage B must execute only because Stage A has no admissible design.');
stageBCandidateTable = selection.stageB.candidateTable;

[bestStageASettling, bestStageAIndex] = min( ...
    stageACandidateTable.WorstSettlingTime);
[bestStageBSettling, bestStageBIndex] = min( ...
    stageBCandidateTable.WorstSettlingTime);
bestStageARow = stageACandidateTable(bestStageAIndex, :);
bestStageBRow = stageBCandidateTable(bestStageBIndex, :);
bestStageBDesign = selection.stageB.designs{bestStageBIndex};
bestStageBNff = selection.stageB.nff{bestStageBIndex};

feasibilityTable = sortrows(stageBCandidateTable, ...
    {'WorstSettlingTime', 'WorstOvershoot', 'PeakUNormalized', ...
    'CandidateIndex'}, {'ascend', 'ascend', 'ascend', 'ascend'});
feasibilityTable = feasibilityTable(:, {'Candidate', 'Wi', 'RhoU', ...
    'WorstSettlingTime', 'WorstOvershoot', 'PeakU', ...
    'PeakUNormalized', 'PeakDelta', 'PeakDeltaNormalized', ...
    'NormKx', 'NormKi', 'NormNff', 'Nff11', 'Nff12', ...
    'Nff21', 'Nff22', 'DominantRealPart', ...
    'DominantImaginaryMagnitude'});

feedforwardComparison = stageACandidateTable(:, {'Candidate', 'Wi', ...
    'RhoU', 'OneDofWorstSettlingTime', 'WorstSettlingTime', ...
    'OneDofWorstOvershoot', 'WorstOvershoot', 'OneDofPeakU', ...
    'PeakU', 'OneDofPeakXi', 'PeakXi', 'OneDofDisturbanceOffset', ...
    'WorstDisturbanceSteadyStateOffset', ...
    'DisturbanceOffsetNffDifference'});

validationMetrics.status = "PARTIAL";
validationMetrics.reason = ...
    "Stage A and the single authorized Stage B are both infeasible";
validationMetrics.previousCheckpointPreserved = isfile(fullfile( ...
    dataDirectory, 'm7_lqi_grid_partial.mat'));
validationMetrics.previousCheckpointCandidate = ...
    checkpoint.diagnosticCandidate;
validationMetrics.stageA.candidateCount = height(stageACandidateTable);
validationMetrics.stageA.stableCount = sum(stageACandidateTable.Stable);
validationMetrics.stageA.admissibleCount = ...
    sum(stageACandidateTable.FundamentalPass);
validationMetrics.stageA.bestRow = bestStageARow;
validationMetrics.stageA.bestSettling = bestStageASettling;
validationMetrics.stageB.executed = selection.stageBExecuted;
validationMetrics.stageB.candidateCount = height(stageBCandidateTable);
validationMetrics.stageB.stableCount = sum(stageBCandidateTable.Stable);
validationMetrics.stageB.admissibleCount = ...
    sum(stageBCandidateTable.FundamentalPass);
validationMetrics.stageB.bestRow = bestStageBRow;
validationMetrics.stageB.bestSettling = bestStageBSettling;
validationMetrics.feedforward.maximumResidual = max( ...
    selection.lqiCandidateTable.FeedforwardResidual);
validationMetrics.feedforward.maximumCondition = max( ...
    selection.lqiCandidateTable.GdcCondition);
validationMetrics.feedforward.allWellConditioned = all( ...
    selection.lqiCandidateTable.FeedforwardWellConditioned);
validationMetrics.feedforward.maximumDisturbanceOffsetDifference = ...
    max(selection.lqiCandidateTable.DisturbanceOffsetNffDifference);
validationMetrics.feedforward.bestStageANff = ...
    selection.stageA.nff{bestStageAIndex};
validationMetrics.feedforward.bestStageBNff = bestStageBNff;
validationMetrics.m6CostExactReuse = all(cellfun(@(design) isequal( ...
    design.Qaug(1:14, 1:14), m6.Q), selection.designs));
validationMetrics.m5SourceUnchanged = isequaln(m5.spec, performance_specs_m5);
validationMetrics.noAutomaticM5Change = true;
validationMetrics.finalControllerBuilt = false;
validationMetrics.selectedCandidateExists = ~isempty( ...
    selection.selectedIndex);
validationMetrics.antiWindupEnabled = config.antiWindupEnabled;
validationMetrics.saturationEnabled = config.saturationEnabled;

assert(height(stageACandidateTable) == 28 && ...
    isequal(unique(stageACandidateTable.Wi), config.wiCandidates) && ...
    isequal(unique(stageACandidateTable.RhoU), ...
    config.rhoUCandidates), 'M7Completion:StageAGrid', ...
    'Stage A did not reproduce the complete checkpoint grid first.');
assert(height(stageBCandidateTable) == 25 && ...
    isequal(unique(stageBCandidateTable.Wi), ...
    config.stageBWiCandidates) && ...
    isequal(unique(stageBCandidateTable.RhoU), ...
    config.stageBRhoUCandidates), 'M7Completion:StageBGrid', ...
    'The single authorized Stage B grid is incomplete.');
assert(all(stageACandidateTable.Stable) && ...
    all(stageBCandidateTable.Stable), 'M7Completion:Stability', ...
    'At least one evaluated candidate is unstable.');
assert(validationMetrics.feedforward.allWellConditioned && ...
    validationMetrics.feedforward.maximumResidual <= ...
    config.feedforwardResidualTolerance, 'M7Completion:Feedforward', ...
    'A candidate feedforward is ill-conditioned or inconsistent at DC.');
assert(validationMetrics.feedforward.maximumDisturbanceOffsetDifference ...
    <= 10 * eps && all(selection.lqiCandidateTable. ...
    WorstDisturbanceSteadyStateOffset <= ...
    config.disturbanceSteadyStateTolerance), ...
    'M7Completion:DisturbanceIndependence', ...
    'Nff changed the DC disturbance rejection supplied by the integrator.');
assert(validationMetrics.m6CostExactReuse && ...
    validationMetrics.m5SourceUnchanged, 'M7Completion:BaselineChanged', ...
    'M6 Q or the M5 source of truth changed during M7 completion.');
assert(validationMetrics.stageA.admissibleCount == 0 && ...
    validationMetrics.stageB.admissibleCount == 0 && ...
    isempty(selection.selectedIndex), 'M7Completion:UnexpectedSelection', ...
    'An inadmissible or extreme candidate was promoted unexpectedly.');

localPlotCandidateFeasibility(stageACandidateTable, ...
    stageBCandidateTable, bestStageBIndex, m5.spec, fullfile( ...
    figureDirectory, 'm7_lqi_candidate_comparison.png'));
localPlotFeedforwardEffect(selection.stageA, bestStageAIndex, ...
    m5.spec, fullfile(figureDirectory, ...
    'm7_lqi_feedforward_effect.png'));

datasetPath = fullfile(dataDirectory, 'm7_lqi_2dof_feasibility.mat');
save(datasetPath, 'stageACandidateTable', 'stageBCandidateTable', ...
    'feasibilityTable', 'feedforwardComparison', 'bestStageARow', ...
    'bestStageBRow', 'bestStageBDesign', 'bestStageBNff', ...
    'validationMetrics', '-v7');

fprintf('\n=== M7 completion: servo LQI 2-DoF feasibility ===\n');
fprintf(['Stage A: %d candidates, stable=%d, admissible=%d; ' ...
    'best settling %.6g s (%s).\n'], height(stageACandidateTable), ...
    sum(stageACandidateTable.Stable), ...
    sum(stageACandidateTable.FundamentalPass), ...
    bestStageASettling, bestStageARow.Candidate{1});
fprintf(['Stage B: %d candidates, stable=%d, admissible=%d; ' ...
    'best %s wi=%.3g rhoU=%.3g, settling=%.6g s, ' ...
    'overshoot=%.6g%%, peakU/uScale=%.6g.\n'], ...
    height(stageBCandidateTable), sum(stageBCandidateTable.Stable), ...
    sum(stageBCandidateTable.FundamentalPass), ...
    bestStageBRow.Candidate{1}, bestStageBRow.Wi, ...
    bestStageBRow.RhoU, bestStageBRow.WorstSettlingTime, ...
    bestStageBRow.WorstOvershoot, bestStageBRow.PeakUNormalized);
fprintf(['Nff: max cond(Gdc_x)=%.6g, max residual=%.3e; ' ...
    'max change in DC disturbance offset=%.3e rad.\n'], ...
    validationMetrics.feedforward.maximumCondition, ...
    validationMetrics.feedforward.maximumResidual, ...
    validationMetrics.feedforward.maximumDisturbanceOffsetDifference);
fprintf(['[PARTIAL] Stage A e Stage B non soddisfano il gate; ' ...
    'M5 invariata, nessun controllore finale pubblicato.\n']);

metrics.config = config;
metrics.selection = selection;
metrics.stageACandidateTable = stageACandidateTable;
metrics.stageBCandidateTable = stageBCandidateTable;
metrics.feasibilityTable = feasibilityTable;
metrics.feedforwardComparison = feedforwardComparison;
metrics.validationMetrics = validationMetrics;
metrics.datasetPath = datasetPath;
end

function localPlotCandidateFeasibility(stageA, stageB, ...
    bestStageBIndex, spec, filePath)
figureHandle = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1180, 800]);
layout = tiledlayout(figureHandle, 2, 1, 'TileSpacing', 'compact');
title(layout, ['M7 — Servo 2-DoF: Stage A e Stage B ' ...
    'senza candidati ammissibili']);

axesHandle = nexttile;
plotSettling = stageA.WorstSettlingTime;
plotSettling(~isfinite(plotSettling)) = 3.2;
scatter(axesHandle, stageA.Wi, plotSettling, 60, stageA.RhoU, 'filled');
hold(axesHandle, 'on');
yline(axesHandle, spec.settlingTimeTarget, '--r', 'settling target', ...
    'HandleVisibility', 'off');
grid(axesHandle, 'on');
xlabel(axesHandle, 'w_i — Stage A');
ylabel(axesHandle, 'Worst settling [s] (Inf clipped)');
colorbarHandle = colorbar(axesHandle);
colorbarHandle.Label.String = 'rho_U';

axesHandle = nexttile;
scatter(axesHandle, stageB.WorstSettlingTime, stageB.WorstOvershoot, ...
    70, stageB.PeakUNormalized, 'filled');
hold(axesHandle, 'on');
xline(axesHandle, spec.settlingTimeTarget, '--r', 'settling target', ...
    'HandleVisibility', 'off');
yline(axesHandle, spec.overshootTarget, '--r', 'overshoot target', ...
    'HandleVisibility', 'off');
scatter(axesHandle, stageB.WorstSettlingTime(bestStageBIndex), ...
    stageB.WorstOvershoot(bestStageBIndex), 150, ...
    [0.90, 0.15, 0.10], 'p', 'filled');
grid(axesHandle, 'on');
xlabel(axesHandle, 'Worst settling [s] — Stage B');
ylabel(axesHandle, 'Worst overshoot [%]');
colorbarHandle = colorbar(axesHandle);
colorbarHandle.Label.String = 'peak |u| / u_{scale}';
exportgraphics(figureHandle, filePath, 'Resolution', 180);
close(figureHandle);
end

function localPlotFeedforwardEffect(stageA, representativeIndex, spec, filePath)
oneDof = stageA.oneDofEvaluations{representativeIndex};
twoDof = stageA.evaluations{representativeIndex};
candidate = stageA.candidateTable(representativeIndex, :);
figureHandle = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1180, 800]);
layout = tiledlayout(figureHandle, 2, 1, 'TileSpacing', 'compact');
title(layout, sprintf(['M7 — Effetto Nff su %s (wi=%g, rho_U=%g); ' ...
    'punto diagnostico, non selezionato'], candidate.Candidate{1}, ...
    candidate.Wi, candidate.RhoU));

axesHandle = nexttile;
plot(axesHandle, oneDof.referenceTime, rad2deg( ...
    oneDof.referenceOutput{1}(:, 1)), '--', 'LineWidth', 1.7, ...
    'DisplayName', '1-DoF, Nff=0');
hold(axesHandle, 'on');
plot(axesHandle, twoDof.referenceTime, rad2deg( ...
    twoDof.referenceOutput{1}(:, 1)), 'LineWidth', 1.8, ...
    'DisplayName', '2-DoF, Nff candidato');
yline(axesHandle, rad2deg(spec.referenceAmplitude), ':k', ...
    'r_1', 'HandleVisibility', 'off');
grid(axesHandle, 'on'); ylabel(axesHandle, 'q_1 [deg]');
legend(axesHandle, 'Location', 'best');

axesHandle = nexttile;
plot(axesHandle, oneDof.disturbanceTime, rad2deg( ...
    oneDof.disturbanceOutput{1}(:, 1)), '--', 'LineWidth', 1.7, ...
    'DisplayName', '1-DoF, Nff=0');
hold(axesHandle, 'on');
plot(axesHandle, twoDof.disturbanceTime, rad2deg( ...
    twoDof.disturbanceOutput{1}(:, 1)), 'LineWidth', 1.4, ...
    'DisplayName', '2-DoF, Nff candidato');
grid(axesHandle, 'on'); xlabel(axesHandle, 'Tempo [s]');
ylabel(axesHandle, 'q_1 sotto d_1 [deg]');
legend(axesHandle, 'Location', 'best');
exportgraphics(figureHandle, filePath, 'Resolution', 180);
close(figureHandle);
end
