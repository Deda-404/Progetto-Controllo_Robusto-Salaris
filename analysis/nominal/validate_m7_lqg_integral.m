function metrics = validate_m7_lqg_integral
%VALIDATE_M7_LQG_INTEGRAL Validate the M7 LQI grid checkpoint.
%   The prescribed grid currently has no fundamental-admissible candidate.
%   This routine therefore records a PARTIAL checkpoint and deliberately
%   does not synthesize or publish a final LQG-I controller.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

m3Path = fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat');
m5Path = fullfile(dataDirectory, 'm5_performance_specs.mat');
m6Path = fullfile(dataDirectory, 'm6_lqg_no_integrator.mat');
assert(isfile(m3Path) && isfile(m5Path) && isfile(m6Path), ...
    'M7:ApprovedInputsMissing', ...
    'Approved M3, M5 and M6 datasets are required before M7.');
m3 = load(m3Path);
m5 = load(m5Path);
m6 = load(m6Path);
config = lqg_specs_m7;

selection = select_lqi_integral(m3, m5, m6, config);
lqiCandidateTable = selection.lqiCandidateTable;
[bestSettlingTime, diagnosticIndex] = min( ...
    lqiCandidateTable.WorstSettlingTime);
diagnosticDesign = selection.designs{diagnosticIndex};
diagnosticEvaluation = selection.evaluations{diagnosticIndex};
diagnosticCandidate = lqiCandidateTable(diagnosticIndex, :);

validationMetrics.status = "PARTIAL";
validationMetrics.reason = ...
    "no grid candidate meets the M5 tracking settling-time target";
validationMetrics.candidateCount = height(lqiCandidateTable);
validationMetrics.admissibleCandidateCount = ...
    sum(lqiCandidateTable.FundamentalPass);
validationMetrics.stableCandidateCount = sum(lqiCandidateTable.Stable);
validationMetrics.trackingPassCount = sum(lqiCandidateTable.TrackingPass);
validationMetrics.disturbancePassCount = ...
    sum(lqiCandidateTable.DisturbancePass);
validationMetrics.bestSettlingTime = bestSettlingTime;
validationMetrics.settlingTarget = m5.spec.settlingTimeTarget;
validationMetrics.settlingGap = ...
    bestSettlingTime - m5.spec.settlingTimeTarget;
validationMetrics.diagnosticIndex = diagnosticIndex;
validationMetrics.diagnosticCandidate = diagnosticCandidate;
validationMetrics.xiScale = diagnosticDesign.xiScale;
validationMetrics.m6CostExactReuse = isequal( ...
    diagnosticDesign.Qaug(1:14, 1:14), m6.Q);
validationMetrics.augmentedControllablePbh = ...
    diagnosticDesign.structural.controllablePbh;
validationMetrics.augmentedStabilizable = ...
    diagnosticDesign.structural.isStabilizable;
validationMetrics.zeroPbhRank = ...
    diagnosticDesign.structural.zeroPbhRank;
validationMetrics.zeroRosenbrockRank = ...
    diagnosticDesign.structural.zeroRosenbrockRank;
validationMetrics.rawControllabilityMatrixRank = ...
    diagnosticDesign.structural.controllabilityRank;
validationMetrics.m6DisturbanceOffsets = ...
    m6.disturbanceMetrics.lqg.SteadyStateOffset;
validationMetrics.diagnosticDisturbanceOffsets = ...
    diagnosticEvaluation.disturbanceMetrics.SteadyStateOffset;
validationMetrics.diagnosticFinalSimulatedOffsets = [ ...
    diagnosticEvaluation.disturbanceOutput{1}(end, 1); ...
    diagnosticEvaluation.disturbanceOutput{2}(end, 2)];
validationMetrics.noAutomaticM5Change = true;
validationMetrics.finalControllerBuilt = false;
validationMetrics.antiWindupEnabled = config.antiWindupEnabled;
validationMetrics.saturationEnabled = config.saturationEnabled;

assert(height(lqiCandidateTable) == 28, 'M7:GridSize', ...
    'The prescribed 7-by-4 LQI grid was not evaluated completely.');
assert(all(lqiCandidateTable.Stable), 'M7:CandidateStability', ...
    'At least one prescribed LQI candidate is unstable.');
assert(validationMetrics.augmentedStabilizable && ...
    validationMetrics.zeroPbhRank == 16 && ...
    validationMetrics.zeroRosenbrockRank == 16, ...
    'M7:AugmentedStructure', ...
    'The augmented plant failed the PBH or zero-obstruction check.');
assert(validationMetrics.m6CostExactReuse, 'M7:M6CostReuse', ...
    'The M6 physical-state cost was not reused exactly.');
assert(validationMetrics.disturbancePassCount == 28, ...
    'M7:DisturbanceRejection', ...
    'Not every stable grid candidate eliminates the DC disturbance offset.');
assert(isempty(selection.selectedIndex) && ...
    validationMetrics.admissibleCandidateCount == 0, ...
    'M7:UnexpectedSelection', ...
    'A candidate unexpectedly satisfies the complete M7 gate.');

localPlotPartialGrid(lqiCandidateTable, diagnosticIndex, m5.spec, ...
    fullfile(figureDirectory, 'm7_lqi_candidate_comparison.png'));

partialDatasetPath = fullfile(dataDirectory, ...
    'm7_lqi_grid_partial.mat');
Aaug = diagnosticDesign.Aaug;
Baug = diagnosticDesign.Baug;
QaugDiagnostic = diagnosticDesign.Qaug;
RDiagnostic = diagnosticDesign.R;
KaugDiagnostic = diagnosticDesign.Kaug;
save(partialDatasetPath, 'Aaug', 'Baug', 'QaugDiagnostic', ...
    'RDiagnostic', 'KaugDiagnostic', 'lqiCandidateTable', ...
    'diagnosticCandidate', 'validationMetrics', '-v7');

fprintf('\n=== Checkpoint M7: griglia LQI con due integratori ===\n');
fprintf(['Augmented plant: 16 states, PBH controllable=%d, ' ...
    'stabilizable=%d, zero PBH rank=%d, Rosenbrock rank=%d\n'], ...
    validationMetrics.augmentedControllablePbh, ...
    validationMetrics.augmentedStabilizable, ...
    validationMetrics.zeroPbhRank, ...
    validationMetrics.zeroRosenbrockRank);
fprintf(['Grid: %d candidates, stable=%d, disturbance PASS=%d, ' ...
    'tracking PASS=%d, fundamental-admissible=%d\n'], ...
    validationMetrics.candidateCount, ...
    validationMetrics.stableCandidateCount, ...
    validationMetrics.disturbancePassCount, ...
    validationMetrics.trackingPassCount, ...
    validationMetrics.admissibleCandidateCount);
fprintf(['Closest tracking candidate: %s, wi=%.3g, rhoU=%.3g, ' ...
    'settling=%.6g s (target %.3g s), peakU/uScale=%.6g\n'], ...
    diagnosticCandidate.Candidate{1}, diagnosticCandidate.Wi, ...
    diagnosticCandidate.RhoU, diagnosticCandidate.WorstSettlingTime, ...
    m5.spec.settlingTimeTarget, diagnosticCandidate.PeakUNormalized);
fprintf(['M6 offsets [%.9g %.9g] rad -> diagnostic M7 DC offsets ' ...
    '[%.3e %.3e] rad.\n'], validationMetrics.m6DisturbanceOffsets(1), ...
    validationMetrics.m6DisturbanceOffsets(2), ...
    validationMetrics.diagnosticDisturbanceOffsets(1), ...
    validationMetrics.diagnosticDisturbanceOffsets(2));
fprintf('[PARTIAL] Nessun candidato soddisfa insieme tracking e disturbo.\n');
fprintf(['M5 non e'' stato modificato e nessun controllore LQG-I finale ' ...
    'e'' stato pubblicato.\n']);

metrics.config = config;
metrics.selection = selection;
metrics.diagnosticDesign = diagnosticDesign;
metrics.diagnosticEvaluation = diagnosticEvaluation;
metrics.validationMetrics = validationMetrics;
metrics.partialDatasetPath = partialDatasetPath;
end

function localPlotPartialGrid(candidateTable, diagnosticIndex, spec, filePath)
plotSettling = candidateTable.WorstSettlingTime;
finiteSettling = plotSettling(isfinite(plotSettling));
clippedValue = max(finiteSettling) + 0.25;
plotSettling(~isfinite(plotSettling)) = clippedValue;
figureHandle = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1150, 780]);
layout = tiledlayout(figureHandle, 2, 1, 'TileSpacing', 'compact');
title(layout, ['M7 — Griglia LQI prescritta: nessun candidato ' ...
    'raggiunge il target di tracking']);

axesHandle = nexttile;
for rhoU = unique(candidateTable.RhoU).'
    mask = candidateTable.RhoU == rhoU;
    semilogx(axesHandle, candidateTable.Wi(mask), ...
        plotSettling(mask), '-o', ...
        'LineWidth', 1.5, 'DisplayName', sprintf('rho_U=%g', rhoU));
    hold(axesHandle, 'on');
end
yline(axesHandle, spec.settlingTimeTarget, '--r', 'target M5 0.8 s', ...
    'HandleVisibility', 'off');
scatter(axesHandle, candidateTable.Wi(diagnosticIndex), ...
    candidateTable.WorstSettlingTime(diagnosticIndex), 140, ...
    [0.85, 0.15, 0.10], 'p', 'filled', ...
    'DisplayName', 'minimo settling nella griglia');
grid(axesHandle, 'on');
ylabel(axesHandle, 'Worst settling [s] (Inf clipped)');
legend(axesHandle, 'Location', 'bestoutside');

axesHandle = nexttile;
scatter(axesHandle, candidateTable.PeakUNormalized, ...
    plotSettling, 55, candidateTable.Wi, 'filled');
hold(axesHandle, 'on');
yline(axesHandle, spec.settlingTimeTarget, '--r', 'target M5', ...
    'HandleVisibility', 'off');
scatter(axesHandle, candidateTable.PeakUNormalized(diagnosticIndex), ...
    candidateTable.WorstSettlingTime(diagnosticIndex), 140, ...
    [0.85, 0.15, 0.10], 'p', 'filled');
grid(axesHandle, 'on');
xlabel(axesHandle, 'Picco |u| / u_{scale}');
ylabel(axesHandle, 'Worst settling [s] (Inf clipped)');
colorbarHandle = colorbar(axesHandle);
colorbarHandle.Label.String = 'w_i';
exportgraphics(figureHandle, filePath, 'Resolution', 180);
close(figureHandle);
end
