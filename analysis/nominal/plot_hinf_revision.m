function plot_hinf_revision
%PLOT_HINF_REVISION Esporta soltanto le nuove figure e tabelle dello studio.
radice=fileparts(fileparts(fileparts(mfilename('fullpath'))));
a=load(fullfile(radice,'results','data','hinf_weight_revision.mat'));
studio=a.studio; j=studio.selezionato; r=studio.mappe{j}; w=studio.pesi{j};
omega=studio.diagnosi.omega; tempo=studio.tempo;

f=figure('Visible','off','Color','white','Position',[100 100 1150 480]);
tiledlayout(1,2,'TileSpacing','compact');
nexttile;
semilogx(omega,sigma(r.S,omega),'LineWidth',1.3); hold on;
semilogx(omega,1./squeeze(abs(freqresp(w.W1(1,1),omega))),'--k','LineWidth',1.5);
grid on; xlabel('Frequenza [rad/s]'); ylabel('Valore singolare / limite');
title('S: due direzioni singolari e inviluppo 1/|W_1|');
legend('sigma_1(S)','sigma_2(S)','1/|W_1|','Location','best');
nexttile;
semilogx(omega,sigma(r.T,omega),'LineWidth',1.3); hold on;
semilogx(omega,1./squeeze(abs(freqresp(w.W3(1,1),omega))),'--k','LineWidth',1.5);
grid on; xlabel('Frequenza [rad/s]'); ylabel('Valore singolare / limite');
title('T: due direzioni singolari e inviluppo 1/|W_3|');
legend('sigma_1(T)','sigma_2(T)','1/|W_3|','Location','best');
localSalva(f,'hinf_revision_sensitivity_envelopes.png',radice);

f=figure('Visible','off','Color','white','Position',[100 100 1000 480]);
mappe={w.W1*r.S,w.W2*r.KS,w.W3*r.T}; hold on;
for k=1:3
    sv=sigma(mappe{k},omega);
    semilogx(omega,sv(1,:),'LineWidth',1.5);
end
set(gca,'XScale','log');
yline(1,'--k','Target normalizzato','HandleVisibility','off');
grid on; xlabel('Frequenza [rad/s]'); ylabel('Massimo valore singolare');
legend('W_1 S','W_2 KS','W_3 T','Location','best');
title('Candidato illustrativo: i superamenti di uno restano visibili');
localSalva(f,'hinf_revision_weighted_channels.png',radice);

f=figure('Visible','off','Color','white','Position',[100 100 1150 700]);
tiledlayout(2,2,'TileSpacing','compact','Padding','compact');
for giunto=1:2
    y=r.risposte{giunto};
    nexttile(giunto);
    plot(tempo,rad2deg(y(:,1:2)),'LineWidth',1.3); hold on;
    yline(rad2deg(studio.spec.referenceAmplitude),'--k','HandleVisibility','off');
    grid on; xlabel('Tempo [s]'); ylabel('Delta q [deg]');
    title(sprintf('r_%d=5 deg, altro r=0, d=0, x0=0',giunto));
    legend('q_1','q_2','Location','best');
    nexttile(giunto+2);
    plot(tempo,y(:,3:4),'LineWidth',1.3);
    grid on; xlabel('Tempo [s]'); ylabel('Comando [N m]');
    title(sprintf('Comando per il gradino al giunto %d',giunto));
    legend('u_1','u_2','Location','best');
end
localSalva(f,'hinf_revision_tracking_control.png',radice);

f=figure('Visible','off','Color','white','Position',[100 100 1200 430]);
tiledlayout(1,3,'TileSpacing','compact');
originali={studio.pesi{1}.W1,studio.pesi{1}.W2,studio.pesi{1}.W3};
nuovi={w.W1,w.W2,w.W3}; titoli=["W_1: errore","W_2: comando fisico","W_3: roll-off"];
for k=1:3
    nexttile; hold on;
    if k<3
        semilogx(omega,squeeze(abs(freqresp(originali{k}(1,1),omega))), ...
            '--','LineWidth',1.4,'DisplayName','Originale');
    end
    semilogx(omega,squeeze(abs(freqresp(nuovi{k}(1,1),omega))), ...
        'LineWidth',1.4,'DisplayName','Studio');
    set(gca,'XScale','log','YScale','log','XLim',[omega(1) omega(end)], ...
        'XTick',10.^(-3:1:3)); grid on;
    xlabel('Frequenza [rad/s]'); ylabel('Modulo del peso');
    title(titoli(k)); legend('Location','best');
end
localSalva(f,'hinf_revision_weights.png',radice);

t=studio.tabella;
righe=["% Generated by plot_hinf_revision.m.";
    "\begin{table}[htbp]\centering\small";
    "\begin{tabular}{rrrrrrrr}\toprule";
    "ID & $\omega_B$ & $\beta_U$ & $\omega_T$ & $\gamma$ & OS [\%] & picco $u$ & stabili/5 \\\midrule"];
for k=1:height(t)
    righe=[righe;join([localNumero(t.Id(k)),localNumero(t.OmegaB(k)), ...
        localNumero(t.BetaU(k)),localNumero(t.OmegaT(k)),localNumero(t.Gamma(k)), ...
        localNumero(t.OvershootPercent(k)),localNumero(t.PeakControlNm(k)), ...
        localNumero(t.StableSamples(k))]," & ")+" \\"]; %#ok<AGROW>
end
righe=[righe;"\bottomrule\end{tabular}";
    "\caption{Campagna deterministica. ID 0 è la baseline ricaricata; ID 1 isola la nuova scala di comando senza $W_3$. Le frequenze sono in rad/s, il comando in N m. Tutti sono nominalmente stabili; nessuno supera tutti i target M5. I cinque campioni M4 non certificano robustezza.}";
    "\label{tab:hinf-campagna}\end{table}";
    "\begin{table}[htbp]\centering\small";
    "\begin{tabular}{lrr}\toprule";
    "Metrica & M10 originale & candidato illustrativo \\\midrule"];
etichette=["$\gamma$";"$\|W_1S\|_\infty$";"$\|W_2KS\|_\infty$";"$\|W_3T\|_\infty$"; ...
    "$T_s$ [s]";"Overshoot [\%]";"Errore statico relativo";"Cross-coupling"; ...
    "Picco comando [N m]";"RMS comando [N m]";"Ordine"];
variabili=["Gamma","W1SNorm","W2KSNorm","W3TNorm","SettlingTime", ...
    "OvershootPercent","SteadyErrorRelative","CrossCoupling","PeakControlNm","RmsControlNm","Ordine"];
for k=1:numel(variabili)
    righe=[righe;etichette(k)+" & "+localNumero(t{1,variabili(k)})+" & "+ ...
        localNumero(t{j,variabili(k)})+" \\"]; %#ok<AGROW>
end
righe=[righe;"\bottomrule\end{tabular}";
    "\caption{Metriche peggiori fra due gradini nominali separati da 5 gradi, 12 s, senza disturbi o rumore. I valori $\gamma$ riguardano problemi pesati diversi: non sono direttamente una graduatoria di robustezza.}";
    "\label{tab:hinf-nuovo-confronto}\end{table}"];
localScrivi(fullfile(radice,'report','generated','hinf_revision_results.tex'),righe);
fprintf('Esportati gli asset Hinf dalla cache; nessuna sintesi ripetuta.\n');
end

function localSalva(f,nome,radice)
set_scientific_figure_style(f);
exportgraphics(f,fullfile(radice,'results','figures',nome),'Resolution',180);
close(f);
copyfile(fullfile(radice,'results','figures',nome),fullfile(radice,'report','figures',nome));
end
function testo=localNumero(valore)
if isinf(valore), testo="\(\infty\)";
else
    testo=string(sprintf('%.5g',valore));
    if contains(testo,"e"), testo="\num{"+testo+"}"; end
end
end
function localScrivi(percorso,righe)
fid=fopen(percorso,'w');
assert(fid~=-1,'Revision:WriteError','Impossibile scrivere %s.',percorso);
chiudi=onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',righe);
end
