function selection = select_m5_performance_specs(m2Data, m3Data, spec)
%SELECT_M5_PERFORMANCE_SPECS Deterministic M5 candidate analysis.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dataDirectory = fullfile(projectRoot, 'results', 'data');
if nargin < 1 || isempty(m2Data)
    m2Data = load(fullfile(dataDirectory, ...
        'm2_linearization_nominal.mat'));
end
if nargin < 2 || isempty(m3Data)
    m3Data = load(fullfile(dataDirectory, ...
        'm3_nominal_actuated_plant.mat'));
end
if nargin < 3 || isempty(spec)
    spec = performance_specs_m5;
end

assert(isfield(m2Data, 'poles') && isfield(m3Data, 'actuatorInfo'), ...
    'M5Selection:MissingDynamicData', ...
    'Validated M2 poles and M3 actuator information are required.');
assert(isfield(m3Data.actuatorInfo, 'actuatorBandwidth'), ...
    'M5Selection:MissingActuatorBandwidth', ...
    'The M3 dataset does not contain the validated actuator bandwidth.');

stabilityTolerance = 1e-8;
unstablePoles = m2Data.poles(real(m2Data.poles) > stabilityTolerance);
elasticPoles = m2Data.poles(abs(imag(m2Data.poles)) > ...
    stabilityTolerance);
assert(~isempty(unstablePoles) && ~isempty(elasticPoles), ...
    'M5Selection:MissingCharacteristicModes', ...
    'M2 must contain unstable poles and complex elastic modes.');

criteria.lambdaUMax = max(real(unstablePoles));
criteria.omegaElasticMin = min(abs(elasticPoles));
criteria.omegaActuator = m3Data.actuatorInfo.actuatorBandwidth;
criteria.bandwidthMinimum = spec.bandwidthUnstableMultiplier * ...
    criteria.lambdaUMax;
criteria.actuatorCeiling = spec.bandwidthActuatorFraction * ...
    criteria.omegaActuator;
criteria.elasticCeiling = spec.bandwidthElasticFraction * ...
    criteria.omegaElasticMin;
criteria.bandwidthMaximum = min(criteria.actuatorCeiling, ...
    criteria.elasticCeiling);
criteria.source = ...
    "validated M2 poles and M3 actuator bandwidth with M5 criteria";
assert(criteria.bandwidthMinimum < criteria.bandwidthMaximum, ...
    'M5Selection:EmptyBandwidthWindow', ...
    'The derived M5 bandwidth window is empty.');

omegaB = spec.omegaBCandidates(:);
numberBandwidthCandidates = numel(omegaB);
candidate = compose("B%02d", (1:numberBandwidthCandidates).');
lowerMargin = omegaB - criteria.bandwidthMinimum;
actuatorMargin = criteria.actuatorCeiling - omegaB;
elasticMargin = criteria.elasticCeiling - omegaB;
admissible = lowerMargin >= 0 & actuatorMargin >= 0 & ...
    elasticMargin >= 0;
separationMargin = min([lowerMargin, actuatorMargin, elasticMargin], ...
    [], 2);
windowMidpoint = (criteria.bandwidthMinimum + ...
    criteria.bandwidthMaximum) / 2;
rankingMatrix = [~admissible, -separationMargin, ...
    abs(omegaB - windowMidpoint), omegaB, ...
    (1:numberBandwidthCandidates).'];
[~, bandwidthOrder] = sortrows(rankingMatrix, ...
    1:size(rankingMatrix, 2));
ranking = zeros(numberBandwidthCandidates, 1);
ranking(bandwidthOrder) = (1:numberBandwidthCandidates).';
bandwidthCandidateTable = table(candidate, omegaB, lowerMargin, ...
    actuatorMargin, elasticMargin, admissible, separationMargin, ...
    ranking, 'VariableNames', {'Candidate', 'OmegaB', 'LowerMargin', ...
    'ActuatorMargin', 'ElasticMargin', 'Admissible', ...
    'SeparationMargin', 'Ranking'});
selectedBandwidthIndex = bandwidthOrder(find( ...
    admissible(bandwidthOrder), 1, 'first'));

[AsGrid, MsGrid] = ndgrid(spec.AsCandidates(:), spec.MsCandidates(:));
As = AsGrid(:);
Ms = MsGrid(:);
dcWeight = 1 ./ As;
hfAsymptote = 1 ./ Ms;
severityRatio = dcWeight ./ hfAsymptote;
medianAs = median(spec.AsCandidates);
medianMs = median(spec.MsCandidates);
w1RankingMatrix = [abs(log(As / medianAs)), ...
    abs(log(Ms / medianMs)), As, Ms, (1:numel(As)).'];
[~, w1Order] = sortrows(w1RankingMatrix, 1:size(w1RankingMatrix, 2));
w1Ranking = zeros(numel(As), 1);
w1Ranking(w1Order) = (1:numel(As)).';
w1Selected = w1Ranking == 1;
interpretation = strings(numel(As), 1);
for index = 1:numel(As)
    lowFrequencyText = localSeverityText(As(index), medianAs, ...
        "stronger LF attenuation", "balanced LF target", ...
        "looser LF attenuation");
    peakText = localSeverityText(Ms(index), medianMs, ...
        "tighter peak target", "balanced peak target", ...
        "looser peak target");
    interpretation(index) = lowFrequencyText + "; " + peakText;
end
W1CandidateTable = table(As, Ms, dcWeight, hfAsymptote, ...
    severityRatio, interpretation, w1Selected, w1Ranking, ...
    'VariableNames', {'As', 'Ms', 'DCWeight', 'HFAsymptote', ...
    'SeverityRatio', 'Interpretation', 'Selected', 'Ranking'});
selectedW1Index = w1Order(1);

[uScaleGrid, omegaUGrid, alphaGrid] = ndgrid( ...
    spec.uScaleCandidates(:), spec.omegaUCandidates(:), ...
    spec.controlWeightAlphaCandidates(:));
uScale = uScaleGrid(:);
omegaU = omegaUGrid(:);
alpha = alphaGrid(:);
lfPenalty = 1 ./ uScale;
hfPenalty = alpha ./ uScale;
distanceFromActuatorBW = criteria.omegaActuator - omegaU;
distanceFromElasticModes = criteria.omegaElasticMin - omegaU;
elasticOnsetCeiling = spec.controlOnsetElasticFraction * ...
    criteria.omegaElasticMin;
w2Admissible = omegaU < criteria.omegaActuator & ...
    omegaU <= elasticOnsetCeiling & alpha > 1 & uScale > 0;
medianUScale = median(spec.uScaleCandidates);
w2RankingMatrix = [~w2Admissible, abs(uScale - medianUScale), ...
    abs(distanceFromActuatorBW), -alpha, omegaU, ...
    (1:numel(uScale)).'];
[~, w2Order] = sortrows(w2RankingMatrix, 1:size(w2RankingMatrix, 2));
w2Ranking = zeros(numel(uScale), 1);
w2Ranking(w2Order) = (1:numel(uScale)).';
w2Selected = w2Ranking == 1;
W2CandidateTable = table(uScale, omegaU, alpha, lfPenalty, ...
    hfPenalty, distanceFromActuatorBW, distanceFromElasticModes, ...
    w2Admissible, w2Selected, w2Ranking, ...
    'VariableNames', {'UScale', 'OmegaU', 'Alpha', 'LFPenalty', ...
    'HFPenalty', 'DistanceFromActuatorBW', ...
    'DistanceFromElasticModes', 'Admissible', 'Selected', 'Ranking'});
selectedW2Index = w2Order(find(w2Admissible(w2Order), 1, 'first'));

selection.criteria = criteria;
selection.bandwidthCandidateTable = bandwidthCandidateTable;
selection.W1CandidateTable = W1CandidateTable;
selection.W2CandidateTable = W2CandidateTable;
selection.selected.omegaB = omegaB(selectedBandwidthIndex);
selection.selected.As = As(selectedW1Index);
selection.selected.Ms = Ms(selectedW1Index);
selection.selected.uScale = uScale(selectedW2Index);
selection.selected.omegaU = omegaU(selectedW2Index);
selection.selected.controlWeightAlpha = alpha(selectedW2Index);
selection.selectedBandwidth = bandwidthCandidateTable( ...
    selectedBandwidthIndex, :);
selection.selectedW1 = W1CandidateTable(selectedW1Index, :);
selection.selectedW2 = W2CandidateTable(selectedW2Index, :);
selection.declaredBaselineMatches = ...
    selection.selected.omegaB == spec.omegaB && ...
    selection.selected.As == spec.As && ...
    selection.selected.Ms == spec.Ms && ...
    selection.selected.uScale == spec.uScale && ...
    selection.selected.omegaU == spec.omegaU && ...
    selection.selected.controlWeightAlpha == spec.controlWeightAlpha;
selection.rules.bandwidth = [ ...
    "retain candidates inside every M2/M3-derived bound"; ...
    "maximize the minimum absolute margin from the active bounds"; ...
    "break ties by midpoint distance, lower omegaB and candidate index"];
selection.rules.W1 = [ ...
    "compare the complete local As/Ms grid"; ...
    "prefer the median severity in As, then the median severity in Ms"; ...
    "break ties deterministically by As, Ms and row index"];
selection.rules.W2 = [ ...
    "require onset below actuator bandwidth and below half the first elastic mode"; ...
    "prefer the median effort normalization scale"; ...
    "then prefer onset closest to actuator bandwidth from below"; ...
    "then prefer larger alpha and use fixed numeric tie-breaks"];
end

function text = localSeverityText(value, medianValue, lowerText, ...
    medianText, upperText)
if value < medianValue
    text = lowerText;
elseif value > medianValue
    text = upperText;
else
    text = medianText;
end
end
