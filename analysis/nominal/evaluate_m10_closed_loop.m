function evaluation = evaluate_m10_closed_loop( ...
    reconstruction, synthesis, plant, m5, m6, m9, config)
%EVALUATE_M10_CLOSED_LOOP Evaluate M10 and compare frozen M6/M9 baselines.

arguments
    reconstruction (1, 1) struct
    synthesis (1, 1) struct
    plant (1, 1) struct
    m5 (1, 1) struct
    m6 (1, 1) struct
    m9 (1, 1) struct
    config (1, 1) struct = hinf_specs_m10
end

currentAlias.controllerOrder = synthesis.controllerOrder;
current = evaluate_m9_closed_loop( ...
    reconstruction, m5, m6, currentAlias, config);

m9SynthesisAlias.Kmix = m9.Kmix;
m9SynthesisAlias.CLmix = m9.CLmix;
m9SynthesisAlias.gamma = m9.gamma;
m9Reconstruction = reconstruct_m9_mixed_sensitivity( ...
    plant.G, plant.Gd, m5.W1, m5.W2, m9SynthesisAlias, config);
m9Alias.controllerOrder = order(m9.Kmix);
m9Regenerated = evaluate_m9_closed_loop( ...
    m9Reconstruction, m5, m6, m9Alias, config);

m9TrackingRegenerationError = localMaximumTableError( ...
    m9Regenerated.trackingMetrics, m9.trackingMetrics);
m9DisturbanceRegenerationError = localMaximumTableError( ...
    m9Regenerated.disturbanceMetrics, m9.disturbanceMetrics);
m6FrozenTracking = m9.comparisonM6.tracking( ...
    m9.comparisonM6.tracking.Controller == "M6 LQG", 2:end);
m6FrozenDisturbance = m9.comparisonM6.disturbance( ...
    m9.comparisonM6.disturbance.Controller == "M6 LQG", 2:end);
m6TrackingRegenerationError = localMaximumTableError( ...
    current.m6TrackingMetrics, m6FrozenTracking);
m6DisturbanceRegenerationError = localMaximumTableError( ...
    current.m6DisturbanceMetrics, m6FrozenDisturbance);

comparison.tracking = [ ...
    localLabelTable(current.m6TrackingMetrics, "M6 LQG"); ...
    localLabelTable(m9.trackingMetrics, "M9 mixsyn"); ...
    localLabelTable(current.trackingMetrics, "M10 hinfsyn")];
comparison.disturbance = [ ...
    localLabelTable(current.m6DisturbanceMetrics, "M6 LQG"); ...
    localLabelTable(m9.disturbanceMetrics, "M9 mixsyn"); ...
    localLabelTable(current.disturbanceMetrics, "M10 hinfsyn")];
comparison.summary = localBuildSummary(current, m9, m6, ...
    synthesis, reconstruction);

consistency = struct( ...
    'gammaRelativeDifference', abs(synthesis.gammaHinf - m9.gamma) / ...
        m9.gamma, ...
    'weightedMapError', localSystemNormDifference( ...
        reconstruction.weightedClosedLoop, m9.weightedClosedLoop), ...
    'sensitivityError', localSystemNormDifference( ...
        reconstruction.S, m9.S), ...
    'complementarySensitivityError', localSystemNormDifference( ...
        reconstruction.T, m9.T), ...
    'controlSensitivityError', localSystemNormDifference( ...
        reconstruction.KS, m9.KS), ...
    'controllerTransferError', localSystemNormDifference( ...
        synthesis.Khinf, m9.Kmix), ...
    'closedLoopPoleSetDistance', localPoleSetDistance( ...
        reconstruction.internalPoles, m9.closedLoopPoles), ...
    'm9TrackingRegenerationError', m9TrackingRegenerationError, ...
    'm9DisturbanceRegenerationError', ...
        m9DisturbanceRegenerationError, ...
    'm6TrackingRegenerationError', m6TrackingRegenerationError, ...
    'm6DisturbanceRegenerationError', ...
        m6DisturbanceRegenerationError, ...
    'diagnosticRelativeGammaTolerance', ...
        config.gammaConsistencyDiagnosticTolerance);
consistency.passed = consistency.gammaRelativeDifference <= ...
    config.gammaConsistencyDiagnosticTolerance && ...
    consistency.weightedMapError <= config.m9EquivalenceTolerance && ...
    consistency.m9TrackingRegenerationError <= 1e-10 && ...
    consistency.m9DisturbanceRegenerationError <= 1e-10 && ...
    consistency.m6TrackingRegenerationError <= 1e-10 && ...
    consistency.m6DisturbanceRegenerationError <= 1e-10;
if consistency.passed
    consistency.interpretation = "quasi-equivalent";
else
    consistency.interpretation = "requires methodological investigation";
end

assert(consistency.passed, 'M10Evaluation:M9M10Mismatch', ...
    ['M10 differs materially from the equivalent M9 problem or the ' ...
    'frozen comparison artifacts were not reproduced.']);

evaluation = current;
evaluation.m9TrackingResponses = m9Regenerated.trackingResponses;
evaluation.m9DisturbanceResponses = m9Regenerated.disturbanceResponses;
evaluation.comparison = comparison;
evaluation.consistencyM9M10 = consistency;
end

function summary = localBuildSummary(current, m9, m6, ...
    synthesis, reconstruction)
controller = ["M6 LQG"; "M9 mixsyn"; "M10 hinfsyn"];
controllerOrder = [order(m6.Klqg); order(m9.Kmix); ...
    synthesis.controllerOrder];
gamma = [NaN; m9.gamma; synthesis.gammaHinf];
weightedNorm = [NaN; m9.normMetrics.weightedNorm; ...
    reconstruction.metrics.weightedNorm];
nominallyStable = [isstable(m6.lqgClosedLoop); ...
    m9.qualityGate.nominalStability == "PASS"; ...
    reconstruction.metrics.nominallyStable];

trackingSets = {current.m6TrackingMetrics, m9.trackingMetrics, ...
    current.trackingMetrics};
disturbanceSets = {current.m6DisturbanceMetrics, ...
    m9.disturbanceMetrics, current.disturbanceMetrics};
numberControllers = numel(trackingSets);
worstTrackingTs = zeros(numberControllers, 1);
worstOvershoot = zeros(numberControllers, 1);
worstSteadyErrorRelative = zeros(numberControllers, 1);
worstTrackingCrossCoupling = zeros(numberControllers, 1);
worstTrackingPeakU = zeros(numberControllers, 1);
worstDisturbancePeakQ = zeros(numberControllers, 1);
worstDisturbanceOffset = zeros(numberControllers, 1);
worstDisturbanceCrossCoupling = zeros(numberControllers, 1);
worstDisturbancePeakU = zeros(numberControllers, 1);
for index = 1:numberControllers
    tracking = trackingSets{index};
    disturbance = disturbanceSets{index};
    worstTrackingTs(index) = max(tracking.SettlingTime);
    worstOvershoot(index) = max(tracking.OvershootPercent);
    worstSteadyErrorRelative(index) = ...
        max(tracking.SteadyStateErrorRelative);
    worstTrackingCrossCoupling(index) = ...
        max(tracking.CrossCouplingPeakRatio);
    worstTrackingPeakU(index) = max(tracking.PeakControlNm);
    worstDisturbancePeakQ(index) = max(disturbance.PeakQRad);
    worstDisturbanceOffset(index) = ...
        max(abs(disturbance.SteadyStateOffsetRad));
    worstDisturbanceCrossCoupling(index) = ...
        max(disturbance.CrossCouplingPeakRatio);
    worstDisturbancePeakU(index) = max(disturbance.PeakControlNm);
end
summary = table(controller, controllerOrder, gamma, weightedNorm, ...
    nominallyStable, worstTrackingTs, worstOvershoot, ...
    worstSteadyErrorRelative, worstTrackingCrossCoupling, ...
    worstTrackingPeakU, worstDisturbancePeakQ, ...
    worstDisturbanceOffset, worstDisturbanceCrossCoupling, ...
    worstDisturbancePeakU);
end

function labeled = localLabelTable(inputTable, label)
labeled = addvars(inputTable, repmat(label, height(inputTable), 1), ...
    'Before', 1, 'NewVariableNames', 'Controller');
end

function maximumError = localMaximumTableError(first, second)
assert(isequal(first.Properties.VariableNames, ...
    second.Properties.VariableNames), ...
    'M10Evaluation:TableSchemaMismatch', ...
    'Frozen and regenerated metric tables use different schemas.');
maximumError = max(abs(first{:,:} - second{:,:}), [], 'all');
end

function value = localSystemNormDifference(first, second)
first = localClearNames(first);
second = localClearNames(second);
value = norm(first - second, inf);
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function distance = localPoleSetDistance(first, second)
pairwiseDistance = abs(first(:) - second(:).');
distance = max([max(min(pairwiseDistance, [], 1)), ...
    max(min(pairwiseDistance, [], 2))]);
end
