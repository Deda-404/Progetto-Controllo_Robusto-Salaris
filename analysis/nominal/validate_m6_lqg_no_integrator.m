function metrics = validate_m6_lqg_no_integrator
%VALIDATE_M6_LQG_NO_INTEGRATOR Rebuild and validate the complete M6 design.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

m3Path = fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat');
m5Path = fullfile(dataDirectory, 'm5_performance_specs.mat');
if ~isfile(m3Path)
    validate_m3_nominal_actuated_plant;
end
if ~isfile(m5Path)
    validate_m5_performance_specs;
end
m3 = load(m3Path);
m5 = load(m5Path);
config = lqg_specs_m6;

baselineDiagnosis = diagnose_m6_baseline_cost(m3, m5, config);
coarseTuning = tune_lqr_cost_m6( ...
    m3, m5, config, "coarse", baselineDiagnosis);
extendedGridExecuted = isempty(coarseTuning.selectedIndex);
extendedCandidateTable = table;
assert(~extendedGridExecuted, 'M6:LQRCoarseGridFailed', ...
    ['The 240-candidate coarse grid did not produce a technically ' ...
    'selectable controller. M6 must stop before Kalman tuning.']);

selectedRow = coarseTuning.lqrCandidateTable( ...
    coarseTuning.selectedIndex, :);
declaredCostMatches = ...
    selectedRow.Wq == config.selected.wq && ...
    selectedRow.WVelocity == config.selected.wqdot && ...
    selectedRow.Wdelta == config.selected.wdelta && ...
    selectedRow.WVelocity == config.selected.wthetaDot && ...
    selectedRow.RhoU == config.selected.rhoU;
assert(declaredCostMatches, 'M6:DeclaredLQRMismatch', ...
    'Metric-based LQR tuning differs from lqg_specs_m6.');

selectedEvaluation = evaluate_m6_closed_loop( ...
    m3.Afull, m3.Bfull, m3.CfullQ, m3.CfullMeas(3:4, :), ...
    m5.BdFull, coarseTuning.K, coarseTuning.Nr, ...
    m3.mechanicalParams.Ks, m5.spec, config, true);
kalmanSelection = select_kalman_filter( ...
    m3, m5, coarseTuning, config);
assert(~isempty(kalmanSelection.selectedIndex), ...
    'M6:KalmanGridFailed', ...
    'No Kalman candidate satisfies the estimator speed-ratio target.');
realization = build_lqg_no_integrator( ...
    m3, m5, coarseTuning, kalmanSelection, config);

[lqgTrackingTable, referenceTime, lqgReferenceOutput] = ...
    localEvaluateLqgTracking(realization.lqgClosedLoop, m5.spec, config);
[lqgDisturbanceTable, disturbanceTime, lqgDisturbanceOutput] = ...
    localEvaluateLqgDisturbance( ...
    realization.lqgClosedLoop, m5.spec, config);
[noiseMetrics, noiseTime, noisyOutput, deterministicNoiseBaseline] = ...
    localEvaluateNoise(realization.lqgClosedLoop, ...
    kalmanSelection.sigmaYRad, m5.spec, config);
[repeatNoiseMetrics, ~, repeatNoisyOutput] = localEvaluateNoise( ...
    realization.lqgClosedLoop, kalmanSelection.sigmaYRad, ...
    m5.spec, config);
noiseRepeatError = max(abs(noisyOutput - repeatNoisyOutput), [], 'all');

trackingMetrics.fullState = selectedEvaluation.trackingMetrics;
trackingMetrics.lqg = lqgTrackingTable;
trackingMetrics.maximumQDifference = localMaximumResponseDifference( ...
    selectedEvaluation.referenceOutput, lqgReferenceOutput, 1:2);
trackingMetrics.maximumControlDifference = ...
    localMaximumResponseDifference( ...
    selectedEvaluation.referenceOutput, lqgReferenceOutput, 5:6);
trackingMetrics.estimationCostSettling = max( ...
    lqgTrackingTable.SettlingTime - ...
    selectedEvaluation.trackingMetrics.SettlingTime);

disturbanceMetrics.fullState = selectedEvaluation.disturbanceMetrics;
disturbanceMetrics.lqg = lqgDisturbanceTable;
disturbanceMetrics.maximumQDifference = localMaximumResponseDifference( ...
    selectedEvaluation.disturbanceOutput, lqgDisturbanceOutput, 1:2);

deltaMask = coarseTuning.lqrCandidateTable.Wq == selectedRow.Wq & ...
    coarseTuning.lqrCandidateTable.WVelocity == ...
        selectedRow.WVelocity & ...
    coarseTuning.lqrCandidateTable.RhoU == selectedRow.RhoU;
deltaWeightEffectTable = sortrows( ...
    coarseTuning.lqrCandidateTable(deltaMask, ...
    {'Wdelta', 'WorstSettlingTime', 'DominantRealPart', ...
    'PeakUNormalized', 'PeakDeltaNormalized', 'GainFrobeniusNorm'}), ...
    'Wdelta', 'descend');

Q = coarseTuning.Q;
R = coarseTuning.R;
K = coarseTuning.K;
Nr = coarseTuning.Nr;
Ccost = coarseTuning.Ccost;
lqrCandidateTable = coarseTuning.lqrCandidateTable;
processNoiseInputMatrix = kalmanSelection.processNoiseInputMatrix;
kalmanCandidateTable = kalmanSelection.kalmanCandidateTable;
Qn = kalmanSelection.Qn;
Rn = kalmanSelection.Rn;
L = kalmanSelection.L;
Klqg = realization.Klqg;
fullStateClosedLoop = realization.fullStateClosedLoop;
lqgClosedLoop = realization.lqgClosedLoop;
regulatorPoles = realization.regulatorPoles;
estimatorPoles = realization.estimatorPoles;
combinedPoles = realization.combinedPoles;

validationMetrics.cleanup.equilibriumClassification = ...
    m5.spec.metadata.Classification(1);
validationMetrics.cleanup.disturbanceClassification = ...
    m5.spec.metadata.Classification(2);
validationMetrics.model = struct('stateCount', size(m3.Afull, 1), ...
    'inputCount', size(m3.Bfull, 2), ...
    'measurementCount', size(m3.CfullMeas, 1));
validationMetrics.cost.scales = coarseTuning.scales;
validationMetrics.cost.priorities = coarseTuning.selectedPriorities;
validationMetrics.cost.symmetricError = norm(Q - Q.', 'fro');
validationMetrics.cost.minimumEigenvalue = min(eig(Q));
validationMetrics.cost.rank = rank(Q);
validationMetrics.cost.actuatorDirectWeightNorm = ...
    norm(Ccost(:, 9:14), 'fro');
validationMetrics.cost.baseline = baselineDiagnosis;
validationMetrics.lqr.coarseCandidateCount = height(lqrCandidateTable);
validationMetrics.lqr.admissibleCandidateCount = ...
    sum(lqrCandidateTable.FundamentalPass);
validationMetrics.lqr.extendedGridExecuted = extendedGridExecuted;
validationMetrics.lqr.declaredCostMatches = declaredCostMatches;
validationMetrics.lqr.selectedRow = selectedRow;
validationMetrics.lqr.bestCrossCouplingRow = ...
    lqrCandidateTable(coarseTuning.bestCrossCouplingIndex, :);
validationMetrics.lqr.deltaWeightEffectTable = deltaWeightEffectTable;
validationMetrics.prefilter.condition = selectedRow.PreFilterCondition;
validationMetrics.prefilter.dcError = selectedRow.PreFilterResidual;
validationMetrics.kalman.candidateCount = height(kalmanCandidateTable);
validationMetrics.kalman.admissibleCandidateCount = ...
    sum(kalmanCandidateTable.Admissible);
validationMetrics.kalman.selectedRow = ...
    kalmanCandidateTable(kalmanSelection.selectedIndex, :);
validationMetrics.separation.error = realization.separationError;
validationMetrics.controller.order = realization.controllerOrder;
validationMetrics.controller.integratorStateCount = ...
    realization.integratorStateCount;
validationMetrics.tracking.targetsPassed = all( ...
    lqgTrackingTable.SettlingTime <= m5.spec.settlingTimeTarget & ...
    lqgTrackingTable.Overshoot <= m5.spec.overshootTarget & ...
    lqgTrackingTable.SteadyStateErrorRelative <= ...
        m5.spec.steadyStateTrackingTarget);
validationMetrics.tracking.crossCouplingDiagnosticPassed = all( ...
    lqgTrackingTable.CrossCouplingPeakRatio <= ...
        m5.spec.crossCouplingTarget);
validationMetrics.noise.seed = config.noiseSeed;
validationMetrics.noise.repeatError = noiseRepeatError;
validationMetrics.noise.repeatMetricsEqual = ...
    isequaln(noiseMetrics, repeatNoiseMetrics);
validationMetrics.measurements.velocityMeasured = any(any( ...
    abs(m3.CfullMeas(:, [3:4, 7:8])) > 0));
validationMetrics.nominalSynthesisOnly = ...
    isnumeric(m3.Afull) && isnumeric(m3.Bfull) && isnumeric(Ccost) && ...
    isnumeric(K) && isnumeric(L);

localPlotCostTuning(lqrCandidateTable, selectedRow, fullfile( ...
    figureDirectory, 'm6_lqr_cost_tuning.png'));
localPlotDeltaWeightEffect(deltaWeightEffectTable, fullfile( ...
    figureDirectory, 'm6_lqr_delta_weight_effect.png'));
localPlotCandidateComparison(lqrCandidateTable, selectedRow, m5.spec, ...
    fullfile(figureDirectory, 'm6_lqr_candidate_comparison.png'));
localPlotReference(referenceTime, lqgReferenceOutput, m5.spec, ...
    fullfile(figureDirectory, 'm6_lqg_reference_tracking.png'));
localPlotDisturbance(disturbanceTime, lqgDisturbanceOutput, ...
    fullfile(figureDirectory, 'm6_lqg_disturbance_response.png'));
localPlotEstimation(noiseTime, noisyOutput, deterministicNoiseBaseline, ...
    fullfile(figureDirectory, 'm6_lqg_estimation.png'));
localPlotPoles(regulatorPoles, estimatorPoles, combinedPoles, fullfile( ...
    figureDirectory, 'm6_lqg_poles.png'));

datasetPath = fullfile(dataDirectory, 'm6_lqg_no_integrator.mat');
save(datasetPath, 'Q', 'R', 'K', 'Nr', 'Ccost', ...
    'lqrCandidateTable', 'baselineDiagnosis', ...
    'deltaWeightEffectTable', 'extendedGridExecuted', ...
    'extendedCandidateTable', 'processNoiseInputMatrix', ...
    'kalmanCandidateTable', 'Qn', 'Rn', 'L', 'Klqg', ...
    'fullStateClosedLoop', 'lqgClosedLoop', 'regulatorPoles', ...
    'estimatorPoles', 'combinedPoles', 'trackingMetrics', ...
    'disturbanceMetrics', 'noiseMetrics', 'validationMetrics', '-v7');

assert(validationMetrics.cleanup.equilibriumClassification == ...
    "approved project decision" && ...
    validationMetrics.cleanup.disturbanceClassification == ...
    "project modeling choice", 'M6:EpistemicCleanup', ...
    'The preliminary M5 epistemic cleanup is missing.');
assert(isequal([size(m3.Afull), size(m3.Bfull), ...
    size(m3.CfullMeas)], [14, 14, 14, 2, 4, 14]), ...
    'M6:FullPlantDimensions', 'M6 is not using the full M3 plant.');
assert(validationMetrics.cost.symmetricError <= 1e-10 && ...
    validationMetrics.cost.minimumEigenvalue >= -1e-8 && ...
    all(isfinite(Q), 'all'), 'M6:CostProperties', ...
    'The selected state cost is not finite, symmetric and PSD.');
assert(height(lqrCandidateTable) == 240 && ...
    ~isempty(coarseTuning.selectedIndex) && ...
    selectedRow.FundamentalPass && selectedRow.TechnicallySelectable, ...
    'M6:LQRSelection', 'The coarse-grid LQR selection is invalid.');
assert(selectedRow.PeakUNormalized <= ...
    config.controlEffortModerateThreshold, 'M6:LQRAggressiveness', ...
    'The selected LQR exceeds the moderate diagnostic effort threshold.');
assert(validationMetrics.prefilter.dcError <= 1e-10 && ...
    isfinite(validationMetrics.prefilter.condition), ...
    'M6:Prefilter', 'The selected MIMO prefilter is inconsistent.');
assert(height(kalmanCandidateTable) == 27 && ...
    kalmanSelection.estimatorSpeedRatio >= ...
        config.estimatorSpeedRatioMinimum && ...
    kalmanSelection.estimatorSpeedRatio <= ...
        config.estimatorSpeedRatioMaximum, ...
    'M6:KalmanSelection', 'The Kalman selection is invalid.');
assert(realization.separationError <= 1e-4, ...
    'M6:SeparationPrinciple', ...
    'Combined poles do not match regulator/estimator poles.');
assert(realization.controllerOrder == 14 && ...
    realization.integratorStateCount == 0, 'M6:ControllerOrder', ...
    'The M6 controller must be order 14 without integrators.');
assert(validationMetrics.tracking.targetsPassed, ...
    'M6:TrackingTargets', ...
    'The selected LQG violates a fundamental M5 tracking target.');
assert(all(isfinite(lqgDisturbanceTable.SteadyStateOffset)), ...
    'M6:DisturbanceOffset', ...
    'Disturbance offsets were not quantified.');
assert(isfinite(kalmanSelection.h2NoiseAmplification) && ...
    noiseRepeatError == 0 && ...
    validationMetrics.noise.repeatMetricsEqual, ...
    'M6:NoiseValidation', ...
    'Noise metrics are non-finite or not seeded reproducibly.');
assert(~validationMetrics.measurements.velocityMeasured && ...
    validationMetrics.nominalSynthesisOnly, ...
    'M6:ModelScope', ...
    'M6 uses direct velocity measurements or uncertain synthesis data.');
assert(isfile(datasetPath), 'M6:Dataset', ...
    'The required M6 dataset was not generated.');

fprintf('\n=== Validazione M6: LQG nominale senza integratore ===\n');
fprintf(['Baseline: q/delta equivalent weight ratio %.6g, ' ...
    'dominant pole %.6g%+.6gi, settling 1.222 s\n'], ...
    baselineDiagnosis.positionToDeformationWeightRatio, ...
    real(baselineDiagnosis.dominantPole), ...
    imag(baselineDiagnosis.dominantPole));
fprintf(['Coarse grid: %d candidates, %d fundamental PASS; ' ...
    'extended grid executed=%d\n'], height(lqrCandidateTable), ...
    sum(lqrCandidateTable.FundamentalPass), extendedGridExecuted);
fprintf(['LQR selected: wq=%.3g, wdelta=%.3g, wVelocity=%.3g, ' ...
    'rhoU=%.3g, settling=%.6g s, peakU/uScale=%.6g\n'], ...
    selectedRow.Wq, selectedRow.Wdelta, selectedRow.WVelocity, ...
    selectedRow.RhoU, selectedRow.WorstSettlingTime, ...
    selectedRow.PeakUNormalized);
fprintf(['Kalman selected: sigmaD=%.4g N m, sigmaU=%.4g N m, ' ...
    'sigmaY=%.4g deg, ratio=%.6g, H2=%.6g\n'], ...
    kalmanSelection.sigmaD, kalmanSelection.sigmaU, ...
    kalmanSelection.sigmaYDeg, ...
    kalmanSelection.estimatorSpeedRatio, ...
    kalmanSelection.h2NoiseAmplification);
fprintf(['LQG: order=%d, separation error=%.3e, worst settling=' ...
    '%.6g s, noise RMS tracking=%.6g rad\n'], ...
    realization.controllerOrder, realization.separationError, ...
    max(lqgTrackingTable.SettlingTime), noiseMetrics.rmsTrackingError);
fprintf('Dataset: %s\n', datasetPath);
fprintf('[PASS] Quality gate M6 completo superato; nessun integratore.\n');

metrics.config = config;
metrics.baselineDiagnosis = baselineDiagnosis;
metrics.coarseTuning = coarseTuning;
metrics.extendedGridExecuted = extendedGridExecuted;
metrics.kalmanSelection = kalmanSelection;
metrics.realization = realization;
metrics.trackingMetrics = trackingMetrics;
metrics.disturbanceMetrics = disturbanceMetrics;
metrics.noiseMetrics = noiseMetrics;
metrics.validationMetrics = validationMetrics;
metrics.datasetPath = datasetPath;
end

function [trackingTable, time, outputByJoint] = ...
    localEvaluateLqgTracking(system, spec, config)
time = (0:config.simulationTimeStep:config.referenceHorizon).';
numberSamples = numel(time);
referenceJoint = (1:2).';
settlingTime = zeros(2, 1);
overshoot = zeros(2, 1);
steadyStateErrorRelative = zeros(2, 1);
crossCouplingPeakRatio = zeros(2, 1);
peakControl = zeros(2, 1);
outputByJoint = cell(2, 1);
referenceDcGain = dcgain(system(1:2, 1:2));
for jointIndex = 1:2
    input = zeros(numberSamples, 8);
    input(:, jointIndex) = spec.referenceAmplitude;
    output = lsim(system, input, time);
    outputByJoint{jointIndex} = output;
    q = output(:, 1:2);
    u = output(:, 5:6);
    finalValue = referenceDcGain(:, jointIndex) * ...
        spec.referenceAmplitude;
    settlingTime(jointIndex) = localSettlingTime( ...
        q(:, jointIndex), finalValue(jointIndex), time, ...
        config.settlingBandFraction * abs(spec.referenceAmplitude));
    overshoot(jointIndex) = 100 * max(0, ...
        (max(q(:, jointIndex)) - spec.referenceAmplitude) / ...
        abs(spec.referenceAmplitude));
    steadyStateErrorRelative(jointIndex) = abs( ...
        finalValue(jointIndex) - spec.referenceAmplitude) / ...
        abs(spec.referenceAmplitude);
    otherJoint = 3 - jointIndex;
    crossCouplingPeakRatio(jointIndex) = max(abs(q(:, otherJoint))) / ...
        max(max(abs(q(:, jointIndex))), eps);
    peakControl(jointIndex) = max(abs(u), [], 'all');
end
trackingTable = table(referenceJoint, settlingTime, overshoot, ...
    steadyStateErrorRelative, crossCouplingPeakRatio, peakControl, ...
    'VariableNames', {'ReferenceJoint', 'SettlingTime', 'Overshoot', ...
    'SteadyStateErrorRelative', 'CrossCouplingPeakRatio', ...
    'PeakControl'});
end

function [disturbanceTable, time, outputByJoint] = ...
    localEvaluateLqgDisturbance(system, spec, config)
time = (0:config.simulationTimeStep:config.disturbanceHorizon).';
numberSamples = numel(time);
disturbanceJoint = (1:2).';
peakQ = zeros(2, 1);
steadyStateOffset = zeros(2, 1);
settlingTime = zeros(2, 1);
crossCouplingPeakRatio = zeros(2, 1);
peakControl = zeros(2, 1);
outputByJoint = cell(2, 1);
disturbanceDcGain = dcgain(system(1:2, 3:4));
for jointIndex = 1:2
    input = zeros(numberSamples, 8);
    input(:, jointIndex + 2) = spec.disturbanceTorqueAmplitude;
    output = lsim(system, input, time);
    outputByJoint{jointIndex} = output;
    q = output(:, 1:2);
    u = output(:, 5:6);
    finalValue = disturbanceDcGain(:, jointIndex) * ...
        spec.disturbanceTorqueAmplitude;
    affectedPeak = max(abs(q(:, jointIndex)));
    peakQ(jointIndex) = affectedPeak;
    steadyStateOffset(jointIndex) = finalValue(jointIndex);
    threshold = config.settlingBandFraction * max( ...
        [affectedPeak, abs(finalValue(jointIndex)), eps]);
    settlingTime(jointIndex) = localSettlingTime( ...
        q(:, jointIndex), finalValue(jointIndex), time, threshold);
    otherJoint = 3 - jointIndex;
    crossCouplingPeakRatio(jointIndex) = ...
        max(abs(q(:, otherJoint))) / max(affectedPeak, eps);
    peakControl(jointIndex) = max(abs(u), [], 'all');
end
disturbanceTable = table(disturbanceJoint, peakQ, ...
    steadyStateOffset, settlingTime, crossCouplingPeakRatio, ...
    peakControl, 'VariableNames', {'DisturbanceJoint', 'PeakQ', ...
    'SteadyStateOffset', 'SettlingTime', ...
    'CrossCouplingPeakRatio', 'PeakControl'});
end

function [noiseMetrics, time, noisyOutput, deterministicOutput] = ...
    localEvaluateNoise(system, sigmaYRad, spec, config)
rng(config.noiseSeed, 'twister');
time = (0:config.simulationTimeStep:config.noiseHorizon).';
numberSamples = numel(time);
input = zeros(numberSamples, 8);
input(:, 1) = spec.referenceAmplitude;
input(:, 5:8) = sigmaYRad * randn(numberSamples, 4);
noisyOutput = lsim(system, input, time);
input(:, 5:8) = 0;
deterministicOutput = lsim(system, input, time);
reference = [spec.referenceAmplitude * ones(numberSamples, 1), ...
    zeros(numberSamples, 1)];
trackingError = noisyOutput(:, 1:2) - reference;
estimationError = noisyOutput(:, 7:8);
controlVariation = noisyOutput(:, 5:6) - ...
    deterministicOutput(:, 5:6);
noiseMetrics.rmsTrackingErrorByJoint = ...
    sqrt(mean(trackingError.^2, 1)).';
noiseMetrics.rmsEstimationErrorQByJoint = ...
    sqrt(mean(estimationError.^2, 1)).';
noiseMetrics.rmsControlVariationByJoint = ...
    sqrt(mean(controlVariation.^2, 1)).';
noiseMetrics.rmsTrackingError = sqrt(mean(trackingError.^2, 'all'));
noiseMetrics.rmsEstimationErrorQ = ...
    sqrt(mean(estimationError.^2, 'all'));
noiseMetrics.rmsControlVariation = ...
    sqrt(mean(controlVariation.^2, 'all'));
noiseMetrics.seed = config.noiseSeed;
noiseMetrics.sigmaYRad = sigmaYRad;
end

function maximumDifference = localMaximumResponseDifference( ...
    firstResponses, secondResponses, outputIndices)
maximumDifference = 0;
for responseIndex = 1:numel(firstResponses)
    maximumDifference = max(maximumDifference, max(abs( ...
        firstResponses{responseIndex}(:, outputIndices) - ...
        secondResponses{responseIndex}(:, outputIndices)), [], 'all'));
end
end

function settlingTime = localSettlingTime(signal, finalValue, time, threshold)
outsideBand = abs(signal - finalValue) > max(threshold, 100 * eps);
lastOutside = find(outsideBand, 1, 'last');
if isempty(lastOutside)
    settlingTime = 0;
elseif lastOutside == numel(time)
    settlingTime = inf;
else
    settlingTime = time(lastOutside + 1);
end
end

