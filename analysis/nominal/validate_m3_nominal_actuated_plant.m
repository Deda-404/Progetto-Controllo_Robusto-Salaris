function metrics = validate_m3_nominal_actuated_plant
%VALIDATE_M3_NOMINAL_ACTUATED_PLANT Rebuild and validate all M3 artifacts.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
m2DatasetPath = fullfile(dataDirectory, 'm2_linearization_nominal.mat');
if ~isfile(m2DatasetPath)
    validate_m2_equilibrium_linearization;
end
m2 = load(m2DatasetPath);

dcGainTolerance = 1e-12;
poleZeroTolerance = 1e-10;
frequencyEquivalenceTolerance = 1e-9;
stabilityTolerance = 1e-8;

actuatorParams = actuator_params_nominal;
[actuatorComparisonTable, engineeringCriteria] = ...
    localCompareActuatorChoices(m2, actuatorParams);
engineeringRationale = [ ...
    "wn=40 rad/s is faster than the unstable mechanical scale"; ...
    "wn=40 rad/s remains below the first elastic mode"; ...
    "zeta=0.8 gives a well-damped response with small overshoot"; ...
    "15 ms delay is checked through its phase loss"; ...
    "first-order Pade preserves a low-order rational synthesis model"];
[GactuatorSiso, actuatorInfo] = build_nominal_actuator(actuatorParams);
[GactuatorsMimo, actuatorBankInfo] = ...
    build_nominal_actuator_bank(actuatorParams);
[GfullMeas, GfullQ, fullInfo] = build_m3_full_plant( ...
    m2.A, m2.B, m2.Cmeas, m2.Dmeas, m2.Cq, m2.Dq, GactuatorsMimo);

GmechanicalMeas = ss(m2.A, m2.B, m2.Cmeas, m2.Dmeas);
GindependentMeas = series(GactuatorsMimo, GmechanicalMeas);

interconnectionFrequencies = logspace(-2, 3, 601);
explicitResponse = freqresp(GfullMeas, interconnectionFrequencies);
independentResponse = freqresp(GindependentMeas, interconnectionFrequencies);
absoluteFrequencyErrors = zeros(size(interconnectionFrequencies));
relativeFrequencyErrors = zeros(size(interconnectionFrequencies));
for index = 1:numel(interconnectionFrequencies)
    responseDifference = explicitResponse(:, :, index) - ...
        independentResponse(:, :, index);
    absoluteFrequencyErrors(index) = norm(responseDifference, 'fro');
    relativeFrequencyErrors(index) = absoluteFrequencyErrors(index) / ...
        max(norm(independentResponse(:, :, index), 'fro'), eps);
end
[maximumAbsoluteError, absoluteWorstIndex] = max(absoluteFrequencyErrors);
[maximumRelativeError, relativeWorstIndex] = max(relativeFrequencyErrors);
interconnectionMetrics.frequencies = interconnectionFrequencies;
interconnectionMetrics.absoluteErrors = absoluteFrequencyErrors;
interconnectionMetrics.relativeErrors = relativeFrequencyErrors;
interconnectionMetrics.maximumAbsoluteError = maximumAbsoluteError;
interconnectionMetrics.maximumRelativeError = maximumRelativeError;
interconnectionMetrics.absoluteWorstFrequency = ...
    interconnectionFrequencies(absoluteWorstIndex);
interconnectionMetrics.relativeWorstFrequency = ...
    interconnectionFrequencies(relativeWorstIndex);

unstableMechanicalPoles = sort(abs(m2.poles(real(m2.poles) > stabilityTolerance)));
elasticMechanicalFrequencies = sort(abs(m2.poles(imag(m2.poles) > 0)));
phaseFrequencies = [1; unstableMechanicalPoles(:); 70; 80];
exactDelayPhaseDeg = -phaseFrequencies * actuatorParams.delay * 180 / pi;
padeDelayPhaseDeg = -2 * atan(phaseFrequencies * actuatorParams.delay / 2) ...
    * 180 / pi;
phaseErrorDeg = abs(padeDelayPhaseDeg - exactDelayPhaseDeg);

delayFrequencyGrid = logspace(-1, log10(200), 601);
exactDelayResponse = exp(-1i * delayFrequencyGrid * actuatorParams.delay);
padeDelayResponse = (1 - 1i * delayFrequencyGrid * actuatorParams.delay / 2) ./ ...
    (1 + 1i * delayFrequencyGrid * actuatorParams.delay / 2);
delayMagnitudeErrors = abs(abs(padeDelayResponse) - abs(exactDelayResponse));
delayMetrics.frequencies = phaseFrequencies;
delayMetrics.exactPhaseDeg = exactDelayPhaseDeg;
delayMetrics.padePhaseDeg = padeDelayPhaseDeg;
delayMetrics.phaseErrorDeg = phaseErrorDeg;
delayMetrics.maximumMagnitudeError = max(delayMagnitudeErrors);
delayMetrics.comparisonGrid = delayFrequencyGrid;

[Afull, Bfull, CfullMeas, DfullMeas] = ssdata(GfullMeas);
[~, ~, CfullQ, DfullQ] = ssdata(GfullQ);
structuralMetricsMeas = analyze_m3_structure( ...
    Afull, Bfull, CfullMeas, stabilityTolerance);
structuralMetricsQ = analyze_m3_structure( ...
    Afull, Bfull, CfullQ, stabilityTolerance);
fullPoles = structuralMetricsMeas.poles;
actuatorPoles = pole(GactuatorsMimo);
actuatorZeros = zero(GactuatorSiso);

delayFigurePath = fullfile(figureDirectory, 'm3_delay_pade_comparison.png');
actuatorFigurePath = fullfile(figureDirectory, 'm3_actuator_bode.png');
fullPlantFigurePath = fullfile(figureDirectory, 'm3_full_plant_sigma.png');
localPlotDelayComparison(delayFrequencyGrid, exactDelayResponse, ...
    padeDelayResponse, actuatorParams.delay, delayFigurePath);
localPlotActuatorBode(actuatorInfo.GsecondOrder, GactuatorSiso, ...
    actuatorParams, actuatorFigurePath);
localPlotFullSigma(GfullMeas, actuatorParams.wn, ...
    elasticMechanicalFrequencies, fullPlantFigurePath);

mechanicalParams = m2.p;
qbar = m2.qbar;
thetabar = m2.thetabar;
xbar = m2.xbar;
taubar = m2.taubar;
Amechanical = m2.A;
Bmechanical = m2.B;
Cq = m2.Cq;
Dq = m2.Dq;
Cmeas = m2.Cmeas;
Dmeas = m2.Dmeas;
datasetPath = fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat');
save(datasetPath, 'mechanicalParams', 'actuatorParams', 'qbar', ...
    'thetabar', 'xbar', 'taubar', 'Amechanical', 'Bmechanical', ...
    'Cq', 'Dq', 'Cmeas', 'Dmeas', 'GactuatorSiso', ...
    'GactuatorsMimo', 'Afull', 'Bfull', 'CfullMeas', 'DfullMeas', ...
    'CfullQ', 'DfullQ', 'GfullMeas', 'GfullQ', 'fullPoles', ...
    'actuatorPoles', 'actuatorZeros', 'actuatorInfo', ...
    'actuatorBankInfo', 'actuatorComparisonTable', 'delayMetrics', ...
    'engineeringCriteria', 'engineeringRationale', ...
    'interconnectionMetrics', 'structuralMetricsMeas', ...
    'structuralMetricsQ', '-v7');

fprintf('\n=== Validazione M3: attuatori e pianta nominale completa ===\n');
fprintf('Confronto manuale: attuatore lento, nominale e veloce.\n');
fprintf(['Finestra di verifica da M2: %.6g <= BW <= %.6g rad/s; ' ...
    'overshoot <= %.6g%%; errore fase a 80 rad/s <= %.6g deg\n'], ...
    engineeringCriteria.bandwidthMinimum, ...
    engineeringCriteria.bandwidthMaximum, ...
    engineeringCriteria.overshootMaximum, ...
    engineeringCriteria.phaseErrorMaximumDeg);
fprintf('Scelta ingegneristica: wn=%.6g rad/s, zeta=%.6g, delay=%.6g s, Pade=%d\n', ...
    actuatorParams.wn, actuatorParams.zeta, actuatorParams.delay, ...
    actuatorParams.padeOrder);
fprintf(['Step attuatore: rise=%.6g s, settling=%.6g s, overshoot=%.6g%%, ' ...
    'bandwidth=%.6g rad/s\n'], actuatorInfo.actuatorStep.RiseTime, ...
    actuatorInfo.actuatorStep.SettlingTime, ...
    actuatorInfo.actuatorStep.Overshoot, actuatorInfo.actuatorBandwidth);
fprintf('Poli attuatore SISO:\n');
for index = 1:numel(actuatorInfo.actuatorPoles)
    fprintf('  % .12g %+.12gi\n', real(actuatorInfo.actuatorPoles(index)), ...
        imag(actuatorInfo.actuatorPoles(index)));
end
fprintf('Zero RHP Pade: %.12g rad/s\n', actuatorInfo.padeZero);
fprintf('Errori fase Pade [deg] a w =');
fprintf(' %.6g', phaseFrequencies);
fprintf(' rad/s:\n                       ');
fprintf(' %.6g', phaseErrorDeg);
fprintf('\nMax errore modulo solo ritardo: %.3e\n', ...
    delayMetrics.maximumMagnitudeError);
fprintf('Ordini: SISO=%d, MIMO=%d, full=%d\n', order(GactuatorSiso), ...
    order(GactuatorsMimo), order(GfullMeas));
fprintf('Interconnessione: max abs %.3e a %.6g rad/s; max rel %.3e a %.6g rad/s\n', ...
    maximumAbsoluteError, interconnectionMetrics.absoluteWorstFrequency, ...
    maximumRelativeError, interconnectionMetrics.relativeWorstFrequency);
fprintf('Poli full: stabili=%d, instabili=%d, marginali=%d, max Re=%.12g\n', ...
    structuralMetricsMeas.numberStable, structuralMetricsMeas.numberUnstable, ...
    structuralMetricsMeas.numberMarginal, structuralMetricsMeas.maximumRealPart);
fprintf(['Controllabilita raw rank=%d/14, tol=%.3e, cond=%.3e; ' ...
    'tempo scalato rank=%d/14, cond=%.3e; PBH controllabile=%d, stabilizzabile=%d\n'], ...
    structuralMetricsMeas.controllability.rank, ...
    structuralMetricsMeas.controllability.tolerance, ...
    structuralMetricsMeas.controllability.conditionNumber, ...
    structuralMetricsMeas.scaledTime.controllability.rank, ...
    structuralMetricsMeas.scaledTime.controllability.conditionNumber, ...
    structuralMetricsMeas.controllability.controllablePbh, ...
    structuralMetricsMeas.controllability.stabilizable);
fprintf(['Osservabilita [q;theta] raw rank=%d/14, tol=%.3e, cond=%.3e; ' ...
    'tempo scalato rank=%d/14, cond=%.3e; PBH osservabile=%d, rilevabile=%d\n'], ...
    structuralMetricsMeas.observability.rank, ...
    structuralMetricsMeas.observability.tolerance, ...
    structuralMetricsMeas.observability.conditionNumber, ...
    structuralMetricsMeas.scaledTime.observability.rank, ...
    structuralMetricsMeas.scaledTime.observability.conditionNumber, ...
    structuralMetricsMeas.observability.observablePbh, ...
    structuralMetricsMeas.observability.detectable);

nominalRow = actuatorComparisonTable( ...
    actuatorComparisonTable.Choice == "nominal", :);
assert(height(nominalRow) == 1 && nominalRow.VerificationPassed, ...
    'M3:ActuatorChoice', ...
    'The declared nominal actuator is incompatible with the M2 dynamics.');
assert(order(actuatorInfo.GsecondOrder) == 2 && ...
    abs(actuatorInfo.secondOrderDcGain - 1) <= dcGainTolerance && ...
    all(real(actuatorInfo.secondOrderPoles) < 0), ...
    'M3:SecondOrder', 'The second-order actuator check failed.');
assert(order(actuatorInfo.Gpade) == 1 && ...
    abs(actuatorInfo.padePole + 2 / actuatorParams.delay) <= poleZeroTolerance && ...
    abs(actuatorInfo.padeZero - 2 / actuatorParams.delay) <= poleZeroTolerance && ...
    abs(actuatorInfo.padeDcGain - 1) <= dcGainTolerance, ...
    'M3:Pade', 'The first-order Pade check failed.');
assert(order(GactuatorSiso) == 3 && ...
    abs(actuatorInfo.actuatorDcGain - 1) <= dcGainTolerance && ...
    all(real(actuatorInfo.actuatorPoles) < 0) && any(actuatorZeros > 0), ...
    'M3:SisoActuator', 'The SISO actuator quality gate failed.');
assert(order(GactuatorsMimo) == 6 && isequal(size(GactuatorsMimo), [2, 2]), ...
    'M3:MimoActuator', 'The two-actuator bank is not 2x2 with six states.');
assert(order(GfullMeas) == 14 && size(GfullMeas, 1) == 4 && ...
    size(GfullMeas, 2) == 2 && order(GfullQ) == 14, ...
    'M3:FullPlantOrder', 'The complete plant does not have the expected order.');
assert(maximumAbsoluteError <= frequencyEquivalenceTolerance && ...
    maximumRelativeError <= frequencyEquivalenceTolerance, ...
    'M3:Interconnection', 'Explicit and independent cascades disagree.');
assert(delayMetrics.maximumMagnitudeError <= 1e-12, ...
    'M3:PadeMagnitude', 'The first-order Pade delay is not all-pass.');
assert(all(real(actuatorPoles) < -stabilityTolerance), ...
    'M3:ActuatorStability', 'An actuator pole is not stable.');
assert(structuralMetricsMeas.numberUnstable == numel(unstableMechanicalPoles) && ...
    structuralMetricsMeas.numberMarginal == 0, ...
    'M3:FullPlantPoles', 'Unexpected unstable or marginal full-plant poles.');
assert(structuralMetricsMeas.scaledTime.controllability.rank == 14 && ...
    structuralMetricsMeas.controllability.controllablePbh && ...
    structuralMetricsMeas.controllability.stabilizable, ...
    'M3:Stabilizability', 'Full plant controllability/stabilizability failed.');
assert(structuralMetricsMeas.scaledTime.observability.rank == 14 && ...
    structuralMetricsMeas.observability.observablePbh && ...
    structuralMetricsMeas.observability.detectable, ...
    'M3:Detectability', 'Full plant observability/detectability failed.');
assert(isfile(datasetPath) && isfile(delayFigurePath) && ...
    isfile(actuatorFigurePath) && isfile(fullPlantFigurePath), ...
    'M3:Artifacts', 'One or more M3 artifacts were not generated.');

metrics.actuatorComparisonTable = actuatorComparisonTable;
metrics.engineeringCriteria = engineeringCriteria;
metrics.actuatorParams = actuatorParams;
metrics.actuatorInfo = actuatorInfo;
metrics.delay = delayMetrics;
metrics.interconnection = interconnectionMetrics;
metrics.structureMeas = structuralMetricsMeas;
metrics.structureQ = structuralMetricsQ;
metrics.GactuatorSiso = GactuatorSiso;
metrics.GactuatorsMimo = GactuatorsMimo;
metrics.GfullMeas = GfullMeas;
metrics.GfullQ = GfullQ;
metrics.fullInfo = fullInfo;
metrics.datasetPath = datasetPath;
metrics.figurePaths = {delayFigurePath; actuatorFigurePath; fullPlantFigurePath};

fprintf('Dataset: %s\n', datasetPath);
fprintf(['[PASS] Quality gate numerico M3/M3.1 superato: ' ...
    'scelta ingegneristica verificata sul modello nominale.\n']);
end

function [comparisonTable, criteria] = localCompareActuatorChoices(m2, nominal)
% Three explicit designs are shown for interpretation, not ranked.
choice = ["slow"; "nominal"; "fast"];
wn = [25; nominal.wn; 60];
zeta = repmat(nominal.zeta, 3, 1);
delay = repmat(nominal.delay, 3, 1);
riseTime = zeros(3, 1);
settlingTime = zeros(3, 1);
overshoot = zeros(3, 1);
actuatorBandwidth = zeros(3, 1);
phaseError80Deg = zeros(3, 1);

unstablePoles = m2.poles(real(m2.poles) > 1e-8);
elasticPoles = m2.poles(imag(m2.poles) > 1e-8);
criteria.lambdaUMax = max(abs(unstablePoles));
criteria.omegaElasticMin = min(abs(elasticPoles));
criteria.bandwidthMinimum = 4 * criteria.lambdaUMax;
criteria.bandwidthMaximum = 0.60 * criteria.omegaElasticMin;
criteria.overshootMaximum = 10;
criteria.phaseErrorMaximumDeg = 10;

for index = 1:3
    current = struct('wn', wn(index), 'zeta', zeta(index), ...
        'delay', delay(index), 'padeOrder', nominal.padeOrder);
    [model, info] = build_nominal_actuator(current);
    stepMetrics = stepinfo(model);
    riseTime(index) = stepMetrics.RiseTime;
    settlingTime(index) = stepMetrics.SettlingTime;
    overshoot(index) = stepMetrics.Overshoot;
    actuatorBandwidth(index) = bandwidth(model);
    exactPhase = -80 * delay(index);
    padePhase = -2 * atan(80 * delay(index) / 2);
    phaseError80Deg(index) = abs(rad2deg(padePhase - exactPhase));
    assert(info.actuatorDcGain > 0, 'M3:ActuatorDcGain', ...
        'Every manual comparison must have positive DC gain.');
end
verificationPassed = actuatorBandwidth >= criteria.bandwidthMinimum & ...
    actuatorBandwidth <= criteria.bandwidthMaximum & ...
    overshoot <= criteria.overshootMaximum & ...
    phaseError80Deg <= criteria.phaseErrorMaximumDeg;
comparisonTable = table(choice, wn, zeta, delay, riseTime, ...
    settlingTime, overshoot, actuatorBandwidth, phaseError80Deg, ...
    verificationPassed, 'VariableNames', {'Choice', 'wn', 'zeta', ...
    'delay', 'RiseTime', 'SettlingTime', 'Overshoot', 'Bandwidth', ...
    'PhaseError80Deg', 'VerificationPassed'});
end

function localPlotDelayComparison( ...
    frequencies, exactResponse, padeResponse, delay, filePath)
exactMagnitudeDb = 20 * log10(abs(exactResponse));
padeMagnitudeDb = 20 * log10(abs(padeResponse));
exactPhaseDeg = -frequencies * delay * 180 / pi;
padePhaseDeg = -2 * atan(frequencies * delay / 2) * 180 / pi;

plotFigure = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1050, 720]);
layout = tiledlayout(plotFigure, 2, 1, 'TileSpacing', 'compact');
title(layout, 'M3 — Ritardo esatto e Padé del primo ordine', ...
    'Color', [0.10, 0.10, 0.10]);

magnitudeAxes = nexttile(layout);
semilogx(magnitudeAxes, frequencies, exactMagnitudeDb, '-', ...
    'LineWidth', 1.8, 'Color', [0.00, 0.35, 0.70], ...
    'DisplayName', 'Ritardo esatto');
hold(magnitudeAxes, 'on');
semilogx(magnitudeAxes, frequencies, padeMagnitudeDb, '--', ...
    'LineWidth', 1.8, 'Color', [0.85, 0.33, 0.10], ...
    'DisplayName', 'Padé ordine 1');
localStyleAxes(magnitudeAxes);
grid(magnitudeAxes, 'on');
xlim(magnitudeAxes, [frequencies(1), frequencies(end)]);
ylim(magnitudeAxes, [-0.02, 0.02]);
ylabel(magnitudeAxes, 'Modulo [dB]', 'Color', [0.10, 0.10, 0.10]);
legend(magnitudeAxes, 'Location', 'best', ...
    'TextColor', [0.10, 0.10, 0.10], 'Color', 'white');

phaseAxes = nexttile(layout);
semilogx(phaseAxes, frequencies, exactPhaseDeg, '-', ...
    'LineWidth', 1.8, 'Color', [0.00, 0.35, 0.70], ...
    'DisplayName', 'Ritardo esatto');
hold(phaseAxes, 'on');
semilogx(phaseAxes, frequencies, padePhaseDeg, '--', ...
    'LineWidth', 1.8, 'Color', [0.85, 0.33, 0.10], ...
    'DisplayName', 'Padé ordine 1');
localStyleAxes(phaseAxes);
grid(phaseAxes, 'on');
xlim(phaseAxes, [frequencies(1), frequencies(end)]);
xlabel(phaseAxes, 'Frequenza [rad/s]', 'Color', [0.10, 0.10, 0.10]);
ylabel(phaseAxes, 'Fase [deg]', 'Color', [0.10, 0.10, 0.10]);
legend(phaseAxes, 'Location', 'best', ...
    'TextColor', [0.10, 0.10, 0.10], 'Color', 'white');
set_scientific_figure_style(plotFigure);
exportgraphics(plotFigure, filePath, 'Resolution', 180);
close(plotFigure);
end

