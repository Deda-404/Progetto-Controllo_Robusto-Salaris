    '-', 'LineWidth', 1.8, 'Color', [0.00, 0.35, 0.70], ...
    'DisplayName', 'Secondo ordine');
hold(magnitudeAxes, 'on');
semilogx(magnitudeAxes, frequencies, 20 * log10(abs(actuatorResponse)), ...
    '--', 'LineWidth', 1.8, 'Color', [0.85, 0.33, 0.10], ...
    'DisplayName', 'Con Padé ordine 1');
