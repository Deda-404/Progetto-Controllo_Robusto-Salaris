legend(phaseAxes, 'Location', 'best', ...
    'TextColor', [0.10, 0.10, 0.10], 'Color', 'white');
set_scientific_figure_style(plotFigure);
exportgraphics(plotFigure, filePath, 'Resolution', 180);
close(plotFigure);
end

function localPlotFullSigma( ...
    GfullMeas, actuatorNaturalFrequency, elasticFrequencies, filePath)
frequencies = logspace(-2, 3, 901);
response = freqresp(GfullMeas, frequencies);
singularValues = zeros(2, numel(frequencies));
for index = 1:numel(frequencies)
    values = svd(response(:, :, index));
    singularValues(:, index) = values(1:2);
end

plotFigure = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1100, 680]);
plotAxes = axes(plotFigure);
semilogx(plotAxes, frequencies, 20 * log10(singularValues(1, :)), ...
    'LineWidth', 1.8, 'Color', [0.00, 0.35, 0.70], ...
    'DisplayName', '\sigma_1');
hold(plotAxes, 'on');
semilogx(plotAxes, frequencies, 20 * log10(singularValues(2, :)), ...
    'LineWidth', 1.8, 'Color', [0.85, 0.33, 0.10], ...
    'DisplayName', '\sigma_2');
xline(plotAxes, actuatorNaturalFrequency, ':', '\omega_n', ...
    'Color', [0.25, 0.25, 0.25], 'LabelVerticalAlignment', 'bottom', ...
    'HandleVisibility', 'off');
labelAlignments = {'middle', 'top'};
for index = 1:numel(elasticFrequencies)
    frequency = elasticFrequencies(index);
    label = sprintf('\\omega_{e%d}=%.1f', index, frequency);
    xline(plotAxes, frequency, '--', label, ...
        'Color', [0.45, 0.45, 0.45], ...
        'LabelVerticalAlignment', labelAlignments{index}, ...
        'HandleVisibility', 'off');
end
localStyleAxes(plotAxes);
grid(plotAxes, 'on');
xlabel(plotAxes, 'Frequenza [rad/s]', 'Color', [0.10, 0.10, 0.10]);
ylabel(plotAxes, 'Singular values [dB]', 'Color', [0.10, 0.10, 0.10]);
title(plotAxes, 'M3 — Singular values della pianta nominale completa', ...
    'Color', [0.10, 0.10, 0.10]);
legend(plotAxes, 'Location', 'best', ...
    'TextColor', [0.10, 0.10, 0.10], 'Color', 'white');
set_scientific_figure_style(plotFigure);
exportgraphics(plotFigure, filePath, 'Resolution', 180);
close(plotFigure);
end

function localStyleAxes(plotAxes)
set(plotAxes, 'Color', 'white', ...
    'XColor', [0.15, 0.15, 0.15], 'YColor', [0.15, 0.15, 0.15], ...
    'GridColor', [0.72, 0.72, 0.72], ...
    'MinorGridColor', [0.86, 0.86, 0.86]);
end
