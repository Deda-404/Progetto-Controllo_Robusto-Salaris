function metrics = validate_m5_performance_specs
%VALIDATE_M5_PERFORMANCE_SPECS Validate M5 targets, weights and d path.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory)
    mkdir(dataDirectory);
end
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

m2Path = fullfile(dataDirectory, 'm2_linearization_nominal.mat');
m3Path = fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat');
if ~isfile(m2Path)
    validate_m2_equilibrium_linearization;
end
if ~isfile(m3Path)
    validate_m3_nominal_actuated_plant;
end
m2 = load(m2Path);
m3 = load(m3Path);

spec = performance_specs_m5;
selection = select_m5_performance_specs(m2, m3, spec);
bandwidthCandidateTable = selection.bandwidthCandidateTable;
W1CandidateTable = selection.W1CandidateTable;
W2CandidateTable = selection.W2CandidateTable;
[W1siso, W1, W2siso, W2, weightInfo] = build_m5_weights(spec);

[Bd, disturbanceInputInfo] = ...
    build_joint_torque_disturbance_input(m2.qbar, m2.p);
finiteDifferenceStep = 1e-6;
BdFiniteDifference = zeros(8, 2);
for inputIndex = 1:2
    direction = zeros(2, 1);
    direction(inputIndex) = finiteDifferenceStep;
    positiveDerivative = sea_nonlinear_rhs_with_link_disturbance( ...
        m2.xbar, m2.taubar, direction, m2.p);
    negativeDerivative = sea_nonlinear_rhs_with_link_disturbance( ...
        m2.xbar, m2.taubar, -direction, m2.p);
    BdFiniteDifference(:, inputIndex) = ...
        (positiveDerivative - negativeDerivative) / ...
        (2 * finiteDifferenceStep);
end
bdAbsoluteError = max(abs(Bd - BdFiniteDifference), [], 'all');
bdRelativeError = norm(Bd - BdFiniteDifference, 'fro') / ...
    max(norm(Bd, 'fro'), eps);

numberActuatorStates = size(m3.Afull, 1) - size(Bd, 1);
BdFull = [Bd; zeros(numberActuatorStates, 2)];
Bcombined = [m3.Bfull, BdFull];
Dcombined = zeros(size(m3.CfullMeas, 1), 4);
disturbancePlant = ss(m3.Afull, Bcombined, m3.CfullMeas, ...
    Dcombined, 'StateName', m3.GfullMeas.StateName, ...
    'InputName', {'u1', 'u2', 'd1', 'd2'}, ...
    'OutputName', {'q1', 'q2', 'theta1', 'theta2'});

pathFrequencies = logspace(-2, 3, 301);
uPathDifference = freqresp(disturbancePlant(:, 1:2), ...
    pathFrequencies) - freqresp(m3.GfullMeas, pathFrequencies);
uPathMaximumError = max(abs(uPathDifference), [], 'all');

[~, ~, ~, linearizationInfo] = ...
    sea_linearize_static_equilibrium_analytic(m2.qbar, m2.p);
referenceDegrees = spec.referenceAmplitudeScenariosDeg(:);
referenceRadians = deg2rad(referenceDegrees);
maximumGravityLinearizationRelativeError = zeros(size(referenceDegrees));
maximumGravityTorque = zeros(size(referenceDegrees));
directions = [1, 0; 0, 1; 1, 1; 1, -1].';
directions = directions ./ vecnorm(directions, 2, 1);
gravityAtEquilibrium = sea_gravity(m2.qbar, m2.p);
for amplitudeIndex = 1:numel(referenceRadians)
    for directionIndex = 1:size(directions, 2)
        for signValue = [-1, 1]
            deltaQ = signValue * referenceRadians(amplitudeIndex) * ...
                directions(:, directionIndex);
            exactGravityDelta = sea_gravity( ...
                m2.qbar + deltaQ, m2.p) - gravityAtEquilibrium;
            linearGravityDelta = ...
                linearizationInfo.gravityJacobian * deltaQ;
            relativeError = norm(exactGravityDelta - ...
                linearGravityDelta, 2) / ...
                max(norm(exactGravityDelta, 2), eps);
            maximumGravityLinearizationRelativeError(amplitudeIndex) = ...
                max(maximumGravityLinearizationRelativeError(amplitudeIndex), ...
                relativeError);
            maximumGravityTorque(amplitudeIndex) = max( ...
                maximumGravityTorque(amplitudeIndex), ...
                norm(exactGravityDelta, inf));
        end
    end
end
referenceNominalScenario = abs(referenceRadians - ...
    spec.referenceAmplitude) <= 10 * eps;
referenceScenarioTable = table(referenceDegrees, referenceRadians, ...
    maximumGravityLinearizationRelativeError, maximumGravityTorque, ...
    referenceNominalScenario, 'VariableNames', {'Degrees', 'Radians', ...
    'MaxGravityLinearizationRelativeError', 'MaxGravityTorque', ...
    'NominalScenario'});

disturbanceTorque = spec.disturbanceTorqueScenarios(:);
seaDeformationJoint1 = disturbanceTorque / m2.p.Ks(1, 1);
seaDeformationJoint2 = disturbanceTorque / m2.p.Ks(2, 2);
disturbanceNominalScenario = abs(disturbanceTorque - ...
    spec.disturbanceTorqueAmplitude) <= 10 * eps;
disturbanceScenarioTable = table(disturbanceTorque, ...
    seaDeformationJoint1, seaDeformationJoint2, ...
    disturbanceNominalScenario, 'VariableNames', {'Torque', ...
    'SEADeformationJoint1', 'SEADeformationJoint2', 'NominalScenario'});

nominalReferenceIndex = find(referenceNominalScenario, 1);
nominalDisturbanceIndex = find(disturbanceNominalScenario, 1);
validationMetrics.dynamic = selection.criteria;
validationMetrics.weights = weightInfo;
validationMetrics.disturbance.BdFiniteDifference = BdFiniteDifference;
validationMetrics.disturbance.finiteDifferenceStep = finiteDifferenceStep;
validationMetrics.disturbance.maximumAbsoluteError = bdAbsoluteError;
validationMetrics.disturbance.relativeError = bdRelativeError;
validationMetrics.disturbance.uPathMaximumError = uPathMaximumError;
validationMetrics.disturbance.controlInputStateMatrix = m3.Bfull;
validationMetrics.disturbance.linkTorqueStateMatrix = BdFull;
validationMetrics.scenarios.nominalReferenceLocalError = ...
    maximumGravityLinearizationRelativeError(nominalReferenceIndex);
validationMetrics.scenarios.nominalReferenceGravityTorque = ...
    maximumGravityTorque(nominalReferenceIndex);
validationMetrics.scenarios.disturbanceToGravityScaleRatio = ...
    disturbanceTorque(nominalDisturbanceIndex) / ...
    maximumGravityTorque(nominalReferenceIndex);
validationMetrics.scenarios.nominalSEADeformation = [ ...
    seaDeformationJoint1(nominalDisturbanceIndex); ...
    seaDeformationJoint2(nominalDisturbanceIndex)];
validationMetrics.noControllerSynthesis = ...
    ~spec.controllerSynthesisAllowed && ~spec.useW3;

w1FigurePath = fullfile(figureDirectory, 'm5_weight_W1.png');
w2FigurePath = fullfile(figureDirectory, 'm5_weight_W2.png');
frequencyMapPath = fullfile(figureDirectory, ...
    'm5_spec_frequency_map.png');
localPlotW1Candidates(spec, w1FigurePath);
localPlotW2Candidates(spec, w2FigurePath);
localPlotFrequencyMap(selection, m2.poles, spec, frequencyMapPath);

datasetPath = fullfile(dataDirectory, 'm5_performance_specs.mat');
save(datasetPath, 'spec', 'W1siso', 'W1', 'W2siso', 'W2', ...
    'bandwidthCandidateTable', 'W1CandidateTable', ...
    'W2CandidateTable', 'Bd', 'BdFull', 'disturbanceInputInfo', ...
    'disturbancePlant', 'referenceScenarioTable', ...
    'disturbanceScenarioTable', 'selection', 'validationMetrics', '-v7');

asymptoteTolerance = 1e-7;
assert(selection.declaredBaselineMatches, ...
    'M5:DeclaredBaselineMismatch', ...
    'Metric-based selection differs from performance_specs_m5.');
assert(selection.selectedBandwidth.Admissible, ...
    'M5:BandwidthSelection', ...
    'The selected bandwidth is outside the derived M2/M3 window.');
assert(weightInfo.W1.stable && weightInfo.W1.proper && ...
    weightInfo.W2.stable && weightInfo.W2.proper && ...
    weightInfo.finite, 'M5:WeightProperties', ...
    'One or more M5 weights are unstable, improper or non-finite.');
assert(abs(weightInfo.W1.dcMeasured - weightInfo.W1.dcExpected) <= ...
    asymptoteTolerance && abs(weightInfo.W1.hfMeasured - ...
    weightInfo.W1.hfExpected) <= asymptoteTolerance && ...
    abs(weightInfo.W2.dcMeasured - weightInfo.W2.dcExpected) <= ...
    asymptoteTolerance && abs(weightInfo.W2.hfMeasured - ...
    weightInfo.W2.hfExpected) <= asymptoteTolerance, ...
    'M5:WeightAsymptotes', 'A weight asymptote is inconsistent.');
assert(isequal(size(W1), [2, 2]) && isequal(size(W2), [2, 2]) && ...
    norm(dcgain(W1) - diag(diag(dcgain(W1))), 'fro') <= eps && ...
    norm(dcgain(W2) - diag(diag(dcgain(W2))), 'fro') <= eps, ...
    'M5:MimoWeights', 'MIMO weights are not diagonal 2-by-2 systems.');
assert(bdAbsoluteError <= 1e-8 && bdRelativeError <= 1e-9, ...
    'M5:DisturbanceInputVerification', ...
    'Analytic and finite-difference Bd matrices disagree.');
assert(uPathMaximumError <= 1e-10 && ...
    norm(disturbancePlant.B(:, 1:2) - m3.Bfull, 'fro') == 0 && ...
    norm(disturbancePlant.B(:, 3:4) - BdFull, 'fro') == 0 && ...
    norm(disturbancePlant.D, 'fro') == 0, ...
    'M5:DisturbancePath', ...
    'Control and disturbance paths are not physically separated.');
assert(validationMetrics.noControllerSynthesis, ...
    'M5:ControllerOutOfScope', ...
    'M5 must not synthesize a controller or introduce W3.');
assert(all(referenceNominalScenario) == false || ...
    sum(referenceNominalScenario) == 1, 'M5:ReferenceScenarios', ...
    'The nominal reference scenario is not unique.');
assert(sum(referenceNominalScenario) == 1 && ...
    sum(disturbanceNominalScenario) == 1, 'M5:ScenarioSelection', ...
    'Nominal validation scenarios are missing or ambiguous.');
assert(isfile(datasetPath) && isfile(w1FigurePath) && ...
    isfile(w2FigurePath) && isfile(frequencyMapPath), ...
    'M5:Artifacts', 'One or more M5 artifacts were not generated.');

fprintf('\n=== Validazione M5: specifiche, pesi e disturbo ===\n');
fprintf(['Dati: lambda_u,max=%.9g s^-1, omega_el,min=%.9g rad/s, ' ...
    'BW_act=%.9g rad/s\n'], selection.criteria.lambdaUMax, ...
    selection.criteria.omegaElasticMin, ...
    selection.criteria.omegaActuator);
fprintf('Finestra omegaB: %.9g ... %.9g rad/s; selezione %.9g rad/s\n', ...
    selection.criteria.bandwidthMinimum, ...
    selection.criteria.bandwidthMaximum, spec.omegaB);
fprintf('W1: As=%.6g, Ms=%.6g, DC=%.6g, HF=%.6g\n', ...
    spec.As, spec.Ms, weightInfo.W1.dcMeasured, ...
    weightInfo.W1.hfMeasured);
fprintf(['W2: uScale=%.6g N m, omegaU=%.6g rad/s, alpha=%.6g, ' ...
    'DC=%.6g, HF=%.6g\n'], spec.uScale, spec.omegaU, ...
    spec.controlWeightAlpha, weightInfo.W2.dcMeasured, ...
    weightInfo.W2.hfMeasured);
fprintf('Bd: max abs FD error %.3e, relative %.3e\n', ...
    bdAbsoluteError, bdRelativeError);
fprintf(['Scenari nominali: riferimento %.6g deg, disturbo %.6g N m, ' ...
    'deformazioni SEA [%.6g; %.6g] rad\n'], ...
    rad2deg(spec.referenceAmplitude), spec.disturbanceTorqueAmplitude, ...
    validationMetrics.scenarios.nominalSEADeformation);
fprintf('Dataset: %s\n', datasetPath);
fprintf('[PASS] Quality gate numerico M5 superato; nessun controllore sintetizzato.\n');

metrics.spec = spec;
metrics.selection = selection;
metrics.weightInfo = weightInfo;
metrics.Bd = Bd;
metrics.BdFull = BdFull;
metrics.disturbancePlant = disturbancePlant;
metrics.validation = validationMetrics;
metrics.referenceScenarioTable = referenceScenarioTable;
metrics.disturbanceScenarioTable = disturbanceScenarioTable;
metrics.datasetPath = datasetPath;
metrics.figurePaths = {w1FigurePath; w2FigurePath; frequencyMapPath};
end

function localPlotW1Candidates(spec, filePath)
frequencies = logspace(-2, 3, 701);
plotFigure = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1050, 760]);
layout = tiledlayout(plotFigure, 2, 1, 'TileSpacing', 'compact');
title(layout, 'M5 — Sensibilità locale del peso W_1', ...
    'Color', [0.10, 0.10, 0.10]);

asAxes = nexttile(layout);
hold(asAxes, 'on');
for index = 1:numel(spec.AsCandidates)
    candidateSpec = spec;
    candidateSpec.As = spec.AsCandidates(index);
    candidateSpec.Ms = spec.Ms;
    [candidateWeight, ~, ~, ~] = build_m5_weights(candidateSpec);
    response = squeeze(abs(freqresp(candidateWeight, frequencies)));
    lineWidth = 1.4 + 1.2 * (candidateSpec.As == spec.As);
    semilogx(asAxes, frequencies, 20 * log10(response), ...
        'LineWidth', lineWidth, 'DisplayName', ...
        sprintf('A_s = %.2f', candidateSpec.As));
end
localStyleAxes(asAxes);
ylabel(asAxes, '|W_1| [dB]');
title(asAxes, sprintf('Variazione A_s con M_s = %.1f', spec.Ms), ...
    'Color', [0.10, 0.10, 0.10]);
legend(asAxes, 'Location', 'southwest', 'Color', 'white', ...
    'TextColor', [0.10, 0.10, 0.10]);

msAxes = nexttile(layout);
hold(msAxes, 'on');
for index = 1:numel(spec.MsCandidates)
    candidateSpec = spec;
    candidateSpec.As = spec.As;
    candidateSpec.Ms = spec.MsCandidates(index);
    [candidateWeight, ~, ~, ~] = build_m5_weights(candidateSpec);
    response = squeeze(abs(freqresp(candidateWeight, frequencies)));
    lineWidth = 1.4 + 1.2 * (candidateSpec.Ms == spec.Ms);
    semilogx(msAxes, frequencies, 20 * log10(response), ...
        'LineWidth', lineWidth, 'DisplayName', ...
        sprintf('M_s = %.1f', candidateSpec.Ms));
end
localStyleAxes(msAxes);
xlabel(msAxes, 'Frequenza [rad/s]');
ylabel(msAxes, '|W_1| [dB]');
title(msAxes, sprintf('Variazione M_s con A_s = %.2f', spec.As), ...
    'Color', [0.10, 0.10, 0.10]);
legend(msAxes, 'Location', 'southwest', 'Color', 'white', ...
    'TextColor', [0.10, 0.10, 0.10]);
exportgraphics(plotFigure, filePath, 'Resolution', 180);
close(plotFigure);
end

function localPlotW2Candidates(spec, filePath)
frequencies = logspace(-1, 3, 701);
plotFigure = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1050, 760]);
layout = tiledlayout(plotFigure, 2, 1, 'TileSpacing', 'compact');
title(layout, 'M5 — Normalizzazione e roll-up del peso W_2', ...
    'Color', [0.10, 0.10, 0.10]);

scaleAxes = nexttile(layout);
hold(scaleAxes, 'on');
for index = 1:numel(spec.uScaleCandidates)
    candidateSpec = spec;
    candidateSpec.uScale = spec.uScaleCandidates(index);
    [~, ~, candidateWeight] = build_m5_weights(candidateSpec);
    response = squeeze(abs(freqresp(candidateWeight, frequencies)));
    lineWidth = 1.4 + 1.2 * (candidateSpec.uScale == spec.uScale);
    semilogx(scaleAxes, frequencies, 20 * log10(response), ...
        'LineWidth', lineWidth, 'DisplayName', ...
        sprintf('u_{scale} = %.0f N m', candidateSpec.uScale));
end
localStyleAxes(scaleAxes);
ylabel(scaleAxes, '|W_2| [dB]');
title(scaleAxes, sprintf('Scala con omega_U = %.0f rad/s, alpha = %.0f', ...
    spec.omegaU, spec.controlWeightAlpha), ...
    'Color', [0.10, 0.10, 0.10]);
legend(scaleAxes, 'Location', 'northwest', 'Color', 'white', ...
    'TextColor', [0.10, 0.10, 0.10]);

shapeAxes = nexttile(layout);
hold(shapeAxes, 'on');
colors = lines(numel(spec.omegaUCandidates) * ...
    numel(spec.controlWeightAlphaCandidates));
lineIndex = 0;
for omegaIndex = 1:numel(spec.omegaUCandidates)
    for alphaIndex = 1:numel(spec.controlWeightAlphaCandidates)
        lineIndex = lineIndex + 1;
        candidateSpec = spec;
        candidateSpec.omegaU = spec.omegaUCandidates(omegaIndex);
        candidateSpec.controlWeightAlpha = ...
            spec.controlWeightAlphaCandidates(alphaIndex);
        [~, ~, candidateWeight] = build_m5_weights(candidateSpec);
        response = squeeze(abs(freqresp(candidateWeight, frequencies)));
        isBaseline = candidateSpec.omegaU == spec.omegaU && ...
            candidateSpec.controlWeightAlpha == spec.controlWeightAlpha;
        semilogx(shapeAxes, frequencies, 20 * log10(response), ...
            'LineWidth', 1.2 + 1.5 * isBaseline, ...
            'Color', colors(lineIndex, :), 'DisplayName', ...
            sprintf('omega_U=%g, alpha=%g', candidateSpec.omegaU, ...
            candidateSpec.controlWeightAlpha));
    end
end
localStyleAxes(shapeAxes);
xlabel(shapeAxes, 'Frequenza [rad/s]');
ylabel(shapeAxes, '|W_2| [dB]');
title(shapeAxes, sprintf('Forma con u_{scale} = %.0f N m', spec.uScale), ...
    'Color', [0.10, 0.10, 0.10]);
legend(shapeAxes, 'Location', 'northwest', 'NumColumns', 2, ...
    'Color', 'white', 'TextColor', [0.10, 0.10, 0.10]);
exportgraphics(plotFigure, filePath, 'Resolution', 180);
close(plotFigure);
end

function localPlotFrequencyMap(selection, m2Poles, spec, filePath)
elasticFrequencies = sort(abs(m2Poles(imag(m2Poles) > 1e-8)));
plotFigure = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1150, 620]);
plotAxes = axes(plotFigure, 'Color', 'white', ...
    'XColor', [0.10, 0.10, 0.10], 'YColor', [0.10, 0.10, 0.10], ...
    'GridColor', [0.72, 0.72, 0.72]);
hold(plotAxes, 'on');
set(plotAxes, 'XScale', 'log');

bandX = [selection.criteria.bandwidthMinimum, ...
    selection.criteria.bandwidthMaximum, ...
    selection.criteria.bandwidthMaximum, ...
    selection.criteria.bandwidthMinimum];
patch(plotAxes, bandX, [0.55, 0.55, 5.45, 5.45], ...
    [0.84, 0.92, 1.00], 'EdgeColor', 'none', ...
    'FaceAlpha', 0.45, 'DisplayName', 'Finestra omega_B');
localMapMarker(plotAxes, selection.criteria.lambdaUMax, 5, ...
    'Scala poli instabili', [0.80, 0.15, 0.15]);
localMapMarker(plotAxes, spec.omegaB, 4, ...
    'omega_B selezionata', [0.00, 0.45, 0.20]);
localMapMarker(plotAxes, spec.omegaU, 3, ...
    'omega_U', [0.55, 0.25, 0.70]);
localMapMarker(plotAxes, selection.criteria.omegaActuator, 2, ...
    'Banda attuatore', [0.90, 0.45, 0.05]);
for index = 1:numel(elasticFrequencies)
    localMapMarker(plotAxes, elasticFrequencies(index), 1, ...
        sprintf('Modo elastico %d', index), [0.05, 0.35, 0.75]);
end
set(plotAxes, 'YTick', 1:5, 'YTickLabel', { ...
    'modi elastici', 'attuatore', 'W_2', 'W_1', 'instabilità'}, ...
    'YLim', [0.55, 5.45]);
xlim(plotAxes, [4, 120]);
grid(plotAxes, 'on');
xlabel(plotAxes, 'Frequenza / scala dinamica [rad/s]', ...
    'Color', [0.10, 0.10, 0.10]);
title(plotAxes, 'M5 — Separazione delle scale di progetto', ...
    'Color', [0.10, 0.10, 0.10]);
legend(plotAxes, 'Location', 'southoutside', 'NumColumns', 3, ...
    'Color', 'white', 'TextColor', [0.10, 0.10, 0.10]);
exportgraphics(plotFigure, filePath, 'Resolution', 180);
close(plotFigure);
end

function localMapMarker(plotAxes, frequency, level, label, color)
plot(plotAxes, frequency, level, 'o', 'MarkerSize', 9, ...
    'MarkerFaceColor', color, 'MarkerEdgeColor', color, ...
    'DisplayName', sprintf('%s: %.2f', label, frequency));
xline(plotAxes, frequency, ':', 'Color', color, ...
    'HandleVisibility', 'off');
end

function localStyleAxes(plotAxes)
grid(plotAxes, 'on');
plotAxes.Color = 'white';
plotAxes.XScale = 'log';
plotAxes.XColor = [0.12, 0.12, 0.12];
plotAxes.YColor = [0.12, 0.12, 0.12];
plotAxes.GridColor = [0.72, 0.72, 0.72];
end
