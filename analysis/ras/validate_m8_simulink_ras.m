function metrics = validate_m8_simulink_ras(rebuild, refreshRasFigure)
%VALIDATE_M8_SIMULINK_RAS Build all M8 artifacts and enforce its gate.

arguments
    rebuild (1, 1) logical = true
    refreshRasFigure (1,1) logical = false
end

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));
addpath(genpath(fullfile(projectRoot, 'simulink')));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
datasetPath = fullfile(dataDirectory, 'm8_lqg_nonlinear_ras.mat');
if ~rebuild && isfile(datasetPath)
    stored = load(datasetPath, 'qualityGate');
    assert(stored.qualityGate.passed, 'M8:CachedQualityGate', ...
        'The cached M8 dataset does not contain a passing quality gate.');
    metrics = load(datasetPath);
    metrics.datasetPath = datasetPath;
    if refreshRasFigure
        search=struct('convergentPoints',metrics.rasAllPoints(metrics.rasAllPoints.Convergent,:), ...
            'divergentPoints',metrics.rasAllPoints(~metrics.rasAllPoints.Convergent,:), ...
            'boundary',metrics.rasBoundary,'config',metrics.simulationConfig.ras);
        localPlotRas(search,fullfile(figureDirectory,'m8_lqg_ras_q_plane.png'), ...
            'M8 - Mappa empirica: xhat(0)=0, non certificata');
    end
    fprintf('[PASS] Dataset M8 gia'' validato: %s\n', datasetPath);
    return
end
if ~isfolder(dataDirectory), mkdir(dataDirectory); end
if ~isfolder(figureDirectory), mkdir(figureDirectory); end

simulationConfig = m8_specs;
m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m6 = load(fullfile(dataDirectory, 'm6_lqg_no_integrator.mat'));
modelMetadata = build_m8_simulink_model(string(projectRoot));

controllerMetadata = struct( ...
    'sourceDataset', "results/data/m6_lqg_no_integrator.mat", ...
    'K', m6.K, 'L', m6.L, 'Nr', m6.Nr, ...
    'controllerOrder', size(m6.Klqg.A, 1), ...
    'integratorStateCount', 0, 'retunedInM8', false, ...
    'primaryController', "M6 LQG without integrator", ...
    'm7Status', "PARTIAL - frozen; no further tuning", ...
    'integralBenchmarkImplemented', false, ...
    'integralBenchmarkLabel', "representative integral benchmark", ...
    'integralBenchmarkBasis', ...
        "existing linear M7 results only; excluded from the M8 gate");
assert(isequaln(modelMetadata.K, m6.K) && ...
    isequaln(modelMetadata.L, m6.L) && ...
    isequaln(modelMetadata.Nr, m6.Nr), 'M8:ControllerChanged', ...
    'The Simulink controller differs from the validated M6 dataset.');

solverConfig = localCompareSolvers(projectRoot, simulationConfig, m3);

equilibriumResult = simulate_m8_nonlinear(struct( ...
    'horizon', simulationConfig.simulation.equilibriumHorizon), ...
    string(projectRoot), simulationConfig);
equilibriumValidation = struct( ...
    'horizon', equilibriumResult.time(end), ...
    'maxQError', max(abs(equilibriumResult.xMechanical(:, 1:2) - ...
        m3.xbar(1:2).'), [], 'all'), ...
    'maxThetaError', max(abs(equilibriumResult.xMechanical(:, 5:6) - ...
        m3.xbar(5:6).'), [], 'all'), ...
    'maxControlError', max(abs(equilibriumResult.control - ...
        m3.taubar.'), [], 'all'));
equilibriumValidation.passed = ...
    equilibriumValidation.maxQError <= ...
        simulationConfig.equilibrium.positionTolerance && ...
    equilibriumValidation.maxThetaError <= ...
        simulationConfig.equilibrium.positionTolerance && ...
    equilibriumValidation.maxControlError <= ...
        simulationConfig.equilibrium.controlTolerance;

[trackingResults, ltiVsNonlinearMetrics] = localTracking( ...
    projectRoot, simulationConfig, m3, m6);
tracking2deg = trackingResults{1};
tracking5deg = trackingResults{2};
tracking8deg = trackingResults{3};
[disturbanceMetrics, disturbanceResponses] = localDisturbances( ...
    projectRoot, simulationConfig, m3, m6);
[noiseMetrics, noiseResponses] = localNoise( ...
    projectRoot, simulationConfig, m3, m6);

rasSearchConfig = simulationConfig.ras;
rasInitialConditions = struct( ...
    'section', "dq1/dq2", 'qdot0', zeros(2, 1), ...
    'thetaShiftEqualsQShift', true, 'thetaDot0', zeros(2, 1), ...
    'actuatorsAtNominalEquilibrium', true, ...
    'controllerEstimate0', zeros(14, 1), ...
    'searchBoxDeg', rasSearchConfig.searchBoxDeg, ...
    'searchBoxMeaning', ...
        "computational boundary, not a saturation or physical limit");
primaryRas = estimate_lqg_ras(string(projectRoot), ...
    simulationConfig, "zero-estimate");
rasConvergent = primaryRas.convergentPoints;
rasBoundary = primaryRas.boundary;
rasMetrics = primaryRas.metrics;
rasAllPoints = primaryRas.allPoints;
if simulationConfig.ras.secondarySectionEnabled
    secondaryRas = estimate_lqg_ras(string(projectRoot), ...
        simulationConfig, "coherent-estimate");
else
    secondaryRas = struct('section', "not executed", ...
        'reason', "disabled by the M8 source of truth");
end

localPlotTracking(trackingResults, m3, fullfile(figureDirectory, ...
    'm8_lqg_nonlinear_tracking.png'));
localPlotLtiComparison(trackingResults, fullfile(figureDirectory, ...
    'm8_lqg_lti_vs_nonlinear.png'));
localPlotDisturbances(disturbanceResponses, m3, fullfile( ...
    figureDirectory, 'm8_lqg_nonlinear_disturbance.png'));
localPlotRas(primaryRas, fullfile(figureDirectory, ...
    'm8_lqg_ras_q_plane.png'), ...
    'M8 — RAS empirica primaria: xhat(0)=0');
if simulationConfig.ras.secondarySectionEnabled
    localPlotRas(secondaryRas, fullfile(figureDirectory, ...
        'm8_lqg_ras_secondary_section.png'), ...
        'M8 — Sezione diagnostica: stima iniziale coerente');
end

requiredFigures = [ ...
    "m8_lqg_nonlinear_tracking.png"; ...
    "m8_lqg_lti_vs_nonlinear.png"; ...
    "m8_lqg_nonlinear_disturbance.png"; ...
    "m8_lqg_ras_q_plane.png"];
figuresExist = all(arrayfun(@(name) isfile(fullfile( ...
    figureDirectory, name)), requiredFigures));
qualityGate = struct;
qualityGate.repositoryStateUpdated = true;
qualityGate.m7Frozen = ~controllerMetadata.retunedInM8;
qualityGate.modelBuilt = isfile(modelMetadata.modelPath);
qualityGate.actuatorsIncluded = modelMetadata.actuatorStateCount == 6;
qualityGate.controllerUnchanged = isequaln(modelMetadata.K, m6.K) && ...
    isequaln(modelMetadata.L, m6.L) && ...
    isequaln(modelMetadata.Nr, m6.Nr);
qualityGate.coordinatesCorrect = ...
    modelMetadata.absolutePlantCoordinates && ...
    modelMetadata.incrementalControllerCoordinates;
qualityGate.equilibriumPassed = equilibriumValidation.passed;
qualityGate.trackingFinite = all(isfinite( ...
    [tracking2deg.metrics{:,:}; tracking5deg.metrics{:,:}; ...
    tracking8deg.metrics{:,:}]), 'all');
qualityGate.disturbanceFinite = all(isfinite( ...
    disturbanceMetrics{:, 3:end}), 'all');
qualityGate.noiseFinite = all(isfinite([noiseMetrics.rmsTrackingError; ...
    noiseMetrics.rmsEstimationErrorQ; ...
    noiseMetrics.rmsControlVariation]));
qualityGate.ltiNonlinearCompared = height(ltiVsNonlinearMetrics) == 6;
qualityGate.rasDeterministic = height(rasBoundary) == ...
    simulationConfig.ras.numberDirections;
qualityGate.rasBoundaryProduced = all(isfinite(rasBoundary.RadiusDeg));
qualityGate.noInventedSaturation = ~simulationConfig.saturationEnabled;
qualityGate.figuresProduced = figuresExist;
qualityGate.passed = all(structfun(@(value) islogical(value) && value, ...
    qualityGate));

save(datasetPath, 'simulationConfig', 'solverConfig', ...
    'equilibriumValidation', 'tracking2deg', 'tracking5deg', ...
    'tracking8deg', 'disturbanceMetrics', 'disturbanceResponses', ...
    'noiseMetrics', 'noiseResponses', 'ltiVsNonlinearMetrics', ...
    'rasSearchConfig', 'rasInitialConditions', 'rasConvergent', ...
    'rasBoundary', 'rasMetrics', 'rasAllPoints', 'secondaryRas', ...
    'controllerMetadata', 'modelMetadata', 'qualityGate', '-v7.3');
assert(qualityGate.passed, 'M8:QualityGate', ...
    'At least one M8 quality-gate condition failed.');

fprintf('\n=== Validazione M8: Simulink non lineare e RAS LQG ===\n');
fprintf(['Solver: %s, RelTol %.1e, AbsTol %.1e, MaxStep %.4g s; ' ...
    'ode45/ode23t max q difference %.3e rad\n'], ...
    solverConfig.selected, solverConfig.relativeTolerance, ...
    solverConfig.absoluteTolerance, solverConfig.maximumStep, ...
    solverConfig.maximumQDifference);
fprintf('Equilibrio: q %.3e rad, theta %.3e rad, u %.3e N m\n', ...
    equilibriumValidation.maxQError, ...
    equilibriumValidation.maxThetaError, ...
    equilibriumValidation.maxControlError);
fprintf('Tracking: %d casi; max LTI-NL %.4g rad, RMS max %.4g rad\n', ...
    height(ltiVsNonlinearMetrics), ...
    max(ltiVsNonlinearMetrics.MaxQDifference), ...
    max(ltiVsNonlinearMetrics.RmsQDifference));
fprintf(['RAS primaria: %d simulazioni, %d convergenti, %d divergenti, ' ...
    'r=[%.3g, %.3g] deg, area %.4g deg^2\n'], ...
    rasMetrics.numberSimulations, rasMetrics.numberConvergent, ...
    rasMetrics.numberDivergent, rasMetrics.minimumRadiusDeg, ...
    rasMetrics.maximumRadiusDeg, rasMetrics.approximateAreaDeg2);
fprintf('Dataset: %s\n', datasetPath);
fprintf('[PASS] Quality gate M8 completo superato.\n');

metrics = struct('simulationConfig', simulationConfig, ...
    'solverConfig', solverConfig, ...
    'equilibriumValidation', equilibriumValidation, ...
    'ltiVsNonlinearMetrics', ltiVsNonlinearMetrics, ...
    'disturbanceMetrics', disturbanceMetrics, ...
    'noiseMetrics', noiseMetrics, 'rasMetrics', rasMetrics, ...
    'qualityGate', qualityGate, 'datasetPath', datasetPath);
end

function solverConfig = localCompareSolvers(projectRoot, config, m3)
scenario.reference = [deg2rad(2), 0];
scenario.horizon = config.simulation.trackingHorizon;
scenario.solver = config.solver.candidates(1);
standard = simulate_m8_nonlinear(scenario, string(projectRoot), config);
scenario.solver = config.solver.candidates(2);
stiff = simulate_m8_nonlinear(scenario, string(projectRoot), config);
standardQ = standard.xMechanical(:, 1:2) - m3.xbar(1:2).';
stiffQ = stiff.xMechanical(:, 1:2) - m3.xbar(1:2).';
standardOnStiff = interp1(standard.time, standardQ, stiff.time, ...
    'linear', 'extrap');
solverConfig = config.solver;
solverConfig.standardSolver = standard.solver;
solverConfig.moderatelyStiffSolver = stiff.solver;
solverConfig.standardRuntimeSec = standard.elapsedWallTime;
solverConfig.moderatelyStiffRuntimeSec = stiff.elapsedWallTime;
solverConfig.maximumQDifference = max(abs( ...
    standardOnStiff - stiffQ), [], 'all');
solverConfig.selected = config.solver.selected;
solverConfig.selectionReason = ...
    "ode23t retained for the SEA/actuator moderately stiff dynamics; " + ...
    "agreement with ode45 is explicitly quantified";
end

function [trackingResults, comparisonTable] = localTracking( ...
    projectRoot, config, m3, m6)
amplitudes = config.tracking.referenceAmplitudesDeg(:);
trackingResults = cell(numel(amplitudes), 1);
comparisonRows = zeros(numel(amplitudes) * 2, 4);
comparisonIndex = 0;
for amplitudeIndex = 1:numel(amplitudes)
    amplitudeRad = deg2rad(amplitudes(amplitudeIndex));
    metricRows = zeros(2, 7);
    nonlinearResponses = cell(2, 1);
    ltiResponses = cell(2, 1);
    for jointIndex = 1:2
        scenario.reference = zeros(1, 2);
        scenario.reference(jointIndex) = amplitudeRad;
        scenario.horizon = config.simulation.trackingHorizon;
        nonlinear = simulate_m8_nonlinear(scenario, ...
            string(projectRoot), config);
        time = (0:config.simulation.inputTimeStep:scenario.horizon).';
        ltiInput = zeros(numel(time), 8);
        ltiInput(:, jointIndex) = amplitudeRad;
        ltiOutput = lsim(m6.lqgClosedLoop, ltiInput, time);
        qNonlinear = nonlinear.xMechanical(:, 1:2) - m3.xbar(1:2).';
        qLtiAtNl = interp1(time, ltiOutput(:, 1:2), ...
            nonlinear.time, 'linear');
        difference = qNonlinear - qLtiAtNl;
        theta = nonlinear.xMechanical(:, 5:6);
        deformation = theta - nonlinear.xMechanical(:, 1:2);
        responseMetrics = localTrackingMetrics(nonlinear.time, ...
            qNonlinear, nonlinear.control, deformation, ...
            jointIndex, amplitudeRad, config);
        metricRows(jointIndex, :) = responseMetrics;
        comparisonIndex = comparisonIndex + 1;
        comparisonRows(comparisonIndex, :) = [amplitudes(amplitudeIndex), ...
            jointIndex, max(abs(difference), [], 'all'), ...
            sqrt(mean(difference.^2, 'all'))];
        nonlinearResponses{jointIndex} = localCompactResponse( ...
            nonlinear, m3);
        ltiResponses{jointIndex} = struct('time', time, ...
            'q', ltiOutput(:, 1:2), 'theta', ltiOutput(:, 3:4), ...
            'controlDelta', ltiOutput(:, 5:6));
    end
    metrics = array2table(metricRows, 'VariableNames', ...
        {'Joint', 'SettlingTime', 'OvershootPercent', ...
        'SteadyStateErrorRelative', 'CrossCouplingPeakRatio', ...
        'PeakControlNm', 'PeakSeaDeformationRad'});
    metrics.Joint = (1:2).';
    trackingResults{amplitudeIndex} = struct( ...
        'amplitudeDeg', amplitudes(amplitudeIndex), ...
        'metrics', metrics, 'nonlinearResponses', ...
        {nonlinearResponses}, 'ltiResponses', {ltiResponses});
end
comparisonTable = array2table(comparisonRows, 'VariableNames', ...
    {'AmplitudeDeg', 'Joint', 'MaxQDifference', 'RmsQDifference'});
end

function row = localTrackingMetrics(time, q, control, deformation, ...
    jointIndex, reference, config)
otherJoint = 3 - jointIndex;
finalValue = mean(q(max(1, floor(0.9 * end)):end, jointIndex));
settling = localSettlingTime(q(:, jointIndex), finalValue, time, ...
    config.simulation.settlingBandFraction * abs(reference));
overshoot = 100 * max(0, (max(q(:, jointIndex)) - reference) / ...
    abs(reference));
steadyError = abs(finalValue - reference) / abs(reference);
crossCoupling = max(abs(q(:, otherJoint))) / ...
    max(max(abs(q(:, jointIndex))), eps);
row = [jointIndex, settling, overshoot, steadyError, crossCoupling, ...
    max(abs(control), [], 'all'), max(abs(deformation), [], 'all')];
end

function [metricTable, responses] = localDisturbances( ...
    projectRoot, config, m3, m6)
amplitudes = config.disturbance.amplitudesNm(:);
rows = zeros(numel(amplitudes) * 2, 9);
responses = cell(numel(amplitudes), 2);
rowIndex = 0;
for amplitudeIndex = 1:numel(amplitudes)
    for jointIndex = 1:2
        scenario.disturbance = zeros(1, 2);
        scenario.disturbance(jointIndex) = amplitudes(amplitudeIndex);
        scenario.horizon = config.simulation.disturbanceHorizon;
        nonlinear = simulate_m8_nonlinear(scenario, ...
            string(projectRoot), config);
        time = (0:config.simulation.inputTimeStep:scenario.horizon).';
        ltiInput = zeros(numel(time), 8);
        ltiInput(:, jointIndex + 2) = amplitudes(amplitudeIndex);
        ltiOutput = lsim(m6.lqgClosedLoop, ltiInput, time);
        q = nonlinear.xMechanical(:, 1:2) - m3.xbar(1:2).';
        qLtiAtNl = interp1(time, ltiOutput(:, 1:2), ...
            nonlinear.time, 'linear');
        finalValue = mean(q(max(1, floor(0.9 * end)):end, jointIndex));
        affectedPeak = max(abs(q(:, jointIndex)));
        threshold = config.simulation.settlingBandFraction * ...
            max([affectedPeak, abs(finalValue), eps]);
        settling = localSettlingTime(q(:, jointIndex), finalValue, ...
            nonlinear.time, threshold);
        otherJoint = 3 - jointIndex;
        rowIndex = rowIndex + 1;
        rows(rowIndex, :) = [amplitudes(amplitudeIndex), jointIndex, ...
            affectedPeak, finalValue, settling, ...
            max(abs(q(:, otherJoint))) / max(affectedPeak, eps), ...
            max(abs(nonlinear.control), [], 'all'), ...
            max(abs(q - qLtiAtNl), [], 'all'), ...
            sqrt(mean((q - qLtiAtNl).^2, 'all'))];
        responses{amplitudeIndex, jointIndex} = ...
            localCompactResponse(nonlinear, m3);
    end
end
metricTable = array2table(rows, 'VariableNames', ...
    {'AmplitudeNm', 'Joint', 'PeakQRad', 'SteadyStateOffsetRad', ...
    'SettlingTime', 'CrossCouplingPeakRatio', 'PeakControlNm', ...
    'MaxQDifferenceLtiNl', 'RmsQDifferenceLtiNl'});
end

function [noiseMetrics, responses] = localNoise( ...
    projectRoot, config, m3, m6)
rng(config.noise.seed, 'twister');
time = (0:config.simulation.inputTimeStep: ...
    config.simulation.noiseHorizon).';
noise = m6.noiseMetrics.sigmaYRad * randn(numel(time), 4);
scenario.reference = [deg2rad(5), 0];
scenario.measurementNoise = noise;
scenario.horizon = config.simulation.noiseHorizon;
noisy = simulate_m8_nonlinear(scenario, string(projectRoot), config);
repeat = simulate_m8_nonlinear(scenario, string(projectRoot), config);
scenario.measurementNoise = zeros(size(noise));
deterministic = simulate_m8_nonlinear(scenario, ...
    string(projectRoot), config);
q = noisy.xMechanical(:, 1:2) - m3.xbar(1:2).';
reference = [deg2rad(5) * ones(numel(noisy.time), 1), ...
    zeros(numel(noisy.time), 1)];
estimationErrorQ = q - noisy.xhat(:, 1:2);
deterministicControl = interp1(deterministic.time, ...
    deterministic.control, noisy.time, 'linear');
controlVariation = noisy.control - deterministicControl;
noiseMetrics = struct( ...
    'seed', config.noise.seed, ...
    'sigmaYRad', m6.noiseMetrics.sigmaYRad, ...
    'rmsTrackingErrorByJoint', sqrt(mean((q - reference).^2, 1)).', ...
    'rmsEstimationErrorQByJoint', sqrt(mean(estimationErrorQ.^2, 1)).', ...
    'rmsControlVariationByJoint', sqrt(mean(controlVariation.^2, 1)).', ...
    'rmsTrackingError', sqrt(mean((q - reference).^2, 'all')), ...
    'rmsEstimationErrorQ', sqrt(mean(estimationErrorQ.^2, 'all')), ...
    'rmsControlVariation', sqrt(mean(controlVariation.^2, 'all')), ...
    'repeatError', max(abs(noisy.xMechanical - ...
        repeat.xMechanical), [], 'all'), ...
    'linearM6RmsTrackingError', m6.noiseMetrics.rmsTrackingError, ...
    'linearM6RmsEstimationErrorQ', ...
        m6.noiseMetrics.rmsEstimationErrorQ, ...
    'linearM6RmsControlVariation', ...
        m6.noiseMetrics.rmsControlVariation);
responses = struct('noisy', localCompactResponse(noisy, m3), ...
    'deterministic', localCompactResponse(deterministic, m3));
end

function response = localCompactResponse(result, m3)
response = struct('time', result.time, ...
    'q', result.xMechanical(:, 1:2) - m3.xbar(1:2).', ...
    'theta', result.xMechanical(:, 5:6) - m3.xbar(5:6).', ...
    'qdot', result.xMechanical(:, 3:4), ...
    'thetaDot', result.xMechanical(:, 7:8), ...
    'xhat', result.xhat, 'control', result.control, ...
    'motorTorque', result.motorTorque);
end

function settlingTime = localSettlingTime(signal, finalValue, time, threshold)
outside = abs(signal - finalValue) > max(threshold, 100 * eps);
lastOutside = find(outside, 1, 'last');
if isempty(lastOutside)
    settlingTime = 0;
elseif lastOutside == numel(time)
    settlingTime = inf;
else
    settlingTime = time(lastOutside + 1);
end
end

function localPlotTracking(results, m3, filePath) %#ok<INUSD>
figureHandle = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 1200, 850]);
layout = tiledlayout(3, 2, 'TileSpacing', 'compact');
for amplitudeIndex = 1:3
    for jointIndex = 1:2
        nexttile;
        response = results{amplitudeIndex}.nonlinearResponses{jointIndex};
        firstLine = plot(response.time, rad2deg(response.q(:, 1)), ...
            'LineWidth', 1.6);
        hold on;
        secondLine = plot(response.time, rad2deg(response.q(:, 2)), ...
            'LineWidth', 1.6);
        yline(results{amplitudeIndex}.amplitudeDeg, '--');
        grid on; box on;
        title(sprintf('%g deg, r_%d', ...
            results{amplitudeIndex}.amplitudeDeg, jointIndex));
        ylabel('delta q [deg]');
        if amplitudeIndex == 1 && jointIndex == 1
            legend([firstLine, secondLine], {'q_1', 'q_2'}, ...
                'Location', 'best');
        end
    end
end
xlabel(layout, 'Tempo [s]');
title(layout, 'M8 — Tracking non lineare LQG M6');
set_scientific_figure_style(figureHandle);
exportgraphics(figureHandle, filePath, 'Resolution', 180);
close(figureHandle);
end

