function localPlotRas(search, filePath, plotTitle)
figureHandle = figure('Visible', 'off', 'Color', 'white', ...
    'Position', [100, 100, 850, 780]);
convergent = search.convergentPoints;
divergent = search.divergentPoints;
legendHandles = gobjects(0);
legendLabels = strings(0);
if ~isempty(convergent)
    legendHandles(end + 1) = scatter( ...
        convergent.Dq1Deg, convergent.Dq2Deg, 28, ...
        [0.18, 0.62, 0.32], 'filled');
    legendLabels(end + 1) = "Convergente";
    hold on;
end
if ~isempty(divergent)
    legendHandles(end + 1) = scatter( ...
        divergent.Dq1Deg, divergent.Dq2Deg, 34, ...
        [0.82, 0.22, 0.18], 'x', 'LineWidth', 1.3);
    legendLabels(end + 1) = "Divergente";
    hold on;
end
boundary = [search.boundary.Dq1Deg, search.boundary.Dq2Deg];
boundary = [boundary; boundary(1, :)];
legendHandles(end + 1) = plot( ...
    boundary(:, 1), boundary(:, 2), 'k-', 'LineWidth', 2);
legendLabels(end + 1) = "Frontiera empirica";
legendHandles(end + 1) = plot(0, 0, 'kp', ...
    'MarkerFaceColor', 'yellow', 'MarkerSize', 12);
legendLabels(end + 1) = "Origine";
axis equal; grid on; box on;
xlim(1.08 * [-search.config.searchBoxDeg, search.config.searchBoxDeg]);
ylim(1.08 * [-search.config.searchBoxDeg, search.config.searchBoxDeg]);
xlabel('delta q_1(0) [deg]');
ylabel('delta q_2(0) [deg]');
title(plotTitle);
legend(legendHandles, legendLabels, 'Location', 'southoutside');
set_scientific_figure_style(figureHandle);
exportgraphics(figureHandle, filePath, 'Resolution', 180);
close(figureHandle);
end
