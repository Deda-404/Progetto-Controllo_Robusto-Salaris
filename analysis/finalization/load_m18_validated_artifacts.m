function evidence = load_m18_validated_artifacts
%LOAD_M18_VALIDATED_ARTIFACTS Load the frozen M1-M17 evidence for M18.

root = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
dataRoot = fullfile(root, "results", "data");
sourceKeys = ["M1"; "M2"; "M3"; "M4"; "M5"; "M6"; "M7"; "M8"; ...
    "M9"; "M10"; "M11"; "M12"; "M13"; "M14"; "M15"; "M16"; "M17"];
sourcePaths = [ ...
    fullfile(root, "docs", "MODELLO_NON_LINEARE.md"); ...
    fullfile(dataRoot, "m2_linearization_nominal.mat"); ...
    fullfile(dataRoot, "m3_nominal_actuated_plant.mat"); ...
    fullfile(dataRoot, "m4_uncertain_plant.mat"); ...
    fullfile(dataRoot, "m5_performance_specs.mat"); ...
    fullfile(dataRoot, "m6_lqg_no_integrator.mat"); ...
    fullfile(dataRoot, "m7_augmented_cost_feasibility.mat"); ...
    fullfile(dataRoot, "m8_lqg_nonlinear_ras.mat"); ...
    fullfile(dataRoot, "m9_hinf_mixsyn_nominal.mat"); ...
    fullfile(dataRoot, "m10_hinfsyn_nominal.mat"); ...
    fullfile(dataRoot, "m11_hinfstruct_structured.mat"); ...
    fullfile(dataRoot, "m12_mu_analysis_a5.mat"); ...
    fullfile(dataRoot, "m13_musyn_dk.mat"); ...
    fullfile(dataRoot, "m14_final_mu_analysis_kmu.mat"); ...
    fullfile(dataRoot, "m15_nonlinear_robust_validation.mat"); ...
    fullfile(dataRoot, "m16_monte_carlo_uncertain_linear.mat"); ...
    fullfile(dataRoot, "m17_final_controller_comparison.mat")];
exists = isfile(sourcePaths);
assert(all(exists), "M18:MissingFrozenEvidence", ...
    "Missing frozen evidence: %s", strjoin(sourcePaths(~exists), ", "));
evidence = struct;
evidence.root = root;
evidence.config = finalization_specs_m18;
evidence.sourceInventory = table(sourceKeys, sourcePaths, exists, ...
    'VariableNames', {'Milestone', 'Path', 'Exists'});
for index = 2:numel(sourceKeys)
    evidence.(lower(sourceKeys(index))) = load(sourcePaths(index));
end
evidence.m1.documentPath = sourcePaths(1);
evidence.m1.documentText = string(fileread(sourcePaths(1)));
evidence.nominalParameters = sea_params_nominal;
evidence.nominalActuator = actuator_params_nominal;
end
