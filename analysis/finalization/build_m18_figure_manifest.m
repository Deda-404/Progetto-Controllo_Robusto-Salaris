function localWriteTex(m,path)
f=fopen(path,'w'); c=onCleanup(@() fclose(f));
fprintf(f,'%% Generated by build_m18_figure_manifest.m. Do not edit.\n\\begin{table}[p]\\centering\\small\n\\begin{tabular}{p{1.8cm}p{7.6cm}p{1.8cm}p{1.8cm}}\n\\toprule\nMilestone & File & Capitolo & Uso slide \\\\\n\\midrule\n');
for k=1:height(m), use="no"; if m.PresentationUse(k), use="si"; end; fprintf(f,'%s & \\texttt{%s} & %s & %s \\\\\n',m.Milestone(k),tex(m.FileName(k)),m.ReportSection(k),use); end
fprintf(f,'\\bottomrule\n\\end{tabular}\n\\caption{Inventario completo degli asset: baseline e studio mirato.}\n\\label{tab:manifest-figure}\n\\end{table}\n');
end
function t=tex(v), t=char(v); t=strrep(t,'_','\_'); t=strrep(t,'%','\%'); t=strrep(t,'&','\&'); end
