function manifest = build_m18_figure_manifest(evidence)
%BUILD_M18_FIGURE_MANIFEST Select and trace frozen figures for M18.

arguments
    evidence (1, 1) struct = load_m18_validated_artifacts
end
fileName=["m2_open_loop_poles.png";"m3_delay_pade_comparison.png"; ...
    "m4_actuator_uncertainty_cover.png";"m5_spec_frequency_map.png"; ...
    "m6_lqg_reference_tracking.png";"m7_augmented_cost_tradeoff.png"; ...
    "m8_lqg_ras_q_plane.png";"m10_weighted_comparison_m9.png"; ...
    "m11_gamma_vs_order.png";"m14_ns_np_rs_rp_summary.png"; ...
    "m15_tracking_khinf_vs_kmu.png";"m15_ras_m6_khinf_kmu.png"; ...
    "m16_empirical_stability_summary.png";"m17_m16_stability_tracking.png"; ...
    "m17_final_tradeoff_summary.png"];
milestone=["M2";"M3";"M4";"M5";"M6";"M7";"M8";"M10";"M11";"M14";"M15";"M15";"M16";"M17";"M17"];
reportSection=["3";"4";"5";"6";"7";"7";"7";"8";"8";"9";"10";"10";"11";"12";"12"];
presentationUse=[true;true;true;true;true;false;true;true;false;true;true;true;true;true;true];
caption=["Poli del modello meccanico linearizzato in anello aperto."; ...
    "Confronto fra ritardo esatto e approssimazione di Pade del primo ordine."; ...
    "Copertura dell'incertezza dinamica degli attuatori mediante W_I."; ...
    "Mappa frequenziale delle specifiche e dei pesi M5."; ...
    "Tracking nominale lineare del controllore LQG M6."; ...
    "Trade-off della feasibility LQG-I M7 senza candidato finale ammissibile."; ...
    "Stima empirica della RAS M6 nel piano delle coordinate articolari."; ...
    "Confronto della prestazione pesata M9/M10 sul problema nominale congelato."; ...
    "Trade-off fra ordine e objective nella campagna hinfstruct M11."; ...
    "Esiti NS, NP, RS e RP della post-analisi Kmu M14."; ...
    "Tracking non lineare nominale dei controllori Khinf e Kmu."; ...
    "Confronto delle stime empiriche RAS M6, Khinf e Kmu."; ...
    "Stabilita empirica dei tre controllori sui 40 campioni lineari M4."; ...
    "Stabilita e core tracking M16 riportati nel confronto finale M17."; ...
    "Sintesi del trade-off e assegnazione finale per ruolo M17."];
sourcePath=fullfile("results","figures",fileName); reportPath=fullfile("report","figures",fileName);
manifest=table(fileName,milestone,sourcePath,reportPath,caption,reportSection,presentationUse, ...
    'VariableNames',{'FileName','Milestone','SourcePath','ReportPath','Caption','ReportSection','PresentationUse'});
reportRoot=fullfile(evidence.root,"report","figures"); generatedRoot=fullfile(evidence.root,"report","generated");
if ~isfolder(reportRoot), mkdir(reportRoot); end
if ~isfolder(generatedRoot), mkdir(generatedRoot); end
for k=1:height(manifest)
    source=fullfile(evidence.root,manifest.SourcePath(k)); destination=fullfile(evidence.root,manifest.ReportPath(k));
    assert(isfile(source),"M18:MissingFigure","Missing frozen figure %s",source); copyfile(source,destination,'f');
end
save(fullfile(generatedRoot,"figure_manifest.mat"),'manifest'); writetable(manifest,fullfile(generatedRoot,"figure_manifest.csv"));
localWriteTex(manifest,fullfile(generatedRoot,"figure_manifest.tex"));
end
function localWriteTex(m,path)
f=fopen(path,'w'); c=onCleanup(@() fclose(f));
fprintf(f,'%% Generated by build_m18_figure_manifest.m. Do not edit.\n\\small\n\\begin{longtable}{p{1.8cm}p{7.6cm}p{1.8cm}p{1.8cm}}\n\\toprule\nMilestone & File & Capitolo & Uso slide \\\\\n\\midrule\n\\endhead\n');
for k=1:height(m), use="no"; if m.PresentationUse(k), use="si"; end; fprintf(f,'%s & \\texttt{%s} & %s & %s \\\\\n',m.Milestone(k),tex(m.FileName(k)),m.ReportSection(k),use); end
fprintf(f,'\\bottomrule\n\\end{longtable}\n\\normalsize\n');
end
function t=tex(v), t=char(v); t=strrep(t,'_','\_'); t=strrep(t,'%','\%'); t=strrep(t,'&','\&'); end
