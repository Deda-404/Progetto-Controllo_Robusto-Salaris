function comparison = compare_m14_a5_kmu_robustness( ...
    m12, nominal, manualMu, robustStability, robustPerformance, ...
    criticalBlockTable, Kmu, m13Objective, config)
%COMPARE_M14_A5_KMU_ROBUSTNESS Compare frozen M12 A5 and M14 Kmu.

a5Dominant = localDominantBlock( ...
    m12.criticalBlockDiagnostics.BlockName, ...
    m12.criticalBlockDiagnostics.RSSensitivity);
kmuDominant = localDominantBlock(criticalBlockTable.BlockName, ...
    criticalBlockTable.RSSensitivity);

Controller = ["A5 M12"; "Kmu M14"];
Order = [m12.selectedController.order; order(Kmu)];
NominalWeightedNorm = [m12.NPMetrics.gammaNominal; ...
    nominal.metrics.gammaNominal];
NSMaximumRealPole = [m12.NSMetrics.maximumRealPart; ...
    nominal.metrics.maximumRealPart];
NSOutcome = [m12.nominalReconstruction.NSOutcome; nominal.NSOutcome];
RSLowerBound = [m12.robustStability.margin.LowerBound; ...
    robustStability.margin.LowerBound];
RSUpperBound = [m12.robustStability.margin.UpperBound; ...
    robustStability.margin.UpperBound];
RSCriticalFrequency = [m12.robustStability.margin.CriticalFrequency; ...
    robustStability.margin.CriticalFrequency];
RSOutcome = [m12.robustStability.outcome; robustStability.outcome];
ManualMuMaximumUpper = [m12.manualMuRS.maximumUpperBound; ...
    manualMu.maximumUpperBound];
ManualMuMaximumLower = [m12.manualMuRS.maximumLowerBound; ...
    manualMu.maximumLowerBound];
RPLowerBound = [m12.robustPerformance.performanceMargin.LowerBound; ...
    robustPerformance.performanceMargin.LowerBound];
RPUpperBound = [m12.robustPerformance.performanceMargin.UpperBound; ...
    robustPerformance.performanceMargin.UpperBound];
RPOutcome = [m12.robustPerformance.outcome; robustPerformance.outcome];
WCGainLowerBound = [m12.robustPerformance.worstCaseGain.LowerBound; ...
    robustPerformance.worstCaseGain.LowerBound];
WCGainUpperBound = [m12.robustPerformance.worstCaseGain.UpperBound; ...
    robustPerformance.worstCaseGain.UpperBound];
DominantRSBlock = [a5Dominant; kmuDominant];
controllerTable = table(Controller, Order, NominalWeightedNorm, ...
    NSMaximumRealPole, NSOutcome, RSLowerBound, RSUpperBound, ...
    RSCriticalFrequency, RSOutcome, ManualMuMaximumUpper, ...
    ManualMuMaximumLower, RPLowerBound, RPUpperBound, RPOutcome, ...
    WCGainLowerBound, WCGainUpperBound, DominantRSBlock);

Metric = ["controller order"; "nominal weighted norm"; ...
    "NS max real pole"; "NS outcome"; "RS LowerBound"; ...
    "RS UpperBound"; "RS critical frequency"; "RS outcome"; ...
    "manual mu max upper"; "manual mu max lower"; ...
    "RP LowerBound"; "RP UpperBound"; "RP outcome"; ...
    "wcgain LowerBound"; "wcgain UpperBound"; ...
    "dominant RS sensitivity block"];
A5M12 = [localNumber(Order(1)); localNumber(NominalWeightedNorm(1)); ...
    localNumber(NSMaximumRealPole(1)); NSOutcome(1); ...
    localNumber(RSLowerBound(1)); localNumber(RSUpperBound(1)); ...
    localNumber(RSCriticalFrequency(1)); RSOutcome(1); ...
    localNumber(ManualMuMaximumUpper(1)); ...
    localNumber(ManualMuMaximumLower(1)); ...
    localNumber(RPLowerBound(1)); localNumber(RPUpperBound(1)); ...
    RPOutcome(1); localNumber(WCGainLowerBound(1)); ...
    localNumber(WCGainUpperBound(1)); DominantRSBlock(1)];
KmuM14 = [localNumber(Order(2)); localNumber(NominalWeightedNorm(2)); ...
    localNumber(NSMaximumRealPole(2)); NSOutcome(2); ...
    localNumber(RSLowerBound(2)); localNumber(RSUpperBound(2)); ...
    localNumber(RSCriticalFrequency(2)); RSOutcome(2); ...
    localNumber(ManualMuMaximumUpper(2)); ...
    localNumber(ManualMuMaximumLower(2)); ...
    localNumber(RPLowerBound(2)); localNumber(RPUpperBound(2)); ...
    RPOutcome(2); localNumber(WCGainLowerBound(2)); ...
    localNumber(WCGainUpperBound(2)); DominantRSBlock(2)];
metricTable = table(Metric, A5M12, KmuM14);

a5Lower = RSLowerBound(1);
a5Upper = RSUpperBound(1);
kmuLower = RSLowerBound(2);
kmuUpper = RSUpperBound(2);
deltaLower = kmuLower - a5Lower;
deltaUpper = kmuUpper - a5Upper;
relativeDeltaLower = deltaLower / max(abs(a5Lower), eps);
relativeDeltaUpper = deltaUpper / max(abs(a5Upper), eps);
tolerance = config.rsComparisonRelativeTolerance;
lowerClearlyHigher = relativeDeltaLower > tolerance;
upperClearlyHigher = relativeDeltaUpper > tolerance;
a5Rank = localOutcomeRank(RSOutcome(1));
kmuRank = localOutcomeRank(RSOutcome(2));
if lowerClearlyHigher && upperClearlyHigher && kmuRank > a5Rank
    classification = "CLEAR_IMPROVEMENT";
elseif lowerClearlyHigher && upperClearlyHigher && ...
        a5Upper < 1 && kmuUpper < 1
    classification = "PARTIAL_MARGIN_IMPROVEMENT";
elseif (~lowerClearlyHigher && ~upperClearlyHigher) || ...
        relativeDeltaLower < -tolerance || ...
        relativeDeltaUpper < -tolerance
    classification = "NO_MEANINGFUL_IMPROVEMENT";
else
    classification = "INCONCLUSIVE_COMPARISON";
end
rsImprovement = struct( ...
    'A5LowerBound', a5Lower, ...
    'A5UpperBound', a5Upper, ...
    'KmuLowerBound', kmuLower, ...
    'KmuUpperBound', kmuUpper, ...
    'deltaLowerBound', deltaLower, ...
    'deltaUpperBound', deltaUpper, ...
    'relativeDeltaLowerBound', relativeDeltaLower, ...
    'relativeDeltaUpperBound', relativeDeltaUpper, ...
    'lowerClearlyHigher', lowerClearlyHigher, ...
    'upperClearlyHigher', upperClearlyHigher, ...
    'classificationTransition', RSOutcome(1) + " -> " + RSOutcome(2), ...
    'classification', classification, ...
    'midpointUsedForDecision', false, ...
    'comparisonTolerance', tolerance);

comparison.controllerTable = controllerTable;
comparison.metricTable = metricTable;
comparison.rsImprovement = rsImprovement;
comparison.rsSensitivityTable = table(criticalBlockTable.BlockName, ...
    criticalBlockTable.A5RSSensitivity, ...
    criticalBlockTable.RSSensitivity, ...
    'VariableNames', {'BlockName', 'A5RSSensitivity', ...
    'KmuRSSensitivity'});
comparison.musynDiagnostic = struct( ...
    'musynObjective', m13Objective, ...
    'nominalWeightedNorm', nominal.metrics.gammaNominal, ...
    'RSLowerBound', robustStability.margin.LowerBound, ...
    'RSUpperBound', robustStability.margin.UpperBound, ...
    'RPOutcome', robustPerformance.outcome, ...
    'WCGainLowerBound', robustPerformance.worstCaseGain.LowerBound, ...
    'WCGainUpperBound', robustPerformance.worstCaseGain.UpperBound, ...
    'objectiveIsIndependentCertification', false);
end

function name = localDominantBlock(names, values)
finiteRows = isfinite(values);
assert(any(finiteRows), 'M14:MissingRSSensitivity', ...
    'No finite Robust Stability sensitivity is available.');
maximum = max(values(finiteRows));
candidates = sort(names(finiteRows & values == maximum));
name = candidates(1);
end

function value = localNumber(number)
value = string(compose('%.12g', number));
end

function rank = localOutcomeRank(outcome)
if outcome == "PASS_CERTIFIED"
    rank = 2;
elseif outcome == "INCONCLUSIVE"
    rank = 1;
elseif outcome == "FAIL_CERTIFIED"
    rank = 0;
else
    error('M14:UnknownRSOutcome', ...
        'Unknown Robust Stability outcome.');
end
end
