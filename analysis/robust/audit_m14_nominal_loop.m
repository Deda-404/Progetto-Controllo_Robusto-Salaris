function audit = audit_m14_nominal_loop( ...
    G, Kmu, W1, W2, TzwNominal, m13Nominal, config)
%AUDIT_M14_NOMINAL_LOOP Reconstruct Kmu nominal maps and internal poles.

arguments
    G {mustBeA(G, {'ss', 'tf', 'zpk'})}
    Kmu {mustBeA(Kmu, {'ss', 'tf', 'zpk'})}
    W1 {mustBeA(W1, {'ss', 'tf', 'zpk'})}
    W2 {mustBeA(W2, {'ss', 'tf', 'zpk'})}
    TzwNominal {mustBeA(TzwNominal, {'ss', 'tf', 'zpk'})}
    m13Nominal (1, 1) struct
    config (1, 1) struct = mu_analysis_specs_m14
end

G = localClearNames(ss(G));
Kmu = localClearNames(ss(Kmu));
W1 = localClearNames(ss(W1));
W2 = localClearNames(ss(W2));
TzwNominal = localClearNames(ss(TzwNominal));
identity = ss(eye(2));
S = feedback(identity, G * Kmu);
T = identity - S;
KS = Kmu * S;
weightedW1S = W1 * S;
weightedW2KS = W2 * KS;
weightedClosedLoop = [weightedW1S; weightedW2KS];

[Ag, Bg, Cg, Dg] = ssdata(G);
[Ak, Bk, Ck, Dk] = ssdata(Kmu);
assert(norm(Dg, 'fro') == 0, 'M14:PlantFeedthrough', ...
    'The explicit internal-state audit requires zero plant feedthrough.');
Ainternal = [Ag - Bg * Dk * Cg, Bg * Ck; -Bk * Cg, Ak];
internalPoles = eig(Ainternal);
internallyStable = all(real(internalPoles) < ...
    -config.stabilityTolerance) && isstable(S) && isstable(T) && ...
    isstable(KS) && isstable(weightedClosedLoop);
[gammaNominal, peakFrequency] = norm(weightedClosedLoop, inf);

mapError = localFrequencyError(weightedClosedLoop, TzwNominal, ...
    config.auditFrequencyGrid);
sError = localFrequencyError(S, m13Nominal.S, ...
    config.auditFrequencyGrid);
tError = localFrequencyError(T, m13Nominal.T, ...
    config.auditFrequencyGrid);
ksError = localFrequencyError(KS, m13Nominal.KS, ...
    config.auditFrequencyGrid);
weightedError = localFrequencyError(weightedClosedLoop, ...
    m13Nominal.weightedClosedLoop, config.auditFrequencyGrid);
poleError = localPoleSetError(m13Nominal.internalPoles, internalPoles);
normRelativeError = abs(gammaNominal - ...
    m13Nominal.metrics.weightedNorm) / ...
    m13Nominal.metrics.weightedNorm;

reconstructionPassed = mapError <= config.closedLoopMapTolerance && ...
    sError <= config.nominalFrequencyTolerance && ...
    tError <= config.nominalFrequencyTolerance && ...
    ksError <= config.nominalFrequencyTolerance && ...
    weightedError <= config.closedLoopMapTolerance && ...
    poleError <= config.nominalPoleTolerance && ...
    normRelativeError <= config.nominalNormRelativeTolerance;
assert(reconstructionPassed, 'M14:NominalM13Mismatch', ...
    'The nominal Kmu closure does not reproduce the frozen M13 result.');

audit.S = S;
audit.T = T;
audit.KS = KS;
audit.weightedW1S = weightedW1S;
audit.weightedW2KS = weightedW2KS;
audit.weightedClosedLoop = weightedClosedLoop;
audit.Ainternal = Ainternal;
audit.internalPoles = internalPoles;
audit.metrics = struct( ...
    'plantStates', order(G), ...
    'controllerStates', order(Kmu), ...
    'internalStateCount', numel(internalPoles), ...
    'maximumRealPart', max(real(internalPoles)), ...
    'internallyStable', internallyStable, ...
    'sensitivityStable', isstable(S), ...
    'complementarySensitivityStable', isstable(T), ...
    'controlSensitivityStable', isstable(KS), ...
    'weightedClosedLoopStable', isstable(weightedClosedLoop), ...
    'gammaNominal', gammaNominal, ...
    'peakFrequency', peakFrequency, ...
    'puncNominalMapError', mapError, ...
    'sErrorVsM13', sError, ...
    'tErrorVsM13', tError, ...
    'ksErrorVsM13', ksError, ...
    'weightedErrorVsM13', weightedError, ...
    'normRelativeErrorVsM13', normRelativeError, ...
    'poleErrorVsM13', poleError, ...
    'reconstructionPassed', reconstructionPassed, ...
    'minrealUsedForGate', false);
audit.NSOutcome = localPassFail(internallyStable);
audit.NPOutcome = localPassFail(gammaNominal < config.gammaTarget);
end

function error = localFrequencyError(first, second, frequencies)
first = localClearNames(ss(first));
second = localClearNames(ss(second));
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
error = max(abs(difference), [], 'all');
end

function error = localPoleSetError(reference, actual)
reference = reference(:);
remaining = actual(:);
assert(numel(reference) == numel(remaining), 'M14:PoleCount', ...
    'Internal pole counts differ from M13.');
errors = zeros(numel(reference), 1);
for index = 1:numel(reference)
    [errors(index), match] = min(abs(remaining - reference(index)));
    remaining(match) = [];
end
error = max(errors);
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function status = localPassFail(condition)
if condition
    status = "PASS";
else
    status = "FAIL";
end
end
