function audit = audit_m13_nominal_controller( ...
    G, W1, W2, Kmu, CLmuNominal, m10, m11, config)
%AUDIT_M13_NOMINAL_CONTROLLER Audit Kmu without controller reduction.

arguments
    G {mustBeA(G, {'ss', 'tf', 'zpk'})}
    W1 {mustBeA(W1, {'ss', 'tf', 'zpk'})}
    W2 {mustBeA(W2, {'ss', 'tf', 'zpk'})}
    Kmu {mustBeA(Kmu, {'ss', 'tf', 'zpk'})}
    CLmuNominal {mustBeA(CLmuNominal, {'ss', 'tf', 'zpk'})}
    m10 (1, 1) struct
    m11 (1, 1) struct
    config (1, 1) struct = mu_synthesis_specs_m13
end

G = localClearNames(ss(G));
W1 = localClearNames(ss(W1));
W2 = localClearNames(ss(W2));
Kmu = localClearNames(ss(Kmu));
CLmuNominal = localClearNames(ss(CLmuNominal));
identity = ss(eye(2));
S = feedback(identity, G * Kmu);
T = identity - S;
KS = Kmu * S;
weightedW1S = W1 * S;
weightedW2KS = W2 * KS;
weightedClosedLoop = [weightedW1S; weightedW2KS];

[Ag, Bg, Cg, Dg] = ssdata(G);
[Ak, Bk, Ck, Dk] = ssdata(Kmu);
assert(norm(Dg, 'fro') == 0, 'M13:PlantFeedthrough', ...
    'The explicit internal-state audit requires zero plant feedthrough.');
Ainternal = [Ag - Bg * Dk * Cg, Bg * Ck; -Bk * Cg, Ak];
internalPoles = eig(Ainternal);
controllerPoles = pole(Kmu);
controllerMatricesFinite = all(isfinite(Ak), 'all') && ...
    all(isfinite(Bk), 'all') && all(isfinite(Ck), 'all') && ...
    all(isfinite(Dk), 'all');
internallyStable = all(real(internalPoles) < ...
    -config.stabilityTolerance) && isstable(S) && isstable(T) && ...
    isstable(KS) && isstable(weightedClosedLoop);

[W1SNorm, W1SPeakFrequency] = norm(weightedW1S, inf);
[W2KSNorm, W2KSPeakFrequency] = norm(weightedW2KS, inf);
[weightedNorm, weightedPeakFrequency] = ...
    norm(weightedClosedLoop, inf);
closedLoopMapError = localFrequencyError( ...
    weightedClosedLoop, CLmuNominal, config.auditFrequencyGrid);

a5Index = find(string({m11.representativeResults.architectureID}) == ...
    "A5", 1);
assert(~isempty(a5Index), 'M13:A5Missing', ...
    'The frozen M11 A5 representative is unavailable.');
a5 = m11.representativeResults(a5Index);
comparison = table( ...
    ["M10 Hinf full-order"; "M11 A5"; "M13 Kmu"], ...
    [order(m10.Khinf); order(a5.controller); order(Kmu)], ...
    [m10.normMetrics.weightedNorm; ...
        a5.reconstruction.metrics.weightedNorm; weightedNorm], ...
    [m10.normMetrics.maximumClosedLoopRealPart; ...
        a5.reconstruction.metrics.maximumClosedLoopRealPart; ...
        max(real(internalPoles))], ...
    [m10.normMetrics.nominallyStable; ...
        a5.reconstruction.metrics.internallyStable; internallyStable], ...
    'VariableNames', {'Controller', 'Order', 'NominalWeightedNorm', ...
        'MaximumRealInternalPole', 'NominallyStable'});
lowerBoundRelativeDifference = ...
    (m10.normMetrics.weightedNorm - weightedNorm) / ...
    m10.normMetrics.weightedNorm;
lowerBoundSanityPassed = lowerBoundRelativeDifference <= ...
    config.m10LowerBoundRelativeTolerance;

audit.Kmu = Kmu;
audit.S = S;
audit.T = T;
audit.KS = KS;
audit.weightedW1S = weightedW1S;
audit.weightedW2KS = weightedW2KS;
audit.weightedClosedLoop = weightedClosedLoop;
audit.Ainternal = Ainternal;
audit.internalPoles = internalPoles;
audit.controllerPoles = controllerPoles;
audit.metrics = struct( ...
    'controllerInputCount', size(Kmu, 2), ...
    'controllerOutputCount', size(Kmu, 1), ...
    'controllerOrder', order(Kmu), ...
    'controllerStableInIsolation', isstable(Kmu), ...
    'controllerMatricesFinite', controllerMatricesFinite, ...
    'plantOrder', order(G), ...
    'internalStateCount', numel(internalPoles), ...
    'maximumRealPart', max(real(internalPoles)), ...
    'internallyStable', internallyStable, ...
    'sensitivityStable', isstable(S), ...
    'complementarySensitivityStable', isstable(T), ...
    'controlSensitivityStable', isstable(KS), ...
    'weightedClosedLoopStable', isstable(weightedClosedLoop), ...
    'W1SNorm', W1SNorm, ...
    'W1SPeakFrequency', W1SPeakFrequency, ...
    'W2KSNorm', W2KSNorm, ...
    'W2KSPeakFrequency', W2KSPeakFrequency, ...
    'weightedNorm', weightedNorm, ...
    'weightedPeakFrequency', weightedPeakFrequency, ...
    'closedLoopMapError', closedLoopMapError, ...
    'lowerBoundRelativeDifference', lowerBoundRelativeDifference, ...
    'lowerBoundSanityPassed', lowerBoundSanityPassed, ...
    'controllerReductionPerformed', false);
audit.comparisonM10A5Kmu = comparison;
audit.NSOutcome = localPassFail(internallyStable);
audit.nominalWeightedReconstructionOutcome = localPassFail( ...
    closedLoopMapError <= config.closedLoopMapTolerance && ...
    isfinite(weightedNorm));
audit.M10LowerBoundSanityOutcome = ...
    localPassFail(lowerBoundSanityPassed);
end

function error = localFrequencyError(first, second, frequencies)
first = localClearNames(ss(first));
second = localClearNames(ss(second));
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
error = max(abs(difference), [], 'all');
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function status = localPassFail(condition)
if condition
    status = "PASS";
else
    status = "FAIL";
end
end
