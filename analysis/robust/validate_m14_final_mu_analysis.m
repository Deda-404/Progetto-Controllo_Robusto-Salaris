function metrics = validate_m14_final_mu_analysis
%VALIDATE_M14_FINAL_MU_ANALYSIS Verify NS/NP/RS/RP for frozen M13 Kmu.

projectRoot = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory), mkdir(dataDirectory); end
if ~isfolder(figureDirectory), mkdir(figureDirectory); end

config = mu_analysis_specs_m14;
m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m4 = load(fullfile(dataDirectory, 'm4_uncertain_plant.mat'));
m5 = load(fullfile(dataDirectory, 'm5_performance_specs.mat'));
m12 = load(fullfile(dataDirectory, 'm12_mu_analysis_a5.mat'));
controller = load_m14_kmu_closed_loop(projectRoot, config);
m13 = controller.m13;
Kmu = controller.Kmu;
KmuSourceAudit = controller.sourceAudit;

frozen = load_m13_uncertain_generalized_plant(projectRoot, config);
Punc = frozen.Punc;
uncertaintySourceAudit = frozen.uncertaintyAudit;
weightAudit = frozen.weightAudit;
PuncIdentityAudit = localPuncIdentityAudit(frozen, m12, m13, config);
assert(PuncIdentityAudit.passed && uncertaintySourceAudit.passed && ...
    weightAudit.passed, 'M14:FrozenProblemMismatch', ...
    'The frozen M4/M5/Punc source gate failed.');

Tzw_mu_unc = lft(Punc, Kmu);
assert(isequal(size(Tzw_mu_unc), [4, 2]), ...
    'M14:ClosedLoopDimensions', ...
    'Tzw_mu_unc must be 4-by-2.');
nominalReconstruction = audit_m14_nominal_loop( ...
    m3.GfullQ, Kmu, m5.W1, m5.W2, ...
    Tzw_mu_unc.NominalValue, m13.nominalReconstruction, config);
assert(nominalReconstruction.NSOutcome == "PASS", ...
    'M14:NominalStability', ...
    'NS failed; RS/RP analysis is stopped.');
NSMetrics = nominalReconstruction.metrics;
NPMetrics = struct( ...
    'gammaTarget', config.gammaTarget, ...
    'gammaNominal', NSMetrics.gammaNominal, ...
    'peakFrequency', NSMetrics.peakFrequency, ...
    'outcome', nominalReconstruction.NPOutcome);

decomposition = decompose_m12_ndelta(Tzw_mu_unc, config);
M = decomposition.M;
Delta = decomposition.Delta;
BlkStruct = decomposition.BlkStruct;
normunc = decomposition.normunc;
deltaStructureTable = decomposition.structureTable;
lftEquivalenceAudit = decomposition.audit;
manualMuRS = analyze_m12_manual_mu( ...
    decomposition.M11mu, BlkStruct, config);
robustStability = analyze_m12_robust_stability( ...
    Tzw_mu_unc, m4.GuncQ, Kmu, m5.W1, m5.W2, manualMuRS, config);
robustPerformance = analyze_m12_robust_performance( ...
    Tzw_mu_unc, m4.GuncQ, nominalReconstruction, config);
assert(~(NPMetrics.outcome == "FAIL" && ...
    robustPerformance.outcome == "PASS_CERTIFIED"), ...
    'M14:NominalRobustPerformanceLogic', ...
    'RP cannot pass when NP fails.');

criticalBlockTable = build_m14_critical_block_table( ...
    deltaStructureTable, robustStability, robustPerformance, m12);
robustComparison = compare_m14_a5_kmu_robustness( ...
    m12, nominalReconstruction, manualMuRS, robustStability, ...
    robustPerformance, criticalBlockTable, Kmu, ...
    KmuSourceAudit.musynObjective, config);
A5KmuComparison = robustComparison.metricTable;
RSImprovementClassification = robustComparison.rsImprovement;
summaryNSNPRSRP = localSummaryTable( ...
    nominalReconstruction, robustStability, robustPerformance);

qualityGate = struct;
qualityGate.frozenKmuCorrectness = ...
    localPassFail(KmuSourceAudit.passed);
qualityGate.frozenUncertaintyCorrectness = ...
    localPassFail(uncertaintySourceAudit.passed);
qualityGate.frozenWeightsCorrectness = ...
    localPassFail(weightAudit.passed);
qualityGate.PuncIdentity = localPassFail(PuncIdentityAudit.passed);
qualityGate.nominalReconstruction = localPassFail( ...
    nominalReconstruction.metrics.reconstructionPassed);
qualityGate.nDeltaDecomposition = ...
    localPassFail(lftEquivalenceAudit.passed);
qualityGate.nominalStability = nominalReconstruction.NSOutcome;
qualityGate.nominalPerformance = nominalReconstruction.NPOutcome;
qualityGate.robustStability = robustStability.outcome;
qualityGate.manualMuRSConsistency = ...
    robustStability.manualMuConsistency.outcome;
qualityGate.robustPerformance = robustPerformance.outcome;
qualityGate.worstCaseGain = "QUANTIFIED";
qualityGate.A5KmuRobustComparison = "QUANTIFIED";
qualityGate.criticalUncertaintyBlocks = "QUANTIFIED";
qualityGate.softwareCorrectness = localPassFail( ...
    qualityGate.frozenKmuCorrectness == "PASS" && ...
    qualityGate.frozenUncertaintyCorrectness == "PASS" && ...
    qualityGate.frozenWeightsCorrectness == "PASS" && ...
    qualityGate.PuncIdentity == "PASS" && ...
    qualityGate.nominalReconstruction == "PASS" && ...
    qualityGate.nDeltaDecomposition == "PASS" && ...
    qualityGate.nominalStability == "PASS" && ...
    qualityGate.manualMuRSConsistency ~= "FAIL_METHODOLOGICAL" && ...
    robustPerformance.worstGainSubstitutionCoherent);
if qualityGate.softwareCorrectness ~= "PASS" || ...
        qualityGate.manualMuRSConsistency == "FAIL_METHODOLOGICAL"
    qualityGate.overallStatus = "BLOCKED";
elseif qualityGate.nominalStability == "PASS" && ...
        qualityGate.nominalPerformance == "PASS" && ...
        qualityGate.robustStability == "PASS_CERTIFIED" && ...
        qualityGate.robustPerformance == "PASS_CERTIFIED"
    qualityGate.overallStatus = "COMPLETE";
else
    qualityGate.overallStatus = "PARTIAL";
end

metadata = struct( ...
    'milestone', "M14", ...
    'analysisOnly', true, ...
    'baselineCommit', config.baselineCommit, ...
    'mergedPullRequest', config.mergedPullRequest, ...
    'mergedPullRequestState', config.mergedPullRequestState, ...
    'controllerSource', config.controllerSource, ...
    'uncertaintySource', config.uncertaintySource, ...
    'weightSource', config.weightSource, ...
    'pipelineSource', config.pipelineSourceMilestone, ...
    'controllerTuningPerformed', false, ...
    'weightRetuningPerformed', false, ...
    'uncertaintyRetuningPerformed', false, ...
    'W3Used', false, ...
    'musynPerformed', false, ...
    'hinfsynPerformed', false, ...
    'mixsynPerformed', false, ...
    'hinfstructPerformed', false, ...
    'dkIterationPerformed', false, ...
    'controllerReductionPerformed', false, ...
    'prefilterUsed', false, ...
    'twoDegreeOfFreedomUsed', false, ...
    'monteCarloPerformed', false, ...
    'nonlinearValidationPerformed', false, ...
    'm15Started', false, ...
    'minrealUsedForGate', false, ...
    'responsible', "Alessio", ...
    'matlabRelease', string(version('-release')));
figurePaths = plot_m14_results(m12, manualMuRS, ...
    nominalReconstruction, robustStability, robustPerformance, ...
    criticalBlockTable, summaryNSNPRSRP, figureDirectory, config);

robustStabilityMargin = robustStability.margin;
wcuRS = robustStability.worstUncertainty;
infoRS = robustStability.info;
robustPerformanceMargin = robustPerformance.performanceMargin;
wcuRP = robustPerformance.worstPerformanceUncertainty;
infoRP = robustPerformance.performanceInfo;
worstCaseGain = robustPerformance.worstCaseGain;
wcuGain = robustPerformance.worstGainUncertainty;
infoGain = robustPerformance.worstGainInfo;
datasetPath = fullfile(dataDirectory, ...
    'm14_final_mu_analysis_kmu.mat');
save(datasetPath, 'config', 'Kmu', 'KmuSourceAudit', ...
    'uncertaintySourceAudit', 'weightAudit', 'PuncIdentityAudit', ...
    'Punc', 'Tzw_mu_unc', 'nominalReconstruction', 'NSMetrics', ...
    'NPMetrics', 'M', 'Delta', 'BlkStruct', 'normunc', ...
    'deltaStructureTable', 'decomposition', 'lftEquivalenceAudit', ...
    'manualMuRS', 'robustStability', 'robustStabilityMargin', ...
    'wcuRS', 'infoRS', 'robustPerformance', ...
    'robustPerformanceMargin', 'wcuRP', 'infoRP', ...
    'worstCaseGain', 'wcuGain', 'infoGain', 'criticalBlockTable', ...
    'robustComparison', 'A5KmuComparison', ...
    'RSImprovementClassification', 'summaryNSNPRSRP', ...
    'qualityGate', 'metadata', 'figurePaths', '-v7.3');

assert(qualityGate.softwareCorrectness == "PASS", ...
    'M14:SoftwareQualityGate', ...
    'M14 failed a methodological software quality gate.');
assert(isfile(datasetPath) && all(structfun(@isfile, figurePaths)), ...
    'M14:Artifacts', 'One or more M14 artifacts are missing.');

fprintf('\n=== Validazione M14: mu-analysis finale Kmu ===\n');
fprintf(['Kmu: best iteration=%d, order=%d, objective M13=%.12g; ' ...
    'Punc identity=%s\n'], KmuSourceAudit.bestIteration, ...
    KmuSourceAudit.controllerOrder, KmuSourceAudit.musynObjective, ...
    qualityGate.PuncIdentity);
fprintf('NS=%s, max pole=%.12g; NP=%s, gamma=%.12g @ %.12g rad/s\n', ...
    nominalReconstruction.NSOutcome, NSMetrics.maximumRealPart, ...
    nominalReconstruction.NPOutcome, NPMetrics.gammaNominal, ...
    NPMetrics.peakFrequency);
fprintf(['RS=%s, margin=[%.12g, %.12g] @ %.12g rad/s; ' ...
    'manual margin=[%.12g, %.12g], consistency=%s\n'], ...
    robustStability.outcome, robustStabilityMargin.LowerBound, ...
    robustStabilityMargin.UpperBound, ...
    robustStabilityMargin.CriticalFrequency, ...
    manualMuRS.marginLowerApproximation, ...
    manualMuRS.marginUpperApproximation, ...
    robustStability.manualMuConsistency.outcome);
fprintf(['RP=%s, margin=[%.12g, %.12g]; wcgain=[%.12g, %.12g], ' ...
    'substituted gain=%.12g\n'], robustPerformance.outcome, ...
    robustPerformanceMargin.LowerBound, ...
    robustPerformanceMargin.UpperBound, worstCaseGain.LowerBound, ...
    worstCaseGain.UpperBound, robustPerformance.worstGainActual);
fprintf(['A5 -> Kmu RS: %s, delta bounds=[%.12g, %.12g], ' ...
    'transition=%s\n'], RSImprovementClassification.classification, ...
    RSImprovementClassification.deltaLowerBound, ...
    RSImprovementClassification.deltaUpperBound, ...
    RSImprovementClassification.classificationTransition);
fprintf('Software=%s, M14=%s\n', ...
    qualityGate.softwareCorrectness, qualityGate.overallStatus);
fprintf('Dataset: %s\n', datasetPath);

metrics.config = config;
metrics.KmuSourceAudit = KmuSourceAudit;
metrics.nominalReconstruction = nominalReconstruction;
metrics.decomposition = decomposition;
metrics.manualMuRS = manualMuRS;
metrics.robustStability = robustStability;
metrics.robustPerformance = robustPerformance;
metrics.robustComparison = robustComparison;
metrics.summary = summaryNSNPRSRP;
metrics.qualityGate = qualityGate;
metrics.figurePaths = figurePaths;
metrics.datasetPath = datasetPath;
end

function audit = localPuncIdentityAudit(frozen, m12, m13, config)
[Mcurrent, DeltaCurrent, BlkCurrent] = lftdata(frozen.Punc);
[Mreference, DeltaReference, BlkReference] = lftdata(m12.Punc);
audit = struct( ...
    'currentSize', size(frozen.Punc), ...
    'm12Size', size(m12.Punc), ...
    'inputNamesEqualM12', isequal(string(frozen.Punc.InputName), ...
        string(m12.Punc.InputName)), ...
    'outputNamesEqualM12', isequal(string(frozen.Punc.OutputName), ...
        string(m12.Punc.OutputName)), ...
    'uncertaintyNamesEqualM12', isequal( ...
        sort(string(fieldnames(frozen.Punc.Uncertainty))), ...
        sort(string(fieldnames(m12.Punc.Uncertainty)))), ...
    'nominalFrequencyErrorM12', localFrequencyError( ...
        frozen.Punc.NominalValue, m12.Punc.NominalValue, ...
        config.auditFrequencyGrid), ...
    'lftMSizeEqualM12', isequal(size(Mcurrent), size(Mreference)), ...
    'lftDeltaSizeEqualM12', isequal(size(DeltaCurrent), ...
        size(DeltaReference)), ...
    'lftBlockStructureEqualM12', isequaln(BlkCurrent, BlkReference), ...
    'lftMFrequencyErrorM12', localFrequencyError( ...
        Mcurrent, Mreference, config.auditFrequencyGrid), ...
    'm13RecordedAuditPassed', m13.PuncSourceAudit.passed, ...
    'currentAuditMatchesM13Record', ...
        isequaln(frozen.plantAudit, m13.PuncSourceAudit));
audit.passed = frozen.plantAudit.passed && ...
    isequal(audit.currentSize, [6, 4]) && ...
    isequal(audit.m12Size, [6, 4]) && ...
    audit.inputNamesEqualM12 && audit.outputNamesEqualM12 && ...
    audit.uncertaintyNamesEqualM12 && ...
    audit.nominalFrequencyErrorM12 <= ...
        config.identityFrequencyTolerance && ...
    audit.lftMSizeEqualM12 && audit.lftDeltaSizeEqualM12 && ...
    audit.lftBlockStructureEqualM12 && ...
    audit.lftMFrequencyErrorM12 <= ...
        config.identityFrequencyTolerance && ...
    audit.m13RecordedAuditPassed && ...
    audit.currentAuditMatchesM13Record;
end

function tableData = localSummaryTable(nominal, rs, rp)
Property = ["NS"; "NP"; "RS"; "RP"];
MetricName = ["maximum internal real pole"; ...
    "nominal weighted norm"; "robust stability margin"; ...
    "robust performance margin at gamma=1"];
Metric = [nominal.metrics.maximumRealPart; ...
    nominal.metrics.gammaNominal; NaN; NaN];
Lower = [NaN; NaN; rs.margin.LowerBound; ...
    rp.performanceMargin.LowerBound];
Upper = [NaN; NaN; rs.margin.UpperBound; ...
    rp.performanceMargin.UpperBound];
CriticalFrequency = [NaN; nominal.metrics.peakFrequency; ...
    rs.margin.CriticalFrequency; rp.performanceMargin.CriticalFrequency];
Outcome = [nominal.NSOutcome; nominal.NPOutcome; rs.outcome; rp.outcome];
tableData = table(Property, MetricName, Metric, Lower, Upper, ...
    CriticalFrequency, Outcome);
end

function error = localFrequencyError(first, second, frequencies)
first = localClearNames(ss(first));
second = localClearNames(ss(second));
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
error = max(abs(difference), [], 'all');
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function status = localPassFail(condition)
if condition
    status = "PASS";
else
    status = "FAIL";
end
end
