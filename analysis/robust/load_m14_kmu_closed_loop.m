function frozen = load_m14_kmu_closed_loop(projectRoot, config)
%LOAD_M14_KMU_CLOSED_LOOP Load and audit the frozen M13 controller.

arguments
    projectRoot (1, 1) string
    config (1, 1) struct = mu_analysis_specs_m14
end

datasetPath = fullfile(projectRoot, config.controllerSource);
assert(isfile(datasetPath), 'M14:MissingM13Artifact', ...
    'The frozen M13 artifact is unavailable.');
m13 = load(datasetPath);
required = {'Kmu', 'rawInfo', 'history', 'musynObjective', ...
    'controllerOrder', 'nominalReconstruction', 'CLmu', ...
    'qualityGate', 'metadata', 'PuncSourceAudit'};
assert(all(isfield(m13, required)), 'M14:IncompleteM13Artifact', ...
    'The M13 artifact does not contain all frozen source fields.');

bestIteration = m13.history.bestIteration;
assert(isscalar(bestIteration) && bestIteration >= 1 && ...
    bestIteration <= numel(m13.rawInfo), 'M14:BestIteration', ...
    'The recorded M13 best iteration is invalid.');
rawK = m13.rawInfo(bestIteration).K;
[Ak, Bk, Ck, Dk] = ssdata(m13.Kmu);
[Ar, Br, Cr, Dr] = ssdata(rawK);
matrixError = max([norm(Ak - Ar, inf), norm(Bk - Br, inf), ...
    norm(Ck - Cr, inf), norm(Dk - Dr, inf)]);
frequencyError = localFrequencyError(m13.Kmu, rawK, ...
    config.auditFrequencyGrid);
objectiveError = abs(m13.musynObjective - ...
    m13.rawInfo(bestIteration).PeakMu);

sourceAudit = struct( ...
    'sourceArtifact', config.controllerSource, ...
    'loadedDirectlyFromArtifact', true, ...
    'loadedWithoutSynthesis', true, ...
    'bestIteration', bestIteration, ...
    'historyIterationCount', m13.history.iterationCount, ...
    'controllerSize', size(m13.Kmu), ...
    'controllerOrder', order(m13.Kmu), ...
    'savedControllerOrder', m13.controllerOrder, ...
    'rawControllerOrder', order(rawK), ...
    'exactRawControllerIdentity', isequaln(m13.Kmu, rawK), ...
    'rawControllerMatrixError', matrixError, ...
    'rawControllerFrequencyError', frequencyError, ...
    'musynObjective', m13.musynObjective, ...
    'bestIterationObjectiveError', objectiveError, ...
    'nominalWeightedNorm', ...
        m13.nominalReconstruction.metrics.weightedNorm, ...
    'nominalMaximumRealPart', ...
        m13.nominalReconstruction.metrics.maximumRealPart, ...
    'm13Status', m13.qualityGate.overallStatus, ...
    'controllerReductionPerformedInM13', ...
        m13.metadata.controllerReductionPerformed, ...
    'controllerReductionPerformedInM14', false);
sourceAudit.passed = isequal(sourceAudit.controllerSize, [2, 2]) && ...
    sourceAudit.controllerOrder == config.expectedControllerOrder && ...
    sourceAudit.savedControllerOrder == sourceAudit.controllerOrder && ...
    sourceAudit.rawControllerOrder == sourceAudit.controllerOrder && ...
    sourceAudit.exactRawControllerIdentity && matrixError == 0 && ...
    frequencyError == 0 && objectiveError == 0 && ...
    sourceAudit.m13Status == "COMPLETE" && ...
    ~sourceAudit.controllerReductionPerformedInM13 && ...
    ~sourceAudit.controllerReductionPerformedInM14;
assert(sourceAudit.passed, 'M14:FrozenKmuMismatch', ...
    'Kmu does not coincide with the frozen M13 best controller.');

frozen.Kmu = m13.Kmu;
frozen.CLmuNominal = m13.CLmu.NominalValue;
frozen.sourceAudit = sourceAudit;
frozen.m13 = m13;
end

function error = localFrequencyError(first, second, frequencies)
first = localClearNames(ss(first));
second = localClearNames(ss(second));
difference = freqresp(first, frequencies) - ...
    freqresp(second, frequencies);
error = max(abs(difference), [], 'all');
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end
