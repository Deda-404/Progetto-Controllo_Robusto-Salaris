function metrics = validate_m13_mu_synthesis
%VALIDATE_M13_MU_SYNTHESIS Execute or audit the single frozen M13 campaign.

projectRoot = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory), mkdir(dataDirectory); end
if ~isfolder(figureDirectory), mkdir(figureDirectory); end
datasetPath = fullfile(dataDirectory, 'm13_musyn_dk.mat');
checkpointPath = fullfile(dataDirectory, ...
    'm13_musyn_single_campaign_checkpoint.mat');

if isfile(datasetPath)
    saved = load(datasetPath);
    if isfield(saved, 'qualityGate') && isfield(saved, 'metadata') && ...
            saved.metadata.singleCampaignCompleted
        metrics = localSavedMetrics(saved, datasetPath);
        localPrint(metrics, true);
        return;
    end
end

config = mu_synthesis_specs_m13;
frozen = load_m13_uncertain_generalized_plant(projectRoot, config);
m10 = load(fullfile(dataDirectory, 'm10_hinfsyn_nominal.mat'));
m11 = load(fullfile(dataDirectory, 'm11_hinfstruct_structured.mat'));

if isfile(checkpointPath)
    checkpoint = load(checkpointPath, 'synthesis', 'config');
    assert(isequaln(checkpoint.config, config), 'M13:CheckpointConfig', ...
        'The existing single-campaign checkpoint uses another config.');
    synthesis = checkpoint.synthesis;
else
    synthesis = run_m13_musyn(frozen.Punc, config);
    save(checkpointPath, 'synthesis', 'config', '-v7.3');
end

history = extract_m13_dk_history( ...
    synthesis.rawInfo, synthesis.musynObjective, config);
nominalAudit = audit_m13_nominal_controller( ...
    frozen.Gnominal, frozen.W1, frozen.W2, synthesis.Kmu, ...
    synthesis.CLmu.NominalValue, m10, m11, config);

a5Index = find(string({m11.representativeResults.architectureID}) == ...
    "A5", 1);
a5 = m11.representativeResults(a5Index);
comparisonM10A5Kmu = nominalAudit.comparisonM10A5Kmu;
comparisonM10A5Kmu.SynthesisObjective = [m10.gammaHinf; ...
    a5.objective; synthesis.musynObjective];
comparisonM10A5Kmu.DKIterationCount = [0; 0; history.iterationCount];
comparisonM10A5Kmu.ObjectiveInterpretation = [ ...
    "nominal Hinf objective"; "nominal hinfstruct objective"; ...
    "musyn objective, not independently certified"];

qualityGate = struct;
qualityGate.frozenGeneralizedPlant = ...
    localPassFail(frozen.plantAudit.passed);
qualityGate.frozenUncertainty = ...
    localPassFail(frozen.uncertaintyAudit.passed);
qualityGate.frozenWeights = localPassFail(frozen.weightAudit.passed);
qualityGate.dkExecution = localPassFail( ...
    synthesis.callCountForCampaign == 1 && ...
    isfinite(synthesis.musynObjective) && ~isempty(synthesis.rawInfo));
qualityGate.dkHistory = localPassFail( ...
    history.iterationCount >= 1 && ...
    history.iterationCount <= config.maxIterations && ...
    height(history.table) == history.iterationCount && ...
    history.completeUnfilteredHistory);
qualityGate.controllerExtraction = localPassFail( ...
    isequal(size(synthesis.Kmu), [2, 2]) && ...
    nominalAudit.metrics.controllerMatricesFinite);
qualityGate.nominalInternalStability = nominalAudit.NSOutcome;
qualityGate.nominalWeightedReconstruction = ...
    nominalAudit.nominalWeightedReconstructionOutcome;
qualityGate.m10LowerBoundSanity = ...
    nominalAudit.M10LowerBoundSanityOutcome;
qualityGate.robustSynthesisObjective = "QUANTIFIED";
qualityGate.controllerOrder = "QUANTIFIED";
qualityGate.softwareCorrectness = localPassFail( ...
    qualityGate.frozenGeneralizedPlant == "PASS" && ...
    qualityGate.frozenUncertainty == "PASS" && ...
    qualityGate.frozenWeights == "PASS" && ...
    qualityGate.dkExecution == "PASS" && ...
    qualityGate.dkHistory == "PASS" && ...
    qualityGate.controllerExtraction == "PASS" && ...
    qualityGate.nominalWeightedReconstruction == "PASS" && ...
    qualityGate.m10LowerBoundSanity == "PASS");
if qualityGate.softwareCorrectness ~= "PASS" || ...
        qualityGate.m10LowerBoundSanity ~= "PASS"
    qualityGate.overallStatus = "BLOCKED";
elseif qualityGate.nominalInternalStability ~= "PASS"
    qualityGate.overallStatus = "PARTIAL";
else
    qualityGate.overallStatus = "COMPLETE";
end

figurePaths = plot_m13_results(history, nominalAudit, m10, m11, ...
    synthesis, figureDirectory);
metadata = struct( ...
    'milestone', "M13", ...
    'studyType', "D-K feasibility on frozen M4/M5 problem", ...
    'baselineCommit', config.baselineCommit, ...
    'singleCampaignCompleted', true, ...
    'musynCallCountForCampaign', synthesis.callCountForCampaign, ...
    'controllerRetuningAfterResult', false, ...
    'weightRetuningPerformed', false, ...
    'uncertaintyRetuningPerformed', false, ...
    'W3Used', false, ...
    'twoDegreeOfFreedomUsed', false, ...
    'prefilterUsed', false, ...
    'monteCarloPerformed', false, ...
    'nonlinearValidationPerformed', false, ...
    'formalRobustAnalysisPerformed', false, ...
    'controllerReductionPerformed', false, ...
    'm14Started', false, ...
    'responsible', "Alessio", ...
    'matlabRelease', string(version('-release')));

PuncSourceAudit = frozen.plantAudit;
uncertaintyMetadata = frozen.uncertaintyAudit;
weightAudit = frozen.weightAudit;
Kmu = synthesis.Kmu;
CLmu = synthesis.CLmu;
musynObjective = synthesis.musynObjective;
rawInfo = synthesis.rawInfo;
normalizedHistory = history.table;
controllerOrder = synthesis.controllerOrder;
controllerPoles = synthesis.controllerPoles;
nominalReconstruction = nominalAudit;
configSnapshot = config;
save(datasetPath, 'config', 'configSnapshot', 'PuncSourceAudit', ...
    'uncertaintyMetadata', 'weightAudit', 'Kmu', 'CLmu', ...
    'musynObjective', 'rawInfo', 'history', 'normalizedHistory', ...
    'controllerOrder', 'controllerPoles', 'nominalReconstruction', ...
    'comparisonM10A5Kmu', 'qualityGate', 'metadata', 'figurePaths', ...
    'synthesis', '-v7.3');

assert(isfile(datasetPath) && all(structfun(@isfile, figurePaths)), ...
    'M13:Artifacts', 'One or more M13 artifacts are missing.');
if isfile(checkpointPath), delete(checkpointPath); end
assert(qualityGate.softwareCorrectness == "PASS", ...
    'M13:SoftwareGate', 'M13 software correctness is not PASS.');
assert(qualityGate.nominalInternalStability == "PASS", ...
    'M13:NominalStability', ...
    'Kmu is nominally internally unstable; no further synthesis is allowed.');

saved = load(datasetPath);
metrics = localSavedMetrics(saved, datasetPath);
localPrint(metrics, false);
end

function metrics = localSavedMetrics(saved, datasetPath)
metrics.config = saved.config;
metrics.synthesis = saved.synthesis;
metrics.history = saved.history;
metrics.nominalAudit = saved.nominalReconstruction;
metrics.comparison = saved.comparisonM10A5Kmu;
metrics.qualityGate = saved.qualityGate;
metrics.figurePaths = saved.figurePaths;
metrics.datasetPath = datasetPath;
end

function localPrint(metrics, reused)
fprintf('\n=== Validazione M13: singola D-K synthesis ===\n');
if reused
    fprintf('Artifact M13 congelato ricaricato; nessuna seconda campagna.\n');
end
fprintf(['D-K: iterations=%d/%d, termination=%s, ' ...
    'objective=%.12g\n'], metrics.history.iterationCount, ...
    metrics.config.maxIterations, ...
    metrics.history.terminationClassification, ...
    metrics.synthesis.musynObjective);
fprintf(['Kmu: order=%d, NS=%s, max pole=%.12g, ' ...
    'nominal weighted norm=%.12g @ %.12g rad/s\n'], ...
    metrics.synthesis.controllerOrder, ...
    metrics.nominalAudit.NSOutcome, ...
    metrics.nominalAudit.metrics.maximumRealPart, ...
    metrics.nominalAudit.metrics.weightedNorm, ...
    metrics.nominalAudit.metrics.weightedPeakFrequency);
fprintf('M10 lower-bound sanity=%s; software=%s; M13=%s\n', ...
    metrics.qualityGate.m10LowerBoundSanity, ...
    metrics.qualityGate.softwareCorrectness, ...
    metrics.qualityGate.overallStatus);
fprintf('Dataset: %s\n', metrics.datasetPath);
end

function status = localPassFail(condition)
if condition
    status = "PASS";
else
    status = "FAIL";
end
end
