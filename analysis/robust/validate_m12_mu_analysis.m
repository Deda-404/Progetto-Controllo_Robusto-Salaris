function metrics = validate_m12_mu_analysis
%VALIDATE_M12_MU_ANALYSIS Analyze NS/NP/RS/RP for frozen M11 A5.

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(projectRoot, 'src')));
addpath(genpath(fullfile(projectRoot, 'controllers')));
addpath(genpath(fullfile(projectRoot, 'analysis')));
dataDirectory = fullfile(projectRoot, 'results', 'data');
figureDirectory = fullfile(projectRoot, 'results', 'figures');
if ~isfolder(dataDirectory), mkdir(dataDirectory); end
if ~isfolder(figureDirectory), mkdir(figureDirectory); end

m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m4 = load(fullfile(dataDirectory, 'm4_uncertain_plant.mat'));
m5 = load(fullfile(dataDirectory, 'm5_performance_specs.mat'));
m10 = load(fullfile(dataDirectory, 'm10_hinfsyn_nominal.mat'));
m11 = load(fullfile(dataDirectory, 'm11_hinfstruct_structured.mat'));
config = mu_analysis_specs_m12;
selectedController = load_m12_a5_controller(m11, config);
K_A5 = selectedController.controller;

[~, regeneratedW1, ~, regeneratedW2] = build_m5_weights(m5.spec);
weightAudit = struct( ...
    'W1Error', norm(m5.W1 - regeneratedW1, inf), ...
    'W2Error', norm(m5.W2 - regeneratedW2, inf), ...
    'W3Absent', isempty(config.W3), ...
    'retuningPerformed', config.weightRetuningEnabled);
M4SourceAudit = localAuditM4(m4, m3, config);
assert(M4SourceAudit.passed && weightAudit.W1Error <= ...
    config.nominalFrequencyTolerance && weightAudit.W2Error <= ...
    config.nominalFrequencyTolerance && weightAudit.W3Absent && ...
    ~weightAudit.retuningPerformed, 'M12:FrozenSources', ...
    'The frozen M4/M5 source audit failed.');

uncertainModel = build_m12_uncertain_generalized_plant( ...
    m4.GuncQ, m5.W1, m5.W2, K_A5, config);
Punc = uncertainModel.Punc;
Tzw_unc = uncertainModel.TzwUnc;
PuncNominalError = localFrequencyError(Punc.NominalValue, m10.P, ...
    config.auditFrequencyGrid);
assert(PuncNominalError <= config.nominalFrequencyTolerance, ...
    'M12:PuncNominalMismatch', ...
    'The uncertain generalized plant does not reproduce M10 nominally.');

nominalReconstruction = audit_m12_nominal_loop( ...
    m3.GfullQ, K_A5, m5.W1, m5.W2, Tzw_unc.NominalValue, ...
    selectedController.m11Representative, config);
assert(nominalReconstruction.NSOutcome == "PASS", ...
    'M12:NominalStability', ...
    'NS failed; robust analyses requiring stability are stopped.');
NSMetrics = nominalReconstruction.metrics;
NPMetrics = struct( ...
    'gammaTarget', config.gammaTarget, ...
    'gammaNominal', NSMetrics.gammaNominal, ...
    'peakFrequency', NSMetrics.peakFrequency, ...
    'outcome', nominalReconstruction.NPOutcome);

decomposition = decompose_m12_ndelta(Tzw_unc, config);
M = decomposition.M;
Delta = decomposition.Delta;
BlkStruct = decomposition.BlkStruct;
normunc = decomposition.normunc;
deltaStructureTable = decomposition.structureTable;
lftEquivalenceAudit = decomposition.audit;
manualMuRS = analyze_m12_manual_mu( ...
    decomposition.M11mu, BlkStruct, config);
robustStability = analyze_m12_robust_stability( ...
    Tzw_unc, m4.GuncQ, K_A5, m5.W1, m5.W2, manualMuRS, config);
robustPerformance = analyze_m12_robust_performance( ...
    Tzw_unc, m4.GuncQ, nominalReconstruction, config);
criticalBlockDiagnostics = localCriticalBlockTable( ...
    deltaStructureTable, robustStability, robustPerformance);
summaryNSNPRSRP = localSummaryTable( ...
    nominalReconstruction, robustStability, robustPerformance);

qualityGate = struct;
qualityGate.frozenControllerCorrectness = localPassFail( ...
    selectedController.loadedWithoutTuning && ...
    selectedController.internalStableM11);
qualityGate.frozenUncertaintyCorrectness = ...
    localPassFail(M4SourceAudit.passed);
qualityGate.nDeltaDecomposition = ...
    localPassFail(lftEquivalenceAudit.passed);
qualityGate.nominalStability = nominalReconstruction.NSOutcome;
qualityGate.nominalPerformance = nominalReconstruction.NPOutcome;
qualityGate.robustStability = robustStability.outcome;
qualityGate.manualMuRSConsistency = ...
    robustStability.manualMuConsistency.outcome;
qualityGate.robustPerformance = robustPerformance.outcome;
qualityGate.worstCaseGain = "QUANTIFIED";
qualityGate.criticalUncertaintyBlocks = "QUANTIFIED";
qualityGate.softwareCorrectness = localPassFail( ...
    qualityGate.frozenControllerCorrectness == "PASS" && ...
    qualityGate.frozenUncertaintyCorrectness == "PASS" && ...
    qualityGate.nDeltaDecomposition == "PASS" && ...
    qualityGate.nominalStability == "PASS" && ...
    qualityGate.manualMuRSConsistency ~= "FAIL_METHODOLOGICAL" && ...
    robustPerformance.worstGainSubstitutionCoherent);
if qualityGate.softwareCorrectness ~= "PASS" || ...
        qualityGate.manualMuRSConsistency == "FAIL_METHODOLOGICAL"
    qualityGate.overallStatus = "BLOCKED";
elseif qualityGate.nominalPerformance == "PASS" && ...
        qualityGate.robustStability == "PASS_CERTIFIED" && ...
        qualityGate.robustPerformance == "PASS_CERTIFIED"
    qualityGate.overallStatus = "COMPLETE";
else
    qualityGate.overallStatus = "PARTIAL";
end

metadata = struct( ...
    'milestone', "M12", ...
    'analysisOnly', true, ...
    'controllerSource', selectedController.sourceArtifact, ...
    'uncertaintySource', "results/data/m4_uncertain_plant.mat", ...
    'weightSource', "results/data/m5_performance_specs.mat", ...
    'controllerTuningPerformed', false, ...
    'weightRetuningPerformed', false, ...
    'W3Used', false, ...
    'monteCarloPerformed', false, ...
    'nonlinearValidationPerformed', false, ...
    'musynPerformed', false, ...
    'dkIterationPerformed', false, ...
    'm13Started', false, ...
    'minrealUsedForGate', false);
figurePaths = plot_m12_results(manualMuRS, nominalReconstruction, ...
    robustStability, robustPerformance, criticalBlockDiagnostics, ...
    summaryNSNPRSRP, figureDirectory, config);

robustStabilityMargin = robustStability.margin;
worstUncertaintyRS = robustStability.worstUncertainty;
infoRS = robustStability.info;
robustPerformanceMargin = robustPerformance.performanceMargin;
worstUncertaintyRP = robustPerformance.worstPerformanceUncertainty;
infoRP = robustPerformance.performanceInfo;
worstCaseGain = robustPerformance.worstCaseGain;
worstUncertaintyGain = robustPerformance.worstGainUncertainty;
infoGain = robustPerformance.worstGainInfo;
datasetPath = fullfile(dataDirectory, 'm12_mu_analysis_a5.mat');
save(datasetPath, 'config', 'selectedController', 'K_A5', ...
    'M4SourceAudit', 'weightAudit', 'Punc', 'Tzw_unc', ...
    'PuncNominalError', 'nominalReconstruction', 'NSMetrics', ...
    'NPMetrics', 'M', 'Delta', 'BlkStruct', 'normunc', ...
    'deltaStructureTable', 'decomposition', 'lftEquivalenceAudit', ...
    'manualMuRS', 'robustStability', 'robustStabilityMargin', ...
    'worstUncertaintyRS', 'infoRS', 'robustPerformance', ...
    'robustPerformanceMargin', 'worstUncertaintyRP', 'infoRP', ...
    'worstCaseGain', 'worstUncertaintyGain', 'infoGain', ...
    'criticalBlockDiagnostics', 'summaryNSNPRSRP', 'qualityGate', ...
    'metadata', 'figurePaths', '-v7.3');

assert(qualityGate.softwareCorrectness == "PASS", ...
    'M12:SoftwareQualityGate', ...
    'M12 failed a methodological software quality gate.');
assert(isfile(datasetPath) && all(structfun(@isfile, figurePaths)), ...
    'M12:Artifacts', 'One or more M12 artifacts are missing.');

fprintf('\n=== Validazione M12: mu-analysis A5 ===\n');
fprintf(['A5: start=%d, order=%d, M11 norm=%.12g; ' ...
    'M4 nominal error=%.3e, Punc error=%.3e\n'], ...
    selectedController.startIndex, selectedController.order, ...
    selectedController.weightedNormM11, ...
    M4SourceAudit.maximumFrequencyError, PuncNominalError);
fprintf(['N-Delta: M=%dx%d, Delta=%dx%d, blocks=%d, ' ...
    'reconstruction=%.3e\n'], size(M, 1), size(M, 2), ...
    size(Delta, 1), size(Delta, 2), numel(BlkStruct), ...
    lftEquivalenceAudit.probeFrequencyError);
fprintf('NS=%s, max pole=%.12g; NP=%s, gamma=%.12g @ %.12g rad/s\n', ...
    nominalReconstruction.NSOutcome, NSMetrics.maximumRealPart, ...
    nominalReconstruction.NPOutcome, NPMetrics.gammaNominal, ...
    NPMetrics.peakFrequency);
fprintf(['RS=%s, margin=[%.12g, %.12g] @ %.12g rad/s; ' ...
    'manual mu margin=[%.12g, %.12g], consistency=%s\n'], ...
    robustStability.outcome, robustStabilityMargin.LowerBound, ...
    robustStabilityMargin.UpperBound, ...
    robustStabilityMargin.CriticalFrequency, ...
    manualMuRS.marginLowerApproximation, ...
    manualMuRS.marginUpperApproximation, ...
    robustStability.manualMuConsistency.outcome);
fprintf(['RP=%s, margin=[%.12g, %.12g]; wcgain=[%.12g, %.12g], ' ...
    'substituted gain=%.12g\n'], robustPerformance.outcome, ...
    robustPerformanceMargin.LowerBound, ...
    robustPerformanceMargin.UpperBound, worstCaseGain.LowerBound, ...
    worstCaseGain.UpperBound, robustPerformance.worstGainActual);
fprintf('Software=%s, M12=%s\n', ...
    qualityGate.softwareCorrectness, qualityGate.overallStatus);
fprintf('Dataset: %s\n', datasetPath);

metrics.config = config;
metrics.selectedController = selectedController;
metrics.M4SourceAudit = M4SourceAudit;
metrics.nominalReconstruction = nominalReconstruction;
metrics.decomposition = decomposition;
metrics.manualMuRS = manualMuRS;
metrics.robustStability = robustStability;
metrics.robustPerformance = robustPerformance;
metrics.summary = summaryNSNPRSRP;
metrics.qualityGate = qualityGate;
metrics.figurePaths = figurePaths;
metrics.datasetPath = datasetPath;
end

function audit = localAuditM4(m4, m3, config)
uncertaintyNames = sort(string(fieldnames(m4.GuncQ.Uncertainty)));
approvedNames = sort(m4.deltaStructureMetadata.Name);
expectedNames = sort(config.expectedUncertaintyNames);
maximumFrequencyError = localFrequencyError( ...
    m4.GuncQ.NominalValue, m3.GfullQ, config.auditFrequencyGrid);
[poleInclusionError, additionalPoles] = localPoleInclusionError( ...
    pole(m3.GfullQ), pole(m4.GuncQ.NominalValue));
additionalPolesStable = all(real(additionalPoles) < ...
    -config.stabilityTolerance);
blocks = m4.GuncQ.Uncertainty;
rangeTable = localUncertaintyRangeTable(blocks);
passed = isequal(uncertaintyNames, approvedNames) && ...
    isequal(uncertaintyNames, expectedNames) && ...
    maximumFrequencyError <= config.nominalFrequencyTolerance && ...
    poleInclusionError <= config.nominalPoleTolerance && ...
    additionalPolesStable && all(rangeTable.ApprovedStructure);
audit.sourceArtifact = "results/data/m4_uncertain_plant.mat";
audit.modelName = "GuncQ";
audit.size = size(m4.GuncQ);
audit.rawNominalOrder = order(m4.GuncQ.NominalValue);
audit.m3Order = order(m3.GfullQ);
audit.maximumFrequencyError = maximumFrequencyError;
audit.poleInclusionError = poleInclusionError;
audit.additionalNominalPoles = additionalPoles;
audit.additionalNominalPolesStable = additionalPolesStable;
audit.uncertaintyNames = uncertaintyNames;
audit.approvedNames = approvedNames;
audit.rangeTable = rangeTable;
audit.WI = m4.WI;
audit.WIOrder = order(m4.WI);
audit.passed = passed;
end

function tableData = localUncertaintyRangeTable(blocks)
names = string(fieldnames(blocks));
numberBlocks = numel(names);
Name = names;
Type = strings(numberBlocks, 1);
Nominal = nan(numberBlocks, 1);
Lower = nan(numberBlocks, 1);
Upper = nan(numberBlocks, 1);
PercentMinus = nan(numberBlocks, 1);
PercentPlus = nan(numberBlocks, 1);
Bound = nan(numberBlocks, 1);
ApprovedStructure = false(numberBlocks, 1);
for index = 1:numberBlocks
    block = blocks.(char(names(index)));
    Type(index) = string(class(block));
    if isa(block, 'ureal')
        Nominal(index) = block.NominalValue;
        Lower(index) = block.Range(1);
        Upper(index) = block.Range(2);
        PercentMinus(index) = block.Percentage(1);
        PercentPlus(index) = block.Percentage(2);
        ApprovedStructure(index) = ...
            ismember(names(index), ["Jm1", "k1", "k2"]) && ...
            max(abs(block.Percentage - [-10, 10])) <= 1e-10;
    elseif isa(block, 'ultidyn')
        Bound(index) = block.Bound;
        ApprovedStructure(index) = block.Bound == 1 && ...
            ismember(names(index), ["Delta_act1", "Delta_act2"]);
    end
end
tableData = table(Name, Type, Nominal, Lower, Upper, PercentMinus, ...
    PercentPlus, Bound, ApprovedStructure);
end

function [error, remaining] = localPoleInclusionError(reference, actual)
reference = reference(:);
remaining = actual(:);
assert(numel(remaining) >= numel(reference), 'M12M4:PoleCount', ...
    'The M4 nominal plant has fewer poles than M3.');
errors = zeros(numel(reference), 1);
for index = 1:numel(reference)
    [errors(index), match] = min(abs(remaining - reference(index)));
    remaining(match) = [];
end
error = max(errors);
end

function tableData = localCriticalBlockTable( ...
    structureTable, robustStability, robustPerformance)
BlockName = structureTable.Name;
Type = structureTable.Type;
Occurrences = structureTable.Occurrences;
numberBlocks = height(structureTable);
RSSensitivity = nan(numberBlocks, 1);
RPSensitivity = nan(numberBlocks, 1);
WCGainSensitivity = nan(numberBlocks, 1);
RSWorstNormalizedMagnitude = nan(numberBlocks, 1);
RPWorstNormalizedMagnitude = nan(numberBlocks, 1);
GainWorstNormalizedMagnitude = nan(numberBlocks, 1);
for index = 1:numberBlocks
    name = char(BlockName(index));
    RSSensitivity(index) = robustStability.sensitivity.(name);
    RPSensitivity(index) = ...
        robustPerformance.performanceSensitivity.(name);
    WCGainSensitivity(index) = ...
        robustPerformance.worstGainSensitivity.(name);
    rsRow = robustStability.worstCaseDiagnostics.BlockName == ...
        BlockName(index);
    rpRow = robustPerformance.worstPerformanceDiagnostics.BlockName == ...
        BlockName(index);
    gainRow = robustPerformance.worstGainDiagnostics.BlockName == ...
        BlockName(index);
    RSWorstNormalizedMagnitude(index) = robustStability. ...
        worstCaseDiagnostics.NormalizedMagnitude(rsRow);
    RPWorstNormalizedMagnitude(index) = robustPerformance. ...
        worstPerformanceDiagnostics.NormalizedMagnitude(rpRow);
    GainWorstNormalizedMagnitude(index) = robustPerformance. ...
        worstGainDiagnostics.NormalizedMagnitude(gainRow);
end
tableData = table(BlockName, Type, Occurrences, RSSensitivity, ...
    RPSensitivity, WCGainSensitivity, RSWorstNormalizedMagnitude, ...
    RPWorstNormalizedMagnitude, GainWorstNormalizedMagnitude);
end

function tableData = localSummaryTable(nominal, rs, rp)
Property = ["NS"; "NP"; "RS"; "RP"];
MetricName = ["maximum internal real pole"; ...
    "nominal weighted norm"; "robust stability margin"; ...
    "robust performance margin at gamma=1"];
Metric = [nominal.metrics.maximumRealPart; ...
    nominal.metrics.gammaNominal; NaN; NaN];
Lower = [NaN; NaN; rs.margin.LowerBound; ...
    rp.performanceMargin.LowerBound];
Upper = [NaN; NaN; rs.margin.UpperBound; ...
    rp.performanceMargin.UpperBound];
CriticalFrequency = [NaN; nominal.metrics.peakFrequency; ...
    rs.margin.CriticalFrequency; rp.performanceMargin.CriticalFrequency];
Outcome = [nominal.NSOutcome; nominal.NPOutcome; rs.outcome; rp.outcome];
tableData = table(Property, MetricName, Metric, Lower, Upper, ...
    CriticalFrequency, Outcome);
end

function error = localFrequencyError(first, second, frequencies)
first = localClearNames(ss(first));
second = localClearNames(ss(second));
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
error = max(abs(difference), [], 'all');
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function status = localPassFail(condition)
if condition
    status = "PASS";
else
    status = "FAIL";
end
end
