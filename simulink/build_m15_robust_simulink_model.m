function metadata = build_m15_robust_simulink_model(projectRoot)
%BUILD_M15_ROBUST_SIMULINK_MODEL Build the dedicated M15 nonlinear model.

arguments
    projectRoot (1, 1) string = string(fileparts(fileparts( ...
        mfilename('fullpath'))))
end

projectRoot = char(projectRoot);
dataDirectory = fullfile(projectRoot, 'results', 'data');
m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
controllers = load_m15_robust_controllers(string(projectRoot));
config = m15_specs;
defaultController = controllers(1);
modelName = char(config.modelName);
modelPath = fullfile(projectRoot, config.modelRelativePath);

load_system('simulink');
if bdIsLoaded(modelName), close_system(modelName, 0); end
if isfile(modelPath)
    load_system(modelPath);
    Simulink.BlockDiagram.deleteContents(modelName);
else
    new_system(modelName);
end
cleanupModel = onCleanup(@() localCloseIfLoaded(modelName));
set_param(modelName, 'Solver', char(config.solver.selected), ...
    'SolverType', 'Variable-step', ...
    'RelTol', localNumber(config.solver.relativeTolerance), ...
    'AbsTol', localNumber(config.solver.absoluteTolerance), ...
    'MaxStep', localNumber(config.solver.maximumStep), ...
    'StopTime', localNumber(config.simulation.equilibriumHorizon), ...
    'ReturnWorkspaceOutputs', 'on', 'SaveOutput', 'on', ...
    'OutputSaveName', 'yout', 'SaveFormat', 'Dataset', ...
    'SignalLogging', 'on', 'SignalLoggingName', 'logsout');

localAddRootPorts(modelName);
localAddController(modelName, m3, defaultController);
localAddActuators(modelName, m3);
localAddNonlinearPlant(modelName, m3);
localAddMeasurementAndLogging(modelName, m3);
localConnectRoot(modelName);

metadata = struct( ...
    'modelName', string(modelName), 'modelPath', string(modelPath), ...
    'architecture', "q-only frozen K(e), e=r-q, u=taubar+K(e)", ...
    'nonlinearPlantSource', "sea_nonlinear_rhs_with_link_disturbance", ...
    'nonlinearSFunction', "m8_nonlinear_sea_sfun", ...
    'actuatorSource', "results/data/m3_nominal_actuated_plant.mat", ...
    'mechanicalStateCount', 8, 'actuatorStateCount', 6, ...
    'physicalPlantStateCount', 14, ...
    'supportedControllerOrders', [controllers.order], ...
    'absolutePlantCoordinates', true, ...
    'incrementalControllerCoordinates', true, ...
    'qOnlyMeasurements', true, 'errorConvention', "e=r-q", ...
    'equilibriumTorqueAdded', true, 'prefilterEnabled', false, ...
    'integralAugmentationEnabled', false, ...
    'baseWorkspaceDependency', false, 'saturationEnabled', false, ...
    'xbar', m3.xbar, 'taubar', m3.taubar, ...
    'actuatorEquilibrium', localActuatorEquilibrium(m3), ...
    'solver', config.solver, 'm8ModelModified', false);
set_param(modelName, 'Description', char(metadata.architecture));
annotation = Simulink.Annotation(modelName, sprintf([ ...
    'M15 — frozen Khinf/Kmu nonlinear validation\n' ...
    'q-only feedback; absolute M1 mechanics + nominal M3 actuators\n' ...
    'runtime controller and initial conditions via SimulationInput']));
annotation.Position = [390, 10, 870, 65];
Simulink.BlockDiagram.arrangeSystem(modelName);
save_system(modelName, modelPath);
metadata.saved = isfile(modelPath);
clear cleanupModel
close_system(modelName, 0);
end

function localAddRootPorts(modelName)
localAddBlock('simulink/Ports & Subsystems/In1', ...
    [modelName '/Reference'], [20, 75, 50, 95], ...
    'Port', '1', 'PortDimensions', '2');
localAddBlock('simulink/Ports & Subsystems/In1', ...
    [modelName '/Disturbance'], [20, 230, 50, 250], ...
    'Port', '2', 'PortDimensions', '2');
localAddBlock('simulink/Ports & Subsystems/In1', ...
    [modelName '/Measurement Noise q'], [20, 340, 50, 360], ...
    'Port', '3', 'PortDimensions', '2');
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [modelName '/Logged Signals'], [1080, 250, 1110, 270], 'Port', '1');
end

function localAddController(modelName, m3, controller)
subsystem = [modelName '/Controller'];
localAddBlock('built-in/Subsystem', subsystem, [190, 60, 400, 180]);
set_param(subsystem, 'BackgroundColor', 'lightBlue');
localAddBlock('simulink/Ports & Subsystems/In1', ...
    [subsystem '/reference'], [20, 25, 50, 45], ...
    'Port', '1', 'PortDimensions', '2');
localAddBlock('simulink/Ports & Subsystems/In1', ...
    [subsystem '/q noisy'], [20, 95, 50, 115], ...
    'Port', '2', 'PortDimensions', '2');
localAddBlock('simulink/Math Operations/Sum', ...
    [subsystem '/Error r minus q'], [90, 50, 120, 80], 'Inputs', '+-');
n = controller.order;
C = [controller.C; eye(n)];
D = [controller.D; zeros(n, 2)];
localAddBlock('simulink/Continuous/State-Space', ...
    [subsystem '/Frozen Dynamic Controller'], [165, 45, 285, 85], ...
    'A', localMatrix(controller.A), 'B', localMatrix(controller.B), ...
    'C', localMatrix(C), 'D', localMatrix(D), ...
    'InitialCondition', localMatrix(zeros(n, 1)));
localAddBlock('simulink/Signal Routing/Demux', ...
    [subsystem '/Delta Control and Controller State'], ...
    [320, 40, 325, 110], 'Outputs', sprintf('[2 %d]', n));
localAddBlock('simulink/Sources/Constant', ...
    [subsystem '/Equilibrium Torque'], [350, 10, 420, 35], ...
    'Value', localMatrix(m3.taubar));
localAddBlock('simulink/Math Operations/Sum', ...
    [subsystem '/Absolute Control'], [450, 40, 480, 70], 'Inputs', '++');
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [subsystem '/u absolute'], [525, 35, 555, 55], 'Port', '1');
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [subsystem '/controller state'], [525, 85, 555, 105], 'Port', '2');
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [subsystem '/u delta'], [525, 130, 555, 150], 'Port', '3');
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [subsystem '/error'], [525, 175, 555, 195], 'Port', '4');
add_line(subsystem, 'reference/1', 'Error r minus q/1');
add_line(subsystem, 'q noisy/1', 'Error r minus q/2');
add_line(subsystem, 'Error r minus q/1', 'Frozen Dynamic Controller/1');
add_line(subsystem, 'Frozen Dynamic Controller/1', ...
    'Delta Control and Controller State/1');
add_line(subsystem, 'Delta Control and Controller State/1', ...
    'Absolute Control/1');
add_line(subsystem, 'Equilibrium Torque/1', 'Absolute Control/2');
add_line(subsystem, 'Absolute Control/1', 'u absolute/1');
add_line(subsystem, 'Delta Control and Controller State/2', ...
    'controller state/1');
add_line(subsystem, 'Delta Control and Controller State/1', 'u delta/1');
add_line(subsystem, 'Error r minus q/1', 'error/1');
end

function localAddActuators(modelName, m3)
subsystem = [modelName '/Actuators'];
localAddBlock('built-in/Subsystem', subsystem, [470, 65, 625, 165]);
set_param(subsystem, 'BackgroundColor', 'orange');
localAddBlock('simulink/Ports & Subsystems/In1', [subsystem '/u'], ...
    [20, 55, 50, 75], 'Port', '1', 'PortDimensions', '2');
[A, B, Cact, Dact] = ssdata(m3.GactuatorsMimo);
C = [Cact; eye(6)]; D = [Dact; zeros(6, 2)];
localAddBlock('simulink/Continuous/State-Space', ...
    [subsystem '/M3 Second Order plus Pade'], [90, 45, 225, 85], ...
    'A', localMatrix(A), 'B', localMatrix(B), 'C', localMatrix(C), ...
    'D', localMatrix(D), 'InitialCondition', ...
    localMatrix(localActuatorEquilibrium(m3)));
localAddBlock('simulink/Signal Routing/Demux', ...
    [subsystem '/Torque and State'], [255, 40, 260, 100], ...
    'Outputs', '[2 6]');
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [subsystem '/tau'], [305, 45, 335, 65], 'Port', '1');
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [subsystem '/xact'], [305, 90, 335, 110], 'Port', '2');
add_line(subsystem, 'u/1', 'M3 Second Order plus Pade/1');
add_line(subsystem, 'M3 Second Order plus Pade/1', 'Torque and State/1');
add_line(subsystem, 'Torque and State/1', 'tau/1');
add_line(subsystem, 'Torque and State/2', 'xact/1');
end

function localAddNonlinearPlant(modelName, m3)
subsystem = [modelName '/Nonlinear SEA Plant'];
localAddBlock('built-in/Subsystem', subsystem, [690, 65, 855, 180]);
set_param(subsystem, 'BackgroundColor', 'green');
localAddBlock('simulink/Ports & Subsystems/In1', ...
    [subsystem '/tau'], [20, 35, 50, 55], ...
    'Port', '1', 'PortDimensions', '2');
localAddBlock('simulink/Ports & Subsystems/In1', ...
    [subsystem '/d link'], [20, 95, 50, 115], ...
    'Port', '2', 'PortDimensions', '2');
localAddBlock(['simulink/User-Defined Functions/' ...
    'Level-2 MATLAB S-Function'], [subsystem '/M1 Nonlinear Dynamics'], ...
    [100, 45, 245, 105], 'FunctionName', ...
    'm8_nonlinear_sea_sfun', 'Parameters', localMatrix(m3.xbar));
localAddBlock('simulink/Ports & Subsystems/Out1', ...
    [subsystem '/x mechanical'], [300, 65, 330, 85], 'Port', '1');
add_line(subsystem, 'tau/1', 'M1 Nonlinear Dynamics/1');
add_line(subsystem, 'd link/1', 'M1 Nonlinear Dynamics/2');
add_line(subsystem, 'M1 Nonlinear Dynamics/1', 'x mechanical/1');
end

function localAddMeasurementAndLogging(modelName, m3)
localAddBlock('simulink/Signal Routing/Demux', ...
    [modelName '/Mechanical Coordinates'], [880, 65, 885, 190], ...
    'Outputs', '[2 2 2 2]');
localAddBlock('simulink/Math Operations/Bias', ...
    [modelName '/Incremental q'], [920, 65, 980, 95], ...
    'Bias', localMatrix(-m3.xbar(1:2)));
localAddBlock('simulink/Math Operations/Sum', ...
    [modelName '/Add q Noise'], [1010, 65, 1040, 95], 'Inputs', '++');
localAddBlock('simulink/Signal Routing/Mux', ...
    [modelName '/Logging'], [910, 220, 915, 505], 'Inputs', '11');
add_line(modelName, 'Mechanical Coordinates/1', 'Incremental q/1');
add_line(modelName, 'Incremental q/1', 'Add q Noise/1');
add_line(modelName, 'Measurement Noise q/1', 'Add q Noise/2');
end

function localConnectRoot(modelName)
add_line(modelName, 'Reference/1', 'Controller/1', 'autorouting', 'on');
add_line(modelName, 'Add q Noise/1', 'Controller/2', 'autorouting', 'on');
add_line(modelName, 'Controller/1', 'Actuators/1', 'autorouting', 'on');
add_line(modelName, 'Actuators/1', 'Nonlinear SEA Plant/1', 'autorouting', 'on');
add_line(modelName, 'Disturbance/1', 'Nonlinear SEA Plant/2', 'autorouting', 'on');
add_line(modelName, 'Nonlinear SEA Plant/1', ...
    'Mechanical Coordinates/1', 'autorouting', 'on');
sources = {'Nonlinear SEA Plant/1', 'Actuators/2', 'Controller/2', ...
    'Controller/3', 'Controller/1', 'Actuators/1', 'Disturbance/1', ...
    'Measurement Noise q/1', 'Reference/1', 'Controller/4', ...
    'Add q Noise/1'};
for index = 1:numel(sources)
    add_line(modelName, sources{index}, sprintf('Logging/%d', index), ...
        'autorouting', 'on');
end
loggedLine = add_line(modelName, 'Logging/1', 'Logged Signals/1', ...
    'autorouting', 'on');
set_param(loggedLine, 'Name', 'm15LoggedSignals');
end

function block = localAddBlock(source, destination, position, varargin)
block = add_block(source, destination, 'Position', position, varargin{:});
end

function equilibrium = localActuatorEquilibrium(m3)
[Aact, Bact] = ssdata(m3.GactuatorsMimo);
equilibrium = -Aact \ (Bact * m3.taubar);
end

function value = localMatrix(matrix), value = mat2str(matrix, 17); end
function value = localNumber(number), value = sprintf('%.17g', number); end
function localCloseIfLoaded(modelName)
if bdIsLoaded(modelName), close_system(modelName, 0); end
end
