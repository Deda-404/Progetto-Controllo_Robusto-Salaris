    'autorouting', 'on');
add_line(modelName, 'Disturbance/1', 'Nonlinear SEA Plant/2', ...
    'autorouting', 'on');
add_line(modelName, 'Nonlinear SEA Plant/1', 'Measurement Interface/1', ...
    'autorouting', 'on');
add_line(modelName, 'Measurement Noise/1', 'Measurement Interface/2', ...
    'autorouting', 'on');
add_line(modelName, 'Reference/1', 'Signal Monitoring/1', ...
    'autorouting', 'on');
add_line(modelName, 'Nonlinear SEA Plant/1', 'Signal Monitoring/2', ...
    'autorouting', 'on');
add_line(modelName, 'Actuator Dynamics/2', 'Signal Monitoring/3', ...
    'autorouting', 'on');
add_line(modelName, 'LQG Controller/2', 'Signal Monitoring/4', ...
    'autorouting', 'on');
add_line(modelName, 'LQG Controller/1', 'Signal Monitoring/5', ...
    'autorouting', 'on');
