function uncertainty = uncertainty_params_m4
%UNCERTAINTY_PARAMS_M4 Single engineering uncertainty set for the SEA model.
%   The percentages below are project assumptions. They are deliberately
%   simple and must not be interpreted as measured manufacturing tolerances
%   or statistically identified confidence intervals.

mechanical = sea_params_nominal;
actuator = actuator_params_nominal;

mechanicalParameter = ["k1"; "k2"; "Jm1"];
mechanicalNominalValue = [ ...
    mechanical.Ks(1, 1); ...
    mechanical.Ks(2, 2); ...
    mechanical.Jm(1, 1)];
mechanicalPercentage = [10; 10; 10];
mechanicalUnit = ["N m/rad"; "N m/rad"; "kg m^2"];
mechanicalLowerBound = mechanicalNominalValue .* ...
    (1 - mechanicalPercentage / 100);
mechanicalUpperBound = mechanicalNominalValue .* ...
    (1 + mechanicalPercentage / 100);
mechanicalRationale = [ ...
    "joint-1 equivalent SEA stiffness: assembly and material uncertainty"; ...
    "joint-2 equivalent SEA stiffness: assembly and material uncertainty"; ...
    "motor-1 reflected inertia: drive-train and load-model uncertainty"];

uncertainty.selectedMechanicalRanges = table( ...
    mechanicalParameter, mechanicalNominalValue, mechanicalUnit, ...
    mechanicalLowerBound, mechanicalUpperBound, mechanicalPercentage, ...
    mechanicalRationale, 'VariableNames', {'Parameter', 'NominalValue', ...
    'Unit', 'LowerBound', 'UpperBound', 'Percentage', 'Rationale'});

actuatorParameter = ["wn"; "zeta"; "delay"];
actuatorNominalValue = [actuator.wn; actuator.zeta; actuator.delay];
actuatorPercentage = [10; 10; 20];
actuatorUnit = ["rad/s"; "-"; "s"];
actuatorLowerBound = actuatorNominalValue .* ...
    (1 - actuatorPercentage / 100);
actuatorUpperBound = actuatorNominalValue .* ...
    (1 + actuatorPercentage / 100);
actuatorRationale = [ ...
    "closed-loop actuator bandwidth varies with drive and load"; ...
    "damping changes with drive tuning and operating condition"; ...
    "latency and jitter around the nominal 15 ms delay"];

uncertainty.selectedActuatorRanges = table( ...
    actuatorParameter, actuatorNominalValue, actuatorUnit, ...
    actuatorLowerBound, actuatorUpperBound, actuatorPercentage, ...
    actuatorRationale, 'VariableNames', {'Parameter', 'NominalValue', ...
    'Unit', 'LowerBound', 'UpperBound', 'Percentage', 'Rationale'});
uncertainty.actuatorNominalSource = "actuator_params_nominal";

% Parameters kept fixed in the adopted uncertainty model. These are model
% assumptions, not experimentally established tolerance statements.
fixedParameter = ["m1"; "m2"; "l1"; "l2"; "Jm2"; ...
    "Bm1"; "Bm2"; "g"];
fixedNominalValue = [mechanical.m1; mechanical.m2; mechanical.l1; ...
    mechanical.l2; mechanical.Jm(2, 2); mechanical.Bm(1, 1); ...
    mechanical.Bm(2, 2); mechanical.g];
fixedUnit = ["kg"; "kg"; "m"; "m"; "kg m^2"; ...
    "N m s/rad"; "N m s/rad"; "m/s^2"];
fixedRole = ["link-1 mass"; "link-2 mass"; "link-1 length"; ...
    "link-2 length"; "motor-2 reflected inertia"; ...
    "motor-1 viscous damping"; "motor-2 viscous damping"; ...
    "gravity acceleration"];
fixedRationale = [ ...
    "nominal rigid-body parameter; not a selected dominant dispersion"; ...
    "nominal rigid-body parameter; not a selected dominant dispersion"; ...
    "nominal geometry used to define the two-link model"; ...
    "nominal geometry used to define the two-link model"; ...
    "kept nominal to avoid duplicating the selected Jm1 inertia direction"; ...
    "small dissipative term kept nominal in the adopted uncertainty set"; ...
    "small dissipative term kept nominal in the adopted uncertainty set"; ...
    "known environmental constant in the model"];
uncertainty.fixedModelParameters = table(fixedParameter, ...
    fixedNominalValue, fixedUnit, fixedRole, fixedRationale, ...
    'VariableNames', {'Parameter', 'NominalValue', 'Unit', 'Role', ...
    'Rationale'});

% Reproducible samples are used only to verify the declared model and to
% construct the actuator-error envelope. They do not define new scenarios.
uncertainty.actuatorFamilySeed = 20260824;
uncertainty.actuatorRandomSamples = 105;
uncertainty.plantSamplingSeed = 20260825;
uncertainty.plantValidationSamples = 40;
uncertainty.weightSafetyFactor = 1.08;
uncertainty.coverageGrid = logspace(-1, 3, 801);
uncertainty.status = ...
    "Single engineering uncertainty set; no scenario hierarchy is used.";
end
