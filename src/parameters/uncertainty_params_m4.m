function uncertainty = uncertainty_params_m4
%UNCERTAINTY_PARAMS_M4 Single engineering uncertainty set for the SEA model.
%   The percentages below are project assumptions. They are deliberately
%   simple and must not be interpreted as measured manufacturing tolerances
%   or statistically identified confidence intervals.

mechanical = sea_params_nominal;
actuator = actuator_params_nominal;

mechanicalParameter = ["k1"; "k2"; "Jm1"];
mechanicalNominalValue = [ ...
    mechanical.Ks(1, 1); ...
    mechanical.Ks(2, 2); ...
    mechanical.Jm(1, 1)];
mechanicalPercentage = [10; 10; 10];
mechanicalRationale = [ ...
    "joint-1 equivalent SEA stiffness: assembly and material uncertainty"; ...
    "joint-2 equivalent SEA stiffness: assembly and material uncertainty"; ...
    "motor-1 reflected inertia: drive-train and load-model uncertainty"];

uncertainty.selectedMechanicalRanges = table( ...
    mechanicalParameter, mechanicalNominalValue, mechanicalPercentage, ...
    mechanicalRationale, 'VariableNames', {'Parameter', 'NominalValue', ...
    'Percentage', 'Rationale'});

actuatorParameter = ["wn"; "zeta"; "delay"];
actuatorNominalValue = [actuator.wn; actuator.zeta; actuator.delay];
actuatorPercentage = [10; 10; 20];
actuatorRationale = [ ...
    "closed-loop actuator bandwidth varies with drive and load"; ...
    "damping changes with drive tuning and operating condition"; ...
    "latency and jitter around the nominal 15 ms delay"];

uncertainty.selectedActuatorRanges = table( ...
    actuatorParameter, actuatorNominalValue, actuatorPercentage, ...
    actuatorRationale, 'VariableNames', {'Parameter', 'NominalValue', ...
    'Percentage', 'Rationale'});
uncertainty.actuatorNominalSource = "actuator_params_nominal";

% Reproducible samples are used only to verify the declared model and to
% construct the actuator-error envelope. They do not define new scenarios.
uncertainty.actuatorFamilySeed = 20260824;
uncertainty.actuatorRandomSamples = 105;
uncertainty.plantSamplingSeed = 20260825;
uncertainty.plantValidationSamples = 40;
uncertainty.weightSafetyFactor = 1.08;
uncertainty.coverageGrid = logspace(-1, 3, 801);
uncertainty.status = ...
    "Single engineering uncertainty set; no scenario hierarchy is used.";
end
