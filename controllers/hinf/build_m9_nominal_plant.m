function plant = build_m9_nominal_plant(m3, m5, config)
%BUILD_M9_NOMINAL_PLANT Audit and expose the frozen nominal M9 channels.

arguments
    m3 (1, 1) struct
    m5 (1, 1) struct
    config (1, 1) struct = hinf_specs_m9
end

requiredM3 = {'GfullQ', 'Afull', 'Bfull', 'CfullQ', 'DfullQ', ...
    'structuralMetricsQ', 'actuatorParams'};
requiredM5 = {'disturbancePlant', 'BdFull', 'W1', 'W2', 'spec'};
assert(all(isfield(m3, requiredM3)), 'M9Plant:MissingM3Fields', ...
    'The validated M3 dataset is missing one or more required fields.');
assert(all(isfield(m5, requiredM5)), 'M9Plant:MissingM5Fields', ...
    'The validated M5 dataset is missing one or more required fields.');

G = m3.GfullQ;
GfromM5 = m5.disturbancePlant(1:2, 1:2);
Gd = ss(m3.Afull, m5.BdFull, m3.CfullQ, zeros(2), ...
    'InputName', {'d1', 'd2'}, 'OutputName', {'q1', 'q2'});
GdFromM5 = m5.disturbancePlant(1:2, 3:4);

frequencies = config.frequencyGrid;
controlPathError = localMaximumFrequencyError(G, GfromM5, frequencies);
disturbancePathError = localMaximumFrequencyError( ...
    Gd, GdFromM5, frequencies);
poles = pole(G);
transmissionZeros = tzero(G);

plant.G = G;
plant.Gd = Gd;
plant.audit = struct( ...
    'inputCount', size(G, 2), ...
    'outputCount', size(G, 1), ...
    'order', order(G), ...
    'controlPathMaximumError', controlPathError, ...
    'disturbancePathMaximumError', disturbancePathError, ...
    'poles', poles, ...
    'numberUnstablePoles', sum(real(poles) > config.stabilityTolerance), ...
    'maximumOpenLoopRealPart', max(real(poles)), ...
    'transmissionZeros', transmissionZeros, ...
    'rightHalfPlaneZeros', transmissionZeros( ...
        real(transmissionZeros) > config.stabilityTolerance), ...
    'stabilizable', m3.structuralMetricsQ.controllability.stabilizable, ...
    'detectable', m3.structuralMetricsQ.observability.detectable, ...
    'nominalOnly', isa(G, 'ss') && ~isa(G, 'uss'), ...
    'actuatorParameters', m3.actuatorParams, ...
    'equilibrium', m5.spec.equilibrium);

assert(isequal(size(G), [2, 2]) && order(G) == 14, ...
    'M9Plant:Dimensions', ...
    'M9 requires the complete 14-state 2-by-2 M3 plant from u to q.');
assert(controlPathError <= config.pathConsistencyTolerance && ...
    disturbancePathError <= config.pathConsistencyTolerance, ...
    'M9Plant:PathMismatch', ...
    'The M3 and M5 control/disturbance paths are inconsistent.');
assert(plant.audit.stabilizable && plant.audit.detectable, ...
    'M9Plant:StructuralConditions', ...
    'The nominal plant is not stabilizable or detectable.');
assert(norm(G.D, 'fro') == 0 && norm(Gd.D, 'fro') == 0, ...
    'M9Plant:UnexpectedFeedthrough', ...
    'The M9 control and disturbance channels must have zero feedthrough.');
end

function maximumError = localMaximumFrequencyError(first, second, frequencies)
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
maximumError = max(abs(difference), [], 'all');
end
