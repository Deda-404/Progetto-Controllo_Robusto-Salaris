function gate = validate_m10_generalized_plant( ...
    generalized, m9, config)
%VALIDATE_M10_GENERALIZED_PLANT Prove M9 equivalence before hinfsyn.

arguments
    generalized (1, 1) struct
    m9 (1, 1) struct
    config (1, 1) struct = hinf_specs_m10
end

requiredM9 = {'Kmix', 'CLmix', 'weightedClosedLoop', 'gamma'};
assert(all(isfield(m9, requiredM9)), ...
    'M10GeneralizedGate:MissingM9Artifact', ...
    'The frozen M9 artifact lacks fields required by the gate.');

closedLoopFromP = lft(generalized.P, m9.Kmix);
clmixError = localSystemNormDifference(closedLoopFromP, m9.CLmix);
weightedError = localSystemNormDifference( ...
    closedLoopFromP, m9.weightedClosedLoop);
[closedLoopNorm, peakFrequency] = norm(closedLoopFromP, inf);
gammaAbsoluteError = abs(closedLoopNorm - m9.gamma);
gammaRelativeError = gammaAbsoluteError / max(m9.gamma, eps);

gate.closedLoopFromP = closedLoopFromP;
gate.metrics = struct( ...
    'clmixError', clmixError, ...
    'weightedClosedLoopError', weightedError, ...
    'closedLoopNorm', closedLoopNorm, ...
    'peakFrequency', peakFrequency, ...
    'm9Gamma', m9.gamma, ...
    'gammaAbsoluteError', gammaAbsoluteError, ...
    'gammaRelativeError', gammaRelativeError, ...
    'tolerance', config.m9EquivalenceTolerance);
gate.passed = clmixError <= config.m9EquivalenceTolerance && ...
    weightedError <= config.m9EquivalenceTolerance && ...
    gammaRelativeError <= config.normRelativeTolerance;

assert(gate.passed, 'M10GeneralizedGate:M9NotReproduced', ...
    ['The explicit generalized plant does not reproduce the frozen M9 ' ...
    'closed loop. hinfsyn must not run.']);
end

function value = localSystemNormDifference(first, second)
first = localClearNames(first);
second = localClearNames(second);
value = norm(first - second, inf);
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end
