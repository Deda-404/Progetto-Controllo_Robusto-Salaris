function reconstruction = reconstruct_m9_mixed_sensitivity( ...
    G, Gd, W1, W2, synthesis, config)
%RECONSTRUCT_M9_MIXED_SENSITIVITY Independently rebuild and audit M9.

arguments
    G {mustBeA(G, {'ss', 'tf', 'zpk'})}
    Gd {mustBeA(Gd, {'ss', 'tf', 'zpk'})}
    W1 {mustBeA(W1, {'ss', 'tf', 'zpk'})}
    W2 {mustBeA(W2, {'ss', 'tf', 'zpk'})}
    synthesis (1, 1) struct
    config (1, 1) struct = hinf_specs_m9
end

Kmix = synthesis.Kmix;
identity = ss(eye(2));
S = feedback(identity, G * Kmix);
T = identity - S;
KS = Kmix * S;
weightedW1S = W1 * S;
weightedW2KS = W2 * KS;
weightedClosedLoop = [weightedW1S; weightedW2KS];

[weightedNorm, weightedPeakFrequency] = norm(weightedClosedLoop, inf);
[W1SNorm, W1SPeakFrequency] = norm(weightedW1S, inf);
[W2KSNorm, W2KSPeakFrequency] = norm(weightedW2KS, inf);
[clmixError, clmixErrorPeakFrequency] = norm( ...
    synthesis.CLmix - weightedClosedLoop, inf);

normAbsoluteError = abs(weightedNorm - synthesis.gamma);
normRelativeError = normAbsoluteError / max(synthesis.gamma, eps);

[Ag, Bg, Cg, Dg] = ssdata(G);
[Ak, Bk, Ck, Dk] = ssdata(Kmix);
assert(norm(Dg, 'fro') == 0, 'M9Reconstruction:PlantFeedthrough', ...
    'The explicit internal-stability construction assumes D_G=0.');
Ainternal = [Ag - Bg * Dk * Cg, Bg * Ck; -Bk * Cg, Ak];
Br = [Bg * Dk; Bk];
Bd = [Gd.B; zeros(size(Ak, 1), size(Gd.B, 2))];
Cq = [Cg, zeros(size(Cg, 1), size(Ak, 1))];
Cu = [-Dk * Cg, Ck];
closedLoopReference = ss(Ainternal, Br, [Cq; Cu], ...
    [zeros(2); Dk], 'InputName', {'r1', 'r2'}, ...
    'OutputName', {'q1', 'q2', 'u1', 'u2'});
closedLoopDisturbance = ss(Ainternal, Bd, [Cq; Cu], zeros(4, 2), ...
    'InputName', {'d1', 'd2'}, ...
    'OutputName', {'q1', 'q2', 'u1', 'u2'});

referenceTransferError = norm(closedLoopReference - [T; KS], inf);
disturbanceTransferError = norm(closedLoopDisturbance - ...
    [S * Gd; -KS * Gd], inf);
internalPoles = eig(Ainternal);

reconstruction.S = S;
reconstruction.T = T;
reconstruction.KS = KS;
reconstruction.weightedW1S = weightedW1S;
reconstruction.weightedW2KS = weightedW2KS;
reconstruction.weightedClosedLoop = weightedClosedLoop;
reconstruction.closedLoopReference = closedLoopReference;
reconstruction.closedLoopDisturbance = closedLoopDisturbance;
reconstruction.Ainternal = Ainternal;
reconstruction.internalPoles = internalPoles;
reconstruction.metrics = struct( ...
    'W1SNorm', W1SNorm, ...
    'W1SPeakFrequency', W1SPeakFrequency, ...
    'W2KSNorm', W2KSNorm, ...
    'W2KSPeakFrequency', W2KSPeakFrequency, ...
    'weightedNorm', weightedNorm, ...
    'weightedPeakFrequency', weightedPeakFrequency, ...
    'gamma', synthesis.gamma, ...
    'normAbsoluteError', normAbsoluteError, ...
    'normRelativeError', normRelativeError, ...
    'clmixError', clmixError, ...
    'clmixErrorPeakFrequency', clmixErrorPeakFrequency, ...
    'referenceTransferError', referenceTransferError, ...
    'disturbanceTransferError', disturbanceTransferError, ...
    'maximumClosedLoopRealPart', max(real(internalPoles)), ...
    'internalStateCount', numel(internalPoles), ...
    'nominallyStable', all(real(internalPoles) < ...
        -config.stabilityTolerance), ...
    'sensitivityStable', isstable(S), ...
    'complementarySensitivityStable', isstable(T), ...
    'controlSensitivityStable', isstable(KS), ...
    'clmixStable', isstable(synthesis.CLmix));

assert(normRelativeError <= config.normRelativeTolerance, ...
    'M9Reconstruction:GammaMismatch', ...
    'The independently reconstructed weighted norm disagrees with gamma.');
assert(clmixError <= config.closedLoopConsistencyTolerance && ...
    referenceTransferError <= config.closedLoopConsistencyTolerance && ...
    disturbanceTransferError <= config.closedLoopConsistencyTolerance, ...
    'M9Reconstruction:TransferMismatch', ...
    'Equivalent M9 closed-loop constructions disagree.');
assert(reconstruction.metrics.nominallyStable && ...
    reconstruction.metrics.sensitivityStable && ...
    reconstruction.metrics.complementarySensitivityStable && ...
    reconstruction.metrics.controlSensitivityStable && ...
    reconstruction.metrics.clmixStable, ...
    'M9Reconstruction:InternalStability', ...
    'The M9 nominal interconnection is not internally stable.');
end
