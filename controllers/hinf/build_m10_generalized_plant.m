function generalized = build_m10_generalized_plant(G, W1, W2, config)
%BUILD_M10_GENERALIZED_PLANT Build and audit the explicit M10 plant.

arguments
    G {mustBeA(G, {'ss', 'tf', 'zpk'})}
    W1 {mustBeA(W1, {'ss', 'tf', 'zpk'})}
    W2 {mustBeA(W2, {'ss', 'tf', 'zpk'})}
    config (1, 1) struct = hinf_specs_m10
end

Gnamed = ss(G);
W1named = ss(W1);
W2named = ss(W2);
Gnamed.InputName = {'u(1)', 'u(2)'};
Gnamed.OutputName = {'q(1)', 'q(2)'};
W1named.InputName = {'e(1)', 'e(2)'};
W1named.OutputName = {'z1(1)', 'z1(2)'};
W2named.InputName = {'u(1)', 'u(2)'};
W2named.OutputName = {'z2(1)', 'z2(2)'};
errorSum = sumblk('e = r - q', 2);

inputNames = {'r(1)', 'r(2)', 'u(1)', 'u(2)'};
outputNames = {'z1(1)', 'z1(2)', 'z2(1)', 'z2(2)', ...
    'e(1)', 'e(2)'};
P = connect(Gnamed, W1named, W2named, errorSum, ...
    inputNames, outputNames);

Gplain = localClearNames(ss(G));
W1plain = localClearNames(ss(W1));
W2plain = localClearNames(ss(W2));
Panalytic = [W1plain, -W1plain * Gplain; ...
    ss(zeros(2)), W2plain; ss(eye(2)), -Gplain];
Paugw = augw(Gplain, W1plain, W2plain, []);

partition = struct( ...
    'exogenousInputIndices', 1:2, ...
    'controlInputIndices', 3:4, ...
    'performanceOutputIndices', 1:4, ...
    'measurementOutputIndices', 5:6, ...
    'P11Size', size(P(1:4, 1:2)), ...
    'P12Size', size(P(1:4, 3:4)), ...
    'P21Size', size(P(5:6, 1:2)), ...
    'P22Size', size(P(5:6, 3:4)), ...
    'nmeas', config.nmeas, ...
    'ncont', config.ncont, ...
    'inputNames', string(P.InputName), ...
    'outputNames', string(P.OutputName));

frequencies = config.frequencyGrid;
audit = struct( ...
    'size', size(P), ...
    'order', order(P), ...
    'analyticMaximumFrequencyError', localMaximumFrequencyError( ...
        P, Panalytic, frequencies), ...
    'P22MaximumFrequencyError', localMaximumFrequencyError( ...
        P(5:6, 3:4), -Gplain, frequencies), ...
    'P21MaximumFrequencyError', localMaximumFrequencyError( ...
        P(5:6, 1:2), ss(eye(2)), frequencies), ...
    'augwMaximumFrequencyError', localMaximumFrequencyError( ...
        P, Paugw, frequencies), ...
    'constructedWithConnectAndSumblk', true, ...
    'augwUsedOnlyAfterIndependentConstruction', true, ...
    'nominalOnly', isa(P, 'ss') && ~isa(P, 'uss'), ...
    'W3Absent', isempty(config.W3), ...
    'signalEquation', "e=r-q; z1=W1*e; z2=W2*u; y=e");

assert(isequal(size(P), [6, 4]) && order(P) == ...
    order(G) + order(W1) + order(W2), ...
    'M10GeneralizedPlant:Dimensions', ...
    'The explicit generalized plant has unexpected dimensions or order.');
assert(audit.analyticMaximumFrequencyError <= ...
    config.generalizedPlantTolerance && ...
    audit.P22MaximumFrequencyError <= ...
        config.generalizedPlantTolerance && ...
    audit.P21MaximumFrequencyError <= ...
        config.generalizedPlantTolerance, ...
    'M10GeneralizedPlant:AnalyticMismatch', ...
    'The connect/sumblk plant disagrees with the analytic partition.');
assert(~config.augwCrossCheckEnabled || ...
    audit.augwMaximumFrequencyError <= ...
        config.augwCrossCheckTolerance, ...
    'M10GeneralizedPlant:AugwMismatch', ...
    'The independent generalized plant disagrees with augw.');

generalized.P = P;
generalized.Panalytic = Panalytic;
generalized.Paugw = Paugw;
generalized.partition = partition;
generalized.audit = audit;
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end

function maximumError = localMaximumFrequencyError(first, second, frequencies)
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
maximumError = max(abs(difference), [], 'all');
end
