function selected = load_m12_a5_controller(m11, config)
%LOAD_M12_A5_CONTROLLER Load the frozen A5 representative from M11.

arguments
    m11 (1, 1) struct
    config (1, 1) struct = mu_analysis_specs_m12
end

representativeIDs = string({m11.representativeResults.architectureID});
representativeIndex = find( ...
    representativeIDs == config.selectedArchitecture, 1);
tableIndex = find(m11.representativeTable.ArchitectureID == ...
    config.selectedArchitecture, 1);
campaignIndex = find(string({m11.campaign.architectureResults.id}) == ...
    config.selectedArchitecture, 1);
assert(~isempty(representativeIndex) && ~isempty(tableIndex) && ...
    ~isempty(campaignIndex), 'M12Controller:MissingA5', ...
    'The selected architecture is absent from the M11 artifact.');

representative = m11.representativeResults(representativeIndex);
tableRow = m11.representativeTable(tableIndex, :);
campaignRow = m11.campaign.architectureResults(campaignIndex);
assert(representative.available && tableRow.Valid && tableRow.Stable, ...
    'M12Controller:InvalidRepresentative', ...
    'The selected M11 representative is not valid and stable.');
assert(representative.startIndex == ...
    campaignRow.representativeStartIndex && ...
    representative.startIndex == tableRow.BestStart, ...
    'M12Controller:StartMismatch', ...
    'The selected start is inconsistent inside the M11 artifact.');
assert(order(representative.controller) == tableRow.Order && ...
    order(representative.controller) == ...
        campaignRow.definition.NominalOrder, ...
    'M12Controller:OrderMismatch', ...
    'The frozen controller order is inconsistent with M11 metadata.');
assert(representative.reconstruction.metrics.internallyStable && ...
    abs(representative.reconstruction.metrics.weightedNorm - ...
        tableRow.WeightedNorm) <= ...
        config.nominalNormRelativeTolerance * ...
        max(1, abs(tableRow.WeightedNorm)), ...
    'M12Controller:MetricMismatch', ...
    'The A5 weighted norm is inconsistent inside the M11 artifact.');

selected.architectureID = config.selectedArchitecture;
selected.architectureType = tableRow.ArchitectureType;
selected.sourceArtifact = ...
    "results/data/m11_hinfstruct_structured.mat";
selected.controller = representative.controller;
selected.order = order(representative.controller);
selected.startIndex = representative.startIndex;
selected.objective = representative.objective;
selected.weightedNormM11 = ...
    representative.reconstruction.metrics.weightedNorm;
selected.internalStableM11 = ...
    representative.reconstruction.metrics.internallyStable;
selected.maximumClosedLoopRealPartM11 = ...
    representative.reconstruction.metrics.maximumClosedLoopRealPart;
selected.m11Representative = representative;
selected.loadedWithoutTuning = true;
end
