function frozen = load_m13_uncertain_generalized_plant(projectRoot, config)
%LOAD_M13_UNCERTAIN_GENERALIZED_PLANT Rebuild and audit frozen M12 Punc.

arguments
    projectRoot (1, 1) string
    config (1, 1) struct = mu_synthesis_specs_m13
end

dataDirectory = fullfile(projectRoot, 'results', 'data');
m3 = load(fullfile(dataDirectory, 'm3_nominal_actuated_plant.mat'));
m4 = load(fullfile(dataDirectory, 'm4_uncertain_plant.mat'));
m5 = load(fullfile(dataDirectory, 'm5_performance_specs.mat'));
m11 = load(fullfile(dataDirectory, 'm11_hinfstruct_structured.mat'));
m12 = load(fullfile(dataDirectory, 'm12_mu_analysis_a5.mat'));

m12Config = mu_analysis_specs_m12;
selected = load_m12_a5_controller(m11, m12Config);
rebuilt = build_m12_uncertain_generalized_plant( ...
    m4.GuncQ, m5.W1, m5.W2, selected.controller, m12Config);
Punc = rebuilt.Punc;
PuncReference = m12.Punc;

[Mrebuilt, DeltaRebuilt, BlkRebuilt] = lftdata(Punc);
[Mreference, DeltaReference, BlkReference] = lftdata(PuncReference);
uncertaintyTable = localUncertaintyIdentity( ...
    Punc.Uncertainty, PuncReference.Uncertainty, ...
    config.expectedUncertaintyNames);
plantAudit = struct( ...
    'sourceArtifact', config.PuncSource, ...
    'rebuiltSize', size(Punc), ...
    'referenceSize', size(PuncReference), ...
    'inputNamesEqual', isequal(string(Punc.InputName), ...
        string(PuncReference.InputName)), ...
    'outputNamesEqual', isequal(string(Punc.OutputName), ...
        string(PuncReference.OutputName)), ...
    'uncertaintyNamesEqual', isequal( ...
        sort(string(fieldnames(Punc.Uncertainty))), ...
        sort(string(fieldnames(PuncReference.Uncertainty)))), ...
    'nominalFrequencyError', localFrequencyError( ...
        Punc.NominalValue, PuncReference.NominalValue, ...
        config.auditFrequencyGrid), ...
    'lftMSizeEqual', isequal(size(Mrebuilt), size(Mreference)), ...
    'lftDeltaSizeEqual', isequal(size(DeltaRebuilt), ...
        size(DeltaReference)), ...
    'lftBlockStructureEqual', isequaln(BlkRebuilt, BlkReference), ...
    'lftMFrequencyError', localFrequencyError( ...
        Mrebuilt, Mreference, config.auditFrequencyGrid), ...
    'uncertaintyTable', uncertaintyTable);
plantAudit.passed = isequal(plantAudit.rebuiltSize, [6, 4]) && ...
    isequal(plantAudit.referenceSize, [6, 4]) && ...
    plantAudit.inputNamesEqual && plantAudit.outputNamesEqual && ...
    plantAudit.uncertaintyNamesEqual && ...
    plantAudit.nominalFrequencyError <= ...
        config.identityFrequencyTolerance && ...
    plantAudit.lftMSizeEqual && plantAudit.lftDeltaSizeEqual && ...
    plantAudit.lftBlockStructureEqual && ...
    plantAudit.lftMFrequencyError <= config.identityFrequencyTolerance && ...
    all(uncertaintyTable.Identical);

[~, rebuiltW1, ~, rebuiltW2] = build_m5_weights(m5.spec);
weightAudit = struct( ...
    'sourceArtifact', config.weightSource, ...
    'W1Error', localFrequencyError(m5.W1, rebuiltW1, ...
        config.auditFrequencyGrid), ...
    'W2Error', localFrequencyError(m5.W2, rebuiltW2, ...
        config.auditFrequencyGrid), ...
    'W3Absent', isempty(config.W3), ...
    'retuningPerformed', config.weightRetuningEnabled);
weightAudit.passed = weightAudit.W1Error <= config.weightTolerance && ...
    weightAudit.W2Error <= config.weightTolerance && ...
    weightAudit.W3Absent && ~weightAudit.retuningPerformed;

uncertaintyAudit = struct( ...
    'sourceArtifact', config.uncertaintySource, ...
    'currentNames', sort(string(fieldnames(m4.GuncQ.Uncertainty))), ...
    'expectedNames', sort(config.expectedUncertaintyNames), ...
    'm12SourceAuditPassed', m12.M4SourceAudit.passed, ...
    'rangeTable', m12.M4SourceAudit.rangeTable, ...
    'retuningPerformed', config.uncertaintyRetuningEnabled);
uncertaintyAudit.passed = isequal(uncertaintyAudit.currentNames, ...
    uncertaintyAudit.expectedNames) && ...
    uncertaintyAudit.m12SourceAuditPassed && ...
    all(uncertaintyAudit.rangeTable.ApprovedStructure) && ...
    ~uncertaintyAudit.retuningPerformed;

assert(plantAudit.passed, 'M13:PuncIdentity', ...
    'The rebuilt uncertain generalized plant differs from frozen M12 Punc.');
assert(uncertaintyAudit.passed, 'M13:UncertaintyIdentity', ...
    'The M4 uncertainty set or ranges differ from the frozen source.');
assert(weightAudit.passed, 'M13:WeightIdentity', ...
    'The M5 weights differ from the frozen source.');

frozen.Punc = Punc;
frozen.PuncReference = PuncReference;
frozen.Gnominal = m3.GfullQ;
frozen.W1 = m5.W1;
frozen.W2 = m5.W2;
frozen.plantAudit = plantAudit;
frozen.uncertaintyAudit = uncertaintyAudit;
frozen.weightAudit = weightAudit;
frozen.M12SourceAudit = m12.M4SourceAudit;
frozen.M12Config = m12.config;
frozen.modelFormula = rebuilt.formula;
end

function tableData = localUncertaintyIdentity(first, second, expectedNames)
Name = sort(expectedNames(:));
Class = strings(numel(Name), 1);
NominalError = zeros(numel(Name), 1);
RangeOrBoundError = zeros(numel(Name), 1);
Identical = false(numel(Name), 1);
for index = 1:numel(Name)
    name = char(Name(index));
    a = first.(name);
    b = second.(name);
    Class(index) = string(class(a));
    sameClass = strcmp(class(a), class(b));
    if isa(a, 'ureal') && isa(b, 'ureal')
        NominalError(index) = abs(a.NominalValue - b.NominalValue);
        RangeOrBoundError(index) = max(abs(a.Range - b.Range));
    elseif isa(a, 'ultidyn') && isa(b, 'ultidyn')
        NominalError(index) = 0;
        RangeOrBoundError(index) = abs(a.Bound - b.Bound);
    else
        NominalError(index) = Inf;
        RangeOrBoundError(index) = Inf;
    end
    Identical(index) = sameClass && NominalError(index) == 0 && ...
        RangeOrBoundError(index) == 0;
end
tableData = table(Name, Class, NominalError, RangeOrBoundError, Identical);
end

function error = localFrequencyError(first, second, frequencies)
first = localClearNames(ss(first));
second = localClearNames(ss(second));
difference = freqresp(first, frequencies) - freqresp(second, frequencies);
error = max(abs(difference), [], 'all');
end

function system = localClearNames(system)
system.InputName = repmat({''}, size(system, 2), 1);
system.OutputName = repmat({''}, size(system, 1), 1);
end
