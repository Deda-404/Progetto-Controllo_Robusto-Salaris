function synthesis = run_m13_musyn(Punc, config)
%RUN_M13_MUSYN Execute the one frozen full-order D-K campaign.

arguments
    Punc uss
    config (1, 1) struct = mu_synthesis_specs_m13
end

assert(config.singleCandidate && config.singleCallSite && ...
    ~config.secondSynthesisEnabled && ~config.weightRetuningEnabled && ...
    ~config.uncertaintyRetuningEnabled && ...
    ~config.controllerReductionEnabled && isempty(config.W3), ...
    'M13:SynthesisScope', ...
    'M13 configuration violates the single frozen D-K campaign scope.');
assert(isequal(size(Punc), [6, 4]) && config.nmeas == 2 && ...
    config.ncont == 2, 'M13:SynthesisPartition', ...
    'Punc or the measurement/control partition is inconsistent.');

options = musynOptions( ...
    'Display', config.display, ...
    'MaxIter', config.maxIterations, ...
    'TargetPerf', config.targetPerformance, ...
    'TolPerf', config.performanceTolerance, ...
    'MixedMU', config.mixedMu, ...
    'FullDG', config.fullDG, ...
    'FitOrder', config.fitOrder, ...
    'FrequencyGrid', config.frequencyGrid, ...
    'AutoScale', config.autoScale, ...
    'Regularize', config.regularize, ...
    'LimitGain', config.limitGain, ...
    'RandomStart', config.randomStart, ...
    'UseParallel', config.useParallel, ...
    'MinDecay', config.minimumDecay, ...
    'MaxFrequency', config.maximumFrequency);
optionsSnapshot = localOptionsSnapshot(options);

lastwarn('');
startTime = tic;
[Kmu, musynObjective, rawInfo] = musyn( ...
    Punc, config.nmeas, config.ncont, options);
elapsedSeconds = toc(startTime);
[warningMessage, warningIdentifier] = lastwarn;
CLmu = lft(Punc, Kmu);

assert(isequal(size(Kmu), [2, 2]) && isfinite(musynObjective) && ...
    musynObjective > 0 && ~isempty(rawInfo), ...
    'M13:SynthesisOutput', ...
    'The single D-K campaign returned incomplete or invalid outputs.');

synthesis.Kmu = Kmu;
synthesis.CLmu = CLmu;
synthesis.musynObjective = musynObjective;
synthesis.rawInfo = rawInfo;
synthesis.optionsSnapshot = optionsSnapshot;
synthesis.warningMessage = string(warningMessage);
synthesis.warningIdentifier = string(warningIdentifier);
synthesis.elapsedSeconds = elapsedSeconds;
synthesis.controllerOrder = order(Kmu);
synthesis.controllerPoles = pole(Kmu);
synthesis.method = ...
    "full-order D-K on Punc with nmeas=2, ncont=2 and frozen options";
synthesis.secondOutputMeaning = ...
    "best achieved robust performance scalar (CLperf)";
synthesis.closedLoopReconstructedWithLft = true;
synthesis.callCountForCampaign = 1;
end

function snapshot = localOptionsSnapshot(options)
names = properties(options);
for index = 1:numel(names)
    snapshot.(names{index}) = options.(names{index});
end
end
