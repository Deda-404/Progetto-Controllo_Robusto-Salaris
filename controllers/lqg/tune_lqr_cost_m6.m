function tuning = tune_lqr_cost_m6(m3Data, m5Data, config, gridName, ...
    baselineDiagnosis)
%TUNE_LQR_COST_M6 Deterministic dimensionless-priority grid search for M6.

arguments
    m3Data (1, 1) struct
    m5Data (1, 1) struct
    config (1, 1) struct = lqg_specs_m6
    gridName (1, 1) string {mustBeMember(gridName, ...
        ["coarse", "extended"])} = "coarse"
    baselineDiagnosis (1, 1) struct = struct
end

grid = config.(gridName);
[wqGrid, wdeltaGrid, wVelocityGrid, rhoUGrid] = ndgrid( ...
    grid.wq(:), grid.wdelta(:), grid.wVelocity(:), grid.rhoU(:));
wq = wqGrid(:);
wdelta = wdeltaGrid(:);
wVelocity = wVelocityGrid(:);
rhoU = rhoUGrid(:);
numberCandidates = numel(wq);
candidate = compose("%s%03d", upper(extractBefore(gridName, 2)), ...
    (1:numberCandidates).');

stable = false(numberCandidates, 1);
dominantRealPart = NaN(numberCandidates, 1);
worstSettlingTime = inf(numberCandidates, 1);
worstOvershoot = inf(numberCandidates, 1);
worstSteadyStateErrorRelative = inf(numberCandidates, 1);
worstCrossCouplingPeakRatio = inf(numberCandidates, 1);
peakControl = inf(numberCandidates, 1);
peakUNormalized = inf(numberCandidates, 1);
peakDeltaJoint1 = inf(numberCandidates, 1);
peakDeltaJoint2 = inf(numberCandidates, 1);
peakDeltaNormalized = inf(numberCandidates, 1);
peakElasticTorqueJoint1 = inf(numberCandidates, 1);
peakElasticTorqueJoint2 = inf(numberCandidates, 1);
gainFrobeniusNorm = inf(numberCandidates, 1);
preFilterCondition = inf(numberCandidates, 1);
preFilterResidual = inf(numberCandidates, 1);
numericWarning = strings(numberCandidates, 1);
controller = cell(numberCandidates, 1);
preFilter = cell(numberCandidates, 1);
regulatorPoles = cell(numberCandidates, 1);
evaluations = cell(numberCandidates, 1);

for candidateIndex = 1:numberCandidates
    priorities = struct('wq', wq(candidateIndex), ...
        'wqdot', wVelocity(candidateIndex), ...
        'wdelta', wdelta(candidateIndex), ...
        'wthetaDot', wVelocity(candidateIndex));
    try
        [~, Qcandidate] = build_lqr_state_cost( ...
            m3Data, m5Data.spec, priorities);
        Rcandidate = rhoU(candidateIndex) / ...
            m5Data.spec.uScale^2 * eye(2);
        Kcandidate = lqr(m3Data.Afull, m3Data.Bfull, ...
            Qcandidate, Rcandidate);
        Acl = m3Data.Afull - m3Data.Bfull * Kcandidate;
        polesCandidate = eig(Acl);
        staticTrackingGain = -m3Data.CfullQ * ...
            (Acl \ m3Data.Bfull);
        Nrcandidate = staticTrackingGain \ eye(2);
        evaluation = evaluate_m6_closed_loop( ...
            m3Data.Afull, m3Data.Bfull, m3Data.CfullQ, ...
            m3Data.CfullMeas(3:4, :), m5Data.BdFull, ...
            Kcandidate, Nrcandidate, m3Data.mechanicalParams.Ks, ...
            m5Data.spec, config, false);

        controller{candidateIndex} = Kcandidate;
        preFilter{candidateIndex} = Nrcandidate;
        regulatorPoles{candidateIndex} = polesCandidate;
        evaluations{candidateIndex} = evaluation;
        stable(candidateIndex) = evaluation.summary.stable;
        dominantRealPart(candidateIndex) = max(real(polesCandidate));
        worstSettlingTime(candidateIndex) = ...
            evaluation.summary.worstSettlingTime;
        worstOvershoot(candidateIndex) = ...
            evaluation.summary.worstOvershoot;
        worstSteadyStateErrorRelative(candidateIndex) = ...
            evaluation.summary.worstSteadyStateErrorRelative;
        worstCrossCouplingPeakRatio(candidateIndex) = ...
            evaluation.summary.worstCrossCouplingPeakRatio;
        peakControl(candidateIndex) = ...
            evaluation.summary.worstPeakControl;
        peakUNormalized(candidateIndex) = ...
            peakControl(candidateIndex) / m5Data.spec.uScale;
        peakDeltaJoint1(candidateIndex) = ...
            evaluation.summary.peakDeformationByJoint(1);
        peakDeltaJoint2(candidateIndex) = ...
            evaluation.summary.peakDeformationByJoint(2);
        peakDeltaNormalized(candidateIndex) = ...
            evaluation.summary.peakDeformationNormalized;
        peakElasticTorqueJoint1(candidateIndex) = ...
            evaluation.summary.peakElasticTorqueByJoint(1);
        peakElasticTorqueJoint2(candidateIndex) = ...
            evaluation.summary.peakElasticTorqueByJoint(2);
        gainFrobeniusNorm(candidateIndex) = norm(Kcandidate, 'fro');
        preFilterCondition(candidateIndex) = cond(staticTrackingGain);
        preFilterResidual(candidateIndex) = norm( ...
            staticTrackingGain * Nrcandidate - eye(2), 'fro');
        if preFilterCondition(candidateIndex) > ...
                config.prefilterConditionWarning
            numericWarning(candidateIndex) = ...
                "ill-conditioned prefilter problem";
        end
    catch candidateError
        numericWarning(candidateIndex) = string(candidateError.identifier) + ...
            ": " + string(candidateError.message);
    end
end

fundamentalPass = stable & ...
    worstSettlingTime <= m5Data.spec.settlingTimeTarget & ...
    worstOvershoot <= m5Data.spec.overshootTarget & ...
    worstSteadyStateErrorRelative <= ...
        m5Data.spec.steadyStateTrackingTarget;
crossCouplingDiagnosticPass = worstCrossCouplingPeakRatio <= ...
    m5Data.spec.crossCouplingTarget;
controlEffortCategory = repmat("aggressive warning", ...
    numberCandidates, 1);
controlEffortCategory(peakUNormalized <= ...
    config.controlEffortAggressiveThreshold) = "elevated";
controlEffortCategory(peakUNormalized <= ...
    config.controlEffortModerateThreshold) = "moderate";

unattractiveExtended = false(numberCandidates, 1);
if gridName == "extended" && ~isempty(fieldnames(baselineDiagnosis))
    baselineEvaluation = evaluate_m6_closed_loop( ...
        m3Data.Afull, m3Data.Bfull, m3Data.CfullQ, ...
        m3Data.CfullMeas(3:4, :), m5Data.BdFull, ...
        baselineDiagnosis.K, baselineDiagnosis.Nr, ...
        m3Data.mechanicalParams.Ks, m5Data.spec, config, false);
    baselineDelta = baselineEvaluation.summary.peakDeformationNormalized;
    baselineGain = norm(baselineDiagnosis.K, 'fro');
    unattractiveExtended = peakUNormalized > ...
        config.controlEffortAggressiveThreshold | ...
        peakDeltaNormalized > ...
            config.extendedDeltaBaselineMultiplier * baselineDelta | ...
        gainFrobeniusNorm > ...
            config.extendedGainBaselineMultiplier * baselineGain | ...
        strlength(numericWarning) > 0;
end
technicallySelectable = fundamentalPass & ~unattractiveExtended;

rankingMatrix = [~technicallySelectable, peakUNormalized, ...
    peakDeltaNormalized, gainFrobeniusNorm, -rhoU, ...
    -wq, wdelta, wVelocity, (1:numberCandidates).'];
[~, order] = sortrows(rankingMatrix, 1:size(rankingMatrix, 2));
ranking = zeros(numberCandidates, 1);
ranking(order) = (1:numberCandidates).';
selected = false(numberCandidates, 1);
selectedIndex = order(find(technicallySelectable(order), 1, 'first'));
if ~isempty(selectedIndex)
    selected(selectedIndex) = true;
end

lqrCandidateTable = table(candidate, wq, wdelta, wVelocity, rhoU, ...
    stable, dominantRealPart, worstSettlingTime, worstOvershoot, ...
    worstSteadyStateErrorRelative, worstCrossCouplingPeakRatio, ...
    peakControl, peakUNormalized, peakDeltaJoint1, peakDeltaJoint2, ...
    peakDeltaNormalized, peakElasticTorqueJoint1, ...
    peakElasticTorqueJoint2, gainFrobeniusNorm, ...
    preFilterCondition, preFilterResidual, numericWarning, ...
    fundamentalPass, crossCouplingDiagnosticPass, ...
    unattractiveExtended, technicallySelectable, selected, ranking, ...
    controlEffortCategory, 'VariableNames', {'Candidate', 'Wq', ...
    'Wdelta', 'WVelocity', 'RhoU', 'Stable', 'DominantRealPart', ...
    'WorstSettlingTime', 'WorstOvershoot', ...
    'WorstSteadyStateErrorRelative', ...
    'WorstCrossCouplingPeakRatio', 'PeakControl', ...
    'PeakUNormalized', 'PeakDeltaJoint1', 'PeakDeltaJoint2', ...
    'PeakDeltaNormalized', 'PeakElasticTorqueJoint1', ...
    'PeakElasticTorqueJoint2', 'GainFrobeniusNorm', ...
    'PreFilterCondition', 'PreFilterResidual', 'NumericWarning', ...
    'FundamentalPass', 'CrossCouplingDiagnosticPass', ...
    'UnattractiveExtended', 'TechnicallySelectable', 'Selected', ...
    'Ranking', 'ControlEffortCategory'});

crossCouplingComparisonIndices = find(fundamentalPass);
if isempty(crossCouplingComparisonIndices)
    crossCouplingComparisonIndices = find(stable);
end
[~, bestCrossLocalIndex] = min( ...
    worstCrossCouplingPeakRatio(crossCouplingComparisonIndices));
bestCrossCouplingIndex = ...
    crossCouplingComparisonIndices(bestCrossLocalIndex);
tuning.gridName = gridName;
tuning.grid = grid;
tuning.lqrCandidateTable = lqrCandidateTable;
tuning.candidateControllers = controller;
tuning.candidatePreFilters = preFilter;
tuning.candidatePoles = regulatorPoles;
tuning.candidateEvaluations = evaluations;
tuning.selectedIndex = selectedIndex;
tuning.bestCrossCouplingIndex = bestCrossCouplingIndex;
tuning.rules = [ ...
    "discard unstable candidates"; ...
    "require M5 settling, overshoot and steady-state tracking targets"; ...
    "minimize normalized peak control"; ...
    "then minimize normalized SEA deformation and Frobenius gain norm"; ...
    "then maximize rhoU and use fixed parameter/index tie-breaks"];
tuning.status = "no technically selectable candidate";
if ~isempty(selectedIndex)
    tuning.status = "technically selectable candidate found";
    tuning.selectedPriorities = struct( ...
        'wq', wq(selectedIndex), ...
        'wqdot', wVelocity(selectedIndex), ...
        'wdelta', wdelta(selectedIndex), ...
        'wthetaDot', wVelocity(selectedIndex));
    [tuning.Ccost, tuning.Q, tuning.scales, tuning.costInfo] = ...
        build_lqr_state_cost(m3Data, m5Data.spec, ...
        tuning.selectedPriorities);
    tuning.rhoU = rhoU(selectedIndex);
    tuning.R = tuning.rhoU / m5Data.spec.uScale^2 * eye(2);
    tuning.K = controller{selectedIndex};
    tuning.Nr = preFilter{selectedIndex};
    tuning.regulatorPoles = regulatorPoles{selectedIndex};
    tuning.evaluation = evaluations{selectedIndex};
    tuning.alphaController = min(-real(tuning.regulatorPoles));
end
end
