function selection = search_lqr_weights_m6(m3Data, m5Data, config)
%SEARCH_LQR_WEIGHTS_M6 Compare a small set of interpretable LQR costs.
%   The search has two explicit stages. First, unstable candidates or
%   candidates that violate the mandatory M5 tracking requirements are
%   rejected. Second, the admissible candidates are ranked using a simple
%   weighted mean of normalized performance and control-effort metrics.

arguments
    m3Data (1, 1) struct
    m5Data (1, 1) struct
    config (1, 1) struct = lqg_specs_m6
end

grid = config.lqr.candidates;
[positionGrid, velocityGrid, deformationGrid, controlGrid] = ndgrid( ...
    grid.position(:), grid.velocity(:), grid.deformation(:), ...
    grid.control(:));
positionWeight = positionGrid(:);
velocityWeight = velocityGrid(:);
deformationWeight = deformationGrid(:);
controlWeight = controlGrid(:);
numberCandidates = numel(positionWeight);
assert(numberCandidates == config.lqr.expectedCandidateCount, ...
    'M6LQR:CandidateCount', ...
    'The declared compact LQR search must contain exactly %d candidates.', ...
    config.lqr.expectedCandidateCount);

candidate = compose("LQR%02d", (1:numberCandidates).');
stable = false(numberCandidates, 1);
worstSettlingTime = inf(numberCandidates, 1);
worstOvershoot = inf(numberCandidates, 1);
worstSteadyStateErrorRelative = inf(numberCandidates, 1);
worstCrossCouplingPeakRatio = inf(numberCandidates, 1);
worstPeakControl = inf(numberCandidates, 1);
worstRmsControl = inf(numberCandidates, 1);
worstControlEnergy = inf(numberCandidates, 1);
peakControlNormalized = inf(numberCandidates, 1);
rmsControlNormalized = inf(numberCandidates, 1);
prefilterResidual = inf(numberCandidates, 1);
numericNote = strings(numberCandidates, 1);
controllers = cell(numberCandidates, 1);
prefilters = cell(numberCandidates, 1);
poles = cell(numberCandidates, 1);
evaluations = cell(numberCandidates, 1);
costMatrices = cell(numberCandidates, 1);
costOutputs = cell(numberCandidates, 1);
costScales = cell(numberCandidates, 1);
costInformation = cell(numberCandidates, 1);

for index = 1:numberCandidates
    priorities = struct('wq', positionWeight(index), ...
        'wqdot', velocityWeight(index), ...
        'wdelta', deformationWeight(index), ...
        'wthetaDot', velocityWeight(index));
    try
        [Ccost, Q, scales, costInfo] = build_lqr_state_cost( ...
            m3Data, m5Data.spec, priorities);
        R = controlWeight(index) / m5Data.spec.uScale^2 * eye(2);
        K = lqr(m3Data.Afull, m3Data.Bfull, Q, R);
        Acl = m3Data.Afull - m3Data.Bfull * K;
        regulatorPoles = eig(Acl);
        staticTrackingGain = -m3Data.CfullQ * ...
            (Acl \ m3Data.Bfull);
        Nr = staticTrackingGain \ eye(2);
        evaluation = evaluate_m6_closed_loop( ...
            m3Data.Afull, m3Data.Bfull, m3Data.CfullQ, ...
            m3Data.CfullMeas(3:4, :), m5Data.BdFull, K, Nr, ...
            m3Data.mechanicalParams.Ks, m5Data.spec, config, false);

        stable(index) = all(real(regulatorPoles) < ...
            -config.numericStabilityTolerance);
        worstSettlingTime(index) = evaluation.summary.worstSettlingTime;
        worstOvershoot(index) = evaluation.summary.worstOvershoot;
        worstSteadyStateErrorRelative(index) = ...
            evaluation.summary.worstSteadyStateErrorRelative;
        worstCrossCouplingPeakRatio(index) = ...
            evaluation.summary.worstCrossCouplingPeakRatio;
        worstPeakControl(index) = evaluation.summary.worstPeakControl;
        worstRmsControl(index) = evaluation.summary.worstRmsControl;
        worstControlEnergy(index) = evaluation.summary.worstControlEnergy;
        peakControlNormalized(index) = ...
            worstPeakControl(index) / m5Data.spec.uScale;
        rmsControlNormalized(index) = ...
            worstRmsControl(index) / m5Data.spec.uScale;
        prefilterResidual(index) = norm( ...
            staticTrackingGain * Nr - eye(2), 'fro');
        controllers{index} = K;
        prefilters{index} = Nr;
        poles{index} = regulatorPoles;
        evaluations{index} = evaluation;
        costMatrices{index} = Q;
        costOutputs{index} = Ccost;
        costScales{index} = scales;
        costInformation{index} = costInfo;
    catch candidateError
        numericNote(index) = string(candidateError.identifier) + ...
            ": " + string(candidateError.message);
    end
end

% The cross-coupling target remains a diagnostic in M5, so it is reported
% and included in the compromise score but is not promoted to a new hard
% constraint here. No hardware saturation is invented from uScale.
admissible = stable & ...
    worstSettlingTime <= m5Data.spec.settlingTimeTarget & ...
    worstOvershoot <= m5Data.spec.overshootTarget & ...
    worstSteadyStateErrorRelative <= ...
        m5Data.spec.steadyStateTrackingTarget & ...
    isfinite(prefilterResidual);

scoreTerms = [ ...
    worstSettlingTime / m5Data.spec.settlingTimeTarget, ...
    worstOvershoot / m5Data.spec.overshootTarget, ...
    worstSteadyStateErrorRelative / ...
        m5Data.spec.steadyStateTrackingTarget, ...
    worstCrossCouplingPeakRatio / m5Data.spec.crossCouplingTarget, ...
    peakControlNormalized, rmsControlNormalized];
scoreWeights = [config.lqr.score.settling, ...
    config.lqr.score.overshoot, config.lqr.score.steadyState, ...
    config.lqr.score.crossCoupling, config.lqr.score.peakControl, ...
    config.lqr.score.rmsControl];
assert(abs(sum(scoreWeights) - 1) <= 1e-12, 'M6LQR:ScoreWeights', ...
    'The normalized compromise weights must sum to one.');
compromiseScore = scoreTerms * scoreWeights.';
compromiseScore(~admissible) = inf;
[selectedScore, selectedIndex] = min(compromiseScore);
assert(isfinite(selectedScore), 'M6LQR:NoAdmissibleCandidate', ...
    'The compact search found no LQR satisfying mandatory M5 targets.');
selected = false(numberCandidates, 1);
selected(selectedIndex) = true;
crossCouplingDiagnosticPass = worstCrossCouplingPeakRatio <= ...
    m5Data.spec.crossCouplingTarget;

candidateTable = table(candidate, positionWeight, velocityWeight, ...
    deformationWeight, controlWeight, stable, worstSettlingTime, ...
    worstOvershoot, worstSteadyStateErrorRelative, ...
    worstCrossCouplingPeakRatio, worstPeakControl, worstRmsControl, ...
    worstControlEnergy, peakControlNormalized, rmsControlNormalized, ...
    crossCouplingDiagnosticPass, admissible, compromiseScore, ...
    selected, prefilterResidual, numericNote, 'VariableNames', ...
    {'Candidate', 'PositionWeight', 'VelocityWeight', ...
    'DeformationWeight', 'ControlWeight', 'Stable', ...
    'WorstSettlingTime', 'WorstOvershoot', ...
    'WorstSteadyStateErrorRelative', 'WorstCrossCouplingPeakRatio', ...
    'WorstPeakControl', 'WorstRmsControl', 'WorstControlEnergy', ...
    'PeakControlNormalized', 'RmsControlNormalized', ...
    'CrossCouplingDiagnosticPass', 'Admissible', 'CompromiseScore', ...
    'Selected', 'PrefilterResidual', 'NumericNote'});

selection.status = "complete - compact parametric search selected an admissible LQR";
selection.grid = grid;
selection.numberCandidates = numberCandidates;
selection.numberAdmissible = sum(admissible);
selection.candidateTable = candidateTable;
selection.selectedIndex = selectedIndex;
selection.selectedScore = selectedScore;
selection.scoreWeights = scoreWeights;
selection.scoreDefinition = [ ...
    "0.30 Ts/Ts_target + 0.20 Mp/Mp_target + 0.10 ess/ess_target"; ...
    "+ 0.10 cross/cross_target + 0.15 peakU/uScale + 0.15 rmsU/uScale"];
selection.priorities = struct('wq', positionWeight(selectedIndex), ...
    'wqdot', velocityWeight(selectedIndex), ...
    'wdelta', deformationWeight(selectedIndex), ...
    'wthetaDot', velocityWeight(selectedIndex));
selection.rhoU = controlWeight(selectedIndex);
selection.Ccost = costOutputs{selectedIndex};
selection.Q = costMatrices{selectedIndex};
selection.R = selection.rhoU / m5Data.spec.uScale^2 * eye(2);
selection.K = controllers{selectedIndex};
selection.Nr = prefilters{selectedIndex};
selection.regulatorPoles = poles{selectedIndex};
selection.evaluation = evaluations{selectedIndex};
selection.scales = costScales{selectedIndex};
selection.costInfo = costInformation{selectedIndex};
selection.alphaController = min(-real(selection.regulatorPoles));
selection.staticTrackingGain = -m3Data.CfullQ * ...
    ((m3Data.Afull - m3Data.Bfull * selection.K) \ m3Data.Bfull);
selection.prefilterCondition = cond(selection.staticTrackingGain);
selection.prefilterResidual = prefilterResidual(selectedIndex);
selection.method = ...
    "36-candidate physically parameterized search with admissibility then normalized compromise";
end
