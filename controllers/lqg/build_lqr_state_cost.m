function [Ccost, Q, scales, info] = build_lqr_state_cost( ...
    m3Data, m5Spec, priorities)
%BUILD_LQR_STATE_COST Build the physically normalized M6 LQR state cost.
%   The full-state cost is the squared norm of normalized link position,
%   link velocity, SEA deformation and motor velocity. The six internal
%   actuator realization states receive no arbitrary direct penalty.

arguments
    m3Data (1, 1) struct
    m5Spec (1, 1) struct
    priorities (1, 1) struct = struct
end

requiredM3 = {'Afull', 'mechanicalParams'};
assert(all(isfield(m3Data, requiredM3)), 'M6Cost:MissingM3Data', ...
    'The validated M3 full plant and mechanical parameters are required.');
requiredM5 = {'referenceAmplitude', 'omegaB', ...
    'disturbanceTorqueAmplitude'};
assert(all(isfield(m5Spec, requiredM5)), 'M6Cost:MissingM5Data', ...
    'The validated M5 normalization data are required.');

numberStates = size(m3Data.Afull, 1);
assert(numberStates == 14, 'M6Cost:UnexpectedPlantOrder', ...
    'M6 requires the validated 14-state M3 plant.');

springStiffness = diag(m3Data.mechanicalParams.Ks);
assert(numel(springStiffness) == 2 && all(springStiffness > 0), ...
    'M6Cost:InvalidSpringStiffness', ...
    'Two positive SEA stiffness values are required.');

scales.q = m5Spec.referenceAmplitude;
scales.qdot = m5Spec.omegaB * scales.q;
scales.delta = m5Spec.disturbanceTorqueAmplitude / ...
    min(springStiffness);
scales.thetadot = m5Spec.omegaB * scales.q;

priorityDefaults = struct('wq', 1, 'wqdot', 1, ...
    'wdelta', 1, 'wthetaDot', 1);
priorityNames = fieldnames(priorityDefaults);
for priorityIndex = 1:numel(priorityNames)
    priorityName = priorityNames{priorityIndex};
    if ~isfield(priorities, priorityName)
        priorities.(priorityName) = priorityDefaults.(priorityName);
    end
    assert(isfinite(priorities.(priorityName)) && ...
        priorities.(priorityName) > 0, 'M6Cost:InvalidPriority', ...
        'Every dimensionless cost priority must be positive and finite.');
end

Ccost = zeros(8, numberStates);
Ccost(1:2, 1:2) = sqrt(priorities.wq) * eye(2) / scales.q;
Ccost(3:4, 3:4) = ...
    sqrt(priorities.wqdot) * eye(2) / scales.qdot;
Ccost(5:6, 1:2) = ...
    -sqrt(priorities.wdelta) * eye(2) / scales.delta;
Ccost(5:6, 5:6) = ...
    sqrt(priorities.wdelta) * eye(2) / scales.delta;
Ccost(7:8, 7:8) = ...
    sqrt(priorities.wthetaDot) * eye(2) / scales.thetadot;
Q = Ccost.' * Ccost;
Q = (Q + Q.') / 2;

info.stateOrder = [ ...
    "q1"; "q2"; "q1dot"; "q2dot"; ...
    "theta1"; "theta2"; "theta1dot"; "theta2dot"; ...
    "act1_x1"; "act1_x2"; "act1_x3"; ...
    "act2_x1"; "act2_x2"; "act2_x3"];
info.costOutputOrder = [ ...
    "q1/qScale"; "q2/qScale"; ...
    "q1dot/qdotScale"; "q2dot/qdotScale"; ...
    "(theta1-q1)/deltaScale"; "(theta2-q2)/deltaScale"; ...
    "theta1dot/thetadotScale"; "theta2dot/thetadotScale"];
info.actuatorDirectWeightNorm = norm(Ccost(:, 9:14), 'fro');
info.minimumQEigenvalue = min(eig(Q));
info.isPositiveSemidefinite = info.minimumQEigenvalue >= -1e-10;
info.priorities = priorities;
info.equivalentBlockWeights = struct( ...
    'q', priorities.wq / scales.q^2, ...
    'qdot', priorities.wqdot / scales.qdot^2, ...
    'delta', priorities.wdelta / scales.delta^2, ...
    'thetaDot', priorities.wthetaDot / scales.thetadot^2);
end
