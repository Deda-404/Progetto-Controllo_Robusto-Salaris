function collect_final_dependencies
%COLLECT_FINAL_DEPENDENCIES MATLAB dependency inventory for the hand-in.
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root,genpath(fullfile(root,'src')),genpath(fullfile(root,'controllers')), ...
    genpath(fullfile(root,'analysis')),fullfile(root,'simulink'),fullfile(root,'tools'));
files={'File_di_Funzioni_Progetto-Accorpati/progetto_lqg.m', ...
    'File_di_Funzioni_Progetto-Accorpati/progetto_lqgi.m', ...
    'File_di_Funzioni_Progetto-Accorpati/progetto_hinf_tre_controllori.m', ...
    'File_di_Funzioni_Progetto-Accorpati/progetto_mu.m', ...
    'tools/run_final_student_validation.m','tools/capture_final_robustness.m', ...
    'tools/export_student_baseline_figures.m', ...
    'analysis/run_final_noise_diagnostics.m','analysis/run_practical_robustness.m', ...
    'analysis/run_final_ras_lyapunov.m'};
[dependencies,products]=matlab.codetools.requiredFilesAndProducts(fullfile(root,files));
relative=cellfun(@(v)char(erase(string(v),string(root)+filesep)),dependencies,'UniformOutput',false);
evidence=struct('release',version('-release'),'files',{relative},'products',products, ...
    'note','Static MATLAB dependencies supplemented by dynamic src/support paths and frozen datasets in the delivery manifest.');
f=fopen(fullfile(root,'delivery/source_dependencies.json'),'w');cleanup=onCleanup(@()fclose(f));
fprintf(f,'%s',jsonencode(evidence,PrettyPrint=true));
fprintf('PASS: %d source dependencies.\n',numel(relative));
end
