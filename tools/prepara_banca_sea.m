function prepara_banca_sea
%PREPARA_BANCA_SEA Estrazione portabile, senza cambiare le realizzazioni.
root=fileparts(fileparts(mfilename('fullpath')));
addpath(genpath(fullfile(root,'src')),genpath(fullfile(root,'analysis')), ...
    genpath(fullfile(root,'controllers')), ...
    fullfile(root,'File_di_Funzioni_Progetto-Accorpati','support'));
d=final_closure_load; folder=fullfile(root,'results/data');
a=load(fullfile(folder,'m6_lqg_no_integrator.mat')); m6=a;
a=load(fullfile(folder,'m7_augmented_cost_feasibility.mat')); m7=a;
servo=m7.designs{m7.config.illustrativeIndex};
plant=struct('A',d.m3.Afull,'Bu',d.m3.Bfull,'Bd',d.m5.BdFull, ...
    'C',d.m3.CfullMeas,'Cq',d.m3.CfullQ,'xbar',d.m3.xbar, ...
    'taubar',d.m3.taubar,'act',d.m3.GactuatorsMimo);
lqg=struct('Q',m6.Q,'R',m6.R,'K',m6.K,'L',m6.L,'Nr',m6.Nr, ...
    'Qn',m6.Qn,'Rn',m6.Rn,'Kss',m6.Klqg);
lqgi=struct('P',servo.P,'Kx',servo.Kx,'Ki',servo.Ki, ...
    'wbarI',servo.wbarI,'ru',servo.ru,'Kss',d.controllers(2).K);
a=load(fullfile(folder,'hinf_final_coherent/fixed_PID.mat')); f=a.f;
valid=find(cellfun(@(r)r.valid,f.runs));
[~,idx]=min(cellfun(@(r)r.objective,f.runs(valid))); best=valid(idx);
one=d.study.one{d.study.selectedOne};
hinf=struct('K1',d.controllers(3).K,'Ke',one.Kfeedback, ...
    'K2',d.controllers(4).K,'PID',d.controllers(5).K, ...
    'W1',d.selected.W1,'W2',d.selected.W2,'Mo',d.selected.Mo, ...
    'gamma1',one.gamma,'gamma2',d.selected.gamma, ...
    'pidParameters',parametri_pid_hinf(f.info(best).TunedBlocks), ...
    'pidObjective',f.runs{best}.objective);
a=load(fullfile(folder,'hinf_final_coherent/m13.mat')); mu=a.synthesis;
mu=struct('K',mu.K,'objective',mu.objective, ...
    'history',extract_m13_dk_history(mu.info,mu.objective));
a=load(fullfile(folder,'m4_uncertain_plant.mat'));
historical=struct('family','M4 storico; non S1','WI',a.WI);
a=load(fullfile(folder,'hinf_final_coherent/m12.mat')); historical.hinf=a.audit;
a=load(fullfile(folder,'hinf_final_coherent/m14.mat')); historical.mu=a.audit;
noise=load(fullfile(folder,'noise_redesign/mu_noise_01.mat'),'candidate');
historical.MuN1=struct('K',noise.candidate.K,'status','candidato storico non adottato');
banca=struct('plant',plant,'lqg',lqg,'lqgi',lqgi,'hinf',hinf, ...
    'mu',mu,'controllers',d.controllers,'historical',historical, ...
    'sourceCommit','0ed5611fdbb9c46475543f87eba68d9799b07bc5');
out=fullfile(root,'Progetto_SEA_Consegna/dati');
save(fullfile(out,'banca_consolidata.mat'),'banca','-v7');
fprintf('Banca portabile: sei controllori e provenienza conservati.\n');
end
